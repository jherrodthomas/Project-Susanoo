def frame(number: str, title: str, subtitle: str, ref: str, width: float, body: list[str], body_h: float,
          legend: list[tuple[str, str, str]], source: str) -> str:
    head, y_line = fk.header(width, number, title, subtitle, ref)
    top = y_line + 22
    out = list(head) + [f'<g transform="translate(0 {fk.fmt(top)})">', *body, "</g>"]
    y = top + body_h + 26
    if legend:
        leg, y = fk.legend(M, y, legend, width - M)
        out += leg
        y += 6
    for ln in fk.wrap(f"Generated by {GEN} from {source}. {NOT_CLAIMED}", width - 2 * M, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(width, y + 16, f"Figure {number} · {title}", subtitle, out)


NOT_CLAIMED = "Drafted at independence level I0; nothing shown here is reviewed, verified or accepted."


def chip(x, y, label, tone, size=9.5, h=17) -> tuple[list[str], float]:
    s, f = STATUS[tone] if tone in STATUS else RISK[tone]
    return fk.pill(x, y, label, fill=f, color=s, h=h, size=size, stroke=s)


def risk_chip(x, y, rac: str, level: str, size=9.5) -> tuple[list[str], float]:
    s, f = RISK.get(level, RISK["Eliminated"])
    return fk.pill(x, y, rac, fill=f, color=s, h=17, size=size, stroke=s)


def legend_tone(tone: str, label: str) -> tuple[str, str, str]:
    s, f = STATUS[tone] if tone in STATUS else RISK[tone]
    return (f, s, label)


def lanes(lane_list: list[tuple[str, str, list[dict]]], width: float, card_w: float = 318) -> tuple[list[str], float]:
    """Horizontal lanes (label, sub-label, cards); cards wrap. card: {code, title, tone, note}."""
    out, y = [], 0.0
    label_w = 150
    x0 = M + label_w + 14
    per_row = max(1, int((width - M - x0 + 12) // (card_w + 12)))
    for label, sub, cards in lane_list:
        rows = max(1, -(-len(cards) // per_row))
        heights = []
        laid = []
        for i, c in enumerate(cards):
            lines = fk.wrap(c["title"], card_w - 22, 11, max_lines=3)
            h = 34 + 15 * len(lines) + (14 if c.get("note") else 0)
            laid.append((i // per_row, i % per_row, c, lines, h))
        for r in range(rows):
            heights.append(max([h for rr, _, _, _, h in laid if rr == r] or [44]))
        lane_h = sum(heights) + 12 * (rows - 1) + 24
        out.append(fk.rect(M, y, width - 2 * M, lane_h, fill="#FBFCFE", stroke=HAIR, rx=10))
        out.append(fk.text(M + 14, y + 26, label, size=13, weight=700))
        for k, ln in enumerate(fk.wrap(sub, label_w - 10, 10.5, max_lines=3)):
            out.append(fk.text(M + 14, y + 43 + 14 * k, ln, size=10.5, fill=MUTED))
        row_y = [y + 12 + sum(heights[:r]) + 12 * r for r in range(rows)]
        for r, col, c, lines, h in laid:
            cx, cy = x0 + col * (card_w + 12), row_y[r]
            s, f = STATUS[c["tone"]]
            out.append(fk.rect(cx, cy, card_w, heights[r], fill=f, stroke=s, rx=8, sw=1.2))
            p, _ = fk.pill(cx + 10, cy + 9, c["code"], fill=s, color="#FFFFFF", h=16, size=9.5)
            out += p
            if c.get("tag"):
                tp, tw = fk.pill(0, 0, c["tag"], fill="#FFFFFF", color=s, h=16, size=9, stroke=s)
                out += fk.pill(cx + card_w - 10 - tw, cy + 9, c["tag"], fill="#FFFFFF", color=s, h=16, size=9,
                               stroke=s)[0]
            for k, ln in enumerate(lines):
                out.append(fk.text(cx + 11, cy + 43 + 15 * k, ln, size=11, fill=INK))
            if c.get("note"):
                out.append(fk.text(cx + 11, cy + 43 + 15 * len(lines), c["note"], size=10, fill=MUTED))
        if not cards:
            out.append(fk.text(x0, y + 30, "none", size=11, fill=FAINT))
        y += lane_h + 10
    return out, y - 10


def table(cols: list[tuple[str, float, str]], rows: list[list], width: float, group_of=None,
          row_h: float = 26) -> tuple[list[str], float]:
    """cols: (header, width, align). A cell is text, or a callable(x, y, w) -> svg list. Optional row groups."""
    out, y = [], 0.0
    xs, x = [], M
    for _, w, _ in cols:
        xs.append(x)
        x += w
    for (hd, w, al), cx in zip(cols, xs):
        tx = cx + (w / 2 if al == "middle" else 8)
        out.append(fk.text(tx, y + 14, hd, size=10.5, weight=700, fill=MUTED, anchor="middle" if al == "middle" else ""))
    y += 24
    out.append(fk.line(M, y, width - M, y, stroke=LINE, sw=1))
    last_group = None
    for i, r in enumerate(rows):
        g = group_of(r) if group_of else None
        if g is not None and g != last_group:
            y += 6
            out.append(fk.text(M + 8, y + 16, g, size=11.5, weight=700))
            y += 24
            last_group = g
        rh = row_h + 22 * max([c.extra(w) for c, (_, w, _) in zip(r, cols) if hasattr(c, "extra")] or [0])
        if i % 2 == 0:
            out.append(fk.rect(M, y, width - 2 * M, rh, fill="#F8FAFC", stroke="none", rx=4, sw=0))
        for cell, (hd, w, al), cx in zip(r, cols, xs):
            if callable(cell):
                out += cell(cx, y, w)
            elif cell not in (None, ""):
                s = str(cell)
                lim = w - 14
                while fk.text_w(s, 11) > lim and len(s) > 4:
                    s = s[:-2].rstrip() + "…" if not s.endswith("…") else s[:-2].rstrip() + "…"
                tx = cx + (w / 2 if al == "middle" else 8)
                out.append(fk.text(tx, y + row_h / 2 + 4, s, size=11, fill=INK, anchor="middle" if al == "middle" else ""))
        y += rh
    out.append(fk.line(M, y, width - M, y, stroke=HAIR, sw=1))
    return out, y


def centred_chip(label, tone):
    def draw(cx, cy, w):
        pw = fk.pill_w(label, 9.5)
        return chip(cx + (w - pw) / 2, cy + 4.5, label, tone)[0]
    return draw


def chips_left(items):
    """items: [(label, tone)], wrapping when the cell is full."""
    return _chips_wrap(items)


