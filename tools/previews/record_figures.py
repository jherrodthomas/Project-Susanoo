def _chips_wrap(items, width: float = 0):
    """Chips left to right, wrapping onto further lines; .extra(w) says how many extra lines the cell needs."""
    def layout(w):
        pos, x, line = [], 8.0, 0
        for label, tone in items:
            pw = fk.pill_w(label)
            if x + pw > w - 4 and x > 8:
                x, line = 8.0, line + 1
            pos.append((x, line, label, tone))
            x += pw + 5
        return pos

    def draw(cx, cy, w):
        out = []
        for x, line, label, tone in layout(w):
            out += chip(cx + x, cy + 4.5 + 22 * line, label, tone)[0]
        return out
    draw.extra = lambda w: max([ln for _, ln, _, _ in layout(w)] or [0])
    return draw


def task_tailoring(repo) -> str:
    t = repo.tailoring
    titles = {task["id"]: task["title"] for task in repo.model["tasks"]}
    gates = t.get("gates", {})
    tone = {"selected": "ok", "conditional": "amber", "not-selected": "grey", "not-applicable": "grey"}
    by = defaultdict(list)
    for tid, d in sorted(t["tasks"].items()):
        lane = d.get("gate") if d["disposition"] == "selected" else d["disposition"]
        by[lane].append({"code": f"Task {tid}", "title": titles.get(int(tid), ""), "tone": tone[d["disposition"]],
                         "note": d.get("owner", "")})
    order = [g for g in gates if by.get(g)] + [k for k in ("conditional", "not-selected", "not-applicable") if by.get(k)]
    sub_of = {"conditional": "selected when its trigger occurs", "not-selected": "covered by another task",
              "not-applicable": "nothing in the concept to apply it to"}
    lane_list = [(g if g in gates else g.replace("-", " ").capitalize(),
                  f"{gates[g]['title']} ({gates[g]['phase']})" if g in gates else sub_of[g], by[g]) for g in order]
    body, h = lanes(lane_list, W, card_w=278)
    n = Counter(d["disposition"] for d in t["tasks"].values())
    sub = (f"The project's tailoring of the MIL-STD-882E tasks: {n['selected']} selected (shown at the gate they "
           f"start), {n['conditional']} conditional, {n['not-selected']} not selected, {n['not-applicable']} not "
           f"applicable. Owner roles under each task. Tailoring is proposed until approved on a review record.")
    return frame("1", "Task tailoring", sub, "standards/tailoring/mil-std-882e.yaml", W, body, h,
                 [legend_tone("ok", "Selected"), legend_tone("amber", "Conditional"),
                  legend_tone("grey", "Not selected or not applicable")],
                 "standards/tailoring/mil-std-882e.yaml and standards/mil-std-882e/model.yaml")


