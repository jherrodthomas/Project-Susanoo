def build() -> dict[Path, str]:
    repo = load(ROOT)
    out = {}
    for name, fn in FIGURES.items():
        p = OUT / name
        out[p] = decorate(p.relative_to(ROOT).as_posix(), fn(repo))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    stale = []
    for p, text in build().items():
        if p.exists() and p.read_text(encoding="utf-8") == text:
            continue
        if a.check:
            stale.append(p.relative_to(ROOT).as_posix())
        else:
            p.write_text(text, encoding="utf-8")
            print(f"wrote {p.relative_to(ROOT).as_posix()}")
    if stale:
        print("Record figures are out of date; run: python -m tools.previews.record_figures")
        for s in stale:
            print(f"  {s}")
        return 1
    return 0


