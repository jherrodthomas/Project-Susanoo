def record_model(repo) -> str:
    schemas = {p.stem.replace(".schema", ""): json.loads(p.read_text(encoding="utf-8"))
               for p in sorted((ROOT / "pdac" / "schemas").glob("*.schema.json"))}
    codes = {"hazard": "HAZ", "requirement": "SYS", "ssf": "SSF", "event": "EVT", "verification": "VER",
             "change-request": "CR", "review": "REV", "task-record": "TASK", "item-definition": "ITEM",
             "decision-register": "DQ"}
    folders = {"HAZ": "safety/hazards", "SYS": "requirements", "SSF": "safety/software", "EVT": "safety/events",
               "VER": "verification", "CR": "changes", "REV": "reviews", "TASK": "safety/mil-std-882e/tasks",
               "ITEM": "architecture", "DQ": "decisions"}
    tone = {"HAZ": "safety", "SYS": "system", "SSF": "software", "EVT": "safety", "VER": "work", "CR": "work",
            "REV": "safety", "TASK": "work", "ITEM": "system", "DQ": "work"}
    counts = {"HAZ": "hazard", "SYS": "requirement", "SSF": "ssf", "EVT": "event", "VER": "verification",
              "CR": "change", "REV": "review", "TASK": "task"}
    nodes = []
    for stem, sch in schemas.items():
        c = codes.get(stem)
        if not c:
            continue
        n = len(repo.objects.get(counts.get(c, ""), {})) if c in counts else None
        sub = folders[c] + (f" · {n} record{'s' if n != 1 else ''}" if n is not None else "")
        nodes.append({"id": c, "code": {"ITEM": "SUS-I1", "TASK": "Task"}.get(c, c), "title": sch.get("title", stem).split(" (")[0], "sub": sub,
                      "tone": tone[c]})
    have = {n["id"] for n in nodes}
    edges = [{"src": a, "dst": b, "label": f} for a, b, f in REFS if a in have and b in have]
    spec = {"number": "1", "title": "Record model",
            "subtitle": "The record types the validator checks, one JSON schema each, and the fields by which they "
                        "reference each other. Arrows point from the field's record to the record it names.",
            "ref": "pdac/schemas/", "direction": "RIGHT", "nodes": nodes,
            "edges": [{"src": e["src"], "dst": e["dst"], "label": e["label"]} for e in edges], "legend_only": True,
            "legend": [(TONES["safety"][1], TONES["safety"][0], "Safety records"),
                       (TONES["system"][1], TONES["system"][0], "System definition and requirements"),
                       (TONES["software"][1], TONES["software"][0], "Software safety"),
                       ("#FFFFFF", TONES["work"][0], "Other records")],
            "footer": f"Generated by {GEN} from pdac/schemas/*.schema.json and the records. {NOT_CLAIMED}"}
    return diagram.render_all([spec])[0]


def l1_l2(repo) -> str:
    d = json.loads((ROOT / "sim" / "results" / "l2-crosscheck.json").read_text(encoding="utf-8"))
    fam = d["families"]
    tone = {"safe": "ok", "tip": "red", "fall": "red", "hard-drop": "red", "hard_drop": "red", "stop": "teal"}

    def oc(x):
        o = x.get("outcome", "?")
        t = f" {x['mishap_t']:.2f} s" if x.get("mishap_t") is not None else ""
        return centred_chip(o + t, tone.get(o, "amber"))
    cols = [("Case", 160, ""), ("Level 1 (plant)", 150, "middle"), ("Level 2 (MuJoCo)", 150, "middle"),
            ("Agree", 70, "middle"), ("Note", 0, "")]
    cols[4] = ("Note", W - 2 * M - sum(w for _, w, _ in cols), "")
    rows = [[r["id"], oc(r["l1"]), oc(r["l2"]), centred_chip("yes" if r["agree"] else "no",
                                                               "ok" if r["agree"] else "amber"),
             r.get("note") or ""] for r in d["rows"]]
    body, h = table(cols, rows, W, group_of=lambda r: next(
        (f"{k} · {v['title']} ({v['agree']} of {v['cases']} agree)" for k, v in fam.items()
         if r[0] == k or r[0].startswith(k + "-") or r[0].startswith(k + "/")), "Other"), row_h=25)
    agree = sum(1 for r in d["rows"] if r["agree"])
    sub = (f"The level-1 walker plant and the level-2 MuJoCo multibody model, run on the same {len(d['rows'])} "
           f"cases: {agree} agree on the outcome. Times are when the mishap occurs. Synthetic results: a design aid, "
           f"never verification evidence.")
    return frame("1", "Level 1 against level 2", sub, "sim/results/l2-crosscheck.json", W, body, h,
                 [legend_tone("ok", "Safe"), legend_tone("red", "Mishap (tip, fall or hard drop)"),
                  legend_tone("amber", "Disagreement")],
                 "sim/results/l2-crosscheck.json")


def acceptance(repo) -> str:
    t = repo.tailoring
    roles = t["roles"]
    out = []
    # the path to an acceptance, left to right
    steps = [("I0", "Draft", "hazard, risk and mitigation, by the AI or the author", "work"),
             ("REV", "Review record", "a named human in the role the risk level needs", "safety"),
             ("R13", "Validator rule R13", "checks reviewer, role, level and concurrence", "software"),
             ("HAZ", "Acceptance recorded", "in the hazard record (basis: target or event)", "ok")]
    cw, gap, y0 = 214, 38, 8
    xs = [M + i * (cw + gap) for i in range(len(steps))]
    for i, ((code, title, sub, tone), x) in enumerate(zip(steps, xs)):
        s, f = TONES[tone]
        out.append(fk.rect(x, y0, cw, 86, fill=f if tone != "work" else "#FFFFFF", stroke=s, rx=8, sw=1.3))
        out += fk.pill(x + 12, y0 + 11, code, fill=s, color="#FFFFFF", h=16, size=9.5)[0]
        out.append(fk.text(x + 12, y0 + 47, title, size=13, weight=700))
        for k, ln in enumerate(fk.wrap(sub, cw - 24, 10.5, max_lines=2)):
            out.append(fk.text(x + 12, y0 + 64 + 13 * k, ln, size=10.5, fill=MUTED))
        if i:
            out.append(fk.path(f"M{fk.fmt(x - gap + 2)} {y0 + 43} L{fk.fmt(x - 3)} {y0 + 43}", stroke=MUTED, sw=1.5,
                               marker_end="url(#arr-ink)"))
    # the AI review dead end
    ax, ay = xs[0], y0 + 120
    s, f = TONES["red"]
    out.append(fk.path(f"M{xs[0] + 40} {y0 + 86} L{xs[0] + 40} {ay - 3}", stroke=s, sw=1.4, dash="4 3",
                       marker_end="url(#arr-red)"))
    out.append(fk.rect(ax, ay, cw, 56, fill=f, stroke=s, rx=8, sw=1.3))
    out.append(fk.text(ax + 12, ay + 23, "AI review record (I0)", size=12, weight=700, fill=s))
    out.append(fk.text(ax + 12, ay + 41, "human: false · never accepts", size=10.5, fill=MUTED))
    # the authority table
    ty = ay + 90
    out.append(fk.text(M, ty, "Who may sign the review record (acceptance authority, MIL-STD-882E 4.3.7)", size=13,
                       weight=700))
    rank = {r: i for i, r in enumerate(t.get("authority_rank", []))}
    rows = []
    for level, rid in sorted(t["acceptance_authority"].items(), key=lambda kv: rank.get(kv[1], 99)):
        r = roles[rid]
        conc = level in t.get("user_concurrence_required_for", [])
        ur = roles[t["user_representative"]]
        rows.append([(lambda lv: (lambda cx, cy, w: risk_chip(cx + 8, cy + 4.5, lv, lv)[0]))(level),
                     f"{rid}  {r['title'].replace(' (simulated)', '')}",
                     centred_chip(r.get("holder") or "not yet named", "ok" if r.get("holder") else "red"),
                     centred_chip((ur.get("holder") or "user representative not yet named") if conc else "not needed",
                                  ("ok" if ur.get("holder") else "red") if conc else "grey")])
    cols = [("Risk level", 120, ""), ("Role", 380, ""), ("Holder", 200, "middle"), ("User concurrence", 0, "middle")]
    cols[3] = ("User concurrence", W - 2 * M - sum(w for _, w, _ in cols), "middle")
    tb, th = table(cols, rows, W)
    out.append(f'<g transform="translate(0 {ty + 14})">')
    out += tb
    out.append("</g>")
    sub = ("Only a review record with a named human in the role the risk level requires accepts a hazard's risk "
           "(rule R13); passing CI or an AI review never does. Roles are simulated, and a role with no named holder "
           "cannot sign.")
    return frame("1", "How risk is accepted", sub, "standards/tailoring · reviews/", W, out, ty + 14 + th,
                 [("#FFFFFF", TONES["work"][0], "Draft"), (TONES["safety"][1], TONES["safety"][0], "Review record"),
                  (TONES["software"][1], TONES["software"][0], "Automated check"),
                  (TONES["ok"][1], TONES["ok"][0], "Recorded acceptance or named holder"),
                  (TONES["red"][1], TONES["red"][0], "Cannot accept, or role not yet filled")],
                 "standards/tailoring/mil-std-882e.yaml and pdac/schemas/review.schema.json")


