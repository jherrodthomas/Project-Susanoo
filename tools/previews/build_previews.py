#!/usr/bin/env python3
"""Give every folder a visual preview (docs/previews.yaml).

For each folder listed in docs/previews.yaml:

- with no README, write a README: title, purpose, preview block and a contents table built from the folder;
- with a hand-written README, insert or refresh a preview block (`<!-- preview:start -->` ... `<!-- preview:end -->`)
  right under the page's opening, and leave the rest of the page alone.

A preview is a main figure plus a thumbnail gallery, each linking to the full figure or its page. A folder whose
figure does not exist yet says so (`planned`). Every folder must be listed, follow its own documentation standard or
be exempt; `--check` fails on any other folder, on a missing image, and on stale output.

    python -m tools.previews.build_previews            # write READMEs and preview blocks
    python -m tools.previews.build_previews --check    # fail if any is stale, missing or unlisted

Standard library + PyYAML. Output is deterministic.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.terms.terms import _insert_point, decorate, START as TERMS_START, END as TERMS_END  # noqa: E402

CONFIG = ROOT / "docs" / "previews.yaml"
GEN = "tools/previews/build_previews.py"
P_START = f"<!-- preview:start (generated by {GEN} from docs/previews.yaml; do not edit by hand) -->"
P_END = "<!-- preview:end -->"
GEN_HEAD = f"<!-- GENERATED by {GEN} from docs/previews.yaml; do not edit. Edit the entry there and re-run. -->"
IMAGE = re.compile(r"\.(svg|png|jpe?g|gif)$", re.I)
COLS = 3


class PreviewError(Exception):
    pass


# ------------------------------------------------------------------ config and folder discovery

def load() -> dict:
    return yaml.safe_load(CONFIG.read_text(encoding="utf-8"))


def _pattern(p: str) -> re.Pattern:
    rx = re.escape(p).replace(r"\*\*/", "(?:.*/)?").replace(r"/\*\*", "(?:/.*)?").replace(r"\*", "[^/]*")
    return re.compile("^" + rx + "$")


def all_folders() -> list[str]:
    out = []
    for d, ds, _fs in os.walk(ROOT):
        ds[:] = sorted(x for x in ds if x not in {".git", "node_modules", "__pycache__"})
        rel = Path(d).relative_to(ROOT).as_posix()
        out.append(rel)
    return out


def coverage(cfg: dict) -> tuple[list[str], list[str]]:
    """Folders that are neither listed, under their own standard, nor exempt; and listed folders that do not exist."""
    own = [_pattern(p) for p in cfg.get("own_standard", [])]
    exempt = [_pattern(p) for p in cfg.get("exempt", [])]
    listed = set(cfg["folders"])
    folders = all_folders()
    unlisted = [f for f in folders
                if f not in listed and not any(r.match(f) for r in own) and not any(r.match(f) for r in exempt)]
    missing = sorted(f for f in listed if not (ROOT / f).is_dir())
    return unlisted, missing


# ------------------------------------------------------------------ rendering

def rel(target: str, folder: str) -> str:
    return Path(os.path.relpath(ROOT / target, ROOT / folder)).as_posix()


def _check_image(path: str, folder: str):
    if not (ROOT / path).is_file():
        raise PreviewError(f"{folder}: image not found: {path}")
    if not IMAGE.search(path):
        raise PreviewError(f"{folder}: not an image: {path}")


def _expand_glob(pattern: str) -> list[str]:
    m = re.search(r"\{([^}]+)\}", pattern)
    pats = [pattern[:m.start()] + alt + pattern[m.end():] for alt in m.group(1).split(",")] if m else [pattern]
    found = set()
    for p in pats:
        found.update(x.relative_to(ROOT).as_posix() for x in ROOT.glob(p))
    return sorted(found)


def gallery_items(entry: dict) -> list[dict]:
    items = list(entry.get("gallery") or [])
    if entry.get("gallery_glob"):
        hero = (entry.get("hero") or {}).get("img")
        items += [{"img": p, "caption": Path(p).name} for p in _expand_glob(entry["gallery_glob"]) if p != hero]
    return items


def preview_block(folder: str, entry: dict) -> str:
    lines = [P_START, ""]
    hero = entry.get("hero")
    if hero:
        _check_image(hero["img"], folder)
        link = rel(hero.get("link", hero["img"]), folder)
        lines += [f"[![{hero['caption']}]({rel(hero['img'], folder)})]({link})", "",
                  f"<sub>{hero['caption']}</sub>", ""]
    items = gallery_items(entry)
    if items:
        cells = []
        for it in items:
            _check_image(it["img"], folder)
            link = rel(it.get("link", it["img"]), folder)
            cells.append(f'<td width="33%" valign="top"><a href="{link}"><img src="{rel(it["img"], folder)}" '
                         f'alt="{it["caption"]}" width="300"></a><br><sub>{it["caption"]}</sub></td>')
        lines.append("<table>")
        for i in range(0, len(cells), COLS):
            lines.append("<tr>" + "".join(cells[i:i + COLS]) + "</tr>")
        lines += ["</table>", ""]
    if entry.get("planned"):
        lines += [f"> **Figure planned:** {entry['planned']}", ""]
    if entry.get("links"):
        lines.append("**Open:** " + " · ".join(f"[{l['text']}]({rel(l['href'], folder)})" for l in entry["links"]))
        lines.append("")
    if not (hero or items or entry.get("planned")):
        raise PreviewError(f"{folder}: entry has no hero, gallery or planned figure")
    lines.append(P_END)
    return "\n".join(lines)


def _describe(p: Path) -> str:
    try:
        if p.suffix in (".yaml", ".yml"):
            d = yaml.safe_load(p.read_text(encoding="utf-8"))
            if isinstance(d, dict):
                return " · ".join(str(d[k]) for k in ("title",) if d.get(k)) or ""
        if p.suffix == ".json":
            d = json.loads(p.read_text(encoding="utf-8"))
            return str(d.get("title", "")) if isinstance(d, dict) else ""
        if p.suffix == ".html":
            m = re.search(r"<title>([^<]+)</title>", p.read_text(encoding="utf-8"))
            return m.group(1).strip() if m else ""
        if p.suffix == ".md":
            m = re.search(r"^# (.+)$", p.read_text(encoding="utf-8"), re.M)
            return m.group(1) if m else ""
    except Exception:  # noqa: BLE001 - a description is a convenience, never a failure
        return ""
    return ""


def contents_table(folder: str, titles: dict[str, str]) -> str:
    """Files and subfolders; a subfolder's title comes from its entry here (not its README, which may be stale)."""
    d = ROOT / folder
    rows = []
    for p in sorted(d.iterdir(), key=lambda x: (x.is_file(), x.name.lower())):
        if p.name.startswith((".", "_")) or p.name == "README.md" or p.name in {"node_modules"}:
            continue
        name = p.name + ("/" if p.is_dir() else "")
        sub = p.relative_to(ROOT).as_posix()
        if p.is_dir():
            desc = titles.get(sub) or (_describe(p / "README.md") if (p / "README.md").exists() else "")
        else:
            desc = _describe(p)
        desc = desc.replace("|", "\\|")
        rows.append(f"| [`{name}`]({p.name}{'/' if p.is_dir() else ''}) | {desc} |")
    if not rows:
        return ""
    return "\n".join(["## Folder contents", "", "| Item | Title |", "|---|---|", *rows, ""])


def generated_readme(folder: str, entry: dict, titles: dict[str, str]) -> str:
    for k in ("title", "purpose"):
        if not entry.get(k):
            raise PreviewError(f"{folder}: no README, so the entry needs '{k}'")
    parts = [GEN_HEAD, "", f"# {entry['title']}", "", entry["purpose"].strip(), "", preview_block(folder, entry), ""]
    table = contents_table(folder, titles)
    if table:
        parts += [table]
    return "\n".join(parts).rstrip("\n") + "\n"


def with_block(text: str, block: str) -> str:
    pat = re.compile(re.escape(P_START) + r".*?" + re.escape(P_END), re.S)
    if pat.search(text):
        return pat.sub(lambda _m: block, text)
    t_end = text.find(TERMS_END)
    if text.find(TERMS_START) >= 0 and t_end >= 0:
        i = t_end + len(TERMS_END)
    else:
        i = _insert_point(text)
    head, tail = text[:i].rstrip("\n"), text[i:].lstrip("\n")
    return head + "\n\n" + block + "\n\n" + tail


def build() -> dict[Path, str]:
    cfg = load()
    unlisted, missing = coverage(cfg)
    errors = [f"folder has no preview entry in docs/previews.yaml: {f}" for f in unlisted]
    errors += [f"docs/previews.yaml lists a folder that does not exist: {f}" for f in missing]
    out: dict[Path, str] = {}
    titles = {}
    for f, e in cfg["folders"].items():
        r = ROOT / f / "README.md"
        hand = r.exists() and not r.read_text(encoding="utf-8").startswith(GEN_HEAD)
        titles[f] = _describe(r) if hand else e.get("title", "")
    for folder, entry in sorted(cfg["folders"].items()):
        if folder in missing:
            continue
        readme = ROOT / folder / "README.md"
        try:
            if readme.exists() and not readme.read_text(encoding="utf-8").startswith(GEN_HEAD):
                text = with_block(readme.read_text(encoding="utf-8"), preview_block(folder, entry))
            else:
                text = generated_readme(folder, entry, titles)
        except PreviewError as e:
            errors.append(str(e))
            continue
        out[readme] = decorate(readme.relative_to(ROOT).as_posix(), text)
    if errors:
        raise PreviewError("\n".join(errors))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    try:
        pages = build()
    except PreviewError as e:
        print("Folder previews have errors:")
        for line in str(e).splitlines():
            print(f"  {line}")
        return 1
    stale = []
    for p, text in pages.items():
        if p.exists() and p.read_text(encoding="utf-8") == text:
            continue
        if a.check:
            stale.append(p.relative_to(ROOT).as_posix())
        else:
            p.write_text(text, encoding="utf-8")
            print(f"wrote {p.relative_to(ROOT).as_posix()}")
    if stale:
        print("Folder previews are out of date; run: python -m tools.previews.build_previews")
        for s in stale:
            print(f"  {s}")
        return 1
    print(f"previews: {len(pages)} folders previewed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
