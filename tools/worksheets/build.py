# ================================================================ records
def load() -> dict:
    y = lambda p: yaml.safe_load(p.read_text(encoding="utf-8"))  # noqa: E731
    model = y(ROOT / "standards/mil-std-882e/model.yaml")
    return {
        "model": model,
        "sev": {s["category"]: s for s in model["severity"]},
        "prob": {p["level"]: p for p in model["probability"]},
        "matrix": model["rac_matrix"],
        "prec": {m["code"]: m["name"] for m in model["mitigation_precedence"]},
        "scc": {c["scc"]: c for c in model["software_control_categories"]},
        "sscm": model["sscm"],
        "lor": model["lor_activities"],
        "hazards": [y(p) for p in sorted((ROOT / "safety/hazards").glob("HAZ-*.yaml"))],
        "reqs": [y(p) for p in sorted((ROOT / "requirements").glob("SYS-*.yaml"))],
        "ssfs": [y(p) for p in sorted((ROOT / "safety/software").glob("SSF-*.yaml"))],
        "item": y(ROOT / "architecture/item-definition.yaml"),
        "fha": y(TREE / "02-hazard-identification/task-208-functional-hazard-analysis/fha.yaml"),
    }


# ================================================================ sheet model
@dataclass
class Col:
    head: str
    width: int
    kind: str = "text"          # text title pills sev prob rac level why prec status chip mits sevlist
    group: str = ""
    csv: list[str] | None = None  # CSV column names this cell expands to (default: [head])


@dataclass
class Sheet:
    key: str                    # file stem and workbook tab
    tab: str
    folder: str                 # relative to safety/mil-std-882e
    title: str
    source: str
    cols: list[Col]
    rows: list[list] = field(default_factory=list)
    groups: list[tuple[str, int]] = field(default_factory=list)   # group bands over rows: (label, start index)
    risk_panel: bool = False
    csv_files: dict[str, list[int]] | None = None   # name -> row indexes (default: one CSV of all rows)
    note: str = ""
    empty: str = ""             # message when there are no rows


def risk_cells(d: dict, r: dict) -> list:
    s, p = r["severity"], r["probability"]
    return [("sev", s), ("prob", p), ("rac", s, p), ("why", r.get("rationale", ""))]


def worst(d: dict, hids: list[str]) -> int | None:
    by = {h["id"]: h for h in d["hazards"]}
    sev = [by[h]["initial_risk"]["severity"] for h in hids if h in by]
    return min(sev) if sev else None


