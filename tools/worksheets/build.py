# ================================================================ cell values (CSV and workbook)
def plain(d: dict, c) -> list[str]:
    if not isinstance(c, tuple):
        return [str(c)]
    k = c[0]
    if k == "title":
        return [c[1] if not c[2] else f"{c[1]} {c[2]}"]
    if k == "pills":
        return [" ".join(c[1])]
    if k == "sev":
        return [f"{c[1]} {d['sev'][c[1]]['name']}"]
    if k == "prob":
        return [f"{c[1]} {d['prob'][c[1]]['name']}"]
    if k == "rac":
        return [f"{c[1]}{c[2]} {d['matrix'][c[2]][c[1]]}"]
    if k == "why":
        return [c[1]]
    if k == "list":
        return ["; ".join(c[1])]
    if k == "mits":
        return [" ".join(f"{i}({p})" for i, p in c[1])]
    if k == "prec":
        return [f"{c[1]} {d['prec'][c[1]]}"]
    if k in ("status", "chip"):
        return [c[1] + (f" / {c[2]}" if len(c) > 2 and c[2] else "")]
    return [str(c[1])]


def csv_text(d: dict, s: Sheet, rows: list[int]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow([(f"{c.group.split(' —')[0].title()} · " if c.group else "") + c.head for c in s.cols])
    for i in rows:
        w.writerow([v for c in s.rows[i] for v in plain(d, c)])
    return buf.getvalue()


