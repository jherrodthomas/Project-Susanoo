"""Spreadsheet-style analysis worksheets for the MIL-STD-882E pages, built from the records.

    python -m tools.worksheets.build            # write
    python -m tools.worksheets.build --check    # fail if anything is stale

For every analysis that has data in the records (PHL, PHA, risk register, mitigations, SSHA/FMEA, SHA, FHA,
SwCI, verification) this writes, from the same rows:

  <folder>/<name>.csv              the worksheet the folder README lists (opens in any spreadsheet program)
  <folder>/<name>.svg              a spreadsheet-style image of it, embedded in the folder README
  safety/generated/worksheets.xlsx one Excel workbook with a tab per worksheet; risk levels are live formulas
                                   on a Table III tab, so changing a selected severity or probability re-derives
                                   the level
  <folder>/README.md               a generated block at the top of "Working content" that shows the sheet

Wherever a risk appears, the selected severity and probability, the Table III cell they select and the stated
basis are shown, so a reviewer can challenge the inputs, not just the level. Analyses with no data yet
(O&SHA, HHA, SoSHA, EHA) get an image of their empty columns and an empty workbook tab, but no CSV, so their
folder still lists the worksheet as planned. Nothing here is analysis: every value is read from a record.

Standard library + PyYAML; output is deterministic.
"""
