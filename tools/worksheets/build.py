def ref(c: int, r: int) -> str:
    s = ""
    c += 1
    while c:
        c, m = divmod(c - 1, 26)
        s = chr(65 + m) + s
    return f"{s}{r}"


def xcell(c: int, r: int, v, style: int = 2, formula: str = "") -> str:
    a = ref(c, r)
    if formula:
        t = ' t="str"' if not isinstance(v, (int, float)) else ""
        return f'<c r="{a}" s="{style}"{t}><f>{escape(formula)}</f><v>{escape(str(v))}</v></c>'
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return f'<c r="{a}" s="{style}"><v>{v}</v></c>'
    return f'<c r="{a}" s="{style}" t="inlineStr"><is><t xml:space="preserve">{escape(str(v))}</t></is></c>'


def sheet_xml(rows: list[str], widths: list[float], freeze: tuple[int, int] | None, cond: list[str], autofilter: str = "",
              merges: list[str] | None = None) -> str:
    sv = '<sheetViews><sheetView workbookViewId="0"'
    if freeze:
        c, r = freeze
        sv += (f'><pane xSplit="{c}" ySplit="{r}" topLeftCell="{ref(c, r + 1)}" activePane="bottomRight" state="frozen"/>'
               '</sheetView></sheetViews>')
    else:
        sv += "/></sheetViews>"
    cols = "<cols>" + "".join(f'<col min="{i + 1}" max="{i + 1}" width="{w:.1f}" customWidth="1"/>' for i, w in enumerate(widths)) + "</cols>"
    mg = f'<mergeCells count="{len(merges)}">' + "".join(f'<mergeCell ref="{m}"/>' for m in merges) + "</mergeCells>" if merges else ""
    af = f'<autoFilter ref="{autofilter}"/>' if autofilter else ""
    return ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
            'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
            f'{sv}<sheetFormatPr defaultRowHeight="15"/>{cols}<sheetData>{"".join(rows)}</sheetData>{af}{mg}{"".join(cond)}</worksheet>')


def level_cf(rng: str, prio: int) -> tuple[str, int]:
    rules = "".join(f'<cfRule type="cellIs" dxfId="{i}" priority="{prio + i}" operator="equal"><formula>"{L}"</formula></cfRule>'
                    for i, L in enumerate(LV_ORDER))
    return f'<conditionalFormatting sqref="{rng}">{rules}</conditionalFormatting>', prio + len(LV_ORDER)


def workbook_sheet(d: dict, s: Sheet) -> str:
    # expand columns: rac -> RAC (formula) + Level (formula); sev/prob -> code + name
    heads, widths, kinds = [], [], []
    for c in s.cols:
        g = (c.group.split(" —")[0].title() + " · ") if c.group else ""
        if c.kind == "sev":
            heads += [g + "Severity", g + "Severity name"]
            widths += [9, 14]
            kinds += ["sev", "sevname"]
        elif c.kind == "prob":
            heads += [g + "Probability", g + "Probability name"]
            widths += [10, 14]
            kinds += ["prob", "probname"]
        elif c.kind == "rac":
            heads += [g + "RAC", g + "Level (Table III)"]
            widths += [8, 13]
            kinds += ["rac", "level"]
        else:
            heads.append(g + c.head)
            widths.append(max(10, min(60, c.width / 6.2)))
            kinds.append(c.kind)
    rows = [f'<row r="1" ht="22" customHeight="1">{xcell(0, 1, s.title + " — worksheet", 4)}</row>',
            f'<row r="2">{xcell(0, 2, f"Generated from {s.source} by tools/worksheets/build.py. Edit the records, not this file. AI-drafted (I0), not reviewed; nothing accepted.", 5)}</row>',
            f'<row r="3" ht="30" customHeight="1">' + "".join(xcell(i, 3, h, 1) for i, h in enumerate(heads)) + "</row>"]
    r = 4
    cond, prio = [], 1
    groups = {start: label for label, start in s.groups}
    for i, row in enumerate(s.rows):
        if i in groups:
            rows.append(f'<row r="{r}">{xcell(0, r, groups[i], 14)}' + "".join(xcell(j, r, "", 14) for j in range(1, len(heads))) + "</row>")
            r += 1
        cells, ci, sev_col, prob_col = [], 0, None, None
        for c, v in zip(s.cols, row):
            if c.kind == "sev" and isinstance(v, tuple):
                cells += [xcell(ci, r, v[1], 7), xcell(ci + 1, r, d["sev"][v[1]]["name"], 2)]
                sev_col = ci
                ci += 2
            elif c.kind == "sev":
                cells += [xcell(ci, r, "—", 2), xcell(ci + 1, r, "", 2)]
                ci += 2
            elif c.kind == "prob":
                cells += [xcell(ci, r, v[1], 7), xcell(ci + 1, r, d["prob"][v[1]]["name"], 2)]
                prob_col = ci
                ci += 2
            elif c.kind == "rac":
                s_, p_ = v[1], v[2]
                S, P = ref(sev_col, r), ref(prob_col, r)
                cells += [xcell(ci, r, f"{s_}{p_}", 7, f"{S}&{P}"),
                          xcell(ci + 1, r, d["matrix"][p_][s_], 2,
                                f"INDEX('Table III'!$B$3:$E$8,MATCH({P},'Table III'!$A$3:$A$8,0),{S})")]
                ci += 2
            else:
                val = plain(d, v)[0]
                cells.append(xcell(ci, r, val, 3 if isinstance(v, tuple) and v[0] == "title" else
                                   13 if isinstance(v, tuple) and v[0] == "pills" else 2))
                ci += 1
        rows.append(f'<row r="{r}">' + "".join(cells) + "</row>")
        r += 1
    if not s.rows:
        rows.append(f'<row r="{r}">{xcell(0, r, s.empty, 5)}</row>')
        r += 1
    for j, k in enumerate(kinds):
        if k == "level" and s.rows:
            x, prio = level_cf(f"{ref(j, 4)}:{ref(j, r - 1)}", prio)
            cond.append(x)
    af = f"A3:{ref(len(heads) - 1, max(r - 1, 3))}" if s.rows and not s.groups else ""
    return sheet_xml(rows, widths, (1, 3), cond, af)


