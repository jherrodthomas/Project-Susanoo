"""Render SysML views from the model, and the SysML-Model wiki page.

Usage: python -m tools.sysml.views [--check]

  V-02 element hierarchy (block definition view): every part of SUS-I1 with kind, role, status, functions
  V-07 requirement satisfaction matrix: SYS requirements x the elements that satisfy them, with their hazards
  V-08 N2 chart: every element and external element on the diagonal; cell (row, column) lists interfaces
       flowing from the row element to the column element

Every label is read from the model (tools/sysml/model.py). Each SVG carries a digest of the model files.
--check exits 1 when a committed output is stale.
"""
from __future__ import annotations

import argparse
import hashlib
import sys

from tools.figures import figkit as fk
from tools.pdac.load import ROOT
from tools.sysml.model import MODEL_DIR, MODEL_FILES, SYSTEM_ID, Model, ModelError, load

OUT = {
    "V-02": "docs/wiki/images/sysml-v02-hierarchy.svg",
    "V-07": "docs/wiki/images/sysml-v07-satisfy.svg",
    "V-08": "docs/wiki/images/sysml-v08-n2.svg",
}
PAGE = "docs/wiki/SysML-Model.md"


def digest() -> str:
    h = hashlib.sha256()
    for f in MODEL_FILES:
        h.update((MODEL_DIR / f).read_bytes())
    return h.hexdigest()[:12]


def ref(view: str) -> str:
    return f"{view} · SusanooArchitecture (SysML v2)"


def foot(W, H, dg) -> list[str]:
    return fk.footer(W, H, f"Generated by tools/sysml/views.py from models/sysml/model ({len(MODEL_FILES)} files) · "
                           f"digest {dg} · concept, not reviewed")


def style(el) -> tuple[str, str]:
    if el.external:
        return fk.EXT_BG, fk.EXT
    md = el.meta.get("ItemElement") or {}
    if md.get("safetyRole") == "protective":
        return fk.SAFETY_BG, fk.SAFETY
    if md.get("kind") == "computing":
        return fk.SW_BG, fk.SW
    return fk.HW_BG, fk.HW


def type_doc(m: Model, el) -> str:
    d = m.defs.get((el.type or "").split("::")[-1])
    return d.doc if d else el.doc


def depth(m: Model, el) -> int:
    n = 0
    while el.parent:
        el = m.elements[el.parent]
        n += 1
    return n


# ---------------------------------------------------------------- V-02 hierarchy

def v02(m: Model, dg: str) -> str:
    rows = [e for e in m.elements.values() if not e.external]
    W, RH, top = 1240, 34, 128
    H = top + len(rows) * RH + 70
    cols = [(640, "Kind"), (760, "Role"), (870, "Status"), (990, "Performs")]
    body = fk.header(W, "V-02 · SUS-I1 element hierarchy", "Every part inside the SUS-I1 boundary, as composed in the model",
                     ref("V-02"))
    for x, label in [(40, "Element")] + cols:
        body.append(fk.text(x, top - 12, label, size=10.5, fill=fk.MUTED, weight=700))
    ifcount = {k: 0 for k in m.elements}
    for c in m.connections.values():
        for e in c.ends:
            ifcount[e] += 1
    pos = {}
    for i, el in enumerate(rows):
        d = depth(m, el)
        x, y = 40 + d * 26, top + i * RH
        pos[el.id] = (x, y)
        fill, stroke = style(el)
        md = el.meta.get("ItemElement") or {}
        dash = "4 3" if md.get("status") == "candidate" else ""
        w = 560 - d * 26
        body.append(fk.rect(x, y, w, RH - 8, fill=fill, stroke=stroke, rx=6, sw=1.1, dash=dash))
        body.append(fk.text(x + 8, y + 17, el.id, size=10, fill=stroke, weight=700))
        idw = fk.text_w(el.id, 10, True) + 16
        body.append(fk.text(x + 8 + idw, y + 17, fk.wrap(f"{el.name} : {el.type} — {type_doc(m, el)}", w - idw - 16, 10, 1)[0],
                            size=10, fill=fk.INK))
        if el.parent:
            px, py = pos[el.parent]
            body.append(fk.el("path", None, d=f"M{px + 10},{py + RH - 8} V{y + (RH - 8) / 2} H{x}", fill="none",
                              stroke=fk.LINE, stroke_width=1.2))
        vals = [md.get("kind", "system") if el.id != SYSTEM_ID else "system",
                md.get("safetyRole", "—"), md.get("status", "—") + (f" ({md['decision']})" if md.get("decision") else ""),
                ", ".join(el.performs) or "—"]
        for (cx, _), v in zip(cols, vals):
            body.append(fk.text(cx, y + 17, fk.wrap(str(v), 240 if cx == 990 else 115, 10, 1)[0], size=10,
                                fill=fk.SAFETY if v == "protective" else fk.INK))
    body += foot(W, H, dg)
    desc = "Element hierarchy: " + "; ".join(f"{e.id} ({e.name} : {e.type}) in {e.parent or 'context'}" for e in rows) + "."
    return fk.svg(W, H, "V-02 SUS-I1 element hierarchy", desc, body)


# ---------------------------------------------------------------- V-07 satisfy matrix

def v07(m: Model, dg: str) -> str:
    reqs = list(m.requirements.values())
    sat = {}
    for rid, eid, _, _ in m.satisfies:
        sat.setdefault(rid, set()).add(eid)
    cols = [e for e in m.elements.values() if any(e.id in s for s in sat.values())]
    CW, RH, left, top = 92, 30, 380, 210
    W = left + len(cols) * CW + 200
    H = top + len(reqs) * RH + 80
    body = fk.header(W, "V-07 · Requirement satisfaction", "satisfy relations: which element satisfies each system requirement",
                     ref("V-07"))
    for j, e in enumerate(cols):
        cx = left + j * CW + CW / 2
        body.append(fk.el("text", e.id, x=fk.fmt(cx), y=fk.fmt(top - 10), font_size=10, fill=style(e)[1], font_weight=700,
                          transform=f"rotate(-40 {fk.fmt(cx)} {fk.fmt(top - 10)})"))
    hx = left + len(cols) * CW + 16
    body.append(fk.text(hx, top - 10, "Hazards", size=10.5, fill=fk.MUTED, weight=700))
    for i, r in enumerate(reqs):
        y = top + i * RH
        body.append(fk.rect(40, y, W - 80, RH - 4, fill=fk.CHIP if i % 2 == 0 else "#FFFFFF", stroke="none", rx=4, sw=0))
        body.append(fk.text(48, y + 18, r.id, size=10, weight=700))
        body.append(fk.text(110, y + 18, fk.wrap(r.name, left - 130, 10, 1)[0], size=10, fill=fk.MUTED))
        for j, e in enumerate(cols):
            cx = left + j * CW + CW / 2
            if e.id in sat.get(r.id, set()):
                body.append(fk.el("circle", None, cx=fk.fmt(cx), cy=fk.fmt(y + 13), r=6, fill=fk.GREEN, stroke="none"))
        hz = (r.meta.get("HazardRef") or {}).get("ids") or []
        hz = hz if isinstance(hz, list) else [hz]
        body.append(fk.text(hx, y + 18, ", ".join(hz) or "—", size=10, fill=fk.SAFETY))
    body += foot(W, H, dg)
    desc = "Satisfaction: " + "; ".join(f"{r.id} by {', '.join(sorted(sat.get(r.id, [])))}" for r in reqs) + "."
    return fk.svg(W, H, "V-07 Requirement satisfaction", desc, body)


# ---------------------------------------------------------------- V-08 N2

def v08(m: Model, dg: str) -> str:
    used = {e for c in m.connections.values() for e in c.ends}
    parts = [e for e in m.elements.values() if e.id in used and not e.external] + \
            [e for e in m.elements.values() if e.id in used and e.external]
    idx = {e.id: i for i, e in enumerate(parts)}
    cells: dict = {}
    for c in m.connections.values():
        a, b = c.ends
        cells.setdefault((idx[a], idx[b]), []).append(c.id)
        if (c.meta.get("InterfaceSpec") or {}).get("direction") == "bi":
            cells.setdefault((idx[b], idx[a]), []).append(c.id)
    n = len(parts)
    C, left, top = 46, 210, 120
    W, H = left + n * C + 40, top + n * C + 70
    body = fk.header(W, "V-08 · N2 interface chart", "Row element outputs to column element; bidirectional interfaces appear "
                     "in both cells", ref("V-08"))
    for i, e in enumerate(parts):
        fill, stroke = style(e)
        y = top + i * C
        body.append(fk.text(left - 10, y + C / 2 + 4, e.id, size=10, fill=stroke, weight=700, anchor="end"))
        body.append(fk.text(left + i * C + C / 2, top - 8, str(i + 1), size=9.5, fill=fk.MUTED, anchor="middle"))
        for j in range(n):
            x = left + j * C
            if i == j:
                body.append(fk.rect(x + 1, y + 1, C - 2, C - 2, fill=fill, stroke=stroke, rx=4, sw=1))
                body.append(fk.text(x + C / 2, y + C / 2 + 4, str(i + 1), size=10, fill=stroke, weight=700, anchor="middle"))
                continue
            ids = cells.get((i, j), [])
            body.append(fk.rect(x + 1, y + 1, C - 2, C - 2, fill=fk.AMBER_BG if ids else "#FFFFFF", stroke=fk.HAIR, rx=2, sw=0.8))
            short = [s.replace("IF-PX4-", "P").replace("IF-", "") for s in ids]
            for k, s in enumerate(short[:3]):
                body.append(fk.text(x + C / 2, y + 14 + k * 11, s if k < 2 or len(short) == 3 else f"+{len(short) - 2}",
                                    size=8.5, fill=fk.INK, anchor="middle"))
    body.append(fk.text(40, H - 46, "Cell labels: 001 = IF-001, P005 = IF-PX4-005. Diagonal numbers match the column numbers.",
                        size=10, fill=fk.MUTED))
    body += foot(W, H, dg)
    desc = "N2 chart. " + "; ".join(f"{parts[i].id} to {parts[j].id}: {', '.join(v)}" for (i, j), v in sorted(cells.items())) + "."
    return fk.svg(W, H, "V-08 N2 interface chart", desc, body)


# ---------------------------------------------------------------- page

def page(m: Model, dg: str) -> str:
    gen = {"Requirements.sysml", "Satisfaction.sysml"}
    rows = []
    for f in MODEL_FILES:
        n = (MODEL_DIR / f).read_text(encoding="utf-8").count("\n")
        rows.append(f"| `{f}` | {'generated by `tools/sysml/gen_requirements.py`' if f in gen else 'hand-written'} | {n} |")
    return "".join([
        "<!-- GENERATED by tools/sysml/views.py from models/sysml/model. Do not edit by hand. -->\n\n",
        "# SysML v2 Model\n\n",
        f"Textual SysML v2 model of SUS-I1 in `models/sysml/model` (digest `{dg}`): {len(m.elements)} parts "
        f"({sum(1 for e in m.elements.values() if e.external)} external), {len(m.connections)} connections, "
        f"{len(m.functions)} functions, {len(m.requirements)} requirements, {len(m.satisfies)} satisfy relations.\n\n",
        "> Concept model, not reviewed. Checked against the records by `tools/sysml/check.py` and validated as SysML v2 by the "
        "OMG pilot implementation (`tools/sysml/pilot/validate.sh`). Neither check is a review.\n\n",
        "| File | Source | Lines |\n|---|---|---|\n", "\n".join(rows), "\n\n",
        "## V-02 Element hierarchy\n\n![V-02 element hierarchy](images/sysml-v02-hierarchy.svg)\n\n",
        "## V-08 N2 interface chart\n\n![V-08 N2 chart](images/sysml-v08-n2.svg)\n\n",
        "## V-07 Requirement satisfaction\n\n![V-07 requirement satisfaction](images/sysml-v07-satisfy.svg)\n\n",
        "Context and boundary views: [SUS-I1 Item Definition](SUS-I1-Item-Definition).\n",
    ])


def build() -> dict:
    m = load()
    dg = digest()
    return {OUT["V-02"]: v02(m, dg), OUT["V-07"]: v07(m, dg), OUT["V-08"]: v08(m, dg), PAGE: page(m, dg)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    try:
        out = build()
    except ModelError as exc:
        print(f"ModelError: {exc}")
        return 1
    stale = []
    for rel, text in out.items():
        p = ROOT / rel
        if p.exists() and p.read_text(encoding="utf-8") == text:
            continue
        if args.check:
            stale.append(rel)
        else:
            p.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    if stale:
        print("SysML views are out of date; run: python -m tools.sysml.views")
        for s in stale:
            print(f"  {s}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
