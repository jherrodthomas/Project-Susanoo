"""Generate Requirements.sysml and Satisfaction.sysml from requirements/SYS-*.yaml.

Usage: python -m tools.sysml.gen_requirements [--check]

Requirements carry their statement as doc, the record as @Source and their hazards as @HazardRef. Each
`allocated_to` element becomes `satisfy <req> by <element path>`, with the path read from Architecture.sysml.
--check exits 1 when a committed file differs from what the records produce.
"""
from __future__ import annotations

import argparse
import re
import sys

from tools.pdac.load import ROOT, _read_yaml
from tools.sysml.model import MODEL_DIR, ModelError, load

HEADER = ("// GENERATED by tools/sysml/gen_requirements.py from requirements/SYS-*.yaml. Do not edit;\n"
          "// edit the requirement records and re-run.\n")
OUT_REQ = MODEL_DIR / "Requirements.sysml"
OUT_SAT = MODEL_DIR / "Satisfaction.sysml"


def camel(s: str) -> str:
    w = re.sub(r"[^A-Za-z0-9 ]", " ", s).split()
    return w[0].lower() + "".join(x[:1].upper() + x[1:] for x in w[1:])


def doc(s: str) -> str:
    return " ".join(s.replace("*/", "* /").split())


def records() -> list[dict]:
    return [_read_yaml(p) for p in sorted((ROOT / "requirements").glob("SYS-*.yaml"))]


def build() -> dict:
    arch = load([MODEL_DIR / "SusanooLibrary.sysml", MODEL_DIR / "Functions.sysml", MODEL_DIR / "Architecture.sysml"])
    reqs = records()
    names = set()
    r = [HEADER, "package SusanooRequirements {", "    private import SusanooLibrary::*;", ""]
    s = [HEADER, "package SusanooSatisfaction {", "    private import SusanooRequirements::*;",
         "    private import SusanooArchitecture::*;", ""]
    for q in reqs:
        name = camel(q["title"])
        if name in names:
            raise ModelError(f"{q['id']}: requirement name {name} is not unique")
        names.add(name)
        r.append(f"    requirement <'{q['id']}'> {name} : SystemRequirement {{")
        r.append(f"        doc /* {doc(q['statement'])} */")
        r.append(f'        @Source {{ record = "requirements/{q["id"]}.yaml"; }}')
        hz = (q.get("source") or {}).get("hazard_ids") or []
        if hz:
            r.append("        @HazardRef { ids = (" + ", ".join(f'"{h}"' for h in hz) + "); }")
        r.append("    }")
        for eid in q.get("allocated_to") or []:
            el = arch.elements.get(eid)
            if el is None or el.external:
                raise ModelError(f"{q['id']}: allocated_to {eid} is not an element of the SUS-I1 system in Architecture.sysml")
            s.append(f"    satisfy '{q['id']}' by context.{el.path};")
    r.append("}")
    s.append("}")
    return {OUT_REQ: "\n".join(r) + "\n", OUT_SAT: "\n".join(s) + "\n"}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    try:
        out = build()
    except ModelError as exc:
        print(f"ModelError: {exc}")
        return 1
    stale = []
    for path, text in out.items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("Generated model files are out of date; run: python -m tools.sysml.gen_requirements")
        for x in stale:
            print(f"  {x}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
