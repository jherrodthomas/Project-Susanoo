#!/usr/bin/env python3
"""Abbreviations, acronyms and record codes: defined once, explained on every page and figure that uses them.

The standard (also stated on the generated page docs/terms.md):

1. **One list.** Every abbreviation, acronym and record-code prefix is defined once, in docs/terms.yaml. Element
   and external IDs (SUS-M1-SAF, EXT-PILOT ...) are defined from architecture/item-definition.yaml, the record.
2. **Pages.** Every Markdown page carries a folded "Terms on this page" block near its opening, listing only the
   terms that page uses.
3. **Figures.** Every SVG figure ends with a "Terms:" line for the terms it draws, so a figure copied out of its
   page still explains itself.
4. **Generators call decorate().** Every script that writes a page or a figure passes it through
   `decorate(path, text)`, which adds or refreshes the block or line. decorate is idempotent, so this tool can also
   process hand-written pages and static figures without fighting any generator's --check.
5. **CI.** `--check` fails when a page or figure lacks its current block or line, or uses an abbreviation that is in
   neither TERMS nor NOT_TERMS.

    python -m tools.terms.terms            # write docs/terms.md and decorate every tracked page and figure
    python -m tools.terms.terms --check    # fail on anything stale or undefined

Standard library + PyYAML.
"""
from __future__ import annotations

import html
import re
import subprocess
import sys
from functools import lru_cache
from pathlib import Path
from xml.sax.saxutils import escape

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs" / "terms.yaml"
TERMS_PAGE = ROOT / "docs" / "terms.md"
TERMS_URL = "https://github.com/jherrodthomas/Project-Susanoo/blob/main/docs/terms.md"
START = "<!-- terms:start (generated by tools/terms/terms.py; do not edit by hand) -->"
END = "<!-- terms:end -->"
# Figures that keep their own look: the hero banner (its page, README.md, carries the block).
NO_FOOTER = {"docs/readme/banner.svg"}


# ================================================================ the list
@lru_cache(maxsize=1)
def load() -> tuple[dict[str, str], set[str]]:
    src = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    terms: dict[str, str] = {}
    for section in ("abbreviations", "standards", "codes", "classes"):
        for k, v in (src.get(section) or {}).items():
            terms[str(k)] = str(v)
    item = yaml.safe_load((ROOT / "architecture/item-definition.yaml").read_text(encoding="utf-8"))
    terms.setdefault(item["id"], item["title"].removeprefix(f"{item['id']} ").strip())
    def lower_first(name: str) -> str:              # "Piloted walker" -> "piloted walker"; keep "GNSS ...", "PX4-based"
        return name if len(name) > 1 and not name[1].islower() else name[:1].lower() + name[1:]
    for e in item.get("elements", []):
        terms.setdefault(e["id"], lower_first(e["name"]))
    for x in item.get("externals", []):
        terms.setdefault(x["id"], "external element: " + lower_first(x["name"]))
    return terms, set(src.get("not_terms") or [])


def label(key: str) -> str:
    if key.endswith("#"):
        return load_class_labels().get(key, key)
    return key + "nnn" if key.endswith("-") else key


@lru_cache(maxsize=1)
def load_class_labels() -> dict[str, str]:
    src = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    return {str(k): str(v) for k, v in (src.get("class_labels") or {}).items()}


# ================================================================ finding terms
CODE_RE = re.compile(r"(?<![\w./#-])([A-Z][A-Z0-9]*(?:-[A-Za-z0-9]+)+)(?![\w-])")
WORD_RE = re.compile(r"(?<![\w./#-])([A-Za-z][A-Za-z0-9]*)(?![\w-])")
RAC_RE = re.compile(r"(?<![\w./-])([1-4][A-F])(?![\w-])")


def _abbrev_like(w: str) -> bool:
    up = sum(c.isupper() for c in w)
    low = sum(c.islower() for c in w)
    return w[0].isupper() and up >= 2 and up >= low


def _resolve_code(tok: str, terms: dict) -> str | None:
    """Exact term, else the longest defined prefix: HAZ-WLK-002 -> 'HAZ-', IF-PX4-005 -> 'IF-PX4-'."""
    if tok in terms:
        return tok
    parts = tok.split("-")
    for n in range(len(parts) - 1, 0, -1):
        head = "-".join(parts[:n])
        if head + "-" in terms:
            return head + "-"
        if head in terms:
            return head
    return None


def find(text: str) -> tuple[list[str], list[str]]:
    """(known terms in order of first use, unknown tokens) in a reader-visible text."""
    terms, not_terms = load()
    hits: list[tuple[int, str, str]] = []          # (position, key or '', raw token)
    spans = []
    for m in CODE_RE.finditer(text):
        tok = m.group(1)
        if tok in not_terms:
            spans.append(m.span())
            continue
        key = _resolve_code(tok, terms)
        hits.append((m.start(), key or "", tok))
        spans.append(m.span())
    for m in RAC_RE.finditer(text):
        if m.group(1) in terms:                     # e.g. 3D: a defined term, not a risk code
            hits.append((m.start(), m.group(1), m.group(1)))
            continue
        hits.append((m.start(), "RAC#", m.group(1)))
    for m in WORD_RE.finditer(text):
        if any(a <= m.start() < b for a, b in spans):
            continue
        w = m.group(1)
        if w in terms:
            hits.append((m.start(), w, w))
            continue
        if w in not_terms:
            continue
        cls = re.fullmatch(r"([A-Z]{1,3})(\d{1,3}[A-Z]?)", w)
        if cls and cls.group(1) + "#" in terms:
            hits.append((m.start(), cls.group(1) + "#", w))
            continue
        if w + "-" in terms:                       # a record prefix written as a word: "the SSF list"
            hits.append((m.start(), w + "-", w))
            continue
        if w.endswith("s") and w[:-1] + "-" in terms:
            hits.append((m.start(), w[:-1] + "-", w))
            continue
        if w.endswith("s") and w[:-1] in terms and _abbrev_like(w[:-1]):
            hits.append((m.start(), w[:-1], w))
            continue
        if _abbrev_like(w) or (cls and len(cls.group(1)) >= 2):
            hits.append((m.start(), "", w))
    found, unknown = [], []
    for _, key, tok in sorted(hits):
        if key:
            if key not in found:
                found.append(key)
        elif tok not in unknown:
            unknown.append(tok)
    return found, unknown


def expand(keys: list[str]) -> list[str]:
    """Add the terms used inside the included definitions, so every line explains itself completely."""
    terms, _ = load()
    out = list(keys)
    i = 0
    while i < len(out):
        more, _ = find(terms[out[i]])
        out += [k for k in more if k not in out]
        i += 1
    return out


# ================================================================ Markdown pages
def plain_markdown(s: str) -> str:
    """Page text a reader sees: no fenced code, link targets, tags, comments, URLs or generated term blocks."""
    s = re.sub(re.escape(START) + r".*?" + re.escape(END), " ", s, flags=re.S)
    s = re.sub(r"```.*?```", " ", s, flags=re.S)
    s = re.sub(r"<!--.*?-->", " ", s, flags=re.S)
    s = re.sub(r"<details>\s*<summary>SysML v2 source</summary>.*?</details>", " ", s, flags=re.S)
    s = re.sub(r'alt="([^"]*)"', r" \1 ", s)
    s = re.sub(r"<[^>]+>", " ", s)
    s = re.sub(r"\]\([^)]*\)", "] ", s)
    s = re.sub(r"https?://\S+", " ", s)
    s = re.sub(r"`([^`]*)`", lambda m: " " + (m.group(1) if not re.search(r"[/\\.]\w", m.group(1)) else "") + " ", s)
    return s


def page_block(keys: list[str]) -> str:
    terms, _ = load()
    keys = sorted(expand(keys), key=lambda k: label(k).lower())
    rows = "\n".join(f"| {label(k)} | {terms[k]} |" for k in keys)
    return (f"{START}\n<details><summary><b>Terms on this page ({len(keys)})</b>: abbreviations and codes "
            f"explained</summary>\n\n| Term | Meaning |\n|---|---|\n{rows}\n\nAll terms: "
            f"[abbreviations and record codes]({TERMS_URL}).\n\n</details>\n{END}")


def _insert_point(s: str) -> int:
    """Right under the page's opening: after the first block (paragraph, quote, table) that follows the H1."""
    m = re.search(r"^# .*$", s, re.M)
    if not m:
        return 0
    i = m.end()
    rest = s[i:]
    blocks = re.split(r"\n\s*\n", rest.lstrip("\n"), maxsplit=1)
    if len(blocks) < 2:
        return len(s)
    first = blocks[0]
    if first.startswith("|") or first.startswith("## "):
        return i
    return i + (len(rest) - len(rest.lstrip("\n"))) + len(first)


def decorate_markdown(s: str) -> str:
    keys, _ = find(plain_markdown(s))
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if pat.search(s):                          # an existing block stays where the page put it
        if keys:
            return pat.sub(lambda _m: page_block(keys), s, count=1)
        return re.sub(r"\n*" + pat.pattern + r"\n*", "\n\n", s, count=1, flags=re.S)
    if not keys:
        return s
    i = _insert_point(s)
    head, tail = s[:i].rstrip("\n"), s[i:].lstrip("\n")
    return (head + "\n\n" if head else "") + page_block(keys) + "\n\n" + tail


# ================================================================ SVG figures
FOOT_RE = re.compile(r'<g class="terms" data-base-h="([0-9.]+)"[^>]*>.*?</g>\s*', re.S)


def svg_texts(svg: str) -> str:
    svg = FOOT_RE.sub(" ", svg)
    return " ".join(html.unescape(m) for m in re.findall(r"<text[^>]*>([^<]*)</text>", svg))


def _num(v: str) -> float:
    return float(re.match(r"[-0-9.]+", v).group(0))


def _fmt(v: float) -> str:
    return f"{v:.1f}".rstrip("0").rstrip(".")


def decorate_svg(svg: str, rel: str = "") -> str:
    # strip an existing footer and restore the original height
    m = FOOT_RE.search(svg)
    if m:
        base_h = float(m.group(1))
        svg = FOOT_RE.sub("", svg, count=1)
        svg = _set_height(svg, base_h)
    if rel in NO_FOOTER:
        return svg
    keys, _ = find(svg_texts(svg))
    if not keys:
        return svg
    terms, _ = load()
    root = re.search(r"<svg\b[^>]*>", svg).group(0)
    vb = [float(x) for x in re.search(r'viewBox="([^"]+)"', root).group(1).replace(",", " ").split()]
    minx, miny, vw, vh = vb
    wpx = _num(re.search(r'\bwidth="([^"]+)"', root).group(1)) if re.search(r'\bwidth="', root) else vw
    k = vw / wpx if wpx else 1.0                      # viewBox units per rendered pixel
    size, lh, pad = 10.5 * k, 14.5 * k, 16 * k
    x0 = minx + 40 * k if vw > 400 * k else minx + 12 * k
    width = vw - 2 * (x0 - minx)
    text = "Terms: " + " · ".join(f"{label(key)} = {terms[key]}" for key in sorted(expand(keys), key=lambda q: label(q).lower()))
    per_line = max(30, int(width / (size * 0.52)))
    lines, line = [], ""
    for word in text.split(" "):
        cand = (line + " " + word).strip()
        if len(cand) > per_line and line:
            lines.append(line)
            line = word
        else:
            line = cand
    lines.append(line)
    y0 = miny + vh
    dh = pad + len(lines) * lh + pad * 0.6
    out = [f'<g class="terms" data-base-h="{_fmt(vh)}">',
           f'<rect x="{_fmt(minx)}" y="{_fmt(y0)}" width="{_fmt(vw)}" height="{_fmt(dh)}" fill="#FFFFFF"/>',
           f'<line x1="{_fmt(x0)}" y1="{_fmt(y0 + 4 * k)}" x2="{_fmt(minx + vw - (x0 - minx))}" y2="{_fmt(y0 + 4 * k)}" '
           f'stroke="#E2E8F0" stroke-width="{_fmt(k)}"/>']
    for i, ln in enumerate(lines):
        out.append(f'<text x="{_fmt(x0)}" y="{_fmt(y0 + pad + i * lh + size * 0.35)}" font-size="{_fmt(size)}" '
                   f'fill="#475569" font-family="Inter, \'Segoe UI\', Helvetica, Arial, sans-serif">{escape(ln)}</text>')
    out.append("</g>\n")
    svg = _set_height(svg, vh + dh)
    i = svg.rfind("</svg>")
    return svg[:i] + "\n".join(out) + svg[i:]


def _set_height(svg: str, new_vh: float) -> str:
    root = re.search(r"<svg\b[^>]*>", svg).group(0)
    vb = re.search(r'viewBox="([^"]+)"', root).group(1).replace(",", " ").split()
    minx, miny, vw, vh = [float(x) for x in vb]
    old_vb = re.search(r'viewBox="([^"]+)"', root).group(0)
    new_root = root.replace(old_vb, f'viewBox="{_fmt(minx)} {_fmt(miny)} {_fmt(vw)} {_fmt(new_vh)}"')
    hm = re.search(r'\bheight="([^"]+)"', new_root)
    if hm:
        old_h = _num(hm.group(1))
        unit = hm.group(1)[len(re.match(r"[-0-9.]+", hm.group(1)).group(0)):]
        new_root = new_root.replace(hm.group(0), f'height="{_fmt(old_h * new_vh / vh)}{unit}"', 1)
    return svg.replace(root, new_root, 1)


# ================================================================ API for generators
def decorate(rel: str | Path, text: str) -> str:
    """Add or refresh the terms block (.md) or line (.svg) of a page or figure about to be written."""
    rel = Path(rel).as_posix()
    rel = rel[len(str(ROOT)) + 1:] if rel.startswith(str(ROOT)) else rel
    if rel.endswith(".md") and rel != "docs/terms.md":
        return decorate_markdown(text)
    if rel.endswith(".svg"):
        return decorate_svg(text, rel)
    return text


# ================================================================ the terms page
def terms_page() -> str:
    terms, _ = load()
    src = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    item_ids = set(terms) - {str(k) for s in ("abbreviations", "standards", "codes", "classes")
                             for k in (src.get(s) or {})}

    def table(keys, head):
        rows = [f"| {label(k)} | {terms[k]} |" for k in sorted(keys, key=lambda q: label(q).lower())]
        return [f"| {head} | Meaning |", "|---|---|", *rows, ""]
    out = ["<!-- GENERATED by tools/terms/terms.py from docs/terms.yaml and architecture/item-definition.yaml; "
           "do not edit by hand. -->", "", "# Abbreviations, acronyms and record codes", "",
           "Every abbreviation, acronym and record code used on the Susanoo pages and figures is defined here, once. "
           "Edit [`docs/terms.yaml`](terms.yaml); element IDs come from "
           "[`architecture/item-definition.yaml`](../architecture/item-definition.yaml).", "",
           "## How terms are explained", "",
           "1. **One list.** A term is defined only in `docs/terms.yaml` (or, for an element ID, in the item definition).",
           "2. **Every page** carries a folded *Terms on this page* block near its opening, with only the terms it uses.",
           "3. **Every figure** ends with a *Terms:* line for what it draws, so it still explains itself when copied out.",
           "4. **Checked in CI.** `python -m tools.terms.terms --check` fails on a stale block or line, or on any "
           "abbreviation that is not in the list.", "",
           "## Abbreviations and acronyms", "", *table(src.get("abbreviations") or {}, "Term"),
           "## Standards", "", *table(src.get("standards") or {}, "Standard"),
           "## Record codes", "", "A record code is a prefix and a number, for example `HAZ-WLK-002` or `SYS-010`.", "",
           *table(src.get("codes") or {}, "Code"),
           "## Classes", "", *table(src.get("classes") or {}, "Class"),
           "## System elements and externals", "", "From the item definition.", "", *table(item_ids, "ID")]
    return "\n".join(out).rstrip() + "\n"


# ================================================================ CLI
def tracked() -> list[Path]:
    r = subprocess.run(["git", "ls-files", "*.md", "*.svg"], cwd=ROOT, capture_output=True, text=True, check=True)
    files = [ROOT / p for p in r.stdout.split()]
    return [p for p in files if "node_modules" not in p.parts and p != TERMS_PAGE]


def main(argv: list[str]) -> int:
    check = "--check" in argv
    problems: list[str] = []
    page = terms_page()
    if check:
        if not TERMS_PAGE.exists() or TERMS_PAGE.read_text(encoding="utf-8") != page:
            problems.append("docs/terms.md is stale")
    elif not TERMS_PAGE.exists() or TERMS_PAGE.read_text(encoding="utf-8") != page:
        TERMS_PAGE.write_text(page, encoding="utf-8")
        print("wrote docs/terms.md")
    unknown_all: dict[str, list[str]] = {}
    for key, meaning in load()[0].items():          # definitions must explain themselves too
        for u in find(meaning)[1]:
            unknown_all.setdefault(u, []).append(f"the definition of {key} (docs/terms.yaml)")
    files = tracked() + [p for p in (ROOT / "README.md",) if p not in tracked()]
    for p in files:
        if not p.exists():
            continue
        rel = p.relative_to(ROOT).as_posix()
        cur = p.read_text(encoding="utf-8")
        new = decorate(rel, cur)
        visible = plain_markdown(cur) if rel.endswith(".md") else svg_texts(cur)
        _, unknown = find(visible)
        for u in unknown:
            unknown_all.setdefault(u, []).append(rel)
        if new != cur:
            if check:
                problems.append(f"{rel}: terms block or line missing or stale")
            else:
                p.write_text(new, encoding="utf-8")
                print(f"decorated {rel}")
    for u, where in sorted(unknown_all.items()):
        problems.append(f"undefined term '{u}' in {where[0]}" + (f" (+{len(where) - 1} more)" if len(where) > 1 else ""))
    for pr in problems:
        print(f"terms: {pr}", file=sys.stderr)
    if problems:
        print("run: python -m tools.terms.terms, after adding any undefined term to docs/terms.yaml", file=sys.stderr)
        return 1
    print(f"terms: {len(load()[0])} terms; {len(files)} pages and figures explain what they use")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
