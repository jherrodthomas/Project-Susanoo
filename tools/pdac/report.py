"""Generate HTS log, conformance matrix, applicability and gate readiness from PDaC records.

Usage: python -m tools.pdac.report [--check]
--check exits 1 if committed outputs differ from what the records produce.
Output is deterministic (no timestamps) so it can be checked in CI.
"""
from __future__ import annotations

import argparse
import csv
import io
import sys
from collections import Counter

from .load import load
from .rules import (RULES, ACTIVE_MITIGATION, hazard_ssf_ids, run_all, software_analysis,
                    software_contribution_level, event_applies)
from tools.terms.terms import decorate

BANNER = ("<!-- GENERATED by tools/pdac/report.py from standards/, safety/, requirements/ records. "
          "Do not edit by hand; edit the records and re-run. -->\n\n")
SOURCE = "MIL-STD-882E, 11 May 2012 (base edition)"
DISCLAIMER = ("> Generated status describes records and automated checks only. It is not a compliance claim, "
              "technical review or risk acceptance. All authorities are simulated.\n\n")


def _table(headers, rows) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in r) + " |")
    return "\n".join(out) + "\n"


def _best_precedence(h):
    active = [m["precedence"] for m in h.get("mitigations") or [] if m.get("state") in ACTIVE_MITIGATION]
    allm = [m["precedence"] for m in h.get("mitigations") or [] if m.get("state") != "rejected"]
    if active:
        return min(active)
    return f"({min(allm)} identified)" if allm else "—"


def hts_log(repo, findings, analysis) -> str:
    hz = repo.objects["hazard"]
    model = repo.model
    sev_name = {s["category"]: s["name"] for s in model["severity"]}
    prob_name = {p["level"]: p["name"] for p in model["probability"]}
    out = [BANNER, "# Hazard Tracking Log\n\n", f"**Source standard:** {SOURCE} · Task 106 HTS, Task 107 progress view\n\n",
           DISCLAIMER]
    ini = Counter(h["initial_risk"]["risk_level"] for h in hz.values())
    tgt = Counter(h["target_risk"]["risk_level"] for h in hz.values())
    st = Counter(h["status"] for h in hz.values())
    out.append("## Summary\n")
    out.append(_table(["Risk level", "Initial", "Target"],
                      [[lvl, ini.get(lvl, 0), tgt.get(lvl, 0)] for lvl in ["High", "Serious", "Medium", "Low", "Eliminated"]]))
    out.append("\nStatus: " + ", ".join(f"{k} {v}" for k, v in sorted(st.items())) + f" · total {len(hz)}\n")

    for label, key in (("Initial risk", "initial_risk"), ("Target risk", "target_risk")):
        out.append(f"\n## {label} on the Table III matrix\n")
        rows = []
        for p in "ABCDEF":
            row = [f"{prob_name[p]} ({p})"]
            for s in (1, 2, 3, 4):
                ids = sorted(k for k, h in hz.items() if h[key]["probability"] == p and h[key]["severity"] == s)
                lvl = model["rac_matrix"][p][s]
                row.append(f"**{lvl}**: " + ", ".join(ids) if ids else "")
            rows.append(row)
        out.append(_table(["Probability \\ Severity"] + [f"{sev_name[s]} ({s})" for s in (1, 2, 3, 4)], rows))

    out.append("\n## Hazards\n")
    rows = []
    for hid, h in sorted(hz.items()):
        sw = software_contribution_level(repo, h, analysis)
        rows.append([hid, h["title"], ", ".join(h["modes"]), f"{h['initial_risk']['rac']} {h['initial_risk']['risk_level']}",
                     f"{h['target_risk']['rac']} {h['target_risk']['risk_level']}",
                     "; ".join(f"{e['event_id']}: {e['rac']} {e['risk_level']}" for e in h.get("event_risks") or []) or "—",
                     _best_precedence(h), ", ".join(sorted(hazard_ssf_ids(h))) or "—", sw or "—", h["status"],
                     h["owner"]["role"]])
    out.append(_table(["ID", "Hazard", "Modes", "Initial", "Target", "Event", "Best precedence", "SSFs",
                       "SW contribution (Table VI)", "Status", "Owner"], rows))
    out.append("\n*SW contribution* is the Table VI risk level recorded because required LOR tasks are incomplete (4.4.3b). "
               "It must be decided by the PM and covered by any acceptance.\n")

    out.append("\n## Software contribution (4.4)\n")
    rows = []
    for sid, a in sorted(analysis.items()):
        s = repo.objects["ssf"][sid]
        rows.append([sid, s["title"], f"{s['scc']}", a["severity"] or "—", a["swci"] or "—",
                     ", ".join(a["required"]) or "none", len(a["incomplete"]), a["table_vi_level"] or "—",
                     ", ".join(a["hazards"])])
    out.append(_table(["SSF", "Function", "SCC", "Worst severity", "SwCI", "Required LOR tasks", "Incomplete",
                       "Table VI level", "Hazards"], rows))

    out.append("\n## Test events and exposure (4.3.7, Task 303)\n")
    rows = []
    for eid, ev in sorted(repo.objects["event"].items()):
        exp = ev["exposure"]
        exposed = ", ".join(k for k in ("people", "equipment", "environment") if exp.get(k)) or "none"
        applicable = sorted(h for h, rec in hz.items() if event_applies(ev, rec))
        accepted = [h for h in applicable if any(a.get("basis") == eid for a in hz[h].get("acceptances") or [])]
        need = applicable if exposed != "none" else []
        rows.append([eid, ev["title"], ev["status"], exposed, len(applicable), f"{len(accepted)}/{len(need)}" if need else "n/a"])
    out.append(_table(["Event", "Title", "Status", "Exposure", "Applicable hazards", "Event risk accepted"], rows))
    out.append("\nHazard management log (106.2r): the git history of `safety/hazards/`.\n")
    return "".join(out)


def conformance(repo, findings) -> str:
    model, t = repo.model, repo.tailoring
    by_rule = Counter(f.rule for f in findings if f.level == "error")
    warn_rule = Counter(f.rule for f in findings if f.level == "warning")
    out = [BANNER, "# MIL-STD-882E Conformance Matrix\n\n",
           f"**Source standard:** {SOURCE}. Sections 3 and 4 are mandatory; tasks apply only where selected (4.1, 5.2).\n\n",
           DISCLAIMER,
           "\nStatus key: *no errors* = automated rule found no errors in current records (this includes the case where no records of that kind exist yet); *not-started / in-work / "
           "evidenced / reviewed* = manual status from `standards/tailoring/mil-std-882e.yaml`.\n"]
    for el in model["elements"]:
        out.append(f"\n## {el['id']} — {el['title']} ({el['clause']})\n")
        rows = []
        for ob in el["obligations"]:
            chk = ob["check"]
            if chk.startswith("rule:"):
                rid = chk.split(":")[1]
                e, w = by_rule.get(rid, 0), warn_rule.get(rid, 0)
                status = f"{e} error(s)" if e else "no errors"
                if w:
                    status += f", {w} warning(s)"
                how = f"{rid}: {RULES[rid][0]}"
                arts = ""
            else:
                m = (t.get("obligations") or {}).get(ob["id"], {})
                status = m.get("status", "not-started")
                how = "human review"
                arts = ", ".join(f"`{a}`" for a in m.get("artifacts", []))
            rows.append([ob["id"], ob["clause"], ob["text"], how, status, arts])
        out.append(_table(["ID", "Clause", "Obligation (condensed)", "Check", "Status", "Artifacts"], rows))

    hz = list(repo.objects["hazard"].values())
    out.append("\n## Task 106.2 HTS data elements\n")
    rows = []
    for el in model["hts_elements"]:
        key = el["path"].split("[")[0].split(".")[0]
        if el["id"] == "r":
            filled = "git history"
        elif el["id"] == "o":
            n = sum(1 for h in hz if all((m.get("verification") or {}).get("method") for m in h.get("mitigations") or []))
            filled = f"{n}/{len(hz)}"
        else:
            n = sum(1 for h in hz if h.get(key) not in (None, "", [], {}))
            filled = f"{n}/{len(hz)}"
        rows.append([f"106.2{el['id']}", el["element"], f"`{el['path']}`", filled])
    out.append(_table(["Element", "Data element", "Record field", "Populated"], rows))
    out.append("\nEvent RACs (l) and acceptances (q) are expected to be empty until test events are planned and risk is accepted.\n")

    out.append("\n## Rule results\n")
    out.append(_table(["Rule", "Check", "Clause", "Errors", "Warnings"],
                      [[r, d, c, by_rule.get(r, 0), warn_rule.get(r, 0)] for r, (d, c) in RULES.items()]))
    return "".join(out)


def applicability(repo, findings) -> str:
    model, t = repo.model, repo.tailoring
    cur = t["current_gate"]
    phase = t["gates"][cur]["phase"]
    out = [BANNER, "# MIL-STD-882E Task Applicability and Tailoring\n\n",
           f"**Source standard:** {SOURCE}, Section 5.2 and Appendix A Table A-I. **Tailoring status:** {t['status']} "
           f"(approval: {t['approval']['status']}, simulated authority).\n",
           f"\nCurrent gate **{cur}** maps to acquisition phase **{phase}**. Gate-to-phase mapping: "
           + ", ".join(f"{g}→{v['phase']}" for g, v in t["gates"].items()) + ".\n",
           "\nTable A-I codes: G generally applicable, S selectively applicable, GC generally applicable to design change, "
           "NA not applicable. *Departure* marks a task Table A-I lists as G in the current phase that the project has not selected.\n\n"]
    rows = []
    for task in model["tasks"]:
        dec = t["tasks"].get(task["id"], {})
        code = task["a1"][phase]
        dep = "yes" if code == "G" and dec.get("disposition") != "selected" else ""
        rows.append([task["id"], task["title"], task["type"], " ".join(f"{p}:{task['a1'][p]}" for p in model["phases"]),
                     dec.get("disposition", "—"), dec.get("gate", dec.get("trigger", "—")), dec.get("did", "—"),
                     dec.get("rationale", ""), dep])
    out.append(_table(["Task", "Title", "Type", "Table A-I", "Disposition", "Gate / trigger", "DID", "Rationale", "Departure"], rows))
    rd = t["risk_definitions"]
    out.append(f"\n## Tailored risk definitions ({rd['id']}, {rd['status']})\n")
    out.append("Table III matrix unchanged. Severity monetary thresholds (4.3.3d):\n\n")
    sev = {s["category"]: s for s in model["severity"]}
    out.append(_table(["Category", "Table I minimum loss", "Tailored minimum loss"],
                      [[f"{c} {sev[c]['name']}", f"${sev[c]['criteria']['monetary_min_usd']:,}",
                        f"${rd['severity']['monetary_min_usd'][c]:,}"] for c in (1, 2, 3, 4)]))
    out.append(f"\nDerivation: {rd['severity']['derivation']}\n")
    pb = rd["probability"]
    out.append(f"\nProbability basis (4.3.3e): {pb['basis']}; item life "
               + ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in pb["item_life"].items())
               + "; bands " + ", ".join(f"{k} {v}" for k, v in pb["bands"].items()) + ".\n")
    out.append("\n## Risk acceptance authorities (simulated)\n")
    out.append(_table(["Risk level", "Authority", "User concurrence"],
                      [[lvl, t["roles"][r]["title"], "required" if lvl in t["user_concurrence_required_for"] else "—"]
                       for lvl, r in t["acceptance_authority"].items()]))
    return "".join(out)


def gate_readiness(repo, findings) -> str:
    t = repo.tailoring
    records = repo.objects["task"]
    errors = [f for f in findings if f.level == "error"]
    out = [BANNER, "# Gate Readiness\n\n", f"**Source standard:** {SOURCE}. Gates are project-defined (framework/lifecycle.md).\n\n",
           DISCLAIMER, f"\nCurrent gate: **{t['current_gate']}** · validator errors: **{len(errors)}**\n"]
    for g, info in t["gates"].items():
        out.append(f"\n## {g} — {info['title']} ({info['phase']})\n")
        due = sorted(tid for tid, d in t["tasks"].items() if d.get("disposition") == "selected" and d.get("gate") == g)
        blockers = []
        rows = []
        for tid in due:
            rec = records.get(tid)
            st = rec["status"] if rec else "no record"
            if st != "approved":
                blockers.append(f"Task {tid} {st}")
            rows.append([tid, next(x["title"] for x in repo.model["tasks"] if x["id"] == tid), st,
                         ", ".join(f"`{a}`" for a in (rec or {}).get("artifacts", []))])
        if rows:
            out.append(_table(["Task", "Title", "Record status", "Artifacts"], rows))
        for eid, ev in sorted(repo.objects["event"].items()):
            if ev.get("gate") != g:
                continue
            ev_f = [f for f in findings if f.rule == "R06" and f.obj == eid]
            if ev_f:
                blockers.append(f"{eid}: {len(ev_f)} hazard(s) without accepted event risk")
        if g == t["current_gate"] and errors:
            blockers.append(f"{len(errors)} validator error(s)")
        out.append("\n**Blockers:** " + ("; ".join(blockers) if blockers else "none recorded") + "\n")
    return "".join(out)


def item_page(repo) -> str:
    item = repo.item
    els = {e["id"]: e for e in item["elements"]}
    out = [BANNER, f"# {item['id']} Item Definition\n\n",
           f"**{item['title']}** · revision {item['revision']} · status {item['status']} · configuration "
           f"{item['configuration']}. Source record: `architecture/item-definition.yaml`.\n\n",
           DISCLAIMER, f"\n{item['scope']}\n\n",
           "![SUS-I1 system context](images/sus-i1-context.svg)\n\n",
           "![SUS-I1 boundary and interfaces](images/sus-i1-boundary.svg)\n\n",
           "Figures generated by `tools/figures/fig_item.py` (layout in `architecture/layout.yaml`).\n\n## Functions\n\n"]
    out.append(_table(["ID", "Function", "Performed by", "Modes", "Scenarios"],
                      [[f["id"], f["name"], ", ".join(f["performed_by"]), ", ".join(f.get("modes") or []),
                        ", ".join(f.get("scenarios") or [])] for f in item["functions"]]))
    out.append("\n## Elements inside the boundary\n\n")
    out.append(_table(["ID", "Element", "Parent", "Kind", "Protective", "Status"],
                      [[e["id"], e["name"], e["parent"], e["kind"], "yes" if e["safety_role"] == "protective" else "",
                        e["status"] + (f" ({e['decision']})" if e.get("decision") else "")] for e in item["elements"]]))
    ifs = item["interfaces"]
    out.append("\n## External elements\n\n")
    out.append(_table(["ID", "External element", "Assumption", "Interfaces"],
                      [[x["id"], x["name"], x["assumption"],
                        ", ".join(i["id"] for i in ifs if x["id"] in (i["from"], i["to"]))] for x in item["externals"]]))
    out.append("\n## Interfaces\n\n")
    arrow = {"uni": "→", "bi": "↔"}
    out.append(_table(["ID", "Interface", "Endpoints", "Kind", "Exchange", "Hazards", "Source"],
                      [[i["id"], i["name"] + (f" (candidate, {i['decision']})" if i.get("status") == "candidate" else ""),
                        f"{i['from']} {arrow[i['direction']]} {i['to']}", ", ".join(i["kind"]), i["exchange"],
                        ", ".join(i["hazard_ids"]) or "—", i["source"]] for i in ifs]))
    unused = sorted(h for h in repo.objects["hazard"] if not any(h in i["hazard_ids"] for i in ifs))
    out.append(f"\n{len(item['functions'])} functions, {len(els)} elements, {len(item['externals'])} external elements, "
               f"{len(ifs)} interfaces. Hazards not yet linked to any interface: {', '.join(unused) or 'none'}.\n")
    return "".join(out)


def decision_inbox(repo) -> str:
    decs = (repo.decisions or {}).get("decisions") or []
    st = Counter(d["status"] for d in decs)
    out = [BANNER, "# Decision Inbox\n\n",
           "Questions only the project lead can decide, from `decisions/register.yaml`. Answer in chat or in a pull "
           "request; Claude copies the answer into the register and applies it. Rules: `CLAUDE.md`.\n\n",
           "Status: " + ", ".join(f"{k} {st.get(k, 0)}" for k in ("open", "queued", "answered", "applied", "withdrawn")) + "\n"]
    for d in decs:
        if d["status"] != "open":
            continue
        out.append(f"\n## {d['question']}\n\n`{d['id']}` · reversibility **{d['reversibility']}** · gate {d.get('gate', '—')} · "
                   f"asked {d.get('asked')}\n\n{d['context'].strip()}\n\n")
        out.append(_table(["Option", "What it does and costs"],
                          [[("**" + o["title"] + "** (recommended)") if o["key"] == d["recommendation"] else o["title"], o["detail"]]
                           for o in d["options"]]))
        if d.get("blocks"):
            out.append(f"\nBlocks: {', '.join(d['blocks'])}\n")
        out.append(f"\nSources: {', '.join(d['sources'])}\n")
    queued = [d for d in decs if d["status"] == "queued"]
    if queued:
        out.append("\n## Queued\n\n")
        out.append(_table(["ID", "Question", "Decider", "Recommendation"],
                          [[d["id"], d["question"], d["decider"], next(o["title"] for o in d["options"] if o["key"] == d["recommendation"])]
                           for d in queued]))
    done = [d for d in decs if d["status"] in ("answered", "applied")]
    if done:
        out.append("\n## Decided\n\n")
        out.append(_table(["ID", "Question", "Choice", "By", "Date", "Status", "Applied in"],
                          [[d["id"], d["question"], next(o["title"] for o in d["options"] if o["key"] == d["answer"]["choice"]),
                            d["answer"]["by"], d["answer"]["at"], d["status"], ", ".join(f"`{p}`" for p in d.get("applied_in") or []) or "—"]
                           for d in done]))
    return "".join(out)


def hts_csv(repo, analysis) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["hazard_id", "title", "status", "system", "subsystems", "modes", "mishap", "initial_rac", "initial_level",
                "target_rac", "target_level", "event_racs", "mitigations", "requirement_ids", "ssf_ids",
                "sw_contribution_level", "owner_role", "acceptances"])
    for hid, h in sorted(repo.objects["hazard"].items()):
        w.writerow([hid, h["title"], h["status"], h["system"], ";".join(h["subsystems"]), ";".join(h["modes"]), h["mishap"],
                    h["initial_risk"]["rac"], h["initial_risk"]["risk_level"], h["target_risk"]["rac"],
                    h["target_risk"]["risk_level"],
                    ";".join(f"{e['event_id']}={e['rac']}" for e in h.get("event_risks") or []),
                    ";".join(f"{m['id']}[{m['precedence']}/{m['state']}]" for m in h["mitigations"]),
                    ";".join(h.get("requirement_ids") or []), ";".join(sorted(hazard_ssf_ids(h))),
                    software_contribution_level(repo, h, analysis) or "",
                    h["owner"]["role"], ";".join(f"{a['id']}:{a['risk_level']}" for a in h.get("acceptances") or [])])
    return buf.getvalue()


def build(repo) -> dict:
    findings = run_all(repo)
    analysis = software_analysis(repo)
    return {
        "docs/wiki/Hazard-Tracking-Log.md": hts_log(repo, findings, analysis),
        "docs/wiki/MIL-STD-882E-Conformance.md": conformance(repo, findings),
        "docs/wiki/MIL-STD-882E-Applicability.md": applicability(repo, findings),
        "docs/wiki/Gate-Readiness.md": gate_readiness(repo, findings),
        "docs/wiki/SUS-I1-Item-Definition.md": item_page(repo),
        "docs/wiki/Decision-Inbox.md": decision_inbox(repo),
        "safety/generated/hts.csv": hts_csv(repo, analysis),
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    repo = load()
    outputs = build(repo)
    stale = []
    for rel, text in outputs.items():
        text = decorate(rel, text)          # terms block / line (tools/terms)
        path = repo.root / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    if stale:
        print("Generated files are out of date; run: python -m tools.pdac.report")
        for s in stale:
            print(f"  {s}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
