def fig_sources(d: dict) -> str:
    W, M = 1240, 40
    r = d["rules"]
    head, y0 = fk.header(
        W, "2", "Where every number on a sheet comes from",
        "Each field of a sheet traced to the value and the file it is drawn from. The metrics and the sheets are written "
        "by the same CAD run (tools/cad/make.sh), so a sheet that differs from cad/metrics.json is stale.",
        "tools/cad/drawings.py")
    out = list(head)
    files = []
    for _, rows in SOURCES:
        for _, _, f in rows:
            if f not in files:
                files.append(f)
    lx, lw, mx_, rx = M, 300, M + 330, W - M - 300
    y = y0 + 24
    out.append(fk.text(lx, y, "On the sheet", size=10.5, fill=MUTED, weight=700))
    out.append(fk.text(mx_, y, "Value", size=10.5, fill=MUTED, weight=700))
    out.append(fk.text(rx, y, "Drawn from", size=10.5, fill=MUTED, weight=700))
    y += 12
    fy0 = y
    fh = 30
    fpos = {}
    total = sum(len(rows) for _, rows in SOURCES) * 26 + len(SOURCES) * 24
    gap = (total - len(files) * fh) / max(1, len(files) - 1)
    for i, f in enumerate(files):
        yy = fy0 + i * (fh + gap)
        tone = TONES["external"] if f.startswith("cad/") else TONES["software"]
        out.append(fk.rect(rx, yy, 300, fh, fill=tone[1], stroke=tone[0], rx=6, sw=1.2))
        out.append(fk.text(rx + 10, yy + 19, f, size=10.5, fill=INK, mono=True))
        fpos[f] = yy + fh / 2
    for grp, rows in SOURCES:
        out.append(fk.text(lx, y + 14, grp, size=10.5, fill=MUTED, weight=700))
        y += 24
        for lab, val, f in rows:
            val = val.format(m=r["margin_flag"], r=r["rotor_flag"])
            out.append(fk.rect(lx, y, lw, 20, fill="#FFFFFF", stroke="#CBD5E1", rx=4, sw=1))
            out.append(fk.text(lx + 8, y + 14, lab, size=10, fill=INK))
            out.append(fk.text(mx_, y + 14, val, size=9.5, fill=MUTED, mono=True))
            vx = mx_ + fk.text_w(val, 9.5, mono=True) + 8
            out.append(f'<path d="M{vx},{y + 10} C{vx + 60},{y + 10} {rx - 60},{fpos[f]} {rx},{fpos[f]}" fill="none" '
                       'stroke="#94A3B8" stroke-width="1"/>')
            out.append(fk.line(lx + lw, y + 10, mx_ - 6, y + 10, stroke="#CBD5E1", sw=1))
            y += 26
    y += 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 22
    leg = [(TONES["external"][1], TONES["external"][0], "Record or committed output"),
           (TONES["software"][1], TONES["software"][0], "CAD code")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Where every number on a sheet comes from",
                  "Each field of a drawing sheet traced to the value and file it is drawn from", out)


