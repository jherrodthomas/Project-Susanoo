    nodes = [{"id": "Sheet", "shape": "class", "title": "DrawingSheet", "stereotype": "part def",
              "attrs": ["drawingNumber : String", "layoutId : String", "posture : String", "scaleDenominator : Integer",
                        "part titleBlock : TitleBlock", "part views : View [3]"], "tone": "system"},
             {"id": "TB", "shape": "class", "title": "TitleBlock", "stereotype": "part def",
              "attrs": ["revision : String", "status : String", "source : String"], "tone": "work"},
             {"id": "View", "shape": "class", "title": "View", "stereotype": "part def",
              "attrs": ["direction : String"], "tone": "work"},
             {"id": "Dims", "shape": "class", "title": "PrintedMetrics", "stereotype": "part def",
              "attrs": ["heightMm : Real", "cgHeightMm : Real", "staticMarginMm : Real", "tipAngleDeg : Real",
                        "rotorToPilotMm : Real"], "tone": "external"}]
    edges = [{"src": "Sheet", "dst": "TB", "label": "titleBlock", "arrow": "diamond"},
             {"src": "Sheet", "dst": "View", "label": "views [3]", "arrow": "diamond"},
             {"src": "Sheet", "dst": "Dims", "label": "printed", "arrow": "diamond"}]
