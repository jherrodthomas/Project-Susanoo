# ================================================================ records
def texts(svg: str) -> list[str]:
    return [re.sub(r"<[^>]*>", "", x) for x in re.findall(r"<text[^>]*>[^<]*</text>", svg)]


def drawer_rules() -> dict:
    src = DRAWER.read_text()
    return {"scale": int(re.search(r"^SCALE = (\d+)", src, re.M).group(1)),
            "sheet": [float(x) for x in re.search(r"^SHEET_W, SHEET_H = ([\d.]+), ([\d.]+)", src, re.M).groups()],
            "margin_flag": float(re.search(r"if margin < ([\d.]+):", src).group(1)),
            "rotor_flag": float(re.search(r'if met\["rotor_to_pilot_m"\] < ([\d.]+):', src).group(1))}


def load() -> dict:
    ctx, _, _ = load_reqs()
    metrics = json.loads((ROOT / "cad" / "metrics.json").read_text())["concepts"]
    rev = re.search(r"\*\*Revision:\*\* (\S+)", (ROOT / "cad" / "README.md").read_text()).group(1)
    rules = drawer_rules()
    sheets = []
    for p in sorted(FOLDER.glob("CL-*.svg")):
        t = texts(p.read_text())
        lid, posture = "-".join(p.stem.split("-")[:2]), p.stem[6:] or "standing"
        met = metrics[lid] if posture == "standing" else metrics[lid]["postures"][posture]
        tb = {t[i]: t[i + 1] for i in range(len(t) - 1) if t[i] in ("DRAWING", "REVISION", "STATUS", "SOURCE", "DRAWN",
                                                                  "SCALE / SHEET", "UNITS", "LICENCE")}
        g = lambda rx: next((float(re.search(rx, x).group(1)) for x in t if re.search(rx, x)), None)  # noqa: E731
        nums = [float(x) for x in t if re.fullmatch(r"\d+", x)]
        printed = {"height_m": nums[0] / 1000, "length_m": nums[1] / 1000, "width_m": nums[2] / 1000,
                   "pilot_eye_m": g(r"pilot eye (\d+)") / 1000, "cockpit_floor_m": g(r"cockpit floor (\d+)") / 1000,
                   "hip_height_m": g(r"^hip (\d+)") / 1000, "cg_z_m": g(r"CG height (\d+)") / 1000,
                   "static_margin_m": g(r"static margin (\d+)") / 1000, "tip_deg": g(r"tip angle ([\d.]+)"),
                   "rotor_to_pilot_m": g(r"rotor to pilot (\d+)") / 1000, "track_m": g(r"track (\d+)") / 1000}
        want = {"height_m": met["height_m"], "pilot_eye_m": met["pilot_eye_m"], "cockpit_floor_m": met["cockpit_floor_m"],
                "hip_height_m": met["hip_height_m"], "cg_z_m": met["cg_m"][2], "static_margin_m": met["static_margin_m"],
                "tip_deg": met["static_tip_angle_deg"], "rotor_to_pilot_m": met["rotor_to_pilot_m"]}
        tol = {"tip_deg": 0.05}
        diffs = [k for k, v in want.items() if abs(printed[k] - v) > tol.get(k, 0.006)]
        if tb.get("REVISION") != rev:
            diffs.append("revision")
        warns = [x for x in t if x.startswith("⚠")]
        title = next(x for x in t if x.startswith(p.stem + " · "))
        sheets.append({"file": p.name, "stem": p.stem, "layout": lid, "posture": posture, "tb": tb, "printed": printed,
                       "title": title.split(" · ", 1)[1], "warns": warns, "diffs": diffs,
                       "kb": round(p.stat().st_size / 1024)})
    pdf_pages = len(re.findall(rb"/Type\s*/Page[^s]", PDF.read_bytes())) if PDF.exists() else 0
    return {"ctx": ctx, "sheets": sheets, "rev": rev, "rules": rules, "pdf_pages": pdf_pages,
            "pdf_kb": round(PDF.stat().st_size / 1024) if PDF.exists() else 0,
            "root": next(k for k, v in ctx.nodes.items() if not v.get("parent") and v.get("kind") != "external")}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def mm(v: float) -> str:
    return f"{v * 1000:,.0f}"


# ================================================================ figure 1 · sheet register (drawn directly)
def fig_register(d: dict) -> str:
    W, M = 1240, 40
    sh, r = d["sheets"], d["rules"]
    ok = sum(1 for s in sh if not s["diffs"])
    head, y0 = fk.header(
        W, "1", "Every drawing sheet",
        f"{plural(len(sh), 'sheet')} at 1:{r['scale']} on {r['sheet'][0]:g} × {r['sheet'][1]:g} mm, revision {d['rev']}; {ok} of {len(sh)} print exactly what "
        f"cad/metrics.json holds. Static margin against the {r['margin_flag'] * 1000:.0f} mm review flag and docked rotor "
        f"to pilot against the {r['rotor_flag'] * 1000:.0f} mm flag, as each sheet prints them.", "cad/drawings")
    out = list(head)
    cols = [("Sheet", 150), ("Layout · posture", 290), ("H × L × W (mm)", 150), ("CG height", 80),
            ("Static margin", 190), ("Rotor to pilot", 190), ("In step", 110)]
    xs, x = [], M
    for _, w in cols:
        xs.append(x)
        x += w
    y = y0 + 22
    for (h, _), cx in zip(cols, xs):
        out.append(fk.text(cx, y, h, size=10.5, fill=MUTED, weight=700))
    y += 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 50
    mmax = max(max(s["printed"]["static_margin_m"] for s in sh), r["margin_flag"]) * 1.15
    rmax = max(max(s["printed"]["rotor_to_pilot_m"] for s in sh), r["rotor_flag"]) * 1.1
    for i, s in enumerate(sh):
        yy = y + i * rh
        if i % 2:
            out.append(fk.rect(M, yy + 1, W - 2 * M, rh, fill="#F8FAFC", stroke="none", rx=0, sw=0))
        p, _ = fk.pill(xs[0], yy + 10, s["stem"], "#FFFFFF", color=INK, stroke="#475569")
        out += p
        out.append(fk.text(xs[0], yy + 42, s["tb"].get("DRAWING", ""), size=8.5, fill=FAINT, mono=True))
        out.append(fk.text(xs[1], yy + 22, fk.wrap(s["title"], cols[1][1] - 16, 10.5, bold=True, max_lines=1)[0], size=10.5,
                           fill=INK, weight=700))
        out.append(fk.text(xs[1], yy + 38, f"{s['posture']} · source {s['tb'].get('SOURCE', '')}", size=9.5,
                           fill=MUTED))
        pr = s["printed"]
        out.append(fk.text(xs[2], yy + 22, f"{mm(pr['height_m'])} × {mm(pr['length_m'])}", size=10.5, fill=INK,
                           mono=True))
        out.append(fk.text(xs[2], yy + 38, f"× {mm(pr['width_m'])}", size=10, fill=MUTED, mono=True))
        out.append(fk.text(xs[3], yy + 22, mm(pr["cg_z_m"]), size=10.5, fill=INK, mono=True))
        out.append(fk.text(xs[3], yy + 38, f"tip {pr['tip_deg']:g}°", size=9.5, fill=MUTED))
        for col, key, flag, mx in ((4, "static_margin_m", r["margin_flag"], mmax), (5, "rotor_to_pilot_m",
                                                                                   r["rotor_flag"], rmax)):
            bx, bw = xs[col], cols[col][1] - 30
            v = pr[key]
            under = v < flag
            out.append(fk.rect(bx, yy + 14, bw, 10, fill="#F1F5F9", stroke="none", rx=5, sw=0))
            out.append(fk.rect(bx, yy + 14, bw * min(v, mx) / mx, 10, fill="#F59E0B" if under else "#10B981",
                               stroke="none", rx=5, sw=0))
            fx = bx + bw * flag / mx
            out.append(fk.line(fx, yy + 10, fx, yy + 28, stroke="#B45309", sw=1.2, dash="3 2"))
            out.append(fk.text(bx, yy + 40, f"{mm(v)} mm" + (" · under the flag" if under else ""), size=9.5,
                               fill="#B45309" if under else MUTED, weight=700 if under else ""))
        p, _ = fk.pill(xs[6], yy + 12, "in step" if not s["diffs"] else "differs", "#DCFCE7" if not s["diffs"]
                       else "#FEE2E2", color="#166534" if not s["diffs"] else "#991B1B")
        out += p
        if s["diffs"]:
            out.append(fk.text(xs[6], yy + 40, ", ".join(s["diffs"])[:28], size=8.5, fill="#991B1B"))
    y += len(sh) * rh + 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 22
    leg = [("#10B981", "#10B981", "Clears the review flag"), ("#F59E0B", "#F59E0B", "Under the flag (the sheet prints ⚠)"),
           ("#FFFFFF", "#B45309", "Review flag (provisional, not a requirement)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    out.append(fk.text(M, y + 4, f"concept-layouts.pdf: {d['pdf_pages']} pages for {len(sh)} sheets, "
                                 f"{d['pdf_kb']:,} KB.", size=10.5, fill=MUTED))
    y += 18
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Every drawing sheet",
                  "Every drawing sheet with its size, CG height, static margin and rotor clearance against the flags", out)


