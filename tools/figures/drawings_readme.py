         "        attribute source : String;", "    }",
         "    part def View {", "        doc /* Third-angle: side elevation, plan above it, front view to the right. */",
         "        attribute direction : String;", "    }",
         "    part def PrintedMetrics {", "        doc /* The numbers the sheet prints, read from cad/metrics.json. */",
