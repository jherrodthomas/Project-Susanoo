                    {"src": "I3", "dst": "X", "label": "parameter ranges"},
                    {"src": "X", "dst": "O1", "label": "results"}, {"src": "X", "dst": "O2", "label": "edge cases"},
                    {"src": "X", "dst": "O3", "label": "cases to replay"},
