# ================================================================ records
def load() -> dict:
    ctx, _, hazards = load_reqs()
    fams = yaml.safe_load((FOLDER / "families.yaml").read_text())["families"]
    res = {f["id"]: json.loads((RES / f"search-{f['id']}.json").read_text()) for f in fams}
    doc = (FOLDER / "search.py").read_text().split('"""')[1]
    steps = [{"n": m.group(1), "name": m.group(2).strip(), "text": " ".join(m.group(3).split())}
             for m in re.finditer(r"^\s*(\d)\.\s+([^:]+):\s*(.*?)(?=^\s*\d\.\s|\Z)", doc, re.M | re.S)]
    hz = sorted({r["hazard"] for f in fams for r in f["hazard_rules"] if r.get("hazard")})
    subs = sorted({s for h in hz for s in hazards.get(h, {}).get("subsystems") or []})
    return {"ctx": ctx, "hazards": hazards, "fams": fams, "res": res, "steps": steps, "hz": hz, "subs": subs}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def fmt(v) -> str:
    return f"{v:g}" if isinstance(v, (int, float)) else str(v)


def space_str(sp: dict) -> str:
    out = []
    for k, v in sp.items():
        kind, rng = next(iter(v.items()))
        out.append(f"{k} {kind} {'/'.join(map(str, rng)) if kind == 'choice' else f'{rng[0]}–{rng[1]}'}")
    return "; ".join(out)


# ================================================================ figure 1 · edge cases (drawn directly)
def fig_edges(d: dict) -> str:
    W, M = 1240, 40
    rows = [(f, e) for f in d["fams"] for e in d["res"][f["id"]]["edge_cases"]]
    probes = [p["name"] for p in d["fams"][0]["probes"]]
    head, y0 = fk.header(
        W, "1", "Edge cases and what would have saved them",
        f"The {len(rows)} worst distinct failures the search found, each with its parameters, outcome and mapped "
        "hazard, re-run under every assumption probe: a green probe means that change alone avoids the mishap.",
        "sim/results/search-*.json")
    out = list(head)
    x0 = M + 560
    pw = (W - M - x0) / len(probes)
    y = y0 + 30
    for k, lab in ((M, "Case"), (M + 70, "Parameters"), (M + 400, "Outcome / hazard")):
        out.append(fk.text(k, y, lab, size=10.5, fill=MUTED, weight=700))
    for i, p in enumerate(probes):
        for j, ln in enumerate(fk.wrap(p, pw - 8, 10, True, max_lines=2)):
            out.append(fk.text(x0 + i * pw + 4, y - 12 + 13 * j, ln, size=10, fill=INK, weight=700))
    y += 14
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 42
    for n, (f, e) in enumerate(rows):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(M, cy, e["id"], size=11, fill=INK, weight=700, mono=True))
        ps = e["params"]
        line1 = f"slope {fmt(ps.get('slope_deg'))}° · leak τ {fmt(ps.get('tau_leak_s'))} s · offset {fmt(ps.get('stride_offset_m'))} m"
        line2 = f"pilot {fmt(ps.get('pilot_reaction_s'))} s · load holding {ps.get('load_holding')}"
        out.append(fk.text(M + 70, cy - 6, line1, size=10, fill=INK))
        out.append(fk.text(M + 70, cy + 9, line2, size=10, fill=MUTED))
        t = TONES[OUT_TONE.get(e["outcome"], "amber")]
        p, w = fk.pill(M + 400, cy - 20, e["outcome"], t[1], color=t[0], stroke=t[0])
        out += p
        if e.get("hazard"):
            lv = (d["hazards"].get(e["hazard"], {}).get("initial_risk") or {}).get("risk_level", "")
            ht = TONES[LEVEL_TONE.get(lv, "amber")]
            hp, _ = fk.pill(M + 400, cy - 1, e["hazard"], ht[1], color=ht[0], stroke=ht[0])
            out += hp
        pr = {x["name"]: x for x in e["probes"]}
        for i, name in enumerate(probes):
            x = pr.get(name)
            if not x:
                continue
            pt = TONES[OUT_TONE.get(x["outcome"], "amber")]
            cx = x0 + i * pw
            out.append(fk.rect(cx + 4, top + 5, pw - 8, rh - 10, fill=pt[1], stroke=pt[0], rx=6, sw=1))
            out.append(fk.text(cx + pw / 2, cy, x["outcome"], size=10, fill=pt[0], weight=700, anchor="middle"))
    y += len(rows) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["ok"][1], TONES["ok"][0], "Safe under the probe"),
           (TONES["red"][1], TONES["red"][0], "Mishap: tip or hard drop")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Edge cases and what would have saved them",
                  "Every edge case with its parameters and probe outcomes", out)


# ================================================================ figure 2 · failure map (drawn directly)
def fig_map(d: dict) -> str:
    f = d["fams"][0]
    r = d["res"][f["id"]]
    mc = r["monte_carlo"]
    W, M = 1240, 40
    sp = f["space"]
    xr, yr = sp["slope_deg"]["uniform"], sp["tau_leak_s"]["loguniform"]
    head, y0 = fk.header(
        W, "2", f"Where {f['id']} fails",
        f"The {mc['n']} seeded Monte Carlo samples of {f['id']} ({f['title'].lower()}) by slope and leak time constant, "
        "coloured by outcome, with the edge cases from the falsification marked. "
        + "; ".join(f"{k}: {v['failures']} of {v['n']} fail" for k, v in mc["split"].items()) + ".",
        f"sim/results/search-{f['id']}.json")
    out = list(head)
    px, py, pw, ph = M + 70, y0 + 30, 760, 430
    out.append(fk.rect(px, py, pw, ph, fill="#FFFFFF", stroke=HAIR, rx=0, sw=1))
    X = lambda s: px + pw * (s - xr[0]) / (xr[1] - xr[0])  # noqa: E731
    Y = lambda t: py + ph - ph * (math.log10(t) - math.log10(yr[0])) / (math.log10(yr[1]) - math.log10(yr[0]))  # noqa: E731
    for s in range(int(xr[0]), int(xr[1]) + 1, 5):
        out.append(fk.line(X(s), py, X(s), py + ph, stroke=HAIR, sw=0.6))
        out.append(fk.text(X(s), py + ph + 16, f"{s}°", size=10, fill=MUTED, anchor="middle"))
    for t in (0.05, 0.1, 0.2, 0.5, 1, 2, 5):
        out.append(fk.line(px, Y(t), px + pw, Y(t), stroke=HAIR, sw=0.6))
        out.append(fk.text(px - 8, Y(t) + 4, f"{t:g} s", size=10, fill=MUTED, anchor="end"))
    out.append(fk.text(px + pw / 2, py + ph + 36, "slope (deg)", size=10.5, fill=INK, anchor="middle", weight=700))
    out.append(fk.text(px - 60, py - 10, "leak τ (s, log)", size=10.5, fill=INK, weight=700))
    for s, t, oc in r["map"]:
        c = TONES[OUT_TONE.get(oc, "amber")][0]
        op = "0.35" if oc == "safe" else "0.8"
        out.append(f'<circle cx="{X(s):.1f}" cy="{Y(max(t, yr[0])):.1f}" r="3.2" fill="{c}" fill-opacity="{op}"/>')
    for e in r["edge_cases"]:
        ex, ey = X(e["params"]["slope_deg"]), Y(max(e["params"]["tau_leak_s"], yr[0]))
        out.append(f'<circle cx="{ex:.1f}" cy="{ey:.1f}" r="6" fill="none" stroke="{INK}" stroke-width="1.6"/>')
        out.append(fk.text(ex + 8, ey - 6, e["id"], size=9.5, fill=INK, weight=700, halo=True))
    # side panel: counts
    sx = px + pw + 40
    out.append(fk.text(sx, py + 12, "Monte Carlo outcomes", size=11, fill=INK, weight=700))
    yy = py + 34
    for oc, n in sorted(mc["by_outcome"].items(), key=lambda kv: -kv[1]):
        t = TONES[OUT_TONE.get(oc, "amber")]
        out.append(fk.rect(sx, yy - 10, 260 * n / mc["n"], 14, fill=t[0], stroke="none", rx=3, sw=0))
        out.append(fk.text(sx + 266 * n / mc["n"] + 4, yy + 1, f"{oc} {n}", size=10.5, fill=INK))
        yy += 24
    yy += 12
    out.append(fk.text(sx, yy, "Split by load holding", size=11, fill=INK, weight=700))
    yy += 22
    for k, v in mc["split"].items():
        out.append(fk.text(sx, yy, k, size=10.5, fill=INK, mono=True))
        out.append(fk.text(sx + 210, yy, f"{v['failures']} / {v['n']} fail", size=10.5,
                           fill=TONES["red"][0] if v["failures"] > v["n"] / 2 else INK, weight=700))
        yy += 20
    yy += 12
    fz = r["falsification"]
    out.append(fk.text(sx, yy, "Falsification", size=11, fill=INK, weight=700))
    yy += 20
    for ln in fk.wrap(f"{fz['evaluations']} evaluations over {f['falsification']['rounds']} rounds; worst margin "
                      f"rho {fz['worst_rho']:.2f}. Other dimensions (pilot reaction, stride offset) are sampled too "
                      "and do not show here.", 300, 10):
        out.append(fk.text(sx, yy, ln, size=10, fill=MUTED))
        yy += 14
    y = py + ph + 56
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["ok"][1], TONES["ok"][0], "Safe"), (TONES["red"][1], TONES["red"][0], "Tip or hard drop"),
           ("#FFFFFF", INK, "Edge case (falsification)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, f"Figure 2 · Where {f['id']} fails", "Monte Carlo samples coloured by outcome", out)


# ================================================================ ELK figures and SysML
def step_name(label: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", label)
    return words[0].lower() + "".join(w.capitalize() for w in words[1:])


def search_activity(d: dict) -> dict:
    steps = [{"name": step_name(s["name"]), "label": s["name"]} for s in d["steps"]]
    steps.append({"name": "mapToHazards", "label": "Map edge cases to hazards; unmapped outcomes become findings",
                  "safety": True})
    fam = d["fams"][0]
    fals = next((st["name"] for st in steps if "falsification" in st["label"].lower()), None)
    return {"name": "SearchFamily", "steps": steps,
            "doc": "The failure search for one family, as the numbered steps of sim/search/search.py.",
            "loops": [[fals, fals, f"{fam['falsification']['rounds']} rounds"]] if fals else []}


