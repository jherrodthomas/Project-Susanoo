    act = {**frag, "file": "fig-5-sysml-activity.svg", "number": "5", "title": "SysML activity — SearchFamily",
           "ref": "sim/search/FailureSearch.sysml",
           "subtitle": "The method of search.py for one family, generated into FailureSearch.sysml from its docstring."}
