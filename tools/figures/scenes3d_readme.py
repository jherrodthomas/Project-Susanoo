def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    block = fig_block(ctx, {"scope": d["subs"]})
    by = defaultdict(list)
    for h in d["with_scene"]:
        for s in d["hazards"].get(h, {}).get("subsystems") or []:
            by[s].append(h)
    for n in block["nodes"]:
        if n.get("code") in by:
            n["sub"] = ", ".join(by[n["code"]])
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"SUS-I1 decomposition. The {len(d['subs'])} subsystems named by the hazards that have a scene are "
                          "coloured, with those hazards under each.")
