    out = list(head)
    y = y0 + 22
    rh = 26
    for n, h in enumerate(hz):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=5, sw=0))
        cy = top + rh / 2 + 4
        lv = (d["hazards"][h].get("initial_risk") or {}).get("risk_level", "")
        t = TONES[LEVEL_TONE.get(lv, "amber")]
        p, _ = fk.pill(M, cy - 12, h, t[1], color=t[0], stroke=t[0])
        out += p
        out.append(fk.text(M + 110, cy, fk.wrap(d["hazards"][h].get("title", ""), 360, 10, max_lines=1)[0], size=10,
                           fill=INK))
        if h in d["covered"]:
            x = M + 490
            for sid in d["covered"][h]:
                p, w = fk.pill(x, cy - 12, sid, TONES["ok"][1], color=TONES["ok"][0], stroke=TONES["ok"][0])
