def fig_sysml(d: dict) -> tuple[dict, str]:
    srcs = sorted(SRC_TONE)
    nodes = [{"id": "MotionSource", "shape": "class", "title": "MotionSource", "stereotype": "enum def", "attrs": srcs,
              "tone": "interface"},
             {"id": "Analysis", "shape": "class", "title": "Analysis", "stereotype": "part def",
              "attrs": ["source : MotionSource", "reference : String", "outcome : String", "specDigest : String"],
              "tone": "safety"},
             {"id": "Look", "shape": "class", "title": "Look", "stereotype": "part def",
              "attrs": [f"environment : String  ({', '.join(d['envs'])})", f"condition : String  ({', '.join(d['conds'])})",
                        "camera : String"], "tone": "external"},
             {"id": "Scene3D", "shape": "class", "title": "Scene3D", "stereotype": "part def",
              "attrs": ["hazards : String", "part motionAnalysis : Analysis", "part look : Look"], "tone": "system"}]
    edges = [{"src": "Scene3D", "dst": "Analysis", "label": "motionAnalysis", "arrow": "diamond"},
             {"src": "Scene3D", "dst": "Look", "label": "look (picture only)", "arrow": "diamond"},
             {"src": "Analysis", "dst": "MotionSource", "label": "source", "dash": True}]
    s = ["    enum def MotionSource {", "        doc /* Where a scene's motion comes from. */",
         *[f"        enum '{x}';" for x in srcs], "    }",
         "    part def Analysis {",
         "        doc /* The exported analysis (sim/scenes3d/out): read only from the scene's motion block and the records "
         "it names. */",
         "        attribute source : MotionSource;", "        attribute reference : String;",
         "        attribute outcome : String;", "        attribute specDigest : String;", "    }",
         "    part def Look {",
         "        doc /* Picture only: environment, condition and camera. Never read by export_scene.py. */",
         "        attribute environment : String;", "        attribute condition : String;", "        attribute camera : String;",
         "    }",
         "    part def Scene3D {", "        attribute hazards : String;", "        part motionAnalysis : Analysis;",
         "        part look : Look;", "    }"]
    for r in d["rows"]:
        pn = "s" + r["id"].replace("S3-", "").replace("-", "")
        s += [f"    part {pn} : Scene3D {{", f"        doc /* {r['id']}: {r['title']} */",
              f"        attribute :>> hazards = \"{', '.join(r['hazards'])}\";",
              "        part :>> motionAnalysis {", f"            attribute :>> source = MotionSource::'{r['source']}';",
              f"            attribute :>> reference = \"{r['reference']}\";",
              f"            attribute :>> outcome = \"{r['outcome']}\";", "        }",
              "        part :>> look {", f"            attribute :>> environment = \"{r['look']['environment']}\";",
              f"            attribute :>> condition = \"{r['look']['condition']}\";",
              f"            attribute :>> camera = \"{r['look']['camera']}\";", "        }", "    }"]
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — Scenes3D", "ref": "sim/scenes3d/Scenes3D.sysml",
            "subtitle": f"A scene is an analysis and a look, kept apart: the look never changes the analysis "
                        f"(test_scenes3d.py). Scenes3D.sysml also holds all {len(d['rows'])} scenes and variants as parts.",
            "frame": {"kind": "bdd", "type": "package", "name": "Scenes3D"}, "direction": "RIGHT",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Composition (diamond at owner)"), edge_leg("Typed by", True),
                       ("#FFF7ED", "#C2410C", "Analysis (from simulation)"), ("#F1F5F9", "#475569", "Look (picture only)"),
                       ("#F5F3FF", "#7C3AED", "Enumeration"), ("#EEF2FF", "#4F46E5", "Scene")]}
    sysml = "\n".join([
        f"// Scenes3D — generated by {GEN} from sim/scenes3d/scenes.yaml and the exported analysis.",
        "// Do not edit by hand: change the scenes or the generator and regenerate.",
        "// Status: pictures of synthetic simulation output; no evidence credit.", "",
        "package Scenes3D {",
        "    private import ScalarValues::*;",
        "    doc /* The 3D hazard scenes (sim/scenes3d/README.md). */",
        *s, "}", ""])
    return spec, sysml


