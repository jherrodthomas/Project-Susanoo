def out_tone(o: str) -> str:
    return "ok" if o in GOOD else ("amber" if o == "landed-at-stale-home" else "red")


# ================================================================ records
def load() -> dict:
    ctx, _, hazards = load_reqs()
    cfg = yaml.safe_load((FOLDER / "scenes.yaml").read_text())
    envs = yaml.safe_load((FOLDER / "library" / "environments.yaml").read_text())["environments"]
    conds = yaml.safe_load((FOLDER / "library" / "conditions.yaml").read_text())["conditions"]
    rows = []
    for s in cfg["scenes"]:
        out = json.loads((FOLDER / "out" / f"{s['id']}.json").read_text())
        outcome = out.get("outcome") or (out.get("performed") or {}).get("outcome", "—")
        for vid, look in [(s["id"], s["look"])] + [(v["id"], {**s["look"], **v["look"]}) for v in s.get("variants") or []]:
            rows.append({"id": vid, "base": s["id"], "variant": vid != s["id"], "hazards": s["hazards"],
                         "title": s["title"], "source": out["source"], "reference": out["reference"],
                         "kind": out["kind"], "outcome": outcome, "look": look,
                         "page": (ROOT / "docs" / "3d" / f"{vid}.html").exists(),
                         "still": (ROOT / "docs" / "wiki" / "images" / f"3d-{vid.lower()}.png").exists(),
                         "digest": out.get("spec_digest")})
    covered = defaultdict(list)
    for s in cfg["scenes"]:
        for h in s["hazards"]:
            covered[h].append(s["id"])
    reasons = {x["hazard"]: x["reason"] for x in cfg.get("not_modelled") or []}
    with_scene = sorted(covered)
    subs = sorted({x for h in with_scene for x in hazards.get(h, {}).get("subsystems") or []})
    return {"ctx": ctx, "hazards": hazards, "cfg": cfg, "envs": envs, "conds": conds, "rows": rows,
            "covered": dict(covered), "reasons": reasons, "with_scene": with_scene, "subs": subs,
            "three": cfg.get("three", {}), "sheets": load_sheets()}


def load_sheets() -> list[dict]:
    """The interactive general-arrangement sheets built by build_sheet.py, from sheet.yaml and sheet_uav.yaml."""
    out = []
    for name, page, stills in [("sheet.yaml", "SUS-M1", ["3d-sus-m1.png"]),
                               ("sheet_uav.yaml", "SUS-A1", ["3d-sus-a1.png", "3d-sus-a1-air.png"])]:
        cfg = yaml.safe_load((FOLDER / name).read_text())
        out.append({"file": name, "page": page, "id": cfg["id"], "sheet": cfg.get("sheet", ""),
                    "title": cfg["title"], "layout": cfg.get("layout", ""),
                    "postures": [x["label"] for x in cfg.get("postures") or []],
                    "callouts": sorted(cfg.get("anchors") or {}), "replay": cfg.get("replay") or [],
                    "built": (ROOT / "docs" / "3d" / f"{page}.html").exists(),
                    "stills": [x for x in stills if (ROOT / "docs" / "wiki" / "images" / x).exists()]})
    terrain = FOLDER / "terrain.yaml"
    if terrain.exists():
        cfg = yaml.safe_load(terrain.read_text())
        src = (FOLDER / "build_sheet.py").read_text()
        callouts = sorted(set(re.findall(r"\b(HAZ-[A-Z]{3}-\d{3}|SYS-\d{3})\b", src.split("def sheet3", 1)[1].split("\ndef ", 1)[0])))
        out.append({"file": terrain.name, "page": "SUS-M1-terrain", "id": cfg["id"], "sheet": "3 of 3",
                    "title": "CL-05 walk on the terrain course", "layout": "CL-05",
                    "postures": [f"walk on {len(cfg['terrains'])} terrains"], "callouts": callouts, "replay": [],
                    "built": (ROOT / "docs" / "3d" / "SUS-M1-terrain.html").exists(),
                    "stills": [x for x in ["3d-sus-m1-terrain.png"] if (ROOT / "docs" / "wiki" / "images" / x).exists()]})
    return out


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


# ================================================================ figure 1 · scenes (drawn directly)
def fig_scenes(d: dict) -> str:
    W, M = 1240, 40
    rows = d["rows"]
    base = [r for r in rows if not r["variant"]]
    head, y0 = fk.header(
        W, "1", "The 3D scenes",
        f"{plural(len(base), 'scene')} and {plural(len(rows) - len(base), 'look variant')}: the hazards each shows, the "
        "simulation it replays and its outcome, and the look it is drawn in. A variant changes only the look; the "
        f"analysis is the base scene's. Pages pin three.js {d['three'].get('version', '?')}.", "sim/scenes3d/scenes.yaml")
    out = list(head)
    cx = {"id": M, "t": M + 120, "src": M + 500, "o": M + 720, "look": M + 880, "pg": M + 1090}
    y = y0 + 30
    for k, lab in (("id", "Scene"), ("t", "Title and hazards"), ("src", "Replays"), ("o", "Outcome"), ("look", "Look"),
                   ("pg", "Page · still")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 48
    for n, r in enumerate(rows):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["id"] + (12 if r["variant"] else 0), cy, ("↳ " if r["variant"] else "") + r["id"], size=11,
                           fill=INK if not r["variant"] else MUTED, weight=700, mono=True))
        if not r["variant"]:
            out.append(fk.text(cx["t"], cy - 8, fk.wrap(r["title"], 370, 10.5, True, max_lines=1)[0], size=10.5,
                               fill=INK, weight=700))
            x = cx["t"]
            for h in r["hazards"]:
                lv = (d["hazards"].get(h, {}).get("initial_risk") or {}).get("risk_level", "")
                t = TONES[LEVEL_TONE.get(lv, "amber")]
                p, w = fk.pill(x, cy - 1, h, t[1], color=t[0], stroke=t[0])
                out += p
                x += w + 4
            t = TONES[SRC_TONE.get(r["source"], "system")]
            p, _ = fk.pill(cx["src"], cy - 20, r["source"], t[1], color=t[0], stroke=t[0])
            out += p
            out.append(fk.text(cx["src"], cy + 12, r["reference"], size=10, fill=INK, mono=True))
            t = TONES[out_tone(r["outcome"])]
            p, _ = fk.pill(cx["o"], cy - 12, r["outcome"], t[1], color=t[0], stroke=t[0])
            out += p
        else:
            out.append(fk.text(cx["t"], cy, "same analysis, different look", size=10, fill=MUTED))
        lk = r["look"]
        out.append(fk.text(cx["look"], cy - 6, f"{lk['environment']} · {lk['condition']}", size=10.5, fill=INK))
        out.append(fk.text(cx["look"], cy + 9, f"camera {lk['camera']}", size=9.5, fill=MUTED))
        ok = r["page"] and r["still"]
        out.append(fk.text(cx["pg"], cy, ("page ✓" if r["page"] else "no page") + " · " + ("still ✓" if r["still"] else "no still"),
                           size=10, fill=TONES["ok" if ok else "amber"][0]))
    y += len(rows) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES[t][1], TONES[t][0], SRC_LABEL[s]) for s, t in SRC_TONE.items()] + [
        (TONES["red"][1], TONES["red"][0], "Mishap or unsafe outcome"), (TONES["ok"][1], TONES["ok"][0], "Clear")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · The 3D scenes", "Every 3D scene and variant with what it replays", out)


# ================================================================ figure 2 · coverage (drawn directly)
def fig_coverage(d: dict) -> str:
    W, M = 1240, 40
