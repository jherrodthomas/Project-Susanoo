CELL = re.compile(r'<mxCell ([^>]*?)(?:/>|>(.*?)</mxCell>)', re.S)


def attr(s: str, k: str) -> str:
    m = re.search(rf'\b{k}="([^"]*)"', s)
    return htmlmod.unescape(m.group(1)) if m else ""


def parse(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    name = attr(re.search(r"<diagram [^>]*>", text).group(0), "name")
    cells = []
    for m in CELL.finditer(text):
        a, body = m.group(1), m.group(2) or ""
        if 'vertex="1"' not in a:
            continue
        g = re.search(r"<mxGeometry ([^>]*)", body)
        geo = {k: float(attr(g.group(1), k) or 0) for k in ("x", "y", "width", "height")} if g else {}
        style = attr(a, "style")
        cells.append({"value": attr(a, "value"), "style": style, **geo,
                      "header": "fontColor=#FFFFFF" in style, "text": style.startswith("text;")})
    title = next((c["value"] for c in cells if c["text"] and "fontSize=22" in c["style"]), name)
    notes = [c["value"] for c in cells if c["text"] and c["value"] != title]
    lanes = sorted([c for c in cells if c["header"]], key=lambda c: c["x"])
    out = []
    for ln in lanes:
        steps = sorted([c for c in cells if not c["header"] and not c["text"]
                        and ln["x"] <= c["x"] < ln["x"] + ln["width"]], key=lambda c: c["y"])
        out.append({"lane": ln["value"], "steps": [s["value"] for s in steps]})
    edges = len(re.findall(r'edge="1"', text))
    return {"file": path.name, "rel": str(path.relative_to(ROOT)), "stem": path.stem, "title": title, "lanes": out,
            "note": " ".join(notes), "edges": edges, "kb": round(path.stat().st_size / 1024, 1),
            "labels": [c["value"] for c in cells if c["value"]]}


def svg_text(path: Path) -> str:
    t = path.read_text(encoding="utf-8")
    return htmlmod.unescape(" ".join(re.findall(r">([^<>]+)<", t)) + " " + " ".join(re.findall(r'aria-label="([^"]*)"', t)))


def task_names() -> dict[str, int]:
    """Abbreviation -> MIL-STD-882E task: from the terms list and from the initials of the task titles."""
    terms = yaml.safe_load((ROOT / "docs" / "terms.yaml").read_text())
    out = {}
    for section in terms.values():
        if not isinstance(section, dict):
            continue
        for k, v in section.items():
            m = re.search(r"MIL-STD-882E Task (\d{3})", str(v))
            if m:
                out[str(k)] = int(m.group(1))
    model = yaml.safe_load((ROOT / "standards" / "mil-std-882e" / "model.yaml").read_text())
    for t in model["tasks"]:
        words = re.sub(r"[/-]", " ", t["title"]).split()
        ini = "".join("&" if w.lower() == "and" else w[0] for w in words if w[0].isalpha() and w.lower() not in ("of", "the", "for", "to", "using"))
        if len(ini) >= 3:
            out.setdefault(ini.upper(), t["id"])
    return out


def load() -> dict:
    ctx, _, _ = load_reqs()
    maps = [parse(p) for p in sorted(FOLDER.rglob("*.drawio"))]
    pages = [p for p in ROOT.rglob("*.md") if not (SKIP_PAGES & set(p.parts)) and FOLDER not in p.parents]
    names = task_names()
    model = {t["id"]: t for t in yaml.safe_load((ROOT / "standards/mil-std-882e/model.yaml").read_text())["tasks"]}
    tail = yaml.safe_load((ROOT / "standards/tailoring/mil-std-882e.yaml").read_text())["tasks"]
    for m in maps:
        svg = IMAGES / f"{m['stem']}.svg"
        m["export"] = svg.exists()
        if svg.exists():
            st = re.sub(r"\s+", " ", svg_text(svg))
            m["missing"] = [lab for lab in m["labels"] if re.sub(r"\s+", " ", lab) not in st]
        else:
            m["missing"] = m["labels"]
        m["pages"] = sorted(str(p.relative_to(ROOT)) for p in pages
                            if f"images/{m['stem']}.svg" in p.read_text(encoding="utf-8", errors="ignore"))
        found = set()
        for lab in m["labels"]:
            for tok in re.split(r"[\s/+(),]+", lab):
                if tok.upper() in names and tok.isupper():
                    found.add(names[tok.upper()])
        m["tasks"] = sorted(found)
        m["abbr"] = sorted({tok for lab in m["labels"] for tok in re.split(r"[\s/+(),]+", lab)
                            if tok.isupper() and tok.upper() in names})
    tasks = sorted({t for m in maps for t in m["tasks"]})
    tinfo = {t: {"title": model[t]["title"], "disp": (tail.get(t) or {}).get("disposition", "—"),
                 "gate": (tail.get(t) or {}).get("gate", "")} for t in tasks}
    abbr = {}
    for k, v in names.items():
        if v in tasks:
            abbr.setdefault(v, []).append(k)
    return {"ctx": ctx, "maps": maps, "tasks": tasks, "tinfo": tinfo, "abbr": abbr,
            "root": next(k for k, v in ctx.nodes.items() if not v.get("parent") and v.get("kind") != "external")}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


