# ================================================================ SysML activity
def lifecycle(d: dict) -> dict:
    m = next(x for x in d["maps"] if x["stem"] == LIFECYCLE)
    steps, seen = [], set()
    for ln in m["lanes"]:
        for st in ln["steps"]:
            nm = sysml_name(st)
            nm = nm[0].lower() + nm[1:]
            while nm in seen:
                nm += "2"
            seen.add(nm)
            steps.append({"name": nm, "label": f"{ln['lane']}: {st}"})
    loops = []
    if "reopen" in m["note"].lower() and len(m["lanes"]) > 1 and m["lanes"][1]["steps"]:
        first = next(s["name"] for s in steps if s["label"].startswith(m["lanes"][1]["lane"] + ":"))
        loops.append((steps[-1]["name"], first, "configuration change"))
    return {"name": "SafetyLifecycle", "steps": steps, "loops": loops,
            "doc": f"{m['title']}, from {m['rel']}: {m['note']}", "map": m}


