    stale = [m for m in maps if m["missing"]]
    head, y0 = fk.header(
        W, "1", "The process maps",
        f"{plural(len(maps), 'draw.io map')}, read from the sources: each map's lanes left to right with the steps under "
        f"each, whether its SVG export still carries every label of its source ({len(maps) - len(stale)} of "
        f"{len(maps)} do), and the pages that show it.", "docs/diagrams/**/*.drawio")
    out = list(head)
    y = y0 + 26
    for m in maps:
        out.append(fk.rect(M, y, W - 2 * M, 30, fill=GREY_BG, stroke="none", rx=6, sw=0))
        out.append(fk.text(M + 10, y + 20, m["title"], size=12.5, fill=INK, weight=700))
        out.append(fk.text(M + 420, y + 20, m["file"], size=10, fill=MUTED, mono=True))
        ok = not m["missing"]
        tt = TONES["ok" if ok else "red"]
        lab = "export in step" if ok else f"export missing {len(m['missing'])} label{'s' if len(m['missing']) != 1 else ''}"
        p, w = fk.pill(M + 700, y + 7, lab if m["export"] else "no export", tt[1], color=tt[0], stroke=tt[0])
        out += p
        out.append(fk.text(W - M - 10, y + 20, f"shown on {plural(len(m['pages']), 'page')}", size=10, fill=MUTED,
                           anchor="end"))
        y += 40
        n = max(len(m["lanes"]), 1)
        lw = (W - 2 * M - (n - 1) * 10) / n
        rows = max((len(ln["steps"]) for ln in m["lanes"]), default=0)
        for i, ln in enumerate(m["lanes"]):
            x = M + i * (lw + 10)
            out.append(fk.rect(x, y, lw, 24, fill="#204B70", stroke="none", rx=5, sw=0))
            out.append(fk.text(x + lw / 2, y + 16, fk.wrap(ln["lane"], lw - 10, 10.5, True, max_lines=1)[0], size=10.5,
                               fill="#FFFFFF", weight=700, anchor="middle"))
