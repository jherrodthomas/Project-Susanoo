def fig_wiki(d: dict) -> dict:
    nodes = [{"id": "SRC", "code": "tools/wiki/build_wiki.py",
              "title": f"{sum(d['copied'].values())} repository pages copied",
              "sub": ", ".join(f"{k} {v}" for k, v in sorted(d["copied"].items(), key=lambda kv: (-kv[1], kv[0]))),
              "tone": "work", "maxw": 300, "legend": "Repository pages (copied)"},
             {"id": "GEN", "banner": "Generated pages", "tone": "work"}]
    edges = []
    for prod, n in sorted(d["wiki_by"].items()):
        if prod in ("copy of a repository page", "hand-written"):
            continue
        nodes.append({"id": "g_" + re.sub(r"\W", "_", prod), "parent": "GEN", "code": short(prod),
                      "title": plural(n, "page"), "tone": "system", "legend": "Generator"})
    nodes.append({"id": "HAND", "title": "Wiki-only pages", "sub": plural(d["wiki_by"].get("hand-written", 0), "page")
                  + ", hand-written", "tone": "safety", "legend": "Hand-written"})
    nodes.append({"id": "W", "code": "docs/wiki/", "title": f"{len(d['wiki'])} wiki pages",
                  "sub": f"{d['embeds']} image embeds", "tone": "current"})
    nodes.append({"id": "GH", "title": "GitHub Wiki", "sub": "publish-wiki workflow, on main", "tone": "external",
                  "legend": "External"})
    edges += [{"src": "SRC", "dst": "W", "label": f"{sum(d['copied'].values())} copies (build_wiki)"},
              {"src": "GEN", "dst": "W", "label": "generated pages"},
              {"src": "HAND", "dst": "W", "label": "edited by a person"},
              {"src": "W", "dst": "GH", "label": "published"}]
    return {"file": "fig-2-wiki-sources.svg", "number": "2", "title": "Where the wiki pages come from",
            "subtitle": "Each wiki page is a copy of a repository page, written by a generator, or written by hand "
                        "for the wiki. The publish-wiki workflow copies docs/wiki to the GitHub Wiki on main.",
            "ref": "docs/wiki · tools/wiki/build_wiki.py", "direction": "RIGHT", "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Feeds")]}


def fig_blocks(d: dict) -> dict:
    bf = by_folder(d)
    nodes = [{"id": "D", "banner": "docs/", "tone": "work"}]
    for folder in d["folders"]:
        c = bf[folder]
        gen = sum(v for k, v in c.items() if k != "hand-written")
        nodes.append({"id": "f_" + re.sub(r"\W", "_", folder), "parent": "D", "code": folder.replace("docs", "", 1)
                      .lstrip("/") + "/" if folder != "docs" else "docs/ (top)",
                      "title": f"{plural(sum(c.values()), 'file')}, {gen} generated",
                      "sub": (plural(len([p for p in c if p != "hand-written"]), "generator")
                              + (" · some hand-written" if "hand-written" in c and gen else "")) if gen else
                             "hand-written",
                      "tone": "safety" if gen == 0 else ("system" if gen == sum(c.values()) else "interface"),
                      "maxw": 250, "legend": "All hand-written" if gen == 0 else
                      ("All generated" if gen == sum(c.values()) else "Mixed")})
    fid = {f: "f_" + re.sub(r"\W", "_", f) for f in d["folders"]}
    edges = []
    for a, b, lab in (("docs/diagrams/mil-std-882e", "docs/wiki/images", "SVG exports"),
                      ("docs/wiki", "docs/wiki/images", f"{d['embeds']} embeds"),
                      ("docs/wiki", "docs/3d", "links to scene pages"),
                      ("docs/wiki", "docs/vcycle", "links to the V cycle")):
        if a in fid and b in fid:
            edges.append({"src": fid[a], "dst": fid[b], "label": lab, "dash": True})
    return {"file": "fig-3-block-diagram.svg", "number": "3", "title": "Block diagram",
            "subtitle": "The docs subfolders, how many of their files are generated and by which tools, and how "
                        "they refer to each other.",
            "ref": "docs/", "direction": "DOWN", "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Embeds or links", True)]}


