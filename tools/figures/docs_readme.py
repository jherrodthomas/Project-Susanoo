# ================================================================ records
def producer_of(p: Path) -> str:
    rel = str(p.relative_to(ROOT))
    for pat, prod in PRODUCERS:
        if fnmatch.fnmatch(rel, pat):
            return prod
    if p.suffix in (".md", ".html", ".svg", ".sysml", ".txt"):
        head = p.read_text(errors="ignore")[:4000]
        head = head.split("<!-- terms:start", 1)[0]
        m = MARKER.search(head)
        if m and m.group(1) != "tools/terms/terms.py":
            return m.group(1)
    return "hand-written"


def short(prod: str) -> str:
    return prod.replace("tools/", "").replace("sim/", "sim/")


def load() -> dict:
    ctx, _, _ = load_reqs()
    for _, prod in PRODUCERS:
        if not (ROOT / prod).exists():
            raise SystemExit(f"{GEN}: producer {prod} in PRODUCERS does not exist")
    files = []
    for p in sorted(DOCS.rglob("*")):
        if p.is_dir() or SKIP & set(p.parts):
            continue
        files.append({"rel": str(p.relative_to(ROOT)), "folder": str(p.parent.relative_to(ROOT)), "ext": p.suffix,
                      "prod": producer_of(p)})
    folders = sorted({f["folder"] for f in files})
    src = {str(k.relative_to(ROOT)): v for k, v in wiki_sources().items()}
    copied = Counter(Path(k).parts[0] if len(Path(k).parts) > 1 else "(front page)" for k in src)
    wiki = [f for f in files if f["folder"] == "docs/wiki" and f["ext"] == ".md"]
    wiki_by = Counter("copy of a repository page" if f["prod"] == "tools/wiki/build_wiki.py" else f["prod"] for f in wiki)
    embeds = 0
    for f in wiki:
        embeds += len(re.findall(r"\]\((?:\.\./)*(?:images/|docs/wiki/images/)", (ROOT / f["rel"]).read_text()))
    terms = yaml.safe_load((DOCS / "terms.yaml").read_text())
    return {"ctx": ctx, "files": files, "folders": folders, "copied": copied, "wiki": wiki, "wiki_by": wiki_by,
            "embeds": embeds, "terms": {k: len(v) for k, v in terms.items() if isinstance(v, (list, dict))}}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def by_folder(d: dict) -> dict[str, Counter]:
    out: dict[str, Counter] = defaultdict(Counter)
    for f in d["files"]:
        out[f["folder"]][f["prod"]] += 1
    return out


# ================================================================ figure 1 · inventory (drawn directly)
def fig_inventory(d: dict) -> str:
    bf = by_folder(d)
    gen = sum(1 for f in d["files"] if f["prod"] != "hand-written")
    W, M = 1160, 40
    head, y0 = fk.header(
        W, "1", "What writes each file in docs/",
        f"The {len(d['files'])} files in docs/, by folder and by the tool that writes them: {gen} generated, "
        f"{len(d['files']) - gen} hand-written. Read from each file's GENERATED marker, or the producer map for "
        "images and pages without one.", "docs/")
    out = list(head)
    cx = {"f": M + 12, "p": M + 300, "n": M + 640, "k": M + 720, "bar": M + 880}
    y = y0 + 30
    for k, lab in (("f", "Folder"), ("p", "Written by"), ("n", "Files"), ("k", "Kinds")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 26
    for folder in d["folders"]:
        rows = sorted(bf[folder].items(), key=lambda kv: (kv[0] == "hand-written", -kv[1], kv[0]))
        y += 6
        total = sum(bf[folder].values())
        out.append(fk.text(M, y + 15, folder + "/", size=11, fill=INK, weight=700, mono=True))
        out.append(fk.text(cx["n"], y + 15, str(total), size=11, fill=INK, weight=700))
        y += 22
        for n, (prod, k) in enumerate(rows):
            if n % 2:
                out.append(fk.rect(M, y + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=5, sw=0))
            cy = y + rh / 2 + 4
            hand = prod == "hand-written"
            t = TONES["safety" if hand else "system"]
            p, _ = fk.pill(cx["f"] + 12, cy - 12, "hand" if hand else "generated", t[1], color=t[0], stroke=t[0])
            out += p
            out.append(fk.text(cx["p"], cy, "a person" if hand else prod, size=10, fill=INK, mono=not hand))
            out.append(fk.text(cx["n"], cy, str(k), size=10.5, fill=INK))
            kinds = Counter(f["ext"] or "(none)" for f in d["files"] if f["folder"] == folder and f["prod"] == prod)
            out.append(fk.text(cx["k"], cy, ", ".join(f"{e} ×{c}" for e, c in kinds.most_common(3)), size=10,
                               fill=MUTED))
            out.append(fk.rect(cx["bar"], cy - 9, max(3, 190 * k / max(total, 1)), 10, fill=t[0], stroke="none",
                               rx=3, sw=0))
            y += rh
    y += 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["system"][1], TONES["system"][0], "Generated (never edited by hand)"),
           (TONES["safety"][1], TONES["safety"][0], "Hand-written (a person edits it)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " Bars: share of the folder's files.", W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · What writes each file in docs/",
                  "Every docs folder with the tool or person that writes its files", out)


