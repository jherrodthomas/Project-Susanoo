# ================================================================ records
def read_asset(p: Path) -> dict:
    text = p.read_text(encoding="utf-8")
    head = text.split("\n", 1)[0]
    m = re.search(r"window\.(\w+) = \{meta: (\{.*?\}),\nbin: \"", text, re.S)
    meta = json.loads(m.group(2))
    b64 = len(text) - text.index('bin: "') - 9
    return {"file": p.name, "var": m.group(1), "meta": meta, "kb": round(p.stat().st_size / 1024),
            "json_kb": round(len(m.group(2)) / 1024), "b64_kb": round(b64 / 1024), "head": head,
            "source": (re.search(r"from (\S+?);", head) or [None, ""])[1]}


def read_terrain(a: dict, p: Path) -> dict:
    """The terrain poses: every terrain's walk cycle posed on its ground, with the exporter's own findings."""
    import yaml
    meta = a["meta"]
    labels = {t["key"]: t for t in yaml.safe_load((ROOT / "sim/scenes3d/terrain.yaml").read_text())["terrains"]}
    rows = []
    for t in meta["terrains"]:
        base = {"key": t["key"], "label": labels.get(t["key"], {}).get("label", t["key"]),
                "note": labels.get(t["key"], {}).get("note", "")}
        if "frames" not in t:
            rows.append({**base, "skipped": t.get("skipped") or "not posed"})
            continue
        f = t["findings"]
        rows.append({**base, "skipped": None, "rise": t["rise"], "frames": len(t["frames"]),
                     "own": sum(len(fr["extras"]) for fr in t["frames"]), "drop": f["max_hip_drop_m"],
                     "clear": f["min_body_clearance_m"], "unsolved": len(f["unsolved_frames"])})
    a.update(rows=rows, mode=meta.get("mode", "walk"), pages=sorted(h.name for h in PAGES.glob("*.html")
                                     if f"assets/{p.name}" in h.read_text(encoding="utf-8")),
             tris=sum(m["i"][1] // 3 for m in meta["meshes"]))
    return a


def load() -> dict:
    ctx, _, _ = load_reqs()
    assets = []
    terrains = []
    for p in sorted(FOLDER.glob("*.js")):
        a = read_asset(p)
        if "terrains" in a["meta"]:
            terrains.append(read_terrain(a, p))
            continue
        meta = a["meta"]
        per = defaultdict(lambda: {"meshes": 0, "base": 0, "verts": 0, "tris": 0})
        base = set(meta["base"])
        for i, m in enumerate(meta["meshes"]):
            r = per[m["cls"]]
            r["meshes"] += 1
            r["base"] += i in base
            r["verts"] += m["v"][1]
            r["tris"] += m["i"][1] // 3
        a["classes"] = dict(sorted(per.items(), key=lambda kv: -kv[1]["tris"]))
        a["clips"] = {name: [{"label": f["label"], "moved": sum(1 for v in f["vis"] if v[1] >= 0),
                              "own": sum(1 for v in f["vis"] if v[1] < 0), "x": f["body_x"]} for f in frames]
                      for name, frames in meta["clips"].items()}
        a["pages"] = sorted(h.name for h in PAGES.glob("*.html") if f"assets/{p.name}" in h.read_text(encoding="utf-8"))
        assets.append(a)
    terrains.sort(key=lambda t: (t["mode"] != "walk", t["file"]))
    return {"ctx": ctx, "assets": assets, "terrains": terrains, "colours": class_colours(),
            "root": next(k for k, v in ctx.nodes.items() if not v.get("parent") and v.get("kind") != "external")}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else ('es' if word.endswith(('sh', 'ch', 's', 'x')) else 's')}"


def fmt(n: int) -> str:
    return f"{n:,}"


# ================================================================ figure 1 · contents (drawn directly)
def fig_contents(d: dict) -> str:
    W, M = 1260, 40
    a = d["assets"][0]
    meta, cls = a["meta"], a["classes"]
    tris = sum(c["tris"] for c in cls.values())
    lay = meta["layout"]
    head, y0 = fk.header(
        W, "1", "What is in the geometry file",
        f"{a['file']}: {plural(len(meta['meshes']), 'mesh')} ({len(meta['base'])} in the standing pose, the rest a "
        f"frame's own shape), {fmt(sum(c['verts'] for c in cls.values()))} vertices and {fmt(tris)} triangles in "
        f"{len(cls)} part classes; positions are int16 on a {meta['quantum_m'] * 1000:g} mm grid about "
        f"{meta['origin_m']} m. Read from the file's own mesh table.", f"docs/3d/assets/{a['file']}")
    out = list(head)
    cx = {"c": M, "m": M + 170, "b": M + 250, "v": M + 330, "t": M + 420, "bar": M + 520}
    y = y0 + 30
    for k, lab in (("c", "Part class"), ("m", "Meshes"), ("b", "Standing"), ("v", "Vertices"), ("t", "Triangles"),
                   ("bar", "Share of the triangles")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh, bw = 24, W - M - cx["bar"] - 60
    mx = max(c["tris"] for c in cls.values())
    for n, (name, c) in enumerate(cls.items()):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=4, sw=0))
        cy = top + rh / 2 + 4
        col = d["colours"].get(name, ["#94A3B8", 1])[0]
        out.append(fk.rect(cx["c"], cy - 9, 11, 11, fill=col, stroke="#475569", rx=2, sw=0.6))
        out.append(fk.text(cx["c"] + 18, cy, name, size=10.5, fill=INK, mono=True))
        for k, v in (("m", c["meshes"]), ("b", c["base"]), ("v", c["verts"]), ("t", c["tris"])):
            out.append(fk.text(cx[k], cy, fmt(v), size=10.5, fill=INK))
        w = bw * c["tris"] / mx
        out.append(fk.rect(cx["bar"], cy - 10, w, 12, fill=col, stroke="#475569", rx=2, sw=0.5))
        out.append(fk.text(cx["bar"] + w + 6, cy, f"{100 * c['tris'] / tris:.0f}%", size=9.5, fill=MUTED))
    y += len(cls) * rh + 16
    out.append(fk.text(M, y + 4, "The file", size=11.5, fill=INK, weight=700))
    y += 16
    parts = [("positions (int16 x, y, z)", lay["positions"][1], "#86b6ea"),
             ("indices (uint16)", lay["indices"][1], "#c9a33a"),
             ("transforms (float32 3 × 4)", lay["matrices"][1], "#8a5cd1")]
    total = sum(p[1] for p in parts)
    x = M
    for lab, n, col in parts:
        w = (W - 2 * M) * n / total
        out.append(fk.rect(x, y, w, 26, fill=col, stroke="#FFFFFF", rx=3, sw=1))
        out.append(fk.text(x + 8, y + 17, f"{lab} · {n / 1024:,.0f} KB", size=10, fill="#FFFFFF", weight=700))
        x += w
    y += 42
    out.append(fk.text(M, y, f"Binary buffer {total / 1024:,.0f} KB, carried as base64 ({a['b64_kb']:,} KB) after the "
                             f"{a['json_kb']:,} KB mesh table: {a['kb']:,} KB in all, one <script> file so a page opened "
                             "from a local checkout can load it.", size=10, fill=MUTED))
    y += 22
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · What is in the geometry file",
                  "Meshes, vertices and triangles per part class, and the buffer layout", out)


# ================================================================ figure 2 · clips (drawn directly)
def fig_clips(d: dict) -> str:
    W, M = 1260, 40
    a = d["assets"][0]
    st = a["meta"]["stats"]
    frames = sum(len(f) for f in a["clips"].values())
    head, y0 = fk.header(
        W, "2", "Every frame of every clip",
        f"{plural(len(a['clips']), 'clip')}, {plural(frames, 'frame')}. In each frame a mesh is either a standing mesh "
        f"moved by a fitted transform ({fmt(st['matched'])} in all, {fmt(st['rigid'])} of them by a rigid match) or a "
        f"mesh of its own where the shape changes, such as a hose or a stretching limb ({fmt(st['own_mesh'])}).",
        f"docs/3d/assets/{a['file']} · clips")
    out = list(head)
    y = y0 + 24
    mx = max(f["moved"] + f["own"] for fr in a["clips"].values() for f in fr)
    ch = 90
    for name, fr in a["clips"].items():
        t = TONES[CLIP_TONE.get(name, "system")]
        own = sum(f["own"] for f in fr)
        out.append(fk.text(M, y + 12, name, size=12, fill=INK, weight=700))
        out.append(fk.text(M, y + 28, f"{plural(len(fr), 'frame')} · {own} own meshes", size=9.5, fill=MUTED))
        x0, bw = M + 170, min(32, (W - M - (M + 170)) / max(len(fr), 1))
        for i, f in enumerate(fr):
            x = x0 + i * bw
            hm = ch * f["moved"] / mx
            ho = ch * f["own"] / mx
            out.append(fk.rect(x + 2, y + ch - hm, bw - 4, hm, fill=t[1], stroke=t[0], rx=1, sw=0.6))
            if ho:
                out.append(fk.rect(x + 2, y + ch - hm - ho, bw - 4, ho, fill=t[0], stroke=t[0], rx=1, sw=0.6))
        first, last = fr[0]["label"], fr[-1]["label"]
        out.append(fk.text(x0, y + ch + 14, first, size=9, fill=MUTED))
        if len(fr) > 1:
            out.append(fk.text(x0 + len(fr) * bw, y + ch + 14, last, size=9, fill=MUTED, anchor="end"))
        y += ch + 34
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [("#FFFFFF", "#475569", "Standing mesh moved by a transform (light)"),
           ("#475569", "#475569", "Mesh of its own for that frame (solid)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    out.append(fk.text(M, y + 4, f"Bar height: meshes shown in the frame (up to {mx}).", size=10.5, fill=MUTED))
    y += 20
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Every frame of every clip",
                  "Every frame of every clip: meshes moved by a transform and meshes of their own", out)


