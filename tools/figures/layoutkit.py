#!/usr/bin/env python3
"""Drawing kit for the ELK-laid-out figures (diagram.py): tones, text metrics and SVG primitives.

The palette constants come from figkit.py, the repository's shared figure kit, so every Susanoo figure uses one
palette; this module adds what auto-laid-out diagrams need on top (tone table, markers, rounded orthogonal paths,
wrapping that splits long paths, figure header/legend/footer layout).

House style (shared with the LionDriver assurance figures): white canvas, slate ink, Inter-style type, rounded
cards with a bold title and a muted subtitle, tone colours that mean the same thing in every figure, coloured
banners for partitions and boundaries, pills for IDs and interface codes, a legend row and a "Generated by" footer.

Standard library only; every function is deterministic.
"""
from __future__ import annotations

from xml.sax.saxutils import escape

# ---------------------------------------------------------------- palette
