# ---------------------------------------------------------------- text metrics
def text_w(s: str, size: float, bold: bool = False, mono: bool = False) -> float:
    """Rough rendered width of s (Inter-like metrics; monospace is 0.6 em)."""
    if mono:
        return len(s) * 0.6 * size
    w = 0.0
    for ch in s:
        if ch in "il.,:;'|!·":
            w += 0.28
        elif ch in "fjrt() -/[]":
            w += 0.36
        elif ch.isupper() or ch in "mwMW≥≤–—…→×«»&":
            w += 0.70
        elif ch.isdigit():
            w += 0.56
        else:
            w += 0.55
    return w * size * (1.07 if bold else 1.0)


def wrap(s: str, width: float, size: float, bold: bool = False, mono: bool = False, max_lines: int = 0) -> list[str]:
    """Greedy word wrap to width; tokens wider than a line (paths, long IDs) are split after / - _.
    Optional max_lines ends the last line with an ellipsis."""
    pieces: list[tuple[str, bool]] = []          # (text, glued to the previous piece)
    for wd in str(s).split():
        glued = False
        while text_w(wd, size, bold, mono) > width and len(wd) > 1:
            cut = 0
            for i, ch in enumerate(wd):
                if ch in "/-_" and text_w(wd[:i + 1], size, bold, mono) <= width:
                    cut = i + 1
            if not cut:
                break
            pieces.append((wd[:cut], glued))
            wd, glued = wd[cut:], True
        pieces.append((wd, glued))
    lines, cur = [], ""
    for wd, glued in pieces:
        cand = (cur + wd) if glued else (cur + " " + wd).strip()
        if cur and text_w(cand, size, bold, mono) > width:
            lines.append(cur)
            cur = wd
        else:
            cur = cand
    if cur:
        lines.append(cur)
    if max_lines and len(lines) > max_lines:
        lines = lines[:max_lines]
        lines[-1] = lines[-1].rstrip(",;:") + " …"
    return lines or [""]


# ---------------------------------------------------------------- SVG primitives
def fmt(v: float) -> str:
    return f"{v:.1f}".rstrip("0").rstrip(".")


def el(tag: str, content: str | None = None, raw: bool = False, **attrs) -> str:
    """One SVG element; attribute names use _ for - (stroke_width -> stroke-width), a trailing _ is dropped."""
    a = "".join(f' {k.rstrip("_").replace("_", "-")}="{v}"' for k, v in attrs.items() if v not in ("", None))
    if content is None:
        return f"<{tag}{a}/>"
    return f"<{tag}{a}>{content if raw else escape(content)}</{tag}>"


def text(x, y, s, size=11, fill=INK, weight="", anchor="", mono=False, style="", halo=False) -> str:
    extra = {"stroke": "#FFFFFF", "stroke_width": 3, "paint_order": "stroke", "stroke_linejoin": "round"} if halo else {}
    return el("text", str(s), x=fmt(x), y=fmt(y), font_size=size, fill=fill, font_weight=weight,
              text_anchor=anchor, font_family=MONO if mono else "", font_style=style, **extra)


def rect(x, y, w, h, fill="#FFFFFF", stroke=LINE, sw=1.2, rx=8, dash="", opacity="") -> str:
    return el("rect", x=fmt(x), y=fmt(y), width=fmt(w), height=fmt(h), rx=rx, fill=fill, stroke=stroke,
              stroke_width=sw, stroke_dasharray=dash, opacity=opacity)


def line(x1, y1, x2, y2, stroke=MUTED, sw=1.4, dash="") -> str:
    return el("line", x1=fmt(x1), y1=fmt(y1), x2=fmt(x2), y2=fmt(y2), stroke=stroke, stroke_width=sw,
              stroke_dasharray=dash)


def path(d, stroke=MUTED, sw=1.4, fill="none", dash="", marker_end="", marker_start="") -> str:
    return el("path", d=d, stroke=stroke, stroke_width=sw, fill=fill, stroke_dasharray=dash,
              stroke_linejoin="round", stroke_linecap="round", marker_end=marker_end, marker_start=marker_start)


def circle(cx, cy, r, fill="#FFFFFF", stroke=INK, sw=1.4) -> str:
    return el("circle", cx=fmt(cx), cy=fmt(cy), r=fmt(r), fill=fill, stroke=stroke, stroke_width=sw)


def pill(x, y, label, fill, color="#FFFFFF", h=16, size=9.5, stroke="none") -> tuple[list[str], float]:
    """A rounded label chip at (x, y) top-left; returns (svg, width)."""
    w = text_w(label, size, True) + 12
    return [rect(x, y, w, h, fill=fill, stroke=stroke, rx=h / 2, sw=1),
            text(x + w / 2, y + h / 2 + size * 0.36, label, size=size, fill=color, weight=700, anchor="middle")], w


def pill_w(label: str, size: float = 9.5) -> float:
    return text_w(label, size, True) + 12


def rounded_path(pts: list[tuple[float, float]], r: float = 7) -> str:
    """Orthogonal polyline with rounded corners."""
    if len(pts) < 3:
        return "M" + " L".join(f"{fmt(x)} {fmt(y)}" for x, y in pts)
    d = [f"M{fmt(pts[0][0])} {fmt(pts[0][1])}"]
    for i in range(1, len(pts) - 1):
        (x0, y0), (x1, y1), (x2, y2) = pts[i - 1], pts[i], pts[i + 1]
        l1 = max(abs(x1 - x0), abs(y1 - y0))
        l2 = max(abs(x2 - x1), abs(y2 - y1))
        rr = min(r, l1 / 2, l2 / 2)
        sg = lambda v: 0 if abs(v) <= 1.0 else (1 if v > 0 else -1)  # noqa: E731  (sub-pixel = straight)
        ax, ay = x1 - rr * sg(x1 - x0), y1 - rr * sg(y1 - y0)
        bx, by = x1 + rr * sg(x2 - x1), y1 + rr * sg(y2 - y1)
        d.append(f"L{fmt(ax)} {fmt(ay)} Q{fmt(x1)} {fmt(y1)} {fmt(bx)} {fmt(by)}")
    d.append(f"L{fmt(pts[-1][0])} {fmt(pts[-1][1])}")
    return " ".join(d)


def defs() -> str:
    """Hatch for out-of-scope blocks and one arrowhead / diamond marker per tone."""
    out = ['<pattern id="hatch" patternUnits="userSpaceOnUse" width="6" height="6" patternTransform="rotate(45)">'
           f'<rect width="6" height="6" fill="{GREY_BG}"/><line x1="0" y1="0" x2="0" y2="6" stroke="{HAIR}" '
           'stroke-width="2"/></pattern>']
    colours = {"ink": MUTED, **{k: v[0] for k, v in TONES.items()}}
    for name, c in colours.items():
        out.append(f'<marker id="arr-{name}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" '
                   f'orient="auto-start-reverse"><path d="M0 0 L10 5 L0 10 z" fill="{c}"/></marker>')
        out.append(f'<marker id="dia-{name}" viewBox="0 0 16 10" refX="15" refY="5" markerWidth="12" markerHeight="8" '
                   f'orient="auto-start-reverse"><path d="M1 5 L8 1 L15 5 L8 9 z" fill="{c}"/></marker>')
        out.append(f'<marker id="tri-{name}" viewBox="0 0 12 12" refX="11" refY="6" markerWidth="10" markerHeight="10" '
                   f'orient="auto-start-reverse"><path d="M1 1 L11 6 L1 11 z" fill="#FFFFFF" stroke="{c}" '
                   'stroke-width="1.2"/></marker>')
    return "<defs>" + "".join(out) + "</defs>"


def svg(width: float, height: float, title: str, desc: str, body: list[str]) -> str:
    head = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{fmt(width)}" height="{fmt(height)}" '
            f'viewBox="0 0 {fmt(width)} {fmt(height)}" font-family="{FONT}" role="img">')
    return "\n".join([head, el("title", title), el("desc", desc), defs(),
                      rect(0, 0, width, height, fill="#FFFFFF", stroke="none", rx=0, sw=0), *body, "</svg>"]) + "\n"


def header(width: float, number: str, title: str, subtitle: str, ref: str, m: float = 40) -> tuple[list[str], float]:
    """Figure title, wrapped subtitle and source reference; returns (svg, y of the hairline)."""
    out = [text(m, 44, f"Figure {number} · {title}", size=20, weight=700)]
    ref_w = text_w(ref, 11) if ref else 0
    ref_below = ref and text_w(f"Figure {number} · {title}", 20, True) + ref_w + 32 > width - 2 * m
    if ref_below:
        ref_w = 0
    y = 66
    for ln in wrap(subtitle, width - 2 * m - ref_w - 24, 12.5):
        out.append(text(m, y, ln, size=12.5, fill=MUTED))
        y += 17
    if ref and ref_below:
        out.append(text(m, y, f"Source: {ref}", size=11, fill=FAINT))
        y += 15
    elif ref:
        out.append(text(width - m, 44, ref, size=11, fill=MUTED, anchor="end"))
    y += 2
    out.append(line(m, y, width - m, y, stroke=HAIR, sw=1))
    return out, y


def legend(x: float, y: float, entries: list[tuple[str, str, str]], max_x: float) -> tuple[list[str], float]:
    """entries: (fill, stroke, label); stroke ending ' dashed' is dashed; wraps at max_x. Returns (svg, bottom y)."""
    out, x0 = [], x
    for fill, stroke, label in entries:
        w = 34 + text_w(label, 11)
        if x + w > max_x and x > x0:
            x, y = x0, y + 22
        dash = ""
        if stroke.endswith(" dashed"):
            stroke, dash = stroke[:-7], "3 2"
        if fill.startswith("line:"):
            c = fill[5:]
            out.append(line(x, y - 4, x + 16, y - 4, stroke=c, sw=1.8, dash=dash))
        else:
            out.append(rect(x, y - 10, 14, 12, fill=fill, stroke=stroke, rx=3, dash=dash))
        out.append(text(x + 22, y, label, size=11, fill=MUTED))
        x += w
    return out, y + 8
