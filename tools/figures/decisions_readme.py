#!/usr/bin/env python3
"""Build decisions/README.md, decisions/DecisionRegister.sysml and decisions/figures/*.svg from the register.

Everything on the page is read from decisions/register.yaml (schema pdac/schemas/decision-register.schema.json), so it
cannot drift from it. The lifecycle drawn here is the one the schema's statuses and rule D01 (tools/pdac/rules_ext.py)
enforce, as described in CLAUDE.md "Decisions for the lead":

  queued -> open (about ten at a time) -> answered (the lead's words, quoted) -> applied (applied_in recorded)
  a decider: claude question is never open for the lead: it is decided, applied and recorded as applied

Figures (house style of framework/documentation-standard.md):

  fig-1-register.svg            every decision: gate, decider, status, reversibility, answer, where applied
  fig-2-where-applied.svg       which folders each answered decision changed
  fig-3-block-diagram.svg       SUS-I1 decomposition; elements a decision names are coloured
  fig-4-boundary-diagram.svg    what the register owns and what crosses its boundary
  fig-5-sysml-state-machine.svg SysML state machine of a decision (DecisionRegister.sysml, generated here)
  fig-6-inputs-and-outputs.svg  what the register consumes and feeds

The README part above the END marker is generated; anything below it is preserved.

    python3 tools/figures/decisions_readme.py            # write
    python3 tools/figures/decisions_readme.py --check    # fail if anything is stale
"""
