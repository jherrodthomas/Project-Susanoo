        "Every question for the project lead lives here, with the context, two to four options with the "
        "recommendation first, how hard it is to undo, what it blocks and its sources. When the lead answers, their "
        "choice is recorded with who, when and how, and `applied_in` names every file the answer changed. A "
        "reversible technical choice is marked `decider: claude`: the AI takes the recommendation, applies it and "
        "records it, and it is never left open for the lead.\n",
        "## Decision register\n", img("fig-1-register.svg", "1", "Decision register"),
