def short(p: str) -> str:
    return p.replace("safety/mil-std-882e/", "882E tree/") if len(p) > 34 else p


def fig_trace(d: dict) -> dict:
    nodes = [{"id": "R", "banner": "Records", "tone": "work"}, {"id": "F", "banner": "Figures", "tone": "work"},
             {"id": "S", "banner": "Front-page sections", "tone": "work"}]
    edges, recs, secs = [], {}, {}
    for f in d["figs"]:
        if f["file"].startswith("task-") and f["file"] != "task-flow.svg":
            continue
        fid = "f_" + mid(f["file"])
        label = "task-flow, -thread, -matrix, -hub" if f["file"] == "task-flow.svg" else f["file"].replace(".svg", "")
        nodes.append({"id": fid, "parent": "F", "title": label, "tone": "current", "maxw": 240,
                      "legend": "Front-page figure"})
        for r in f["records"]:
            rid = "r_" + mid(r)
            if rid not in recs:
                recs[rid] = r
                nodes.append({"id": rid, "parent": "R", "title": short(r), "tone": "software", "maxw": 280,
                              "legend": "Record or result"})
            edges.append({"src": rid, "dst": fid, "label": ""})
        sid = "s_" + mid(f["section"])
        if sid not in secs:
            secs[sid] = f["section"]
            nodes.append({"id": sid, "parent": "S", "title": f["section"], "tone": "system", "maxw": 220,
                          "legend": "Front-page section"})
        edges.append({"src": fid, "dst": sid, "label": "", "dash": True})
    return {"file": "fig-2-record-trace.svg", "number": "2", "title": "Which records feed which figure",
            "subtitle": "Records (left) → the figures built from them → the front-page section each sits under, read "
                        "from build_readme.py: the data keys each figure function uses, followed through load() and "
                        "stats(). The four task figures share the catalog and tailoring.",
            "ref": "tools/readme/build_readme.py", "direction": "RIGHT", "orient": "fixed", "nodes": nodes,
            "edges": edges, "legend": [edge_leg("Read by"), edge_leg("Shown under", True)]}


