def fig_figures(d: dict) -> str:
    W, M = 1260, 40
    figs, blocks = d["figs"], d["blocks"]
    head, y0 = fk.header(
        W, "1", "What the front page shows, and from which records",
        f"{plural(len(figs), 'figure')} and {plural(len(blocks), 'number block')} on the repository front page, each "
        "with the section it sits under and the records it reads, found by reading tools/readme/build_readme.py.",
        "tools/readme/build_readme.py · README.md")
    out = list(head)
    cx = {"f": M, "t": M + 140, "s": M + 480, "z": M + 670, "r": M + 740}
    y = y0 + 30
    for k, lab in (("f", "File"), ("t", "Title"), ("s", "Front-page section"), ("z", "Size"), ("r", "Records read")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rows = [(f["file"], f["title"], f["section"], f["records"], f"{f['kb']} KB", "figure") for f in figs] + [
        (f"readme:{b['name']}", f"{b['name'].capitalize()} table, {plural(b['rows'], 'row')}", b["section"],
         b["records"], "—", "block") for b in blocks]
    rh = 50
    for n, (f, t, s, recs, z, kind) in enumerate(rows):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["f"], cy, f, size=10, fill=INK if kind == "figure" else TONES["interface"][0], weight=700,
                           mono=True))
        tl = fk.wrap(t, 320, 10.5, max_lines=2)
        for j, ln in enumerate(tl):
            out.append(fk.text(cx["t"], cy - 6 * (len(tl) - 1) + j * 13, ln, size=10.5, fill=INK))
        out.append(fk.text(cx["s"], cy, fk.wrap(s, 180, 10, max_lines=1)[0], size=10, fill=MUTED if s.startswith("not") else INK))
        lines = fk.wrap(", ".join(recs) or "—", (W - M - cx["r"]) * 0.78, 9, True, max_lines=3)
        for j, ln in enumerate(lines):
            out.append(fk.text(cx["r"], cy - 6 * (len(lines) - 1) + j * 12, ln, size=9, fill=MUTED, mono=True))
        out.append(fk.text(cx["z"], cy, z, size=10, fill=INK))
    y += len(rows) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["system"][1], INK, "Figure (docs/readme/*.svg)"),
           (TONES["interface"][1], TONES["interface"][0], "Number block in README.md (a readme: block)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · What the front page shows, and from which records",
                  "Every front-page figure and number block with its section and records", out)


