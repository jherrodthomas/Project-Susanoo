def build_steps(d: dict) -> list[dict]:
    seen, out = set(), []
    order = ["load", "stats", "banner", "glance", "risk_matrix", "simulation", "roadmap", "task_figures", "blocks",
             "apply_blocks", "decorate", "write_text"]
    present = set(d["steps"])
    for s in order:
        if s in present and STEP_LABEL.get(s) and s not in seen:
            seen.add(s)
            out.append({"name": s.replace("_", "") + "Step", "label": STEP_LABEL[s]})
    return out


