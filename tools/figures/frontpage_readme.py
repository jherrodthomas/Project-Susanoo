# ================================================================ reading the builder
def subs(node: ast.AST, var: str) -> set[str]:
    return {n.slice.value for n in ast.walk(node) if isinstance(n, ast.Subscript) and isinstance(n.value, ast.Name)
            and n.value.id == var and isinstance(n.slice, ast.Constant) and isinstance(n.slice.value, str)}


def path_consts(node: ast.AST) -> set[str]:
    out = set()
    for n in ast.walk(node):
        if isinstance(n, ast.Constant) and isinstance(n.value, str) and re.fullmatch(r"[\w.-]+(/[\w.*-]+)+", n.value):
            base = n.value.split("*")[0].rstrip("/")
            if (ROOT / base).exists() or (ROOT / n.value.rsplit("/", 1)[0]).exists():
                out.add(n.value)
        if (isinstance(n, ast.BinOp) and isinstance(n.op, ast.Div) and isinstance(n.right, ast.Constant)
                and isinstance(n.right.value, str) and "ROOT" in ast.unparse(n.left)
                and re.fullmatch(r"[\w.-]+", n.right.value) and (ROOT / n.right.value).exists()):
            out.add(n.right.value)
    return out


def analyse() -> dict:
    tree = ast.parse(BUILDER.read_text())
    funcs = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    consts = {}
    for n in tree.body:
        if isinstance(n, ast.Assign) and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name):
            pc = path_consts(n.value)
            if pc:
                consts[n.targets[0].id] = pc
    # load(): data key -> record paths
    load_map: dict[str, set[str]] = {}
    for n in ast.walk(funcs["load"]):
        if isinstance(n, ast.Dict):
            for k, v in zip(n.keys, n.values):
                if isinstance(k, ast.Constant):
                    load_map[k.value] = {p.split("*")[0].rstrip("/") if "*" in p else p for p in path_consts(v)}
        if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Subscript):
            k = n.targets[0].slice.value
            load_map[k] = {p for nn in ast.walk(funcs["load"]) if isinstance(nn, ast.Assign)
                           for p in path_consts(nn.value) if p.endswith(".md")}
    for k, v in load_map.items():
        load_map[k] = {re.sub(r"/[^/]*\*[^/]*$", "", p) for p in v}
    # stats(): number key -> data keys (through the locals it assigns)
    st = funcs["stats"]
    local = {}
    for n in st.body:
        if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name):
            local[n.targets[0].id] = subs(n.value, "d")
    stat_map = {}
    for n in ast.walk(st):
        if isinstance(n, ast.Dict):
            for k, v in zip(n.keys, n.values):
                if isinstance(k, ast.Constant):
                    keys = subs(v, "d") | {x for nm in ast.walk(v) if isinstance(nm, ast.Name) and nm.id in local
                                           for x in local[nm.id]}
                    stat_map[k.value] = keys

    def uses(name: str, seen=None) -> tuple[set[str], set[str], set[str]]:
        """(data keys, numbers, extra paths) a function reads, following calls into other module functions."""
        seen = seen or set()
        if name in seen or name not in funcs:
            return set(), set(), set()
        seen.add(name)
        f = funcs[name]
        dk, sk = subs(f, "d"), subs(f, "s")
        extra = path_consts(f) | {p for nm in ast.walk(f) if isinstance(nm, ast.Name) and nm.id in consts
                                  for p in consts[nm.id]}
        for c in ast.walk(f):
            if isinstance(c, ast.Call) and isinstance(c.func, ast.Name) and c.func.id in funcs:
                a, b, e = uses(c.func.id, seen)
                dk |= a
                sk |= b
                extra |= e
        return dk, sk, extra

    # main(): output file -> function
    outputs = {}
    main = funcs["main"]
    for n in ast.walk(main):
        if isinstance(n, ast.Dict):
            for k, v in zip(n.keys, n.values):
                if k is None and isinstance(v, ast.DictComp):     # **{OUT / name: svg for … in task_figures(…)}
                    call = v.generators[0].iter
                    fn = call.func.value.func.id if isinstance(call.func, ast.Attribute) else None
                    args = {x for a in call.func.value.args for x in subs(a, "d")} if fn else set()
                    outputs["task-*"] = ("task_figures", args)
                elif isinstance(k, ast.BinOp) and isinstance(k.right, ast.Constant):
                    outputs[k.right.value] = (v.func.id, None)
                elif isinstance(k, ast.Name) and k.id == "README":
                    outputs["README.md"] = (v.args[1].func.id if isinstance(v.args[1], ast.Call) else "blocks", None)
    rows = {}
    for out, (fn, args) in outputs.items():
        if args is not None:
            dk, sk, extra = set(args), set(), {str(RELATIONS.relative_to(ROOT))}
        else:
            dk, sk, extra = uses(fn)
        allk = dk | {x for k in sk for x in stat_map.get(k, set())}
        recs = sorted({p for k in allk for p in load_map.get(k, set())} | {p for p in extra if not p.endswith(".py")})
        rows[out] = {"fn": fn, "data": sorted(allk), "numbers": sorted(sk), "records": recs}
    # blocks(): each readme: block traced on its own
    bf = funcs["blocks"]
    ret = next(n for n in ast.walk(bf) if isinstance(n, ast.Return) and isinstance(n.value, ast.Dict))
    block_rows = {}
    for k, v in zip(ret.value.keys, ret.value.values):
        names = {n.id for n in ast.walk(v) if isinstance(n, ast.Name)} - {"d", "s"}
        parts = [v] + [st for st in ast.walk(bf) if isinstance(st, (ast.Assign, ast.For))
                       and any(isinstance(n, ast.Name) and n.id in names for n in ast.walk(st))
                       and st is not ret]
        dk, sk = set(), set()
        extra = set()
        for part in parts:
            dk |= subs(part, "d")
            sk |= subs(part, "s")
            for c in ast.walk(part):
                if isinstance(c, ast.Call) and isinstance(c.func, ast.Name) and c.func.id in funcs:
                    a2, b2, e2 = uses(c.func.id)
                    dk |= a2
                    sk |= b2
                    extra |= e2
        allk = dk | {x for kk in sk for x in stat_map.get(kk, set())}
        block_rows[k.value] = sorted({p for kk in allk for p in load_map.get(kk, set())}
                                     | {p for p in extra if not p.endswith(".py")})
    steps = [c.func.id if isinstance(c.func, ast.Name) else c.func.attr
             for c in ast.walk(main) if isinstance(c, ast.Call)]
    return {"rows": rows, "blocks": block_rows, "load_map": load_map, "stat_map": stat_map, "steps": steps}


def sections() -> dict[str, str]:
    """docs/readme file -> the front-page heading it sits under."""
    out, head = {}, "Top of page"
    for ln in FRONT.read_text().splitlines():
        m = re.match(r"#{2,3} (.+)", ln)
        if m:
            head = m.group(1).strip()
        for f in re.findall(r"docs/readme/([\w-]+\.svg)", ln):
            out.setdefault(f, head)
    return out


def blocks_on_page() -> dict[str, tuple[str, int]]:
    text, out, head = FRONT.read_text(), {}, "Top of page"
    lines = text.splitlines()
    for i, ln in enumerate(lines):
        m = re.match(r"#{2,3} (.+)", ln)
        if m:
            head = m.group(1).strip()
        b = re.match(r"<!-- readme:(\w+):start", ln)
        if b:
            n = 0
            for ln2 in lines[i + 1:]:
                if ln2.startswith(f"<!-- readme:{b.group(1)}:end"):
                    break
                n += ln2.startswith("| ") and not ln2.startswith("|---")
            out[b.group(1)] = (head, max(n - 1, 0))
    return out


def load() -> dict:
    ctx, _, _ = load_reqs()
    a = analyse()
    secs = sections()
    figs = []
    for p in sorted(FOLDER.glob("*.svg")):
        t = p.read_text()
        title = re.search(r"<title>([^<]*)", t)
        key = p.name if p.name in a["rows"] else ("task-*" if p.name.startswith("task-") else None)
        r = a["rows"].get(key, {"fn": "?", "records": [], "numbers": [], "data": []})
        figs.append({"file": p.name, "title": (title.group(1).strip() if title else p.stem), "kb": round(p.stat().st_size / 1024),
                     "section": secs.get(p.name, "not on the front page"), **r})
    order = lambda f: (0 if f["file"] == "banner.svg" else 1, int(re.search(r"Figure (\d+)", f["title"]).group(1))  # noqa: E731
                       if re.search(r"Figure (\d+)", f["title"]) else 0)
    figs.sort(key=order)
    bl = blocks_on_page()
    blocks = [{"name": name, "section": sec, "rows": n, "records": a["blocks"].get(name, [])}
              for name, (sec, n) in bl.items()]
    return {"ctx": ctx, "figs": figs, "blocks": blocks,
            "steps": a["steps"], "root": next(k for k, v in ctx.nodes.items()
                                              if not v.get("parent") and v.get("kind") != "external")}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


