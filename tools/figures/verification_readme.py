def fig_obligations(d: dict, s: dict) -> str:
    hazards = d["hazards"]
    methods = METHODS + sorted({x for _, m in d["mits"] for x in (m.get("verification") or {}).get("method", [])}
                               - set(METHODS))
    W, M = 1120, 40
    head, y0 = fk.header(
        W, "1", "Verification obligations",
        f"{plural(s['mits'], 'mitigation')} on {plural(len(hazards), 'hazard')} and {plural(s['reqs'], 'requirement')} "
        f"name a verification method. Each cell counts the mitigations planning that method. "
        f"{plural(s['vers'], 'verification record')} exist; {s['mit_ev']} mitigations and {s['req_ev']} requirements "
        "cite one; " + (", ".join(f"{v} {k}" for k, v in sorted(s["ver_result"].items())) or "none") + ".", "safety/hazards · requirements/ · verification/")
    out = list(head)
    cx = {"id": M, "title": M + 118}
    mx0, mw = M + 400, 80
    cx["state"] = mx0 + mw * len(methods) + 10
    cx["reqs"] = cx["state"] + 118
    cx["ev"] = cx["reqs"] + 104
    y = y0 + 30
    out.append(fk.text(cx["id"], y, "Hazard", size=10.5, fill=MUTED, weight=700))
    out.append(fk.text(cx["title"], y, "Title", size=10.5, fill=MUTED, weight=700))
    for i, m in enumerate(methods):
        out.append(fk.text(mx0 + i * mw + mw / 2, y, m.capitalize(), size=10.5, fill=MUTED, weight=700,
                           anchor="middle"))
    out.append(fk.text(cx["state"], y, "Mitigation state", size=10.5, fill=MUTED, weight=700))
    out.append(fk.text(cx["reqs"], y, "Requirements", size=10.5, fill=MUTED, weight=700))
    out.append(fk.text(cx["ev"], y, "Evidence", size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 36
    accent = TONES["system"]
    for n, (hid, h) in enumerate(hazards.items()):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        lvl = (h.get("initial_risk") or {}).get("risk_level", "")
        tone = TONES[LEVEL_TONE.get(lvl, "amber")]
        p, _ = fk.pill(cx["id"], cy - 12, hid, tone[1], color=tone[0], stroke=tone[0])
        out += p
        lines = fk.wrap(h.get("title", hid), 262, 11.5, True, max_lines=2)
        for j, ln in enumerate(lines):
            out.append(fk.text(cx["title"], cy + (-5 + 14 * j if len(lines) > 1 else 0), ln, size=11.5, fill=INK,
                               weight=700))
        ms = h.get("mitigations") or []
        for i, m in enumerate(methods):
            k = sum(1 for x in ms if m in (x.get("verification") or {}).get("method", []))
            ccx = mx0 + i * mw + mw / 2
            if k:
                r = 8 + 1.1 * k
                out.append(fk.circle(ccx, cy - 4, r, fill=accent[1], stroke=accent[0], sw=1.4))
                out.append(fk.text(ccx, cy, str(k), size=10.5, fill=accent[0], weight=700, anchor="middle"))
            else:
                out.append(fk.text(ccx, cy, "–", size=11, fill=FAINT, anchor="middle"))
        st = count(x.get("state", "identified") for x in ms)
        out.append(fk.text(cx["state"], cy, ", ".join(f"{v} {k}" for k, v in sorted(st.items())), size=11,
                           fill=MUTED))
        rq = h.get("requirement_ids") or []
        out.append(fk.text(cx["reqs"], cy, ", ".join(rq) if len(rq) <= 1 else f"{rq[0]} +{len(rq) - 1}", size=11,
                           fill=MUTED))
        ids = list(dict.fromkeys(i for x in ms for i in (x.get("verification") or {}).get("evidence_ids") or []))
        res = [d["vers"][i].get("result", "") for i in ids if i in d["vers"]]
        passed = sum(1 for r in res if r in ("pass", "passed"))
        etone = TONES["ok" if ids and passed == len(ids) else "amber"]
        if not ids:
            lab = "0 records"
        elif passed == len(ids):
            lab = f"{passed} passed"
        else:
            other = count(r for r in res if r not in ("pass", "passed"))
            lab = ", ".join(f"{v} {k}" for k, v in sorted(other.items())) + (f", {passed} passed" if passed else "")
        p, _ = fk.pill(cx["ev"], cy - 12, lab, etone[1], color=etone[0], stroke=etone[0])
        out += p
    y += len(hazards) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(accent[1], accent[0], "Mitigations planning this method (count)"),
           (TONES["amber"][1], TONES["amber"][0], "No passed verification record yet"),
           (TONES["ok"][1], TONES["ok"][0], "Every cited record passed"),
           (TONES["red"][1], TONES["red"][0], "Hazard, High initial risk"),
           (TONES["safety"][1], TONES["safety"][0], "Serious"), (TONES["amber"][1], TONES["amber"][0], "Medium")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Verification obligations",
                  "Mitigations per hazard by planned verification method, and the evidence held", out)


