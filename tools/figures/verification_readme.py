# ================================================================ records
def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    vers = {p.stem: yaml.safe_load(p.read_text()) for p in sorted(FOLDER.glob("VER-*.yaml"))}
    cat = yaml.safe_load(CATALOG.read_text())
    e6 = next(f for f in cat["folders"] if f["id"] == "E6")
    sims = sorted(p.relative_to(ROOT).as_posix() for p in SIM_RESULTS.glob("*.md"))
    sims += sorted(p.relative_to(ROOT).as_posix() for p in (SIM_RESULTS / "uav").glob("*.md"))
    mits = [(hid, m) for hid, h in hazards.items() for m in h.get("mitigations") or []]
    return {"ctx": ctx, "reqs": reqs, "hazards": hazards, "vers": vers, "e6": e6, "sims": sims, "mits": mits}


def stats(d: dict) -> dict:
    mits, reqs, vers = d["mits"], d["reqs"], d["vers"]
    return {
        "mits": len(mits),
        "mit_state": count(m.get("state", "identified") for _, m in mits),
        "mit_ev": sum(1 for _, m in mits if (m.get("verification") or {}).get("evidence_ids")),
        "reqs": len(reqs),
        "req_disp": count(r["verification"]["disposition"] for r in reqs.values()),
        "req_ev": sum(1 for r in reqs.values() if r["verification"].get("evidence_ids")),
        "vers": len(vers),
        "ver_result": count(v["result"] for v in vers.values()),
        "ver_sim": sum(1 for v in vers.values() if v.get("simulated")),
        "files": sum(len(v.get("evidence") or []) for v in vers.values()),
        "verified": sum(1 for h in d["hazards"].values() if h.get("status") in ("verified", "accepted", "closed")),
    }


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def summary(c: dict) -> str:
    return ", ".join(f"{n} {k}" for k, n in sorted(c.items())) or "none"


