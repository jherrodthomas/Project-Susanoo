GEN = "tools/figures/wikiimages_readme.py"
FOLDER = ROOT / "docs" / "wiki" / "images"
FIGS = FOLDER / "readme"
README = FOLDER / "README.md"
SYSML = FOLDER / "WikiImages.sysml"
COPY = ROOT / "docs" / "wiki" / "Wiki-Images.md"      # this page's own wiki copy: it lists every image
DRAWIO = ROOT / "docs" / "diagrams"
SKIP = {"node_modules", ".git", "__pycache__"}
FOOTER = (f"Generated by {GEN} from the images in docs/wiki/images, the producer map of docs_readme.py and every page "
          "that shows them. Figures show records and synthetic results; nothing in them is verified or accepted (R13).")
KIND = {"generated": ("Generated from the records", "ok"), "still": ("Rendered still (headless Chromium)", "interface"),
        "export": ("Exported by hand from draw.io", "amber"), "hand": ("Hand-made, no source found", "red")}
WHERE = ["Wiki pages", "Repository pages", "Front page", "Interactive pages"]


# ================================================================ records
def drawio_of(stem: str) -> Path | None:
    hits = sorted(DRAWIO.rglob(f"{stem}.drawio"))
    return hits[0] if hits else None


def where_of(p: Path) -> str:
    rel = p.relative_to(ROOT).as_posix()
    if rel == "README.md":
        return "Front page"
    if rel.startswith("docs/wiki/") and p.suffix == ".md":
        return "Wiki pages"
    if p.suffix == ".html":
        return "Interactive pages"
    return "Repository pages"


def load() -> dict:
    ctx, _, hazards = load_reqs()
    imgs = sorted(p for p in FOLDER.iterdir() if p.suffix in (".svg", ".png"))
    pages = [p for p in ROOT.rglob("*") if p.suffix in (".md", ".html") and not (SKIP & set(p.parts))
             and p not in (README, COPY) and FIGS not in p.parents]
    texts = {p: p.read_text(encoding="utf-8", errors="ignore") for p in pages}
    rows = []
    for im in imgs:
        prod = producer_of(im)
        src = None
        if prod == "hand-written":
            src = drawio_of(im.stem)
            kind, prod = ("export", src.relative_to(ROOT).as_posix()) if src else ("hand", "—")
        elif prod.endswith(".mjs"):
            kind = "still"
        else:
            kind = "generated"
        pat = re.compile(rf"(?:^|[/\"(]){re.escape(im.name)}\b")
        users = sorted((p for p, t in texts.items() if f"images/{im.name}" in t and pat.search(t)),
                       key=lambda p: p.as_posix())
        rows.append({"file": im.name, "kind": kind, "prod": prod, "kb": max(1, round(im.stat().st_size / 1024)),
                     "users": [u.relative_to(ROOT).as_posix() for u in users],
                     "where": Counter(where_of(u) for u in users)})
    ids = set()
    for r in rows:
        ids |= set(re.findall(r"(HAZ-[A-Z]+-\d{3})", (FOLDER / r["file"]).read_text(errors="ignore")
                              if r["file"].endswith(".svg") else ""))
    subs = sorted({s for h in ids for s in hazards.get(h, {}).get("subsystems") or []})
    return {"ctx": ctx, "rows": rows, "subs": subs, "hz": sorted(ids),
            "root": next(k for k, v in ctx.nodes.items() if not v.get("parent") and v.get("kind") != "external")}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def groups(d: dict) -> dict[str, list[dict]]:
    g = defaultdict(list)
    for r in d["rows"]:
        g[r["prod"] if r["kind"] != "export" else "draw.io exports"].append(r)
    return dict(sorted(g.items(), key=lambda kv: (["generated", "still", "export", "hand"].index(kv[1][0]["kind"]), kv[0])))


# ================================================================ figure 1 · images (drawn directly)
def fig_images(d: dict) -> str:
    W, M = 1280, 40
    rows = d["rows"]
    unused = [r for r in rows if not r["users"]]
    k = Counter(r["kind"] for r in rows)
    head, y0 = fk.header(
        W, "1", "Every image and what writes it",
        f"{plural(len(rows), 'image')}: {k['generated']} generated from the records, {k['still']} rendered stills, "
        f"{k['export']} exported by hand from draw.io" + (f", {k['hand']} hand-made with no source" if k["hand"] else "")
        + f". The number is how many pages show the image; {len(unused)} are shown by none.", "docs/wiki/images")
    out = list(head)
    y = y0 + 20
    cols, gap = 4, 8
    cw = (W - 2 * M - (cols - 1) * gap) / cols
    for prod, items in groups(d).items():
        lab, tone = KIND[items[0]["kind"]]
        t = TONES[tone]
        out.append(fk.rect(M, y, 10, 10, fill=t[1], stroke=t[0], rx=2, sw=1.2))
        out.append(fk.text(M + 18, y + 9, f"{prod} · {len(items)}", size=11, fill=INK, weight=700, mono=True))
        out.append(fk.text(W - M, y + 9, lab, size=9.5, fill=MUTED, anchor="end"))
        y += 20
        for i, r in enumerate(items):
            x = M + (i % cols) * (cw + gap)
            yy = y + (i // cols) * 26
            none = not r["users"]
            out.append(fk.rect(x, yy, cw, 22, fill=t[1], stroke=TONES["red"][0] if none else t[0], rx=5,
                               sw=1.8 if none else 0.9, dash="4 3" if none else ""))
            out.append(fk.text(x + 7, yy + 15, fk.wrap(r["file"], cw - 90, 9.5, max_lines=1)[0], size=9.5, fill=INK,
                               mono=True))
            out.append(fk.text(x + cw - 34, yy + 15, f"{r['kb']} KB", size=9, fill=MUTED, anchor="end"))
            out.append(fk.text(x + cw - 7, yy + 15, str(len(r["users"])), size=9.5, fill=INK, weight=700, anchor="end"))
        y += ((len(items) + cols - 1) // cols) * 26 + 14
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES[t][1], TONES[t][0], lab) for lab, t in KIND.values()] + [("#FFFFFF", TONES["red"][0], "Shown by no page")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Every image and what writes it",
                  "Every wiki image by producer, with size and the number of pages that show it", out)


# ================================================================ figure 2 · usage (drawn directly)
def fig_usage(d: dict) -> str:
    W, M = 1280, 40
    g = groups(d)
    head, y0 = fk.header(
        W, "2", "Which pages show the images",
        "For each producer, how many pages of each kind show its images (a page counted once per image). Wiki pages use "
        "images/ directly; repository pages reach the same files through ../wiki/images; copied wiki pages use assets/ "
        "and are not counted here.", "every *.md and *.html")
    out = list(head)
    x0, cw, rh = M + 420, (W - 2 * M - 420) / len(WHERE), 32
    y = y0 + 28
    for i, w in enumerate(WHERE):
        out.append(fk.text(x0 + i * cw + cw / 2, y, w, size=10.5, fill=MUTED, weight=700, anchor="middle"))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    mx = max((sum(r["where"][w] for r in items) for items in g.values() for w in WHERE), default=1) or 1
    for n, (prod, items) in enumerate(g.items()):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=5, sw=0))
        cy = top + rh / 2 + 4
        lab, tone = KIND[items[0]["kind"]]
        t = TONES[tone]
        out.append(fk.rect(M, cy - 9, 10, 10, fill=t[1], stroke=t[0], rx=2, sw=1.2))
        out.append(fk.text(M + 18, cy, f"{prod} ({len(items)})", size=10.5, fill=INK, mono=True))
        for i, w in enumerate(WHERE):
            v = sum(r["where"][w] for r in items)
            cx = x0 + i * cw + cw / 2
            if v:
                rad = 5 + 11 * (v / mx) ** 0.5
                out.append(f'<circle cx="{cx:.1f}" cy="{cy - 4:.1f}" r="{rad:.1f}" fill="{t[1]}" stroke="{t[0]}" '
                           'stroke-width="1.2"/>')
                out.append(fk.text(cx, cy, str(v), size=9.5, fill=t[0], weight=700, anchor="middle"))
            else:
                out.append(fk.text(cx, cy, "·", size=12, fill=FAINT, anchor="middle"))
    y += len(g) * rh + 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES[t][1], TONES[t][0], lab) for lab, t in KIND.values()]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Which pages show the images", "Pages of each kind that show each producer's images",
                  out)


# ================================================================ SysML block definition
def fig_sysml(d: dict) -> tuple[dict, str]:
    k = Counter(r["kind"] for r in d["rows"])
    defs = [("GeneratedFigure", "generated", "Written from the records by a generator; CI fails when it is stale.",
             ["generator : String"]),
            ("RenderedStill", "still", "Rendered from an interactive page in headless Chromium by a CI check.",
             ["page : String"]),
            ("HandExport", "export", "Exported by hand from its draw.io source; nothing checks it is current.",
             ["source : String"])]
    nodes = [{"id": "WikiImage", "shape": "class", "title": "WikiImage", "stereotype": "part def",
              "attrs": ["file : String", "kilobytes : Integer", "shownOn : Integer"], "tone": "system"}]
    edges = []
    s = ["    part def WikiImage {", "        doc /* A figure the wiki shows directly from images/. */",
         "        attribute file : String;", "        attribute kilobytes : Integer;", "        attribute shownOn : Integer;",
         "    }"]
    for name, kind, doc, attrs in defs:
        nodes.append({"id": name, "shape": "class", "title": name, "stereotype": "part def :> WikiImage",
                      "attrs": attrs + [f"{plural(k[kind], 'image')} today"], "tone": KIND[kind][1]})
        edges.append({"src": name, "dst": "WikiImage", "label": "specializes", "dash": True})
        a = attrs[0].split(" : ")[0]
        s += [f"    part def {name} :> WikiImage {{", f"        doc /* {doc} */", f"        attribute {a} : String;", "    }"]
    kind_def = {"generated": ("GeneratedFigure", "generator"), "still": ("RenderedStill", "page"),
                "export": ("HandExport", "source"), "hand": ("HandExport", "source")}
    for r in d["rows"]:
        pn = "img" + re.sub(r"\W", "", re.sub(r"\.(svg|png)$", "", r["file"]).title())
        df, a = kind_def[r["kind"]]
        s += [f"    part {pn} : {df} {{", f"        attribute :>> file = \"{r['file']}\";",
              f"        attribute :>> kilobytes = {r['kb']};", f"        attribute :>> shownOn = {len(r['users'])};",
              f"        attribute :>> {a} = \"{r['prod']}\";", "    }"]
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — WikiImages", "ref": "docs/wiki/images/WikiImages.sysml",
            "subtitle": f"Three kinds of wiki image, told apart by what writes them; WikiImages.sysml also holds all "
                        f"{len(d['rows'])} images as parts with their producer, size and the pages that show them.",
            "frame": {"kind": "bdd", "type": "package", "name": "WikiImages"}, "direction": "DOWN",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Specializes", True), ("#EEF2FF", "#4F46E5", "Image"),
                       *[(TONES[KIND[x][1]][1], TONES[KIND[x][1]][0], KIND[x][0]) for x in ("generated", "still", "export")]]}
    sysml = "\n".join([
        f"// WikiImages — generated by {GEN} from docs/wiki/images.",
        "// Do not edit by hand: regenerate the images or change the generator and regenerate.",
        "// Status: documentation figures; nothing in them is reviewed or accepted.", "",
        "package WikiImages {",
        "    private import ScalarValues::*;",
        "    doc /* The figures the wiki shows directly (docs/wiki/images/README.md). */",
        *s, "}", ""])
    return spec, sysml


FLOWS = [["Record generators", "Generated figures", "sus-i1-*, sysml-*, rec-*, sim-*, vcycle-*, wiki-fig-*"],
         ["Interactive pages", "Rendered stills", "3d-* from render.mjs and sheet_check.mjs"],
         ["draw.io sources", "Hand exports", "exported by hand from docs/diagrams"],
         ["@boundary", "Wiki", "copied as images/ by publish-wiki.yml"],
         ["@boundary", "Repository pages", "shown through ../wiki/images"],
         ["CI", "@boundary", "generators and stills --check"]]


def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    block = fig_block(ctx, {"scope": d["subs"] or [d["root"]]})
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"The {len(d['subs'])} subsystems named by the {len(d['hz'])} hazards that appear in the images "
                          "are coloured.")
    boundary = fig_boundary(ctx, {"path": "docs/wiki/images", "boundary": {
        "name": "Wiki images", "inside": ["Generated figures", "Rendered stills", "Hand exports"],
        "outside": ["Record generators", "Interactive pages", "draw.io sources", "Wiki", "Repository pages", "CI"],
        "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="docs/wiki/images/README.md",
                    subtitle="The folder holds the images; what writes them and every page that shows them are outside. "
                             "Crossings are numbered as in the table.")
    sysml_spec, sysml = fig_sysml(d)
    k = Counter(r["kind"] for r in d["rows"])
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "docs/wiki/images/README.md", "direction": "RIGHT",
          "subtitle": "What writes the images (left) and where they are shown (right).",
          "nodes": [
              {"id": "I1", "title": "Record generators", "sub": f"{k['generated']} figures", "tone": "software"},
              {"id": "I2", "title": "Interactive pages", "sub": f"{k['still']} stills", "tone": "work"},
              {"id": "I3", "title": "draw.io sources", "sub": f"{k['export']} exports", "tone": "external"},
              {"id": "X", "code": "docs/wiki/images/", "title": "Wiki images", "sub": plural(len(d["rows"]), "image"),
               "tone": "current"},
              {"id": "O1", "title": "Wiki", "sub": "images/ copied by publish-wiki.yml", "tone": "external"},
              {"id": "O2", "title": "Repository pages", "sub": "READMEs, front page", "tone": "work"}],
          "edges": [{"src": "I1", "dst": "X", "label": "write"}, {"src": "I2", "dst": "X", "label": "render"},
                    {"src": "I3", "dst": "X", "label": "export"}, {"src": "X", "dst": "O1", "label": "published"},
                    {"src": "X", "dst": "O2", "label": "shown"}]}
    specs = [block, boundary, sysml_spec, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    return specs, sysml


# ================================================================ README
def img(file: str, number: str, title: str) -> str:
    return f"![Figure {number} · {title}](readme/{file})\n"


def readme(d: dict, specs: list[dict]) -> str:
    by = {sp["file"]: sp for sp in specs}
    rows = d["rows"]
    k = Counter(r["kind"] for r in rows)
    unused = [r["file"] for r in rows if not r["users"]]
    out = [
        f"<!-- GENERATED by {GEN} from the images in docs/wiki/images and the pages that show them; regenerate. -->\n",
        "# Wiki images\n",
        f"> **Status:** {plural(len(rows), 'image')}: {k['generated']} generated from the records, {k['still']} rendered "
        f"stills, {k['export']} exported by hand from draw.io"
        + (f", **{k['hand']} hand-made with no source**" if k["hand"] else "")
        + (f"; {plural(len(unused), 'image')} shown by no page" if unused else "; every image is shown by some page")
        + ". Never edit a generated image; regenerate it. Nothing in them is verified or accepted (rule R13).\n",
        "| Field | Value |", "|---|---|",
        "| Published | copied to the wiki as `images/` by `.github/workflows/publish-wiki.yml` |",
        "| Shown on | [the wiki source](../README.md), and repository pages through `../wiki/images` |",
        "| SysML | [`WikiImages.sysml`](WikiImages.sysml) (generated) |", "",
        "## Purpose\n",
        "The figures the wiki shows directly: item-definition and SysML views, record figures, simulation scenes, 3D "
        "stills, the V cycle still, the process-map exports and the wiki source page's own figures. This page says what "
        "writes each one and which pages show it, so a stale or orphaned image is easy to spot.\n",
        "## Images\n", img("fig-1-images.svg", "1", "Every image and what writes it"),
        "| Image | Written by | Size | Shown on |", "|---|---|---|---|",
        *[f"| [`{r['file']}`]({r['file']}) | `{r['prod']}` | {r['kb']} KB | "
          + (", ".join(plural(r["where"][w], w.lower().rstrip("s")) for w in WHERE if r["where"][w]) or "**no page**")
          + " |" for r in rows], "",
        "## Where they are shown\n", img("fig-2-usage.svg", "2", "Which pages show the images"),
        "## Block diagram\n", img("fig-3-block-diagram.svg", "3", "Block diagram"),
        "## Boundary diagram\n", img("fig-4-boundary-diagram.svg", "4", "Boundary diagram"),
        "| # | From | To | Crossing / interaction |", "|---|---|---|---|",
        *[f"| {n + 1} | {a.replace('@boundary', 'Wiki images')} | {b.replace('@boundary', 'Wiki images')} | {lab} |"
          for n, (a, b, lab) in enumerate(FLOWS)], "",
        "**Explicitly excluded:** the figures of copied pages (the wiki gets those as `assets/`, listed in "
        "`docs/wiki/assets.txt`), this page's own figures (in `readme/`, which is not published), and any judgement "
        "of what the images show.\n",
        "## SysML model\n",
        "[`WikiImages.sysml`](WikiImages.sysml) is generated from the folder and validated with the project model by "
        "the OMG pilot in CI.\n",
        img("fig-5-sysml-block-definition.svg", "5", by["fig-5-sysml-block-definition.svg"]["title"]),
        "## Inputs and outputs\n", img("fig-6-inputs-and-outputs.svg", "6", "Inputs and outputs"),
        "| Input | Source |", "|---|---|",
        *[f"| {prod} | {len(items)} image{'s' if len(items) != 1 else ''} |" for prod, items in groups(d).items()], "",
        "| Output | Destination |", "|---|---|",
        "| Published images | the GitHub Wiki, `images/` |",
        "| Shown in the repository | the pages listed per image above |", "",
        "## Adding or changing an image\n",
        "1. A generated image: change its records or its generator (Figure 1 names it) and rerun it; never edit the file.",
        "2. A process map: edit its draw.io source in `docs/diagrams/` and export it here with the same name.",
        "3. Regenerate this page and run the full check list in [`CLAUDE.md`](../../../CLAUDE.md).", "",
        "## Folder contents\n",
        "| Item | Description | State |", "|---|---|---|",
        f"| `*.svg`, `*.png` | {plural(len(rows), 'image')}, as in Figure 1 | generated or exported |",
        "| [`WikiImages.sysml`](WikiImages.sysml) | The images as SysML | generated |",
        "| [`readme/`](readme/) | This page's figures (do not edit) | generated |",
        "| `README.md` | This page | generated |", "",
        END_MARKER]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = load()
    specs, sysml = figure_specs(d)
    files = {SYSML: sysml, FIGS / "fig-1-images.svg": fig_images(d), FIGS / "fig-2-usage.svg": fig_usage(d)}
    for spec, svg in zip(specs, diagram.render_all(specs)):
        files[FIGS / spec["file"]] = svg
    files[README] = readme(d, specs)
    return emit(files, FIGS, args.check, GEN)


if __name__ == "__main__":
    sys.exit(main())
