#!/usr/bin/env python3
"""Build docs/wiki/images/README.md, docs/wiki/images/readme/*.svg and docs/wiki/images/WikiImages.sysml: the
figures the wiki shows directly.

Everything is read from the folder and from the pages that show its files:

  docs/wiki/images/*.{svg,png}   every image: what writes it (the producer map and GENERATED markers of
                                 tools/figures/docs_readme.py, so the two pages cannot disagree; a hand-made SVG with a
                                 draw.io source of the same name is that map's export), its size
  every Markdown and HTML page   which pages show each image: wiki pages, repository pages, the front page, the 3D and
                                 V cycle pages

The figures go to readme/ beside the images, not among them: images/ is copied to the wiki as it is.

Figures (house style of framework/documentation-standard.md):

  fig-1-images.svg               every image by what writes it, with its size and how many pages show it
  fig-2-usage.svg                which kinds of page show the images of each producer
  fig-3-block-diagram.svg        the system the images show
  fig-4-boundary-diagram.svg     what the folder holds and what crosses its boundary
  fig-5-sysml-block-definition.svg  WikiImages (generated .sysml): generated figures, rendered stills, hand exports
  fig-6-inputs-and-outputs.svg   what writes the images and where they are shown

    python3 tools/figures/wikiimages_readme.py            # write
    python3 tools/figures/wikiimages_readme.py --check    # fail if anything is stale
"""
