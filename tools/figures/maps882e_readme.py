# ================================================================ records
def homes_of(step: str) -> list[int]:
    s = step.lower()
    return [i for i, (_, _, _, words) in enumerate(RECORD_HOMES)
            if any(re.search(rf"(?<![a-z&]){re.escape(w)}", s) for w in words)]


def load() -> dict:
    ctx, _, _ = load_reqs()
    maps = []
    for p in sorted(FOLDER.glob("*.drawio")):
        m = parse(p)
        text = p.read_text(encoding="utf-8")
        pw = re.search(r'pageWidth="(\d+)" pageHeight="(\d+)"', text)
        m["page"] = (int(pw.group(1)), int(pw.group(2))) if pw else (0, 0)
        m["cells"] = len(re.findall(r'vertex="1"', text))
        m["fills"] = sorted(set(re.findall(r"fillColor=(#[0-9A-Fa-f]{6})", text)))
        svg = IMAGES / f"{p.stem}.svg"
        m["export"] = svg.exists()
        if svg.exists():
            st = svg.read_text(encoding="utf-8")
            vb = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', st)
            m["vb"] = (float(vb.group(1)), float(vb.group(2))) if vb else (0, 0)
            body = re.sub(r"\s+", " ", " ".join(re.findall(r">([^<>]+)<", st)))
            import html as _h
            body = _h.unescape(body)
            m["found"] = sum(1 for lab in m["labels"] if re.sub(r"\s+", " ", lab) in body)
            m["svg_kb"] = round(svg.stat().st_size / 1024, 1)
        else:
            m["vb"], m["found"], m["svg_kb"] = (0, 0), 0, 0
        m["steps"] = [(ln["lane"], st, homes_of(st)) for ln in m["lanes"] for st in ln["steps"]]
        maps.append(m)
    counts = [len(list((ROOT / folder).glob(glob))) if (ROOT / folder).exists() else 0
              for _, folder, glob, _ in RECORD_HOMES]
    root = next(k for k, v in ctx.nodes.items() if not v.get("parent") and v.get("kind") != "external")
    return {"ctx": ctx, "maps": maps, "counts": counts, "root": root}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


# ================================================================ figure 1 · sources (drawn directly)
def fig_sources(d: dict) -> str:
    W, M = 1240, 40
    maps = d["maps"]
    head, y0 = fk.header(
        W, "1", "Every source against its export",
        f"{plural(len(maps), 'draw.io source')} in this folder, each with its page size and cells, and its hand-made "
        "SVG export in docs/wiki/images: the export's width against the page, and how many of the source's labels it "
        "carries. The export is taller than the page by the terms line added under every figure.",
        "docs/diagrams/mil-std-882e")
    out = list(head)
    cx = {"t": M, "p": M + 330, "c": M + 450, "e": M + 540, "l": M + 700, "f": M + 860}
    y = y0 + 30
    for k, lab in (("t", "Map · source"), ("p", "Page"), ("c", "Cells"), ("e", "Export"), ("l", "Labels in export"),
                   ("f", "Fill colours")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 46
    for n, m in enumerate(maps):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["t"], cy - 7, m["title"], size=11, fill=INK, weight=700))
        out.append(fk.text(cx["t"], cy + 8, m["file"], size=9.5, fill=MUTED, mono=True))
        out.append(fk.text(cx["p"], cy, f"{m['page'][0]} × {m['page'][1]}", size=10.5, fill=INK))
        out.append(fk.text(cx["c"], cy, str(m["cells"]), size=10.5, fill=INK))
        same = abs(m["vb"][0] - m["page"][0]) < 1
        out.append(fk.text(cx["e"], cy - 7, f"{m['vb'][0]:g} wide" if m["export"] else "none", size=10.5,
                           fill=TONES["ok" if same else "amber"][0]))
        out.append(fk.text(cx["e"], cy + 8, f"{m['svg_kb']} KB", size=9.5, fill=MUTED))
        ok = m["found"] == len(m["labels"])
        t = TONES["ok" if ok else "red"]
        p, _ = fk.pill(cx["l"], cy - 12, f"{m['found']} of {len(m['labels'])}", t[1], color=t[0], stroke=t[0])
        out += p
        for i, c in enumerate(m["fills"]):
            out.append(fk.rect(cx["f"] + i * 26, cy - 11, 20, 14, fill=c, stroke="#475569", rx=3, sw=0.7))
        out.append(fk.text(cx["f"] + len(m["fills"]) * 26 + 4, cy, " ".join(c.upper() for c in m["fills"]), size=9,
                           fill=MUTED, mono=True))
    y += len(maps) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["ok"][1], TONES["ok"][0], "Export in step with its source"),
           (TONES["red"][1], TONES["red"][0], "Export missing source labels")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Every source against its export",
                  "Every draw.io source with its page, cells, colours and export", out)


# ================================================================ figure 2 · record homes (drawn directly)
def fig_homes(d: dict) -> str:
    W, M = 1280, 40
    maps = d["maps"]
    steps = [(m, lane, st, h) for m in maps for lane, st, h in m["steps"]]
    gaps = [s for s in steps if not s[3]]
    used = sorted({i for s in steps for i in s[3]})
    head, y0 = fk.header(
        W, "2", "Where each step's records live",
        f"Every step of every map ({len(steps)}), matched by its words to the repository folder that holds what it "
        f"works on, with how many records that folder holds today. {len(steps) - len(gaps)} steps have a home; "
        f"{len(gaps)} name work the repository keeps no record of yet.", "RECORD_HOMES in " + GEN)
    out = list(head)
    x0 = M + 360
    cw = (W - M - x0) / len(used)
    y = y0 + 24
    for j, i in enumerate(used):
        name, folder, _, _ = RECORD_HOMES[i]
        cxm = x0 + j * cw + cw / 2
        for k, ln in enumerate(fk.wrap(name, cw - 6, 9, True, max_lines=2)):
            out.append(fk.text(cxm, y + k * 11, ln, size=9, fill=INK, weight=700, anchor="middle"))
        out.append(fk.text(cxm, y + 26, f"{d['counts'][i]} now", size=8.5,
                           fill=TONES["ok" if d["counts"][i] else "amber"][0], anchor="middle"))
    y += 36
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 20
    prev = None
    for m, lane, st, h in steps:
        if m is not prev:
            y += 6
            out.append(fk.text(M, y + 13, m["title"], size=10.5, fill=INK, weight=700))
            y += rh
            prev = m
        out.append(fk.text(M + 12, y + 13, fk.wrap(f"{lane} · {st}", 330, 9.5, max_lines=1)[0], size=9.5,
                           fill=INK if h else TONES["amber"][0]))
        for j, i in enumerate(used):
            cxm = x0 + j * cw + cw / 2
            if i in h:
                out.append(f'<circle cx="{cxm:.1f}" cy="{y + 9:.1f}" r="5.5" fill="{TONES["interface"][0]}"/>')
            else:
                out.append(f'<circle cx="{cxm:.1f}" cy="{y + 9:.1f}" r="1.6" fill="#CBD5E1"/>')
        if not h:
            out.append(fk.text(W - M, y + 13, "no record folder", size=9, fill=TONES["amber"][0], anchor="end"))
        y += rh
    y += 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["interface"][0], TONES["interface"][0], "The step works on records kept here"),
           (TONES["amber"][1], TONES["amber"][0], "No record folder for the step, or a folder with no records yet")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Where each step's records live",
                  "Every step of every process map and the repository folder that holds its records", out)


# ================================================================ SysML
def activity(m: dict) -> dict:
    steps, seen = [], set()
    for lane, st, _ in m["steps"]:
        nm = sysml_name(f"{lane} {st}")
        nm = nm[0].lower() + nm[1:]
        while nm in seen:
            nm += "2"
        seen.add(nm)
        steps.append({"name": nm, "label": f"{lane}: {st}"})
    return {"name": sysml_name(m["stem"]), "steps": steps, "loops": [],
            "doc": f"{m['title']} ({m['file']}): {m['note']}"}


