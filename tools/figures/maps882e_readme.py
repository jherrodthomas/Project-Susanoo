def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    block = fig_block(ctx, {"scope": [d["root"]]})
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"The system the process maps describe the safety process for ({d['root']}).")
    boundary = fig_boundary(ctx, {"path": "docs/diagrams/mil-std-882e", "boundary": {
        "name": "882E map sources", "inside": ["Map sources", "Generated page and model"],
        "outside": ["draw.io editor", "SVG exports", "Process-map pages", "Record folders", "CI"], "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="docs/diagrams/mil-std-882e/README.md",
                    subtitle="The folder holds the six editable sources and the page generated from them; their exports, the pages that show them and "
                             "the records the steps work on are outside. Crossings are numbered as in the table.")
    acts = [activity(m) for m in d["maps"]]
    shown = next(a for a, m in zip(acts, d["maps"]) if m["stem"] == SHOWN)
    frag, _ = view_act(shown)
    act = {**frag, "file": "fig-5-sysml-activity.svg", "number": "5", "title": f"SysML activity — {shown['name']}",
           "ref": "docs/diagrams/mil-std-882e/MapActivities.sysml",
           "subtitle": f"The hazard management map read lane by lane into an activity; MapActivities.sysml holds all "
                       f"{len(acts)} maps as activities in the same way."}
    act["legend"] = [x for x in act["legend"] if "Safety-critical" not in x[2] and "Iteration" not in x[2]]
    bodies = [view_act(a)[1] for a in acts]
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "docs/diagrams/mil-std-882e/README.md", "direction": "RIGHT",
          "subtitle": "What the maps draw on (left) and where they are shown (right).",
          "nodes": [
              {"id": "I1", "title": "MIL-STD-882E process", "sub": "elements and tasks, as tailored", "tone": "external"},
              {"id": "I2", "title": "Project roles and records", "sub": "who does what, where it is kept", "tone": "work"},
              {"id": "X", "code": "docs/diagrams/mil-std-882e/", "title": "882E map sources",
               "sub": plural(len(d["maps"]), "map"), "tone": "current"},
              {"id": "O1", "title": "SVG exports", "sub": "docs/wiki/images", "tone": "work"},
              {"id": "O2", "title": "Process-map pages", "sub": "wiki, standards and safety READMEs", "tone": "work"}],
          "edges": [{"src": "I1", "dst": "X", "label": "process"}, {"src": "I2", "dst": "X", "label": "lanes"},
                    {"src": "X", "dst": "O1", "label": "export by hand"},
                    {"src": "X", "dst": "O2", "label": "via the export"}]}
    specs = [block, boundary, act, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    sysml = "\n".join([
        f"// MapActivities — generated by {GEN} from the draw.io sources in docs/diagrams/mil-std-882e.",
        "// Do not edit by hand: change a source or the generator and regenerate.",
        "// Status: illustrative draft workflows; not normative flowcharts or evidence of completed tasks.", "",
        "package MapActivities {",
        "    doc /* The six MIL-STD-882E process maps as activities (docs/diagrams/mil-std-882e/README.md). */",
        *bodies, "}", ""])
    return specs, sysml


