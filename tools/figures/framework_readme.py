# ================================================================ records
def table_rows(text: str, first: str) -> list[list[str]]:
    rows, on = [], False
    for ln in text.splitlines():
        if ln.startswith(f"| {first} |"):
            on = True
            continue
        if on:
            if not ln.startswith("|"):
                break
            if set(ln.replace("|", "").strip()) <= {"-"}:
                continue
            rows.append([c.strip() for c in ln.strip().strip("|").split("|")])
    return rows


def load() -> dict:
    ctx, _, _ = load_reqs()
    repo = load_repo()
    t = repo.tailoring
    names = {x["id"]: x["title"] for x in repo.model["tasks"]}
    gates = []
    for g, info in t["gates"].items():
        due = sorted(tid for tid, x in t["tasks"].items() if x.get("disposition") == "selected" and x.get("gate") == g)
        tasks = []
        for tid in due:
            rec = repo.objects["task"].get(tid)
            tasks.append({"id": tid, "title": names[tid], "status": rec["status"] if rec else "no record",
                          "artifacts": (rec or {}).get("artifacts", [])})
        gates.append({"id": g, "title": info["title"], "phase": info["phase"], "tasks": tasks})
    app = [{"standard": r[0], "status": r[1], "scope": re.sub(r"`([^`]*)`", r"\1", r[2])}
           for r in table_rows((FOLDER / "standards-applicability.md").read_text(), "Standard")]
    pages = []
    for p in PAGES:
        title = next(ln[2:].strip() for ln in (FOLDER / p).read_text().splitlines() if ln.startswith("# "))
        pages.append({"file": p, "title": title,
                      "tasks": sorted(tid for tid, r in repo.objects["task"].items()
                                      if f"framework/{p}" in r.get("artifacts", []))})
    readme_tasks = sorted(tid for tid, r in repo.objects["task"].items() if "framework/README.md" in r.get("artifacts", []))
    return {"ctx": ctx, "t": t, "gates": gates, "current": t["current_gate"], "app": app, "pages": pages,
            "readme_tasks": readme_tasks}


def not_approved(g: dict) -> str:
    return ", ".join(f"{x['id']} ({x['status']})" for x in g["tasks"] if x["status"] != "approved") or "—"


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


# ================================================================ figure 1 · applicability (drawn directly)
def fig_applicability(d: dict) -> str:
    app = d["app"]
    W, M = 1120, 40
    head, y0 = fk.header(
        W, "1", "Standards applicability",
        f"The {len(app)} standards the framework names and how each is used. Status is a project choice, not a "
        "contractual applicability or a certification claim; only MIL-STD-882E is encoded as data and checked.",
        "framework/standards-applicability.md")
    out = list(head)
    cx = {"std": M, "st": M + 300, "sc": M + 470}
    y = y0 + 30
    for k, lab in (("std", "Standard"), ("st", "Status"), ("sc", "Scope and purpose")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    for n, a in enumerate(app):
        lines = fk.wrap(a["scope"], W - M - cx["sc"], 10.5, max_lines=2)
        rh = 30 if len(lines) == 1 else 42
        if n % 2:
            out.append(fk.rect(M, y + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = y + rh / 2 + 4
        out.append(fk.text(cx["std"], cy, fk.wrap(a["standard"], 250, 11, True, max_lines=1)[0], size=11, fill=INK,
                           weight=700))
        tone = TONES[STATUS_TONE.get(a["status"], "external")]
        p, _ = fk.pill(cx["st"], cy - 12, a["status"], tone[1], color=tone[0], stroke=tone[0])
        out += p
        ly = cy - (len(lines) - 1) * 7
        for ln in lines:
            out.append(fk.text(cx["sc"], ly, ln, size=10.5, fill=MUTED))
            ly += 14
        y += rh
    y += 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    seen, leg = set(), []
    for a in app:
        k = STATUS_TONE.get(a["status"], "external")
        if k not in seen:
            seen.add(k)
            label = {"safety": "Core method (adopted)", "interface": "Tailored (selected techniques)",
                     "amber": "Conditional (trigger-dependent)", "external": "Reference (guidance)"}[k]
            leg.append((TONES[k][1], TONES[k][0], label))
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Standards applicability", "Every standard the framework names with its status",
                  out)


# ================================================================ figure 2 · lifecycle gates (drawn directly)
def fig_gates(d: dict) -> str:
    gates, cur = d["gates"], d["current"]
    W, M = 1240, 40
    ntask = sum(len(g["tasks"]) for g in gates)
    head, y0 = fk.header(
        W, "2", "Lifecycle gates and the MIL-STD-882E tasks due at each",
        f"The {len(gates)} project-defined gates with their Table A-I acquisition phase and the {ntask} selected tasks "
        f"due at each, coloured by task record status. Current gate {cur}; a gate passes only on a named human "
        "review.", "standards/tailoring/mil-std-882e.yaml")
    out = list(head)
    cw = (W - 2 * M) / len(gates)
    y = y0 + 24
    deepest = 0
    for i, g in enumerate(gates):
        x = M + i * cw
        is_cur = g["id"] == cur
        t = TONES["safety" if is_cur else "system"]
        out.append(fk.rect(x + 4, y, cw - 8, 68, fill=t[1], stroke=t[0], rx=8, sw=2 if is_cur else 1))
        out.append(fk.text(x + 14, y + 20, g["id"] + (" · current" if is_cur else ""), size=11, fill=t[0], weight=700))
        for k, ln in enumerate(fk.wrap(g["title"], cw - 28, 10.5, True, max_lines=2)):
            out.append(fk.text(x + 14, y + 36 + 13 * k, ln, size=10.5, fill=INK, weight=700))
        out.append(fk.text(x + 14, y + 62, f"phase {g['phase']}", size=9.5, fill=MUTED))
        if i < len(gates) - 1:
            out.append(fk.text(x + cw - 6, y + 38, "›", size=14, fill=MUTED))
        ty = y + 84
        if not g["tasks"]:
            out.append(fk.text(x + 14, ty + 12, "no task due", size=10, fill=FAINT))
            ty += 24
        for task in g["tasks"]:
            tt = TONES[REC_TONE.get(task["status"], "amber")]
            lines = fk.wrap(task["title"], cw - 32, 9.5, max_lines=4)
            h = 34 + 12 * len(lines)
            out.append(fk.rect(x + 8, ty, cw - 16, h, fill=tt[1], stroke=tt[0], rx=6, sw=1))
            p, _ = fk.pill(x + 16, ty + 7, f"Task {task['id']}", tt[0])
            out += p
            ly = ty + 36
            for ln in lines:
                out.append(fk.text(x + 16, ly, ln, size=9.5, fill=INK))
                ly += 12
            out.append(fk.text(x + cw - 14, ty + 18, task["status"], size=9, fill=tt[0], anchor="end"))
            ty += h + 6
        deepest = max(deepest, ty)
    y = deepest + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["safety"][1], TONES["safety"][0], "Current gate"),
           (TONES["amber"][1], TONES["amber"][0], "Task record in work"),
           (TONES["external"][1], TONES["external"][0], "No task record yet"),
           (TONES["ok"][1], TONES["ok"][0], "Task record approved (named human review)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " Conditional, not-selected and not-applicable tasks are on the task applicability page.",
                      W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Lifecycle gates and the MIL-STD-882E tasks due at each",
                  "Gates G0 to G7 with the selected tasks due at each", out)


# ================================================================ ELK figures and SysML
def lifecycle(d: dict) -> dict:
    gates = d["gates"]
    states = [{"name": g["id"], "doc": f"{g['title']} (phase {g['phase']})"} for g in gates]
    tr = [[a["id"], b["id"], "gate passed (named review)"] for a, b in zip(gates[:-2], gates[1:-1])]
    if len(gates) >= 2:
        tr.append([gates[-2]["id"], gates[-1]["id"], "released"])
        tr.append([gates[-1]["id"], gates[-2]["id"], "change needs a new release"])
    return {"name": "GateLifecycle", "initial": gates[0]["id"], "states": states, "transitions": tr, "final": [],
            "doc": "Project-defined gates of framework/lifecycle.md, in order, as mapped in the 882E tailoring."}


def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx, cur = d["ctx"], d["current"]
    root = next(k for k, v in ctx.nodes.items() if not v.get("parent") and v.get("kind") != "external")
    block = fig_block(ctx, {"scope": [root]})
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"The system the framework governs ({root}, configuration as in the item definition). "
                          "Every element passes through the same gates and process contracts.")
    boundary = fig_boundary(ctx, {"path": "framework", "boundary": {
        "name": "Framework",
        "inside": ["Standards applicability", "Lifecycle and gates", "Process contracts", "Traceability model",
                   "Documentation standard"],
        "outside": ["Published standards", "Standard model and tailoring", "Validator and CI", "Records",
                    "Folder generators", "Project lead"],
        "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="framework/README.md",
                    subtitle="The framework owns the method: which standards apply, the gates, process contracts, "
                             "traceability and documentation rules. Others encode and enforce it. Crossings are "
                             "numbered as in the table.")
    v = lifecycle(d)
    frag, body = view_stm(v)
    for n in frag["nodes"]:
        if n.get("shape") == "state" and n.get("id") == cur:
            n["sub"] = (n.get("sub", "") + " · current gate").lstrip(" ·")
            n["tone"] = "safety"
    frag["legend"] = list(frag.get("legend", [])) + [(TONES["safety"][1], TONES["safety"][0], "Current gate")]
    stm = {**frag, "file": "fig-5-sysml-state-machine.svg", "number": "5",
           "title": "SysML state machine — GateLifecycle", "ref": "framework/Lifecycle.sysml",
           "subtitle": f"The gates in order, generated into Lifecycle.sysml from the tailoring. The project is at "
                       f"{cur}; no gate has passed."}
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "framework/README.md", "direction": "RIGHT",
          "subtitle": "What the framework is built from (left) and what reads it (right).",
          "nodes": [
              {"id": "I1", "title": "Published standards", "sub": "editions, not copied text", "tone": "external"},
              {"id": "I2", "title": "Project lead", "sub": "authority, tailoring", "tone": "safety",
               "legend": "Human authority"},
              {"id": "I3", "title": "Concept", "sub": "CONOPS, system boundary", "tone": "work"},
              {"id": "X", "code": "framework/", "title": "Framework", "tone": "current"},
              {"id": "O1", "title": "Standard model and tailoring", "sub": "standards/", "tone": "work"},
              {"id": "O2", "title": "Validator", "sub": "tools/pdac rules", "tone": "software"},
              {"id": "O3", "title": "Folder READMEs", "sub": "documentation standard", "tone": "work"},
              {"id": "O4", "title": "882E work products", "sub": "Tasks 101, 105", "tone": "work"}],
          "edges": [{"src": "I1", "dst": "X", "label": "standards"},
                    {"src": "I2", "dst": "X", "label": "decisions"},
                    {"src": "I3", "dst": "X", "label": "scope"},
                    {"src": "X", "dst": "O1", "label": "applicability, gates"},
                    {"src": "X", "dst": "O2", "label": "traceability rules"},
                    {"src": "X", "dst": "O3", "label": "sections, figures"},
                    {"src": "X", "dst": "O4", "label": "artifacts"}]}
