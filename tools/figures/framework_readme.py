def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = load()
    specs, sysml = figure_specs(d)
    files = {SYSML: sysml, FIGS / "fig-1-applicability.svg": fig_applicability(d),
             FIGS / "fig-2-lifecycle-gates.svg": fig_gates(d)}
    for spec, svg in zip(specs, diagram.render_all(specs)):
        files[FIGS / spec["file"]] = svg
    if not README.exists() or END_MARKER not in README.read_text():
        raise SystemExit("framework/README.md has no END GENERATED marker; the hand-written part must sit below it")
    tail = README.read_text().split(END_MARKER, 1)[1]
    files[README] = readme(d, specs, tail)
    return emit(files, FIGS, args.check, GEN)


if __name__ == "__main__":
    sys.exit(main())
