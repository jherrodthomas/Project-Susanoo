"""Build requirements/README.md and requirements/figures/*.svg from the requirement records.

Everything on the page is read from records, so it cannot drift from the project:

  requirements/SYS-*.yaml                       statements, status, sources, allocation, verification, derivation
  safety/hazards/HAZ-*.yaml                     hazard titles and preliminary initial risk
  architecture/item-definition.yaml             elements (via tools/gen_safety_docs.Ctx)
  models/sysml/model/{Requirements,Satisfaction}.sysml   SysML names and satisfy relations

Figures (house style of framework/documentation-standard.md; the block, boundary and SysML views reuse the
builders of tools/gen_safety_docs.py so every folder README looks the same):

  fig-1-register.svg            requirement register: status, allocation, verification methods, disposition
  fig-2-traceability.svg        hazard -> requirement -> allocated element, with «deriveReqt»
  fig-3-block-diagram.svg       SUS-I1 decomposition; elements with an allocated requirement are coloured
  fig-4-boundary-diagram.svg    what the register owns and what crosses its boundary
  fig-5-sysml-requirements.svg  SysML requirement view of SusanooRequirements (records, satisfy, derive)
  fig-6-inputs-and-outputs.svg  what the register consumes and feeds

The README part above the END marker is generated; anything below it is preserved.

    python3 tools/figures/requirements_readme.py            # write
    python3 tools/figures/requirements_readme.py --check    # fail if anything is stale
"""
