def fig_obligations(d: dict) -> str:
    m, t = d["m"], d["t"]
    obs = [(e, o) for e in m["elements"] for o in e["obligations"]]
    checks = Counter("rule" if o["check"].startswith("rule:") else o["check"] for _, o in obs)
    W, M = 1120, 40
    head, y0 = fk.header(
        W, "1", "The standard as code: obligations and how each is checked",
        f"{plural(len(obs), 'obligation')} of {m['standard']['id']} ({m['standard']['date']}) across "
        f"{len(m['elements'])} elements: {checks.get('rule', 0)} checked by a validator rule on every push, "
        f"{checks.get('review', 0)} by human review. Tailoring status: {t['status']}.", MODEL)
    out = list(head)
    cx = {"el": M, "id": M + 66, "clause": M + 130, "text": M + 200, "check": M + 860, "tail": M + 950}
    y = y0 + 30
    for k, lab in (("el", "Element"), ("id", "ID"), ("clause", "Clause"), ("text", "Obligation (paraphrased)"),
                   ("check", "Checked by"), ("tail", "Tailoring")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh, prev = 28, None
    for n, (e, o) in enumerate(obs):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        if e["id"] != prev:
            p, _ = fk.pill(cx["el"], cy - 12, e["id"], TONES["system"][1], color=TONES["system"][0],
                           stroke=TONES["system"][0])
            out += p
            prev = e["id"]
        out.append(fk.text(cx["id"], cy, o["id"], size=10, fill=INK, weight=700, mono=True))
        out.append(fk.text(cx["clause"], cy, o.get("clause", ""), size=10, fill=MUTED))
        out.append(fk.text(cx["text"], cy, fk.wrap(o["text"], 640, 10.5, max_lines=1)[0], size=10.5, fill=INK))
        rule = o["check"].startswith("rule:")
        tt = TONES["ok" if rule else "amber"]
        p, _ = fk.pill(cx["check"], cy - 12, o["check"].replace("rule:", "rule "), tt[1], color=tt[0], stroke=tt[0])
        out += p
        st = (t.get("obligations") or {}).get(o["id"], {}).get("status")
        out.append(fk.text(cx["tail"], cy, st or "–", size=10, fill=INK if st else FAINT))
    y += len(obs) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["ok"][1], TONES["ok"][0], "Checked by a validator rule (tools/pdac)"),
           (TONES["amber"][1], TONES["amber"][0], "Needs human review"),
           (TONES["system"][1], TONES["system"][0], "Process element (4.3.1–4.3.8, 4.4)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · The standard as code",
                  "Every encoded obligation and how it is checked", out)


