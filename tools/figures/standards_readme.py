# ================================================================ records
def library() -> dict:
    """Enumerations, attribute and item definitions of SusanooLibrary.sysml (just what figure 5 draws)."""
    text = LIBRARY.read_text()
    out = {}
    for m in re.finditer(r"(enum|attribute|item) def (\w+) \{(.*?)\n    \}", text, re.S):
        kind, name, body = m.groups()
        doc = re.search(r"doc /\*\s*(.*?)\s*\*/", body, re.S)
        if kind == "enum":
            lines = re.findall(r"enum (\w+);", body)
        else:
            lines = [f"{'ref ' if r.startswith('ref') else ''}{n} : {t.replace('ScalarValues::', '')}{mult or ''}"
                     for r, n, t, mult in re.findall(r"(ref item |attribute )\s*(\w+) : ([\w:]+)(\[[^\]]+\])?;", body)]
        out[name] = {"kind": kind, "doc": doc.group(1) if doc else "", "lines": lines}
    return out


def load() -> dict:
    ctx = Ctx({"elements": [], "folders": [], "base": "standards"})
    model = yaml.safe_load((ROOT / MODEL).read_text())
    tail = yaml.safe_load((ROOT / TAILOR).read_text())
    return {"ctx": ctx, "m": model, "t": tail, "lib": library()}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def summary(c) -> str:
    return ", ".join(f"{n} {k}" for k, n in sorted(Counter(c).items())) or "none"


