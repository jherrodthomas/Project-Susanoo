def fig_matrix(d: dict) -> str:
    m, t = d["m"], d["t"]
    rd = t["risk_definitions"]
    sev, prob = m["severity"], m["probability"]
    money = rd["severity"].get("monetary_min_usd", {})
    W, M = 1120, 40
    head, y0 = fk.header(
        W, "2", "Tailored risk matrix and who may accept each level",
        f"{rd['id']} ({rd['status']}): Table III unchanged; severity money thresholds scaled for a demonstrator; "
        f"probability per item over the planned life. Each risk level names the role that may accept it.",
        TAILOR)
    out = list(head)
    x0, y = M + 230, y0 + 40
    cw, ch = (W - M - x0) / len(sev), 46
    for j, s in enumerate(sev):
        cxs = x0 + j * cw
        out.append(fk.text(cxs + cw / 2, y - 22, f"{s['category']} · {s['name']}", size=11.5, fill=INK, weight=700,
                           anchor="middle"))
        mm = money.get(s["category"], money.get(str(s["category"])))
        out.append(fk.text(cxs + cw / 2, y - 6, f"≥ ${mm:,} (tailored)" if mm else "below $1,000" if mm == 0 else "",
                           size=10, fill=MUTED, anchor="middle"))
    for i, p in enumerate(prob):
        cy = y + 8 + i * ch
        out.append(fk.text(M, cy + 18, f"{p['level']} · {p['name']}", size=11.5, fill=INK, weight=700))
        band = rd["probability"].get("bands", {}).get(p["level"], "")
        out.append(fk.text(M, cy + 33, band, size=10, fill=MUTED))
        for j, s in enumerate(sev):
            lvl = m["rac_matrix"][p["level"]][s["category"]]
            tone = TONES[LEVEL_TONE.get(lvl, "external")] if lvl != "Eliminated" else TONES["external"]
            out.append(fk.rect(x0 + j * cw + 3, cy, cw - 6, ch - 6, fill=tone[1], stroke=tone[0], rx=8, sw=1.2))
            out.append(fk.text(x0 + j * cw + cw / 2, cy + 18, f"{s['category']}{p['level']} · {lvl}", size=11.5,
                               fill=tone[0], weight=700, anchor="middle"))
            who = t["acceptance_authority"].get(lvl)
            if who:
                out.append(fk.text(x0 + j * cw + cw / 2, cy + 32, f"accept: {who}", size=10, fill=MUTED,
                                   anchor="middle"))
    y = y + 8 + len(prob) * ch + 18
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    conc = ", ".join(t["user_concurrence_required_for"])
    leg = [(TONES["red"][1], TONES["red"][0], "High"), (TONES["safety"][1], TONES["safety"][0], "Serious"),
           (TONES["amber"][1], TONES["amber"][0], "Medium"), (TONES["ok"][1], TONES["ok"][0], "Low"),
           (TONES["external"][1], TONES["external"][0], "Eliminated")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(f"{conc} also need the concurrence of {t['user_representative']}. All roles are simulated. "
                      + FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Tailored risk matrix",
                  "Severity by probability with risk levels and acceptance authority", out)


# ================================================================ ELK figures
def fig_sysml(d: dict) -> dict:
    lib = d["lib"]
    nodes, edges = [], []
    for name in VOCAB + ITEMS:
        x = lib.get(name)
        if not x:
            continue
        stereo = {"enum": "enumeration", "attribute": "attribute def", "item": "item def"}[x["kind"]]
        nodes.append({"id": name, "shape": "class", "title": name, "stereotype": stereo, "attrs": x["lines"],
                      "tone": "interface" if x["kind"] == "enum" else ("safety" if name == "RiskAcceptanceDecision"
                                                                       else "system")})
    names = {n["id"] for n in nodes}
    for name in ITEMS:
        for ln in lib.get(name, {}).get("lines", []):
            m = re.match(r"(ref )?(\w+) : (\w+)", ln)
            if m and m.group(3) in names:
                ref = bool(m.group(1))
                edges.append({"src": name, "dst": m.group(3), "label": m.group(2), "dash": not ref})
    return {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — the 882E vocabulary", "ref": LIB,
            "subtitle": "The MIL-STD-882E vocabulary as modelled in SusanooLibrary: enumerations for the tables and "
                        "the record items the work-product views use. Read from the .sysml file.",
            "frame": {"kind": "bdd", "type": "package", "name": "SusanooLibrary"}, "direction": "RIGHT",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("ref item (record link)"), edge_leg("attribute typed by", True),
                       ("#F5F3FF", "#7C3AED", "Enumeration (882E table)"), ("#EEF2FF", "#4F46E5", "Item definition"),
                       ("#FFF7ED", "#C2410C", "Acceptance (human authority)")]}


