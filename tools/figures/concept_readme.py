#!/usr/bin/env python3
"""Add the record-driven part of concept/README.md: modes and scenarios, and what rests on each.

concept/README.md is hand-written and its figures 1–5 come from concept/figures.yaml (tools/figures/build_figures.py).
This generator adds what those cannot show, read from the records so it cannot drift from them:

  concept/ConceptOperations.sysml     the operating modes MOD-01..10 (state machine OperatingModes)
  concept/CONOPS.md                   the mode concerns (section 5) and the scenarios SCN-nnn (sections 6–7)
  safety/hazards/HAZ-*.yaml           the modes each hazard occurs in
  requirements/SYS-*.yaml             the scenarios each requirement comes from

  concept/figures/records/fig-6-modes.svg       every mode with its safety concern, the hazards that occur in it and
                                                the requirements behind them
  concept/figures/records/fig-7-scenarios.svg   every CONOPS scenario traced to its requirements and their hazards

The figures and a README section between the concept-records markers are written; the rest of the page is left
alone. Figures sit in figures/records/ because build_figures.py owns figures/*.svg.

    python3 tools/figures/concept_readme.py            # write
    python3 tools/figures/concept_readme.py --check    # fail if anything is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT))
import diagram  # noqa: E402
import layoutkit as fk  # noqa: E402
import sysml_parse  # noqa: E402
from layoutkit import INK, MUTED, FAINT, HAIR, GREY_BG, TONES  # noqa: E402
from gen_safety_docs import edge_leg, mid, state_title  # noqa: E402
from requirements_readme import LEVEL_TONE, emit, load as load_reqs  # noqa: E402

GEN = "tools/figures/concept_readme.py"
FOLDER = ROOT / "concept"
FIGS = FOLDER / "figures" / "records"
README = FOLDER / "README.md"
CONOPS = FOLDER / "CONOPS.md"
SYSML = FOLDER / "ConceptOperations.sysml"
START = f"<!-- concept-records:start (generated by {GEN}; do not edit by hand) -->"
END = "<!-- concept-records:end -->"
FOOTER = (f"Generated by {GEN} from ConceptOperations.sysml, CONOPS.md, safety/hazards/ and requirements/. Concept "
          "stage: hazards and requirements are drafts, risk is preliminary.")


# ================================================================ records
def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    sm = sysml_parse.state_machine(SYSML, "OperatingModes")
    text = CONOPS.read_text()
    concern = {m.group(1): (m.group(2).strip(), m.group(3).strip())
               for m in re.finditer(r"^\| (MOD-\d+) \| ([^|]+) \| [^|]+ \| ([^|]+) \|", text, re.M)}
    scen = []
    for m in re.finditer(r"\*\*(SCN-\d+)(?: ([^:*]+))?:\*\* ([^*]+?)(?=\s*\*\*SCN-|\n\n|$)", text, re.S):
        sid, title, body = m.group(1), m.group(2), " ".join(m.group(3).split())
        if not title:
            title = body.split(".")[0]
        scen.append({"id": sid, "title": title.strip(), "text": body, "kind": "nominal" if sid[4] == "0" else
                     "off-nominal"})
    modes = []
    for s in sm["states"]:
        hz = sorted(h for h, r in hazards.items() if s["id"] in (r.get("modes") or []))
        rq = sorted({q for h in hz for q in hazards[h].get("requirement_ids") or []})
        name, worry = concern.get(s["id"], (state_title(s["name"]), ""))
        modes.append({"id": s["id"], "name": name, "doc": s["doc"], "concern": worry, "hazards": hz, "reqs": rq})
    for sc in scen:
        sc["reqs"] = sorted(q for q, r in reqs.items() if sc["id"] in (r["source"].get("scenario_ids") or []))
        sc["hazards"] = sorted({h for q in sc["reqs"] for h in reqs[q]["source"].get("hazard_ids") or []})
    return {"reqs": reqs, "hazards": hazards, "modes": modes, "scen": scen}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def level(d: dict, h: str) -> str:
    return (d["hazards"].get(h, {}).get("initial_risk") or {}).get("risk_level", "")


# ================================================================ figure 6 · modes (drawn directly)
def fig_modes(d: dict) -> str:
    modes = d["modes"]
    W, M = 1120, 40
    covered = sum(1 for m in modes if m["hazards"])
    head, y0 = fk.header(
        W, "6", "Operating modes and what rests on each",
        f"The {len(modes)} modes of the CONOPS with their safety concern, the hazards recorded as occurring in each "
        f"and the requirements those hazards trace to. {covered} of {len(modes)} modes carry at least one hazard.",
        "concept/ConceptOperations.sysml · safety/hazards")
    out = list(head)
    cx = {"id": M, "name": M + 80, "concern": M + 270, "hz": M + 520, "rq": M + 900}
    y = y0 + 30
    for k, lab in (("id", "Mode"), ("name", "Name"), ("concern", "Safe transition concern"), ("hz", "Hazards"),
                   ("rq", "Requirements")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 40
    for n, m in enumerate(modes):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        p, _ = fk.pill(cx["id"], cy - 12, m["id"], TONES["system"][1], color=TONES["system"][0],
                       stroke=TONES["system"][0])
        out += p
        out.append(fk.text(cx["name"], cy - 6, m["name"], size=11, fill=INK, weight=700))
        out.append(fk.text(cx["name"], cy + 8, fk.wrap(m["doc"], 180, 9.5, max_lines=1)[0], size=9.5, fill=MUTED))
        lines = fk.wrap(m["concern"], 240, 10.5, max_lines=2)
        for j, ln in enumerate(lines):
            out.append(fk.text(cx["concern"], cy + (-6 + 13 * j if len(lines) > 1 else 0), ln, size=10.5, fill=INK))
        x, row = cx["hz"], 0
        for h in m["hazards"]:
            t = TONES[LEVEL_TONE.get(level(d, h), "amber")]
            w = fk.pill_w(h)
            if x + w > cx["rq"] - 10:
                x, row = cx["hz"], row + 1
                if row > 1:
                    break
            p, w = fk.pill(x, cy - 12 + (row * 17 - 8.5 if len(m["hazards"]) > 3 else 0), h, t[1], color=t[0],
                           stroke=t[0])
            out += p
            x += w + 4
        if not m["hazards"]:
            out.append(fk.text(cx["hz"], cy, "none recorded", size=10.5, fill=TONES["amber"][0]))
        rq = m["reqs"]
        out.append(fk.text(cx["rq"], cy, (f"{len(rq)}: " + ", ".join(r.replace("SYS-", "") for r in rq[:4])
                                          + (" …" if len(rq) > 4 else "")) if rq else "–", size=10,
                           fill=INK if rq else FAINT))
    y += len(modes) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["red"][1], TONES["red"][0], "Hazard, High initial risk"),
           (TONES["safety"][1], TONES["safety"][0], "Serious"), (TONES["amber"][1], TONES["amber"][0], "Medium"),
           (TONES["system"][1], TONES["system"][0], "Operating mode")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " Requirements are listed by number (SYS-nnn).", W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 6 · Operating modes and what rests on each",
                  "Each CONOPS mode with its concern, hazards and requirements", out)


# ================================================================ figure 7 · scenarios (ELK)
def fig_scenarios(d: dict) -> dict:
    nodes = [{"id": "SC", "banner": "CONOPS scenarios", "tone": "work"},
             {"id": "RQ", "banner": "Requirements · source.scenario_ids", "tone": "work"},
             {"id": "HZ", "banner": "Hazards they control", "tone": "work"}]
    edges, used_r, used_h = [], [], []
    for s in d["scen"]:
        nodes.append({"id": mid(s["id"]), "parent": "SC", "code": s["id"], "title": s["title"], "sub": s["kind"],
                      "tone": "system" if s["kind"] == "nominal" else "amber", "maxw": 230,
                      "legend": "Nominal scenario" if s["kind"] == "nominal" else "Off-nominal scenario"})
        for q in s["reqs"]:
            edges.append({"src": mid(s["id"]), "dst": mid(q), "label": ""})
            if q not in used_r:
                used_r.append(q)
    for q in sorted(used_r):
        nodes.append({"id": mid(q), "parent": "RQ", "code": q, "title": d["reqs"][q]["title"], "tone": "work",
                      "maxw": 220})
        for h in d["reqs"][q]["source"].get("hazard_ids") or []:
            edges.append({"src": mid(q), "dst": "h_" + mid(h), "label": "", "tone": "safety"})
            if h not in used_h:
                used_h.append(h)
    for h in sorted(used_h):
        lv = level(d, h)
        nodes.append({"id": "h_" + mid(h), "parent": "HZ", "code": h, "title": d["hazards"][h].get("title", h),
                      "sub": f"initial {lv} (preliminary)", "tone": LEVEL_TONE.get(lv, "amber"), "maxw": 230,
                      "legend": f"Hazard, {lv} initial risk"})
    orphan = [s["id"] for s in d["scen"] if not s["reqs"]]
    return {"file": "fig-7-scenarios.svg", "number": "7", "title": "Scenarios traced to requirements and hazards",
            "subtitle": "Each CONOPS scenario linked to the requirements that name it and the hazards those control. "
                        + (f"No requirement names {', '.join(orphan)} yet." if orphan else
                           "Every scenario is named by a requirement."),
            "ref": "concept/CONOPS.md · requirements/", "direction": "RIGHT", "orient": "fixed", "nodes": nodes,
            "edges": edges, "footer": FOOTER,
            "legend": [edge_leg("Requirement names the scenario"), edge_leg("Requirement controls hazard",
                                                                              tone="safety")]}


# ================================================================ README section
def section(d: dict) -> str:
    modes, scen = d["modes"], d["scen"]
    empty_m = [m["id"] for m in modes if not m["hazards"]]
    empty_s = [s["id"] for s in scen if not s["reqs"]]
    out = [START, "",
           "## Modes and scenarios in the records\n",
           "Figures 6 and 7 are generated from the records, so they show what the safety work currently says about "
           "each mode and scenario. A gap here is a prompt for the hazard analysis, not a finding.\n",
           "![Figure 6 · Operating modes and what rests on each](figures/records/fig-6-modes.svg)\n",
           "| Mode | Name | Concern | Hazards | Requirements |", "|---|---|---|---|---|",
           *[f"| {m['id']} | {m['name']} | {m['concern']} | "
             f"{', '.join(f'[{h}](../safety/hazards/{h}.yaml)' for h in m['hazards']) or '—'} | "
             f"{', '.join(m['reqs']) or '—'} |" for m in modes], "",
           "![Figure 7 · Scenarios traced to requirements and hazards](figures/records/fig-7-scenarios.svg)\n",
           "| Scenario | Kind | Title | Requirements | Hazards |", "|---|---|---|---|---|",
           *[f"| {s['id']} | {s['kind']} | {s['title']} | "
             f"{', '.join(f'[{q}](../requirements/{q}.yaml)' for q in s['reqs']) or '—'} | "
             f"{', '.join(s['hazards']) or '—'} |" for s in scen], ""]
    if empty_m or empty_s:
        out.append("**Not yet covered by the records:** "
                   + "; ".join(x for x in (f"modes {', '.join(empty_m)} carry no hazard" if empty_m else "",
                                           f"scenarios {', '.join(empty_s)} are named by no requirement"
                                           if empty_s else "") if x) + ".\n")
    out += [f"Regenerate with `python3 {GEN}`.", "", END]
    return "\n".join(out)


def with_section(text: str, sec: str) -> str:
    if START in text and END in text:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _m: sec, text, count=1, flags=re.S)
    i = text.index("## Inputs and outputs")
    return text[:i] + sec + "\n\n" + text[i:]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = load()
    spec = fig_scenarios(d)
    spec["edges"] = [dict(e) for e in spec["edges"]]
    spec["legend"] = [tuple(x) for x in spec["legend"]]
    files = {FIGS / "fig-6-modes.svg": fig_modes(d), FIGS / spec["file"]: diagram.render_all([spec])[0],
             README: with_section(README.read_text(), section(d))}
    return emit(files, FIGS, args.check, GEN)


if __name__ == "__main__":
    sys.exit(main())
