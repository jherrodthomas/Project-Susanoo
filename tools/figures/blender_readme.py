# ================================================================ SysML and ELK figures
def fig_sysml(d: dict) -> tuple[dict, str]:
    nodes = [{"id": "Shot", "shape": "class", "title": "Shot", "stereotype": "part def",
              "attrs": ["sourceLayout : String", "cameraOffsetM : Real [3]", "lookFraction : Real", "lensMm : Real"],
              "tone": "system"},
             {"id": "Still", "shape": "class", "title": "BlenderStill", "stereotype": "part def",
              "attrs": ["fileName : String", "livery : String", "widthPx : Integer", "heightPx : Integer",
                        "part shot : Shot"], "tone": "work"},
             {"id": "Clip", "shape": "class", "title": "WalkClip", "stereotype": "part def",
              "attrs": ["fileName : String", "livery : String", "loaded : Boolean", "seconds : Real"], "tone": "external"}]
    edges = [{"src": "Still", "dst": "Shot", "label": "shot", "arrow": "diamond"}]
    s = ["    part def Shot {", "        doc /* A camera on the walker: offset from the footprint centre, look height, lens. */",
         "        attribute sourceLayout : String;", "        attribute cameraOffsetM : Real [3];",
         "        attribute lookFraction : Real;", "        attribute lensMm : Real;", "    }",
         "    part def BlenderStill {", "        attribute fileName : String;", "        attribute livery : String;",
         "        attribute widthPx : Integer;", "        attribute heightPx : Integer;", "        part shot : Shot;", "    }",
         "    part def WalkClip {", "        attribute fileName : String;", "        attribute livery : String;",
         "        attribute loaded : Boolean;", "        attribute seconds : Real;", "    }"]

    def nm(prefix: str, f: str) -> str:
        return prefix + re.sub(r"\W", "", f.rsplit(".", 1)[0].title())
    for st in d["stills"]:
        if not st["exists"]:
            continue
        s += [f"    part {nm('still', st['file'])} : BlenderStill {{", f"        attribute :>> fileName = \"{st['file']}\";",
              f"        attribute :>> livery = \"{st['livery']}\";", f"        attribute :>> widthPx = {st['size'][0]};",
              f"        attribute :>> heightPx = {st['size'][1]};", "        part :>> shot {",
              f"            attribute :>> sourceLayout = \"{st['src']}\";",
              "            attribute :>> cameraOffsetM = (" + ", ".join(f"{float(v)}" for v in st["cam"]) + ");",
              f"            attribute :>> lookFraction = {float(st['look'])};",
              f"            attribute :>> lensMm = {float(st['lens'])};", "        }", "    }"]
    for c in d["clips"]:
        s += [f"    part {nm('clip', c['file'])}{c['format'].title()} : WalkClip {{",
              f"        attribute :>> fileName = \"{c['file']}\";", f"        attribute :>> livery = \"{c['livery']}\";",
              f"        attribute :>> loaded = {'true' if c['loaded'] else 'false'};"]
        if c.get("seconds"):
            s.append(f"        attribute :>> seconds = {float(c['seconds'])};")
        s.append("    }")
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — BlenderRenders", "ref": "cad/renders/blender/BlenderRenders.sysml",
            "subtitle": f"A still is a shot in a livery; BlenderRenders.sysml holds the "
                        f"{sum(1 for x in d['stills'] if x['exists'])} stills with their cameras and the "
                        f"{len(d['clips'])} walk clips as parts.",
            "frame": {"kind": "bdd", "type": "package", "name": "BlenderRenders"}, "direction": "RIGHT",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Composition (diamond at owner)"), ("#EEF2FF", "#4F46E5", "Shot"),
                       ("#FFFFFF", "#475569", "Still"), ("#F1F5F9", "#475569", "Walk clip")]}
    sysml = "\n".join([
        f"// BlenderRenders — generated by {GEN} from cad/renders/blender.",
        "// Do not edit by hand: re-render (blender_render.py, blender_walk.py) or change the generator and regenerate.",
        "// Status: renders of placeholder concept geometry, for communication; not a design.", "",
        "package BlenderRenders {",
        "    private import ScalarValues::*;",
        "    doc /* The Blender stills and walk clips of CL-05 (cad/renders/blender/README.md). */",
        *s, "}", ""])
    return spec, sysml


