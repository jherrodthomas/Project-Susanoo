        f"| Walk clips | [`blender_walk.py`](../../../tools/cad/blender_walk.py): {d['walk'].get('fps', '?')} fps, "
        f"default livery {d['walk'].get('livery', '?').strip(chr(34))}, `--loaded` for the carry walk |",
        "| Needs | `bpy` (Blender as a Python module); run locally by `tools/cad/make.sh`, committed, not re-rendered in CI |",
        "| SysML | [`BlenderRenders.sysml`](BlenderRenders.sysml) (generated) |", "",
