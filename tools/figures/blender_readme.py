def literal(src: str, name: str):
    tree = ast.parse(src)
    for n in tree.body:
        if isinstance(n, ast.Assign) and any(getattr(t, "id", "") == name for t in n.targets):
            return ast.literal_eval(n.value)
    raise KeyError(name)


def mp4_seconds(p: Path) -> float | None:
    b = p.read_bytes()
    i = b.find(b"mvhd")
    if i < 0:
        return None
    v = b[i + 4]
    if v == 1:
        ts, dur = struct.unpack(">IQ", b[i + 24:i + 36])
    else:
        ts, dur = struct.unpack(">II", b[i + 16:i + 24])
    return round(dur / ts, 1) if ts else None


def gif_frames(p: Path) -> tuple[int, float, tuple[int, int]]:
    b = p.read_bytes()
    w, h = struct.unpack("<HH", b[6:10])
    n, delay = 0, 0
    i = 0
    while True:
        i = b.find(b"\x21\xf9\x04", i)
        if i < 0:
            break
        delay += struct.unpack("<H", b[i + 4:i + 6])[0]
        n += 1
        i += 8
    return n, round(delay / 100, 1), (w, h)


def walk_options() -> dict:
    src = WALK.read_text()
    return {m.group(1): m.group(2) for m in re.finditer(r'add_argument\("--(\w+)"[^)]*?default=([^,)]+)', src)}


def tracked() -> dict[str, str]:
    import subprocess
    files = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split()
    out = {}
    for f in files:
        if f.startswith("cad/renders/blender/README") or f == "docs/wiki/Blender-Renders.md":
            continue
        if not (f.endswith(".md") or f == "tools/readme/build_readme.py"):
            continue
        t = (ROOT / f).read_text(errors="ignore")
        if "blender" in t:
            out[f] = t
    return out


def shown_by(f: str) -> str | None:
    if f == "cad/renders/README.md":
        return f
    return consumer_of(f)


def load() -> dict:
    ctx, _, _ = load_reqs()
    src = RENDER.read_text()
    shots = literal(src, "SHOTS")
    finish = literal(src, "FINISH")
    liveries = literal(src, "LIVERIES")
    samples = re.search(r'"--samples", type=int, default=(\d+)', src).group(1)
    size = re.search(r"size=\((\d+), (\d+)\)", src).groups()
    pages = tracked()
    stills = []
    for shot, spec in shots.items():
        for lv in liveries:
            name = "-".join(spec["src"].split("-")[:2]) + f"-{shot}" + ("" if lv == "industrial" else f"-{lv}") + ".jpg"
            p = FOLDER / name
            stills.append({"file": name, "shot": shot, "livery": lv, **spec, "exists": p.exists(),
                           "size": jpg_size(p) if p.exists() else None,
                           "kb": round(p.stat().st_size / 1024) if p.exists() else 0,
                           "shown": sorted({c for f, t in pages.items() if name in t and (c := shown_by(f))})})
    clips = []
    for p in sorted(FOLDER.glob("CL-05-walk*")):
        if p.suffix not in (".mp4", ".gif"):
            continue
        c = {"file": p.name, "format": p.suffix[1:], "kb": round(p.stat().st_size / 1024),
             "loaded": "-loaded" in p.name, "livery": next((lv for lv in liveries if f"-{lv}" in p.name), "industrial"),
             "shown": sorted({cs for f, t in pages.items() if p.name in t and (cs := shown_by(f))})}
        if p.suffix == ".mp4":
            c["seconds"] = mp4_seconds(p)
        else:
            c["frames"], c["seconds"], c["size"] = gif_frames(p)
        clips.append(c)
    expected = {s["file"] for s in stills} | {c["file"] for c in clips}
    extra = sorted(p.name for p in FOLDER.iterdir() if p.suffix in (".jpg", ".mp4", ".gif", ".png") and p.name not in expected)
    return {"ctx": ctx, "shots": shots, "finish": finish, "liveries": liveries, "stills": stills, "clips": clips,
            "extra": extra, "samples": int(samples), "size": tuple(int(x) for x in size), "walk": walk_options(),
            "root": next(k for k, v in ctx.nodes.items() if not v.get("parent") and v.get("kind") != "external")}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else ('es' if word.endswith(('s', 'sh', 'ch')) else 's')}"


def srgb(c) -> str:
    """Linear RGB (as Blender takes it) to an sRGB hex for the swatch."""
    def enc(v):
        v = max(0.0, min(1.0, v))
        return 12.92 * v if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055
    return "#" + "".join(f"{round(enc(v) * 255):02x}" for v in c)


