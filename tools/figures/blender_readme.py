def fig_register(d: dict) -> str:
    W, M = 1240, 40
    st, cl = d["stills"], d["clips"]
    unshown = [s["file"] for s in st if s["exists"] and not s["shown"]]
    head, y0 = fk.header(
        W, "1", "Every still and clip",
        f"{len(d['shots'])} shots × {len(d['liveries'])} liveries = {plural(len(st), 'still')} at "
        f"{d['size'][0]}×{d['size'][1]} and {d['samples']} samples, and {plural(len(cl), 'walk clip')}. Camera offsets "
        f"are from the walker's footprint centre; the look point is a fraction of its height. "
        f"{len(unshown)} shown by no page.", "cad/renders/blender")
    out = list(head)
    cols = [("Shot", 120), ("Source layout", 150), ("Camera (m) · look · lens", 250)] + \
           [(lv, 170) for lv in d["liveries"]]
    xs, x = [], M
    for _, w in cols:
        xs.append(x)
        x += w
    y = y0 + 22
    for (h, _), cx in zip(cols, xs):
        out.append(fk.text(cx, y, h, size=10.5, fill=MUTED, weight=700))
    y += 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 48
    for n, (shot, spec) in enumerate(d["shots"].items()):
        yy = y + n * rh
        if n % 2:
            out.append(fk.rect(M, yy + 1, W - 2 * M, rh, fill="#F8FAFC", stroke="none", rx=0, sw=0))
        out.append(fk.text(xs[0], yy + 28, shot, size=11.5, fill=INK, weight=700, mono=True))
        out.append(fk.text(xs[1], yy + 28, spec["src"], size=10.5, fill=INK, mono=True))
        cam = ", ".join(f"{v:g}" for v in spec["cam"])
        out.append(fk.text(xs[2], yy + 22, f"({cam})", size=10, fill=INK, mono=True))
        out.append(fk.text(xs[2], yy + 37, f"look {spec['look']:g} of height · {spec['lens']} mm", size=9.5, fill=MUTED))
        for j, lv in enumerate(d["liveries"]):
            s = next(s for s in st if s["shot"] == shot and s["livery"] == lv)
            bx = xs[3 + j]
            if not s["exists"]:
                tone, lab = ("#FEE2E2", "#B91C1C"), "missing"
            elif s["shown"]:
                tone, lab = ("#DCFCE7", "#15803D"), f"{len(s['shown'])} page" + ("s" if len(s["shown"]) > 1 else "")
            else:
                tone, lab = ("#FEF3C7", "#B45309"), "no page"
            out.append(fk.rect(bx, yy + 8, 150, 32, fill=tone[0], stroke=tone[1], rx=5, sw=1.1,
                               dash="" if s["exists"] and s["shown"] else "4 3"))
            out.append(fk.text(bx + 75, yy + 21, lab, size=10, fill=tone[1], weight=700, anchor="middle"))
            if s["size"]:
                out.append(fk.text(bx + 75, yy + 34, f"{s['size'][0]}×{s['size'][1]} · {s['kb']} KB", size=8.5,
                                   fill=MUTED, anchor="middle", mono=True))
    y += len(d["shots"]) * rh + 18
    out.append(fk.text(M, y, f"Walk clips (blender_walk.py: {d['walk'].get('fps', '?')} fps, "
                             f"{d['walk'].get('size', '?').strip(chr(34))}, {d['walk'].get('cycles', '?')} cycles, "
                             f"{d['walk'].get('samples', '?')} samples)", size=12, fill=INK, weight=700))
    y += 12
    for n, c in enumerate(cl):
        yy = y + n * 34
        out.append(fk.text(M, yy + 22, c["file"], size=10.5, fill=INK, mono=True, weight=700))
        desc = (f"{'loaded' if c['loaded'] else 'unloaded'} walk · {c['livery']} · {c['format']} · "
                + (f"{c['seconds']:g} s" if c.get("seconds") else "")
                + (f" · {c['frames']} frames at {c['size'][0]}×{c['size'][1]}" if c.get("frames") else "")
                + f" · {c['kb']:,} KB")
        out.append(fk.text(M + 330, yy + 22, desc, size=10, fill=MUTED))
        p, _ = fk.pill(W - M - 90, yy + 10, f"{len(c['shown'])} pages" if c["shown"] else "no page",
                       "#DCFCE7" if c["shown"] else "#FEF3C7", color="#15803D" if c["shown"] else "#B45309")
        out += p
    y += len(cl) * 34 + 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 22
    leg = [("#DCFCE7", "#15803D", "Shown by a page (count)"), ("#FEF3C7", "#B45309", "Rendered, shown by no page"),
           ("#FEE2E2", "#B91C1C", "Expected, not rendered")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    if d["extra"]:
        out.append(fk.text(M, y + 4, "Files no shot or clip explains: " + ", ".join(d["extra"]), size=10.5, fill="#B45309"))
        y += 18
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Every still and clip",
                  "Every Blender shot in every livery and every walk clip, with camera, size and the pages that show it", out)


