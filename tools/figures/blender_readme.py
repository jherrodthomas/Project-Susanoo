def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    block = fig_block(ctx, {"scope": [d["root"]]})
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"The system the renders show ({d['root']}): the walker, its dock and the docked UAV.")
    boundary = fig_boundary(ctx, {"path": "cad/renders/blender", "boundary": {
        "name": "Blender renders", "inside": ["Stills", "Walk clips"],
        "outside": ["CAD meshes", "Walk frames", "Blender (bpy)", "Review pages", "Front page", "Concept art"],
        "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="cad/renders/blender/README.md",
                    subtitle="The folder holds the stills and clips; the meshes and walk frames they are rendered "
                             "from, Blender itself and the pages that show them are outside. Crossings are numbered as "
                             "in the table.")
    sysml_spec, sysml = fig_sysml(d)
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "cad/renders/blender/README.md", "direction": "RIGHT",
          "subtitle": "What the renders are made from (left) and where they are shown (right).",
          "nodes": [
              {"id": "I1", "title": "CAD meshes", "sub": "build_concepts.py, cl05.py", "tone": "software"},
              {"id": "I2", "title": "Finishes and shots", "sub": "blender_render.py", "tone": "software"},
              {"id": "I3", "title": "Walk frames", "sub": "cl05.py --walk, blender_walk.py", "tone": "software"},
              {"id": "X", "code": "cad/renders/blender/", "title": "Blender renders",
               "sub": f"{sum(1 for x in d['stills'] if x['exists'])} stills, {len(d['clips'])} clips", "tone": "current"},
              *[{"id": f"O{i}", "title": lab, "sub": key, "tone": "work"} for i, (key, lab) in enumerate(SHOWN_BY, 1)]],
          "edges": [{"src": "I1", "dst": "X", "label": "meshes"}, {"src": "I2", "dst": "X", "label": "stills"},
                    {"src": "I3", "dst": "X", "label": "clips"},
                    *[{"src": "X", "dst": f"O{i}", "label": "shown"} for i in range(1, len(SHOWN_BY) + 1)]]}
    specs = [block, boundary, sysml_spec, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    return specs, sysml


