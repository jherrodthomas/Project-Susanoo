# ================================================================ records
def load() -> dict:
    ctx, _, hazards = load_reqs()
    spec = yaml.safe_load((ROOT / "sim" / "spec" / "walker.yaml").read_text())
    res = json.loads((ROOT / "sim" / "results" / "plant-results.json").read_text())
    doc = (FOLDER / "walker.py").read_text().split('"""')[1]
    assumptions = [{"id": m.group(1), "text": " ".join(m.group(2).split())}
                   for m in re.finditer(r"^(A\d)\s+(.*?)(?=^A\d\s|\Z)", doc, re.M | re.S)]
    params = spec["params"]
    cases = defaultdict(dict)
    for r in res["runs"]:
        cases[r["fault"]][(r["config"], r["slope_deg"])] = r
    cfs = {}
    for f in res["faults"]:
        for ref in f["causes"]:
            hid, cf = ref.split(":")
            h = hazards.get(hid, {})
            desc = next((c.get("description", "") for c in h.get("causal_factors") or [] if c["id"] == cf), "")
            cfs[ref] = {"hazard": hid, "cf": cf, "text": desc}
    hz = sorted({c["hazard"] for c in cfs.values()})
    subs = sorted({s for h in hz for s in hazards.get(h, {}).get("subsystems") or []})
    return {"ctx": ctx, "hazards": hazards, "spec": spec, "params": params, "res": res, "assumptions": assumptions,
            "cases": cases, "configs": [c for c, _ in plant_report.CONFIGS], "config_over": dict(plant_report.CONFIGS),
            "slopes": plant_report.SLOPES, "cfs": cfs, "hz": hz, "subs": subs}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


# ================================================================ figure 1 · outcomes (drawn directly)
def fig_outcomes(d: dict) -> str:
    res, configs, slopes = d["res"], d["configs"], d["slopes"]
    W, M = 1240, 40
    head, y0 = fk.header(
        W, "1", "What each mitigation buys",
        f"Every fault in the catalogue in {len(configs)} configurations on flat ground and an {slopes[-1]:g}° slope, "
        "from the committed plant results: the outcome and the robustness margin rho (negative: margin exhausted). "
        "Below, how steep the walker can stand without any fault.", "sim/results/plant-results.json")
    out = list(head)
    x0 = M + 300
    cw = (W - M - x0) / (len(configs) * len(slopes))
    y = y0 + 26
    for i, c in enumerate(configs):
        out.append(fk.text(x0 + i * cw * len(slopes) + 6, y, c, size=10.5, fill=INK, weight=700))
    y += 16
    for i, c in enumerate(configs):
        for j, s in enumerate(slopes):
            out.append(fk.text(x0 + (i * len(slopes) + j) * cw + 6, y, f"{s:g}°", size=10, fill=MUTED))
    y += 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 50
    for n, f in enumerate(res["faults"]):
        top = y + 6 + n * rh
        if n % 2:
            out.append(fk.rect(M, top, W - 2 * M, rh - 4, fill=GREY_BG, stroke="none", rx=6, sw=0))
        p, w = fk.pill(M + 6, top + 8, f["id"], TONES["safety"][1], color=TONES["safety"][0], stroke=TONES["safety"][0])
        out += p
        out.append(fk.text(M + 6 + w + 8, top + 20, fk.wrap(f["name"], 300 - w - 20, 11, True, max_lines=1)[0],
                           size=11, fill=INK, weight=700))
        out.append(fk.text(M + 6, top + 38, fk.wrap(f"{f['variant']} · {', '.join(f['causes'])}", 290, 9,
                                                    max_lines=1)[0], size=9, fill=MUTED))
        for i, c in enumerate(configs):
            for j, s in enumerate(slopes):
                r = d["cases"][f["id"]].get((c, float(s)))
                x = x0 + (i * len(slopes) + j) * cw
                if not r:
                    continue
                t = TONES[OUT_TONE.get(r["outcome"], "amber")]
                out.append(fk.rect(x + 3, top + 4, cw - 6, rh - 12, fill=t[1], stroke=t[0], rx=6, sw=1))
                out.append(fk.text(x + cw / 2, top + 21, r["outcome"], size=10, fill=t[0], weight=700, anchor="middle"))
                out.append(fk.text(x + cw / 2, top + 35, f"rho {r['rho']:+.2f}", size=9.5, fill=INK, anchor="middle"))
    y += 6 + len(res["faults"]) * rh + 10
    out.append(fk.text(M, y + 14, "No fault: margin by slope", size=11, fill=INK, weight=700))
    nom = res["nominal"]
    bw = (W - M - x0) / len(nom)
    base = y + 70
    for k, nrec in enumerate(nom):
        x = x0 + k * bw
        t = TONES[OUT_TONE.get(nrec["outcome"], "amber")]
        h = max(2, 50 * max(nrec["rho"], 0) / max(x["rho"] for x in nom))
        out.append(fk.rect(x + 8, base - h, bw - 16, h, fill=t[0], stroke="none", rx=3, sw=0))
        out.append(fk.text(x + bw / 2, base + 14, f"{nrec['slope_deg']}°", size=10, fill=MUTED, anchor="middle"))
        out.append(fk.text(x + bw / 2, base - h - 4, nrec["outcome"] if nrec["outcome"] != "safe" else f"{nrec['rho']:.2f}",
                           size=9.5, fill=t[0], anchor="middle", weight=700 if nrec["outcome"] != "safe" else ""))
    out.append(fk.line(x0, base, W - M, base, stroke=HAIR, sw=1))
    y = base + 28
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["ok"][1], TONES["ok"][0], "Safe (run ends stopped, no mishap)"),
           (TONES["red"][1], TONES["red"][0], "Mishap: tip or hard drop"),
           (TONES["safety"][1], TONES["safety"][0], "Fault (sim/faults.yaml)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " A mishap ends the run; contact is not modelled.", W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · What each mitigation buys",
                  "Every plant fault case and the no-fault slope limit", out)


# ================================================================ ELK figures and SysML
def fig_trace(d: dict) -> dict:
    nodes = [{"id": "F", "banner": "Faults", "tone": "work"}, {"id": "C", "banner": "Causal factors", "tone": "work"},
             {"id": "H", "banner": "Hazards", "tone": "work"}]
    edges = []
    for f in d["res"]["faults"]:
        runs = list(d["cases"][f["id"]].values())
        bad = sum(1 for r in runs if r["outcome"] != "safe")
        nodes.append({"id": mid(f["id"]), "parent": "F", "code": f["id"], "title": f["name"],
                      "sub": f"{bad} of {len(runs)} cases end in a mishap", "tone": "safety", "maxw": 230,
                      "legend": "Fault"})
        for ref in f["causes"]:
            edges.append({"src": mid(f["id"]), "dst": "cf_" + mid(ref), "label": ""})
    for ref, c in d["cfs"].items():
        nodes.append({"id": "cf_" + mid(ref), "parent": "C", "code": f"{c['hazard']} {c['cf']}",
                      "title": c["text"] or ref,
                      "tone": "system", "maxw": 260, "legend": "Causal factor"})
        edges.append({"src": "cf_" + mid(ref), "dst": "h_" + mid(c["hazard"]), "label": ""})
    for h in d["hz"]:
        x = d["hazards"].get(h, {})
        lv = (x.get("initial_risk") or {}).get("risk_level", "")
        nodes.append({"id": "h_" + mid(h), "parent": "H", "code": h, "title": x.get("title", h),
                      "sub": f"initial {lv} (preliminary)", "tone": LEVEL_TONE.get(lv, "amber"), "maxw": 220,
                      "legend": f"Hazard, {lv} initial risk"})
    return {"file": "fig-2-fault-trace.svg", "number": "2", "title": "What each fault realises",
            "subtitle": "Each fault in the catalogue traced to the hazard causal factors it realises (checked by "
                        "report.py: every one must exist), and on to the hazards.",
            "ref": "sim/faults.yaml · safety/hazards", "direction": "RIGHT", "orient": "fixed", "nodes": nodes,
            "edges": edges, "legend": [edge_leg("Realises / belongs to")]}


def fig_sysml(d: dict) -> tuple[dict, str]:
    params = d["params"]
    attrs = [f"{camel(n)} : Real = {p['value']:g}  [{p['unit']}]" for n, p in params.items()]
    nodes = [{"id": "WalkerPlant", "shape": "class", "title": "WalkerPlant", "stereotype": "part def",
              "attrs": attrs, "tone": "system"},
             {"id": "FaultCase", "shape": "class", "title": "FaultCase", "stereotype": "part def",
              "attrs": [f"{a} : {t}" for a, t in CASE_ATTRS] + ["ref plant : WalkerPlant"], "tone": "safety"}]
    edges = [{"src": "FaultCase", "dst": "WalkerPlant", "label": "plant", "dash": True}]
    s = ["    part def WalkerPlant {",
         f"        doc /* {d['spec']['id']} revision {d['spec']['revision']}: reduced-order plant parameters; "
         "every value an assumption, not a design value. */",
         *[f"        attribute {camel(n)} : Real = {float(p['value'])};  // {p['unit']}, {p['status']}"
           for n, p in params.items()], "    }",
         "    part def FaultCase {",
         "        doc /* One run of the fault catalogue: a fault, a configuration of the mitigations and a slope. */",
         *[f"        attribute {a} : {t};" for a, t in CASE_ATTRS],
         "        ref part plant : WalkerPlant;", "    }"]
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — WalkerPlant", "ref": "sim/plant/WalkerPlant.sysml",
            "subtitle": f"The {len(params)} plant parameters of {d['spec']['id']} with their values, and the fault case "
                        "that runs the plant, generated into WalkerPlant.sysml from the spec.",
            "frame": {"kind": "bdd", "type": "package", "name": "WalkerPlant"}, "direction": "RIGHT",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Reference (ref part)", True), ("#EEF2FF", "#4F46E5", "Plant parameters"),
                       ("#FFF7ED", "#C2410C", "Fault case")]}
    sysml = "\n".join([
        f"// WalkerPlant — generated by {GEN} from sim/spec/walker.yaml.",
        "// Do not edit by hand: change the spec or the generator and regenerate.",
        "// Status: reduced-order plant assumptions; synthetic, no evidence credit.", "",
        "package WalkerPlant {",
        "    private import ScalarValues::*;",
        "    doc /* The level-1 walker plant (sim/plant/README.md). */",
        *s, "}", ""])
    return spec, sysml


