#!/usr/bin/env python3
"""Render hand-authored figure specs (`<folder>/figures.yaml`) to `<folder>/figures/*.svg`.

Used by folders whose README is written by hand (concept/, integrations/px4/, framework/). The generated
MIL-STD-882E tree uses tools/gen_safety_docs.py instead; both share the same figure kit, so every figure in the
repository has one look.

figures.yaml:

    footer: optional default footer
    figures:
      - file: fig-1-block.svg            # written to <folder>/figures/
        number: "1"
        title: ...
        subtitle: ...
        ref: ...
        direction: RIGHT | DOWN
        orient: fixed                    # optional: keep direction even if wide
        frame: {kind, type, name}        # optional SysML frame
        nodes: [{id, title, ...}]        # as tools/figures/diagram.py
        edges: [[src, dst, label], ...] or [{src, dst, label, code, tone, dash, arrow}]
        legend: [[fill, stroke, label]]
        stm_from: {file: X.sysml, state_def: Name, package: Pkg}   # states/transitions read from the model

    python3 tools/figures/build_figures.py            # write
    python3 tools/figures/build_figures.py --check    # fail if stale
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT))
import diagram  # noqa: E402
import sysml_parse  # noqa: E402
from gen_safety_docs import state_title, stm_frag  # noqa: E402
from tools.terms.terms import decorate  # noqa: E402

FOLDERS = ["concept", "integrations/px4", "framework"]


def normalise(spec: dict, folder: str, footer: str) -> dict:
    spec = dict(spec)
    if spec.get("stm_from"):
        src = spec.pop("stm_from")
        sm = sysml_parse.state_machine(ROOT / folder / src["file"], src["state_def"])
        states = [{"name": s["name"], "id": s["id"], "doc": s["doc"], "title": state_title(s["name"]),
                   "tone": src.get("tones", {}).get(s["name"], "system")} for s in sm["states"]]
        frag = stm_frag(f"{src.get('package', '')}::{src['state_def']}".lstrip(":"), states, sm["initial"],
                        sm["transitions"], src.get("final", []))
        spec = {**frag, **spec}
    edges = []
    for e in spec.get("edges", []):
        if isinstance(e, list):
            d = {"src": e[0], "dst": e[1], "label": e[2] if len(e) > 2 else ""}
            if len(e) > 3:
                d.update(e[3])
            e = d
        edges.append(e)
    spec["edges"] = edges
    spec["legend"] = [tuple(x) for x in spec.get("legend", [])]
    spec.setdefault("footer", footer)
    return spec


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    jobs, specs = [], []
    for folder in FOLDERS:
        cfg_path = ROOT / folder / "figures.yaml"
        if not cfg_path.exists():
            continue
        cfg = yaml.safe_load(cfg_path.read_text())
        footer = cfg.get("footer", f"Generated by tools/figures/build_figures.py from {folder}/figures.yaml.")
        for spec in cfg["figures"]:
            jobs.append(ROOT / folder / "figures" / spec["file"])
            specs.append(normalise(spec, folder, footer))
    stale = []
    for path, svg in zip(jobs, diagram.render_all(specs)):
        svg = decorate(path.relative_to(ROOT).as_posix(), svg)
        if path.exists() and path.read_text() == svg:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(svg)
            print(f"wrote {path.relative_to(ROOT)}")
    for folder in FOLDERS:
        figdir = ROOT / folder / "figures"
        if figdir.exists():
            for old in figdir.glob("*.svg"):
                if old not in jobs:
                    stale.append(str(old.relative_to(ROOT)) + " (orphan)") if args.check else old.unlink()
    if stale:
        print("Stale figures (run python3 tools/figures/build_figures.py):\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
