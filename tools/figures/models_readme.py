# ================================================================ records
def doc_views() -> list[Path]:
    """The documentation .sysml files tools/validate_doc_sysml.sh validates, read from that script."""
    script = (ROOT / "tools" / "validate_doc_sysml.sh").read_text()
    line = next(ln for ln in script.splitlines() if ln.startswith("FILES=("))
    fixed = [ROOT / w for w in re.findall(r"([\w/.-]+\.sysml)", line)]
    tree = sorted((ROOT / "safety" / "mil-std-882e").rglob("*.sysml"))
    return fixed + tree


def sysml_info(p: Path) -> dict:
    text = p.read_text()
    pkg = re.search(r"^\s*(?:standard library )?package (\w+)", text, re.M)
    imports = sorted(set(re.findall(r"\bimport (\w+)::", text)))
    counts = {k: len(re.findall(rx, text, re.M)) for k, rx in KINDS}
    gen = "generated by" in "\n".join(text.splitlines()[:3]).lower()
    return {"path": p.relative_to(ROOT).as_posix(), "package": pkg.group(1) if pkg else p.stem, "imports": imports,
            "counts": counts, "lines": len(text.splitlines()), "generated": gen}


def group_of(path: str) -> str:
    if path.startswith("safety/mil-std-882e/"):
        return "882E work-product views"
    if path.startswith("sim/uav/"):
        return "PX4 observed modes"
    if path.startswith("sim/plant/"):
        return "Walker plant parameters"
    if path.startswith("sim/search/"):
        return "Failure search method"
    if path.startswith("sim/mujoco/"):
        return "Level-2 walker"
    if path.startswith("sim/trades/"):
        return "Supply-loss modes"
    if path.startswith("sim/spec/"):
        return "Plant spec structure"
    if path.startswith("sim/results/"):
        return "Result sets"
    if path.startswith("sim/scenes3d/"):
        return "3D scenes"
    return {"concept": "Concept operations", "integrations": "PX4 integration", "decisions": "Decision register",
            "sim": "Simulation evidence gate", "framework": "Lifecycle gates", "tools": "Docs check (CI)", "docs": "Generated file states", "cad": "Concept layouts"}.get(path.split("/")[0], path.split("/")[0])


def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    model = [sysml_info(MODEL_DIR / f) for f in MODEL_FILES]
    docs = [sysml_info(p) for p in doc_views()]
    return {"ctx": ctx, "reqs": reqs, "hazards": hazards, "model": model, "docs": docs}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def contents(c: dict) -> str:
    return ", ".join(f"{v} {k}" for k, v in c.items() if v) or "—"


# ================================================================ figure 1 · inventory (drawn directly)
def fig_inventory(d: dict) -> str:
    model, docs = d["model"], d["docs"]
    groups: dict[str, list[dict]] = {}
    for x in docs:
        groups.setdefault(group_of(x["path"]), []).append(x)
    rows = [{"name": x["path"].split("/")[-1], "pkg": x["package"], "by": "generated" if x["generated"] else "hand",
             "lines": x["lines"], "what": contents(x["counts"]),
             "checks": ", ".join(sorted(r for r, (_, f, _) in RULES.items()
                                        if f == x["path"].split("/")[-1])) or "OMG pilot",
             "tone": "software"} for x in model]
    for g, xs in groups.items():
        tot = Counter()
        for x in xs:
            tot.update(x["counts"])
        kinds = {x["generated"] for x in xs}
        by = "generated" if kinds == {True} else "hand" if kinds == {False} else "mixed"
        rows.append({"name": g, "pkg": plural(len(xs), "package"), "by": by, "lines": sum(x["lines"] for x in xs),
                     "what": contents(dict(tot)), "checks": "OMG pilot", "tone": "work"})
    W, M = 1120, 40
    head, y0 = fk.header(
        W, "1", "Model inventory",
        f"The project model ({plural(len(model), 'file')}, {sum(x['lines'] for x in model)} lines) and "
        f"{plural(len(docs), 'documentation view')} that import it. All {len(model) + len(docs)} pass the OMG pilot "
        "in CI; the hand-written files are also checked against the records.", "models/sysml/model/")
    out = list(head)
    cx = {"name": M, "pkg": M + 230, "by": M + 420, "lines": M + 500, "what": M + 560, "checks": M + 900}
    y = y0 + 30
    for k, lab in (("name", "File or group"), ("pkg", "Package"), ("by", "Written"), ("lines", "Lines"),
                   ("what", "Defines (count)"), ("checks", "Checked by")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 36
    for n, r in enumerate(rows):
        top = y + n * rh
        if n == len(model):
            out.append(fk.line(M, top, W - M, top, stroke=FAINT, sw=1))
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["name"], cy, r["name"], size=11, fill=INK, weight=700, mono=n < len(model)))
        out.append(fk.text(cx["pkg"], cy, r["pkg"], size=10.5, fill=MUTED))
        t = TONES["ok" if r["by"] == "generated" else "amber"]
        p, _ = fk.pill(cx["by"], cy - 12, r["by"], t[1], color=t[0], stroke=t[0])
        out += p
        out.append(fk.text(cx["lines"] + 30, cy, str(r["lines"]), size=10.5, fill=INK, anchor="end"))
        lines = fk.wrap(r["what"], 330, 10, max_lines=2)
        for j, ln in enumerate(lines):
            out.append(fk.text(cx["what"], cy + (-6 + 12 * j if len(lines) > 1 else 0), ln, size=10, fill=INK))
        t = TONES["system" if r["checks"] != "OMG pilot" else "external"]
        p, _ = fk.pill(cx["checks"], cy - 12, r["checks"], t[1], color=t[0], stroke=t[0])
        out += p
    y += len(rows) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["amber"][1], TONES["amber"][0], "Hand-written"),
           (TONES["ok"][1], TONES["ok"][0], "Generated from records or catalog"),
           (TONES["system"][1], TONES["system"][0], "Model-versus-record rules (tools/sysml/check.py)"),
           (TONES["external"][1], TONES["external"][0], "SysML v2 conformance only")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Model inventory", "Every model file and view with what it defines and checks",
                  out)


# ================================================================ ELK figures
def fig_checks(d: dict) -> dict:
    item_counts = {"Item definition elements": len([k for k, v in d["ctx"].nodes.items()
                                                    if v.get("kind") != "external"]) - 1,
                   "Item definition externals": len([v for v in d["ctx"].nodes.values() if v.get("kind") == "external"]),
                   "Item definition interfaces": len(d["ctx"].interfaces),
                   "Item definition functions": None,
                   "Requirement records": len(d["reqs"]), "Hazard records": len(d["hazards"])}
    nodes = [{"id": "REC", "banner": "Records · source of truth", "tone": "work"},
             {"id": "MOD", "banner": "Model · models/sysml/model", "tone": "software"},
             {"id": "VW", "banner": "Views · tools/sysml/views.py", "tone": "work"}]
    edges, seen = [], set()
    for rule, (rec, f, what) in RULES.items():
        rid = "r_" + re.sub(r"\W", "_", rec)
        if rid not in seen:
            seen.add(rid)
            n = item_counts.get(rec)
            nodes.append({"id": rid, "parent": "REC", "title": rec, "sub": f"{n} records" if n else "",
                          "tone": "work", "maxw": 220})
        fid = "f_" + f.replace(".", "_")
        if fid not in seen:
            seen.add(fid)
            x = next(m for m in d["model"] if m["path"].endswith(f))
            nodes.append({"id": fid, "parent": "MOD", "code": f, "title": x["package"],
                          "sub": "generated" if x["generated"] else "hand-written", "tone": "software", "maxw": 220})
        edges.append({"src": rid, "dst": fid, "code": rule, "label": what, "tone": "safety"})
    lib = next(m for m in d["model"] if m["path"].endswith("SusanooLibrary.sysml"))
    nodes.append({"id": "f_lib", "parent": "MOD", "code": "SusanooLibrary.sysml", "title": lib["package"],
                  "sub": "vocabulary, metadata; OMG pilot only", "tone": "software", "maxw": 220})
    for vid, title, _ in VIEWS:
        nodes.append({"id": "v_" + vid.replace("-", ""), "parent": "VW", "code": vid, "title": title, "tone": "work",
                      "maxw": 200})
    edges += [{"src": "f_Architecture_sysml", "dst": "v_V02", "label": ""},
              {"src": "f_Satisfaction_sysml", "dst": "v_V07", "label": ""},
              {"src": "f_Architecture_sysml", "dst": "v_V08", "label": ""}]
    return {"file": "fig-2-checks.svg", "number": "2", "title": "How the model is checked against the records",
            "subtitle": "Each rule of tools/sysml/check.py compares a record with a model file on every pull request; "
                        "the views are drawn from the checked model. A finding fails CI.",
            "ref": "tools/sysml/check.py", "direction": "RIGHT", "orient": "fixed", "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Rule compares record with model (code)", tone="safety"),
                       edge_leg("View drawn from")]}


def fig_packages(d: dict) -> dict:
    nodes, edges = [], []
    proj = {x["package"] for x in d["model"]}
    for x in d["model"]:
        nodes.append({"id": "p_" + x["package"], "shape": "class", "title": x["package"], "stereotype": "package",
                      "attrs": [x["path"].split("/")[-1]], "tone": "software"})
        for i in x["imports"]:
            if i in proj and i != x["package"]:
                edges.append({"src": "p_" + x["package"], "dst": "p_" + i, "label": "«import»", "dash": True})
    groups: dict[str, list[dict]] = {}
    for x in d["docs"]:
        groups.setdefault(group_of(x["path"]), []).append(x)
    for g, xs in groups.items():
        gid = "g_" + re.sub(r"\W", "_", g)
        pk = [x["package"] for x in xs]
        nodes.append({"id": gid, "shape": "class", "title": g, "stereotype": "package" if len(xs) == 1 else
                      f"{len(xs)} packages", "attrs": pk if len(pk) <= 3 else pk[:2] + [f"… {len(pk) - 2} more"],
                      "tone": "work"})
        imp = Counter(i for x in xs for i in x["imports"] if i in proj)
        for i, n in sorted(imp.items()):
            edges.append({"src": gid, "dst": "p_" + i, "label": f"«import» ×{n}" if n > 1 else "«import»",
                          "dash": True})
    return {"file": "fig-5-sysml-packages.svg", "number": "5", "title": "SysML packages and imports",
            "subtitle": "The five project packages and the documentation views that import them, read from every "
                        ".sysml file the OMG pilot validates. No view redefines a system part or requirement.",
            "ref": "models/sysml/model/", "frame": {"kind": "pkg", "type": "package", "name": "SusanooModel"},
            "direction": "RIGHT", "nodes": nodes, "edges": edges,
            "legend": [edge_leg("«import» (count of packages)", True), ("#F0FDFA", "#0F766E", "Project model package"),
                       ("#FFFFFF", "#475569", "Documentation views")]}


