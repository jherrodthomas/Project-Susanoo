# ================================================================ records
def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    ssfs = {p.stem: yaml.safe_load(p.read_text()) for p in sorted((FOLDER / "software").glob("SSF-*.yaml"))}
    events = {p.stem: yaml.safe_load(p.read_text()) for p in sorted((FOLDER / "events").glob("EVT-*.yaml"))}
    cat = yaml.safe_load(CATALOG.read_text())
    hts = next(f for f in cat["folders"] if f["id"] == "HTS")
    named: dict[str, list[str]] = {}
    for hid, h in hazards.items():
        for e in h.get("subsystems") or []:
            named.setdefault(e, []).append(hid)
    return {"ctx": ctx, "reqs": reqs, "hazards": hazards, "ssfs": ssfs, "events": events, "hts": hts,
            "named": named}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def summary(c) -> str:
    return ", ".join(f"{n} {k}" for k, n in sorted(Counter(c).items())) or "none"


def ssf_ids(h: dict) -> list[str]:
    out = set()
    for cf in h.get("causal_factors") or []:
        out.update(cf.get("ssf_ids") or [])
    for m in h.get("mitigations") or []:
        out.update(m.get("ssf_ids") or [])
    return sorted(out)


def risk(h: dict, key: str) -> tuple[str, str]:
    r = h.get(key) or {}
    return r.get("rac", "?"), r.get("risk_level", "")


# ================================================================ figure 1 · hazard register (drawn directly)
def fig_register(d: dict) -> str:
    hz = d["hazards"]
    W, M = 1120, 40
    init = Counter(risk(h, "initial_risk")[1] for h in hz.values())
    targ = Counter(risk(h, "target_risk")[1] for h in hz.values())
    head, y0 = fk.header(
        W, "1", "Hazard register",
        f"{plural(len(hz), 'hazard')} ({summary(h['status'] for h in hz.values())}). Initial risk: "
        f"{summary(init)}; target risk after planned mitigation: {summary(targ)}. Preliminary; none accepted.",
        "safety/hazards/HAZ-*.yaml")
    out = list(head)
    cx = {"id": M, "title": M + 118, "status": M + 420, "init": M + 490, "targ": M + 600, "mit": M + 710,
          "req": M + 790, "ssf": M + 850, "evt": M + 910, "acc": M + 990}
    y = y0 + 30
    for k, lab in (("id", "Hazard"), ("title", "Title"), ("status", "Status"), ("init", "Initial risk"),
                   ("targ", "Target risk"), ("mit", "Mitigations"), ("req", "Reqs"), ("ssf", "SSFs"),
                   ("evt", "Event risk"), ("acc", "Accepted")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 34
    for n, (hid, h) in enumerate(hz.items()):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        rac, lvl = risk(h, "initial_risk")
        t = TONES[LEVEL_TONE.get(lvl, "amber")]
        p, _ = fk.pill(cx["id"], cy - 12, hid, t[1], color=t[0], stroke=t[0])
        out += p
        lines = fk.wrap(h.get("title", hid), 290, 11, max_lines=2)
        for j, ln in enumerate(lines):
            out.append(fk.text(cx["title"], cy + (-6 + 13 * j if len(lines) > 1 else 0), ln, size=11, fill=INK))
        out.append(fk.text(cx["status"], cy, h["status"], size=10.5, fill=MUTED))
        for k, key in (("init", "initial_risk"), ("targ", "target_risk")):
            rac, lvl = risk(h, key)
            t = TONES[LEVEL_TONE.get(lvl, "amber")]
            p, w = fk.pill(cx[k], cy - 12, rac, t[1], color=t[0], stroke=t[0])
            out += p
            out.append(fk.text(cx[k] + w + 6, cy, lvl, size=10, fill=t[0]))
        ms = h.get("mitigations") or []
        out.append(fk.text(cx["mit"] + 20, cy, str(len(ms)), size=11, fill=INK, weight=700, anchor="middle"))
        for k, v in (("req", len(h.get("requirement_ids") or [])), ("ssf", len(ssf_ids(h)))):
            out.append(fk.text(cx[k] + 12, cy, str(v) if v else "–", size=11, fill=INK if v else FAINT,
                               weight=700 if v else 400, anchor="middle"))
        ev = h.get("event_risks") or []
        if ev:
            e = ev[0]
            t = TONES[LEVEL_TONE.get(e.get("risk_level"), "amber")]
            p, _ = fk.pill(cx["evt"], cy - 12, e.get("rac", "?"), t[1], color=t[0], stroke=t[0])
            out += p
        else:
            out.append(fk.text(cx["evt"], cy, "–", size=11, fill=FAINT))
        acc = len(h.get("acceptances") or [])
        out.append(fk.text(cx["acc"], cy, "yes" if acc else "no", size=10.5,
                           fill=TONES["ok"][0] if acc else TONES["amber"][0], weight=700))
    y += len(hz) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["red"][1], TONES["red"][0], "High"), (TONES["safety"][1], TONES["safety"][0], "Serious"),
           (TONES["amber"][1], TONES["amber"][0], "Medium"), (TONES["ok"][1], TONES["ok"][0], "Low")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " Pills are risk assessment codes (severity 1–4, probability A–F); event risk is for "
                      "the first event the hazard applies to.", W - 2 * M, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Hazard register",
                  "Every hazard with its preliminary risk and the records that control it", out)


