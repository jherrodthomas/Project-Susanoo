#!/usr/bin/env python3
"""Build safety/README.md and safety/figures/*.svg: the front page of the safety records.

Everything on the page is read from records, so it cannot drift from them:

  safety/hazards/HAZ-*.yaml           the hazard tracking system: risk, mitigations, links, acceptances
  safety/software/SSF-*.yaml          safety-significant software functions
  safety/events/EVT-*.yaml            test and demonstration events
  safety/generated/hts.csv            the generated hazard log export
  safety/mil-std-882e/catalog.yaml    the hazard-record lifecycle (HazardTrackingSystem::HazardRecordStatus)

Figures (house style of framework/documentation-standard.md):

  fig-1-hazard-register.svg       every hazard: status, initial and target risk, mitigations, links, event risk, acceptance
  fig-2-safety-record.svg         how the safety records fit together, with today's counts
  fig-3-block-diagram.svg         SUS-I1 decomposition; elements a hazard names as a subsystem are coloured
  fig-4-boundary-diagram.svg      what the safety records own and what crosses their boundary
  fig-5-sysml-state-machine.svg   SysML state machine of a hazard record, with how many hazards are in each state
  fig-6-inputs-and-outputs.svg    what the safety records consume and feed

The subfolders keep their own pages: hazards/, software/, events/, generated/ (previews, docs/previews.yaml) and
mil-std-882e/ (its own generator). The README part above the END marker is generated; anything below it is preserved.

    python3 tools/figures/safety_readme.py            # write
    python3 tools/figures/safety_readme.py --check    # fail if anything is stale
"""
