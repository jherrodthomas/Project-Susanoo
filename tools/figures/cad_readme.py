def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    block = fig_block(ctx, {"scope": d["subs"]})
    names: dict[str, list[str]] = {}
    for h in d["cited"]["hazards"]:
        for s in d["hazards"][h].get("subsystems") or []:
            names.setdefault(s, []).append(h)
    for n in block["nodes"]:
        if n.get("code") in names:
            n["sub"] = ", ".join(names[n["code"]])
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"SUS-I1 decomposition. The {len(d['subs'])} subsystems named by the hazards that cite "
                          "the CAD are coloured, with those hazards under each.")
    boundary = fig_boundary(ctx, {"path": "cad", "boundary": {
        "name": "Concept layouts", "inside": ["Layout parameters", "CAD build", "Metrics, drawings and renders"],
        "outside": ["Decision register", "Hazard and requirement records", "Front page README", "AI concept art",
                    "CI", "Named human review"],
        "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="cad/README.md",
                    subtitle="The folder owns the parameters and what is built from them. Findings leave it as "
                             "citations in the records. Crossings are numbered as in the table.")
    sysml_spec, sysml = fig_sysml(d)
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "cad/README.md", "direction": "RIGHT",
          "subtitle": "What the layouts are built from (left) and what reads them (right).",
          "nodes": [
              {"id": "I1", "title": "Lead's decisions", "sub": ", ".join(d["cited"]["decisions"]) or "—",
               "tone": "work"},
              {"id": "I2", "title": "Layout parameters", "sub": f"{len(d['params'])} layouts + common.yaml",
               "tone": "work"},
              {"id": "I3", "title": "FreeCAD, build123d, Blender", "sub": "pinned tool versions", "tone": "external"},
              {"id": "X", "code": "cad/", "title": "Concept layouts", "tone": "current"},
              {"id": "O1", "title": "Hazard records", "sub": plural(len(d["cited"]["hazards"]), "hazard") + " cite CL-05",
               "tone": "work"},
              {"id": "O2", "title": "Requirements", "sub": ", ".join(d["cited"]["requirements"]) or "—",
               "tone": "work"},
              {"id": "O3", "title": "Front page", "sub": "banner", "tone": "work"},
              {"id": "O4", "title": "Concept art", "sub": "communication only", "tone": "work"}],
          "edges": [{"src": "I1", "dst": "X", "label": "choices"}, {"src": "I2", "dst": "X", "label": "dimensions"},
                    {"src": "I3", "dst": "X", "label": "build, render"},
                    {"src": "X", "dst": "O1", "label": "findings"}, {"src": "X", "dst": "O2", "label": "values"},
                    {"src": "X", "dst": "O3", "label": "renders"}, {"src": "X", "dst": "O4", "label": "source images"}]}
    specs = [fig_findings(d), block, boundary, sysml_spec, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    return specs, sysml


