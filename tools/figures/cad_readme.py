#!/usr/bin/env python3
"""Add the record-driven part of cad/README.md, cad/figures/*.svg and cad/ConceptLayouts.sysml.

cad/README.md stays the hand-written layout review (SUS-CAD-001; its header revision feeds the drawing sheets, and
tools/cad/readme.py writes its layout tables). This generator writes only the section between the cad-records
markers at the end of the page, read from:

  cad/metrics.json                  layout and posture metrics of the placeholder geometry (build_concepts.py)
  cad/params/CL-*.yaml              layout titles, locomotion, dock
  cad/README.md "CL-05 findings"    each finding with the hazards, requirements and decisions it cites
  safety/hazards, requirements/,    the records that cite the CAD (CL-05 or cad/README.md), and the hazards'
  decisions/register.yaml           subsystems

Figures (house style of framework/documentation-standard.md):

  fig-1-layout-metrics.svg       every layout and CL-05 posture against the provisional review flags
  fig-2-findings.svg             CL-05 findings traced to the records that carry them
  fig-3-block-diagram.svg        SUS-I1 decomposition; the subsystems those hazards name are coloured
  fig-4-boundary-diagram.svg     what the CAD folder owns and what crosses its boundary
  fig-5-sysml-block-definition.svg  ConceptLayouts (generated .sysml): the layout block and its values
  fig-6-inputs-and-outputs.svg   what the layouts are built from and what reads them

    python3 tools/figures/cad_readme.py            # write
    python3 tools/figures/cad_readme.py --check    # fail if anything is stale
"""
