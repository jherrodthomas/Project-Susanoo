def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = load()
    specs, sysml = figure_specs(d)
    files = {SYSML: sysml, FIGS / "fig-1-layout-metrics.svg": fig_metrics(d)}
    for spec, svg in zip(specs, diagram.render_all(specs)):
        files[FIGS / spec["file"]] = svg
    text = README.read_text()
    sec = section(d, specs)
    if START in text:
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1]
        files[README] = before + sec + after
    else:
        files[README] = text.rstrip("\n") + "\n\n" + sec + "\n"
    return emit(files, FIGS, args.check, GEN)


