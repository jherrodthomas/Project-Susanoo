ID = re.compile(r"\b((?:HAZ-[A-Z]+-\d{3})|(?:SYS-\d{3})|(?:DQ-\d{3}))\b")


# ================================================================ records
def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    m = json.loads((FOLDER / "metrics.json").read_text())
    rows = []
    for cid, c in m["concepts"].items():
        rows.append({"id": cid, "posture": "standing", "title": c["title"], "dock": c.get("dock", ""), **c})
        for pname, pc in (c.get("postures") or {}).items():
            rows.append({"id": cid, "posture": pname, "title": c["title"], "dock": c.get("dock", ""), **pc})
    text = README.read_text()
    sec = text.split("### CL-05 findings", 1)[1].split("\n## ", 1)[0]
    findings = []
    for mm in re.finditer(r"^- \*\*([^*]+?)\.?\*\*(.*)$", sec, re.M):
        ids = list(dict.fromkeys(ID.findall(mm.group(2))))
        findings.append({"title": mm.group(1), "ids": ids})
    reg = yaml.safe_load((ROOT / "decisions" / "register.yaml").read_text())["decisions"]
    dqs = {d["id"]: d for d in reg}
    cites = lambda obj: "CL-05" in json.dumps(obj, default=str) or "cad/README.md" in json.dumps(obj, default=str)  # noqa: E731
    cited = {"hazards": sorted(h for h, x in hazards.items() if cites(x)),
             "requirements": sorted(r for r, x in reqs.items() if cites(x)),
             "decisions": sorted(d["id"] for d in reg if cites(d))}
    subs = sorted({s for h in cited["hazards"] for s in hazards[h].get("subsystems") or []})
    params = {p.stem: yaml.safe_load(p.read_text()) for p in sorted((FOLDER / "params").glob("CL-*.yaml"))}
    files = {k: len([p for p in (FOLDER / k).rglob("*") if p.is_file()]) for k in ("renders", "concept-art")}
    files["drawings"] = len(list((FOLDER / "drawings").glob("CL-*.svg")))
    files["params"] = len(list((FOLDER / "params").glob("*.yaml")))
    return {"ctx": ctx, "reqs": reqs, "hazards": hazards, "rows": rows, "concepts": m["concepts"], "meta": m,
            "findings": findings, "dqs": dqs, "cited": cited, "subs": subs, "params": params, "files": files}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def flagged(r: dict, key: str) -> bool:
    v = r.get(key)
    if v is None:
        return False
    return (key == "static_margin_m" and v < MARGIN_FLAG) or (key == "rotor_to_pilot_m" and v < ROTOR_FLAG)


def fmt(key: str, v) -> str:
    if v is None:
        return "—"
    if key == "placeholder_mass_kg":
        return f"{v:,.0f}"
    if key == "static_tip_angle_deg":
        return f"{v:.1f}"
    return f"{v:.2f}" if isinstance(v, float) else str(v)


# ================================================================ figure 1 · layout metrics (drawn directly)
def fig_metrics(d: dict) -> str:
    rows = d["rows"]
    W, M = 1220, 40
    nflag = sum(1 for r in rows if flagged(r, "static_margin_m") or flagged(r, "rotor_to_pilot_m"))
    head, y0 = fk.header(
        W, "1", "Layouts against the review flags",
        f"The {len(d['concepts'])} concept layouts and the CL-05 postures, from metrics.json. Red marks a value under "
        f"a provisional review flag (static margin {MARGIN_FLAG:.2f} m, rotor clearance {ROTOR_FLAG:.1f} m); "
        f"{nflag} of {len(rows)} rows have one. Flags are not requirements.", "cad/metrics.json")
    out = list(head)
    x0 = M + 330
    cw = (W - M - x0) / len(METRICS)
    y = y0 + 30
    out.append(fk.text(M, y, "Layout · posture", size=10.5, fill=MUTED, weight=700))
    for i, (_, lab, unit) in enumerate(METRICS):
        out.append(fk.text(x0 + i * cw, y, f"{lab} ({unit})", size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 34
    maxv = {k: max((r.get(k) or 0) for r in rows) for k, _, _ in METRICS}
    for n, r in enumerate(rows):
        top = y + n * rh
        ref = r["id"] == "CL-05"
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=5, sw=0))
        cy = top + rh / 2 + 4
        t = TONES["safety" if ref else "system"]
        p, w = fk.pill(M, cy - 12, r["id"], t[1], color=t[0], stroke=t[0])
        out += p
        out.append(fk.text(M + w + 8, cy - 4, r["posture"] + (" · reference" if ref and r["posture"] == "standing"
                                                              else ""), size=10.5, fill=INK, weight=700))
        out.append(fk.text(M + w + 8, cy + 9, fk.wrap(r.get("dock", "").replace("-", " ") + " dock", 230, 9.5,
                                                      max_lines=1)[0], size=9.5, fill=MUTED))
        for i, (k, _, _) in enumerate(METRICS):
            x = x0 + i * cw
            v = r.get(k)
            bad = flagged(r, k)
            col = TONES["red"][0] if bad else INK
            out.append(fk.text(x, cy - 2, fmt(k, v), size=10.5, fill=col, weight=700 if bad else ""))
            if isinstance(v, (int, float)) and maxv[k]:
                out.append(fk.rect(x, cy + 5, max(2, (cw - 30) * v / maxv[k]), 4,
                                   fill=TONES["red"][0] if bad else TONES["system"][0], stroke="none", rx=2, sw=0))
            if k == "static_margin_m":
                fx = x + (cw - 30) * MARGIN_FLAG / maxv[k]
                out.append(fk.line(fx, cy + 3, fx, cy + 11, stroke=TONES["red"][0], sw=1))
            if k == "rotor_to_pilot_m" and maxv[k]:
                fx = x + (cw - 30) * ROTOR_FLAG / maxv[k]
                out.append(fk.line(fx, cy + 3, fx, cy + 11, stroke=TONES["red"][0], sw=1))
    y += len(rows) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["safety"][1], TONES["safety"][0], "Reference layout CL-05 (DQ-014)"),
           (TONES["system"][1], TONES["system"][0], "Other layout"),
           (TONES["red"][1], TONES["red"][0], "Under a provisional review flag (tick = flag)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " Static margin is a standstill measure only; walking needs a dynamic analysis.",
                      W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Layouts against the review flags",
                  "Every concept layout and posture with its placeholder metrics", out)


# ================================================================ ELK figures
def kind_of(i: str) -> str:
    return "hazard" if i.startswith("HAZ") else ("requirement" if i.startswith("SYS") else "decision")


def fig_findings(d: dict) -> dict:
    nodes = [{"id": "F", "banner": "CL-05 findings", "tone": "work"},
             {"id": "R", "banner": "Records", "tone": "work"}]
    edges, seen = [], set()
    for n, f in enumerate(d["findings"]):
        fid = f"f{n}"
        nodes.append({"id": fid, "parent": "F", "title": f["title"], "tone": "current", "maxw": 200,
                      "legend": "Finding (cad/README.md)"})
        for i in f["ids"]:
            nid = "r_" + mid(i)
            if i not in seen:
                seen.add(i)
                k = kind_of(i)
                if k == "hazard":
                    h = d["hazards"].get(i, {})
                    lv = (h.get("initial_risk") or {}).get("risk_level", "")
                    node = {"title": h.get("title", i), "sub": f"initial {lv} (preliminary)",
                            "tone": LEVEL_TONE.get(lv, "amber"), "legend": f"Hazard, {lv} initial risk"}
                elif k == "requirement":
                    r = d["reqs"].get(i, {})
                    node = {"title": r.get("title", i), "sub": r.get("status", ""), "tone": "interface",
                            "legend": "Requirement"}
                else:
                    q = d["dqs"].get(i, {})
                    node = {"title": fk.wrap(q.get("question", i), 220, 11, max_lines=1)[0],
                            "sub": q.get("status", ""), "tone": "external", "legend": "Decision"}
                nodes.append({"id": nid, "parent": "R", "code": i, "maxw": 240, **node})
            edges.append({"src": fid, "dst": nid, "label": ""})
    return {"file": "fig-2-findings.svg", "number": "2", "title": "Where the CL-05 findings went",
            "subtitle": "Each finding of the reference-layout review, traced to the hazards, requirements and "
                        "decisions it cites. Risk levels are preliminary; the records are drafts.",
            "ref": "cad/README.md · safety/hazards · requirements", "direction": "RIGHT", "orient": "fixed",
            "nodes": nodes, "edges": edges, "legend": [edge_leg("Cited by the finding")]}


def fig_sysml(d: dict) -> tuple[dict, str]:
    keys = ["height_m", "cockpit_floor_m", "placeholder_mass_kg", "static_margin_m", "rotor_to_pilot_m"]
    names = {"height_m": "height", "cockpit_floor_m": "cockpitFloor", "placeholder_mass_kg": "placeholderMass",
             "static_margin_m": "staticMargin", "rotor_to_pilot_m": "rotorToPilot"}
    unit = {"placeholder_mass_kg": "kg"}
    nodes = [{"id": "ConceptLayout", "shape": "class", "title": "ConceptLayout", "stereotype": "part def",
              "attrs": [f"{names[k]} : Real  [{unit.get(k, 'm')}]" for k in keys], "tone": "system"}]
    edges = []
    s = ["    part def ConceptLayout {",
         "        doc /* A concept layout of placeholder geometry (SUS-CAD-001); values are not design data. */",
         *[f"        attribute {names[k]} : Real;  // {unit.get(k, 'm')}" for k in keys], "    }"]
    for cid, c in d["concepts"].items():
        pn = cid.replace("-", "").lower()
        ref = cid == "CL-05"
        nodes.append({"id": pn, "shape": "class", "title": f"{pn} : ConceptLayout", "stereotype": "part",
                      "attrs": [f"{names[k]} = {fmt(k, c.get(k))}" for k in keys],
                      "tone": "safety" if ref else "external"})
        edges.append({"src": pn, "dst": "ConceptLayout", "label": "", "dash": True})
        s.append(f"    part {pn} : ConceptLayout {{")
        s.append(f"        doc /* {cid} {c['title']}{' (reference layout, DQ-014)' if ref else ''} */")
        for k in keys:
            if c.get(k) is not None:
                s.append(f"        attribute :>> {names[k]} = {float(c[k])};")
        s.append("    }")
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — ConceptLayouts", "ref": "cad/ConceptLayouts.sysml",
            "subtitle": "The layout block and each layout's standing values, generated into ConceptLayouts.sysml "
                        "from metrics.json. Placeholder geometry: values are not design data.",
            "frame": {"kind": "bdd", "type": "package", "name": "ConceptLayouts"}, "direction": "DOWN",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Typed by (part : ConceptLayout)", True), ("#FFF7ED", "#C2410C", "Reference layout"),
                       ("#EEF2FF", "#4F46E5", "Part definition"), ("#F1F5F9", "#475569", "Other layout")]}
    sysml = "\n".join([
        f"// ConceptLayouts — generated by {GEN} from cad/metrics.json.",
        "// Do not edit by hand: change the layout parameters, rebuild the CAD and regenerate.",
        "// Status: placeholder concept geometry (SUS-CAD-001), not a design.", "",
        "package ConceptLayouts {",
        "    private import ScalarValues::*;",
        "    doc /* Concept layouts of SUS-M1 with standing metrics of their placeholder geometry. */",
        *s, "}", ""])
    return spec, sysml


