# ================================================================ records
def flat(d: dict, p: tuple = ()):
    for k, v in d.items():
        if isinstance(v, dict):
            yield from flat(v, p + (k,))
        else:
            yield p + (k,), v


def cited(path: Path) -> list[tuple[str, list[str]]]:
    """(dotted key, ids) for every line whose comment cites a record; the key is the YAML path of that line."""
    stack, out = [], []
    for ln in path.read_text().splitlines():
        m = re.match(r"^(\s*)([A-Za-z_0-9]+):", ln)
        if m:
            ind = len(m.group(1))
            stack = [s for s in stack if s[0] < ind] + [(ind, m.group(2))]
        if "#" in ln and m:
            ids = ID.findall(ln.split("#", 1)[1])
            if ids:
                out.append((".".join(s[1] for s in stack), list(dict.fromkeys(ids))))
    return out


def builders() -> dict:
    src = (ROOT / "tools/cad/build_concepts.py").read_text()
    m = re.search(r"^BUILDERS = \{(.*?)\}", src, re.M)
    return dict(re.findall(r'"([\w-]+)":\s*(\w+)', m.group(1)))


def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    texts = {r: (ROOT / r).read_text() for r in READERS}
    bld = builders()
    files = []
    for path in sorted(FOLDER.glob("*.yaml"), key=lambda p: (p.stem == "common", p.stem)):
        d = yaml.safe_load(path.read_text())
        blocks = {}
        for keys, v in flat(d):
            block = keys[0] if len(keys) > 1 else "(top level)"
            who = [r for r in READERS if re.search(r'["\']%s["\']' % re.escape(keys[-1]), texts[r])]
            b = blocks.setdefault(block, {"n": 0, "readers": set(), "unnamed": []})
            b["n"] += 1
            b["readers"] |= set(who)
            if not who:
                b["unnamed"].append(".".join(keys))
        style = d.get("style", "open-frame") if path.stem != "common" else None
        files.append({"name": path.name, "stem": path.stem, "d": d, "blocks": blocks, "style": style,
                      "builder": bld.get(style) if style else None, "cited": cited(path),
                      "title": d.get("title") or (path.read_text().splitlines()[0].lstrip("# ").strip()),
                      "n": sum(b["n"] for b in blocks.values())})
    ids = sorted({i for f in files for _, ii in f["cited"] for i in ii})
    trade = {p.stem: yaml.safe_load(p.read_text()) for p in TRADES.glob("TS-*.yaml")}
    recs = {}
    for i in ids:
        if i.startswith("SYS-"):
            r = reqs.get(i) or {}
            recs[i] = {"kind": "requirement", "title": r.get("title", "missing"), "status": r.get("status", "missing")}
        elif i.startswith("HAZ-"):
            h = hazards.get(i) or {}
            recs[i] = {"kind": "hazard", "title": h.get("title", "missing"), "status": h.get("status", "missing")}
        else:
            t = trade.get(i)
            recs[i] = {"kind": "trade study", "title": t["title"] if t else "no record in architecture/trades/",
                       "status": t["status"] if t else "no record"}
    hz = [i for i in ids if i.startswith("HAZ-")]
    subs = sorted({x for h in hz for x in hazards.get(h, {}).get("subsystems") or []})
    return {"ctx": ctx, "files": files, "ids": ids, "recs": recs, "subs": subs, "hz": hz, "builders": bld}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def unnamed(d: dict) -> list[str]:
    return [f"{f['stem']}: {u}" for f in d["files"] for b in f["blocks"].values() for u in b["unnamed"]]


# ================================================================ figure 1 · parameter blocks (drawn directly)
def fig_blocks(d: dict) -> str:
    W, M = 1240, 40
    files = d["files"]
    order = []
    for f in files:
        for b in f["blocks"]:
            if b not in order:
                order.append(b)
    nu = unnamed(d)
    head, y0 = fk.header(
        W, "1", "Every parameter block",
        f"{plural(len(files), 'file')}, {sum(f['n'] for f in files)} values. Each cell: values set and the readers "
        f"that name them; a red count is values no reader names ({len(nu)}: {', '.join(nu) or 'none'}).",
        "cad/params")
    out = list(head)
    x0 = M + 150
    cw = (W - M - x0) / len(files)
    y = y0 + 22
    for j, f in enumerate(files):
        cx = x0 + j * cw + cw / 2
        out.append(fk.text(cx, y, f["stem"], size=11.5, fill=INK, weight=700, anchor="middle"))
        sub = f"{f['style']} → {f['builder']}" if f["style"] else "shared by every layout"
        out.append(fk.text(cx, y + 14, sub, size=9, fill=MUTED, anchor="middle", mono=bool(f["style"])))
    y += 26
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 34
    code = {"build_concepts.py": "B", "cl05.py": "C", "cl05_web.py": "W", "blender_walk.py": "K", "drawings.py": "D",
            "readme.py": "R"}
    for i, blk in enumerate(order):
        yy = y + i * rh
        if i % 2:
            out.append(fk.rect(M, yy + 1, W - 2 * M, rh, fill="#F8FAFC", stroke="none", rx=0, sw=0))
        out.append(fk.text(M + 4, yy + 21, blk, size=11, fill=INK, mono=True))
        for j, f in enumerate(files):
            b = f["blocks"].get(blk)
            if not b:
                continue
            cx = x0 + j * cw + 8
            p, w = fk.pill(cx, yy + 9, str(b["n"]), TONES["work"][1], color=INK, stroke="#94A3B8")
            out += p
            px = cx + w + 6
            for r in READERS:
                if r in b["readers"]:
                    p, w2 = fk.pill(px, yy + 9, code[SHORT[r]], "#E0E7FF", color="#3730A3", size=8.5)
                    out += p
                    px += w2 + 3
            if b["unnamed"]:
                p, _ = fk.pill(px + 4, yy + 9, f"{len(b['unnamed'])} unread", "#FEE2E2", color="#991B1B", size=8.5)
                out += p
    y += len(order) * rh + 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 22
    out.append(fk.text(M, y, "Readers: " + " · ".join(f"{c} = {n}" for n, c in code.items())
                       + ". A key named in a reader is likely read; a key named in none is certainly unread.",
                       size=10.5, fill=MUTED))
    y += 18
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Every parameter block",
                  "Every block of every parameter file with its value count, the readers that name it and unread values",
                  out)


