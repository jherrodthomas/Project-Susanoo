def fig_cited(d: dict) -> str:
    W, M = 1240, 40
    rows = [(f["stem"], k, ids) for f in d["files"] for k, ids in f["cited"]]
    ids = d["ids"]
    nohome = [i for i in ids if d["recs"][i]["status"] == "no record"]
    head, y0 = fk.header(
        W, "2", "The records the parameters cite",
        f"{plural(len(rows), 'parameter')} whose comment names a requirement, hazard or trade study, traced to "
        f"{plural(len(ids), 'record')}"
        + (f"; {', '.join(nohome)} {'has' if len(nohome) == 1 else 'have'} no record in architecture/trades/." if nohome
           else "."), "cad/params/*.yaml")
    out = list(head)
    lx, lw = M, 330
    rx, rw = M + 640, W - M - (M + 640)
    rh, gh = 26, 40
    y = y0 + 24
    out.append(fk.text(lx, y, "Parameter (file · key)", size=10.5, fill=MUTED, weight=700))
    out.append(fk.text(rx, y, "Record cited", size=10.5, fill=MUTED, weight=700))
    y += 12
    ly = {}
    for i, (stem, key, _) in enumerate(rows):
        yy = y + i * rh
        out.append(fk.rect(lx, yy, lw, rh - 6, fill="#FFFFFF", stroke="#CBD5E1", rx=5, sw=1))
        out.append(fk.text(lx + 8, yy + 14, f"{stem} · {key}", size=10, fill=INK, mono=True))
        ly[i] = yy + (rh - 6) / 2
    ry = {}
    for j, i in enumerate(ids):
        yy = y + j * gh
        r = d["recs"][i]
        tone = {"requirement": TONES["software"], "hazard": TONES["safety"]}.get(r["kind"], TONES["external"])
        missing = r["status"] == "no record"
        out.append(fk.rect(rx, yy, rw, gh - 8, fill="#FEF2F2" if missing else tone[1], stroke="#DC2626" if missing
                           else tone[0], rx=6, sw=1.2, dash="4 3" if missing else ""))
        out.append(fk.text(rx + 10, yy + 14, i, size=10.5, fill=INK, weight=700, mono=True))
        out.append(fk.text(rx + 92, yy + 14, fk.wrap(r["title"], rw - 110, 10, max_lines=1)[0], size=10, fill=INK))
        out.append(fk.text(rx + 92, yy + 27, f"{r['kind']} · {r['status']}", size=9, fill=MUTED))
        ry[i] = yy + (gh - 8) / 2
    for i, (_, _, ii) in enumerate(rows):
        for rid in ii:
            x1, y1, x2, y2 = lx + lw, ly[i], rx, ry[rid]
            out.append(f'<path d="M{x1},{y1} C{x1 + 140},{y1} {x2 - 140},{y2} {x2},{y2}" fill="none" stroke="#94A3B8" '
                       'stroke-width="1.1"/>')
    y += max(len(rows) * rh, len(ids) * gh) + 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 22
    leg = [(TONES["software"][1], TONES["software"][0], "Requirement"), (TONES["safety"][1], TONES["safety"][0], "Hazard"),
           (TONES["external"][1], TONES["external"][0], "Trade study"), ("#FEF2F2", "#DC2626", "Cited, no record")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · The records the parameters cite",
                  "Parameters whose comments cite a requirement, hazard or trade study, traced to those records", out)


