def fig_queue(d: dict, s: dict) -> str:
    q, t = d["queue"], d["t"]
    W, M = 1120, 40
    head, y0 = fk.header(
        W, "1", "What is waiting on a human review",
        f"{s['waiting']} of {s['items']} items need an accepting review with a named human reviewer, in the role "
        f"shown. Hazard risk needs the authority for its target level, and High or Serious also needs the user "
        f"representative. {plural(s['reviews'], 'review record')} exist.", f"{TAILORING} · rule R13")
    out = list(head)
    cx = {"kind": M, "id": M + 112, "title": M + 222, "state": M + 520, "role": M + 690, "concur": M + 880,
          "done": M + 980}
    y = y0 + 30
    for k, lab in (("kind", "Item"), ("id", "ID"), ("title", "Title"), ("state", "State"),
                   ("role", "Reviewer role needed"), ("concur", "Concurrence"), ("done", "Review")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 30
    role_tone = {t["acceptance_authority"][lv]: LEVEL_TONE[lv] for lv in LEVELS if lv in t["acceptance_authority"]}
    prev = None
    for n, x in enumerate(q):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        if x["kind"] != prev:
            out.append(fk.text(cx["kind"], cy, x["kind"], size=10.5, fill=MUTED, weight=700))
            prev = x["kind"]
        out.append(fk.text(cx["id"], cy, x["id"], size=10.5, fill=INK, weight=700, mono=True))
        out.append(fk.text(cx["title"], cy, fk.wrap(x["title"], 285, 11, max_lines=1)[0], size=11, fill=INK))
        out.append(fk.text(cx["state"], cy, fk.wrap(str(x["state"]), 160, 10.5, max_lines=1)[0], size=10.5,
                           fill=MUTED))
        tone = TONES[role_tone.get(x["role"], "system")]
        p, _ = fk.pill(cx["role"], cy - 12, x["role"] or "—", tone[1], color=tone[0], stroke=tone[0])
        out += p
        if x["concur"]:
            p, _ = fk.pill(cx["concur"], cy - 12, x["concur"], TONES["interface"][1], color=TONES["interface"][0],
                           stroke=TONES["interface"][0])
            out += p
        else:
            out.append(fk.text(cx["concur"], cy, "—", size=11, fill=FAINT))
        st = TONES["ok" if x["done"] else "amber"]
        p, _ = fk.pill(cx["done"], cy - 12, "accepted" if x["done"] else "waiting", st[1], color=st[0], stroke=st[0])
        out += p
    y += len(q) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["red"][1], TONES["red"][0], "High-risk authority"),
           (TONES["safety"][1], TONES["safety"][0], "Serious"), (TONES["amber"][1], TONES["amber"][0], "Medium"),
           (TONES["ok"][1], TONES["ok"][0], "Low / accepted"),
           (TONES["interface"][1], TONES["interface"][0], "User representative concurrence")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · What is waiting on a human review",
                  "Items that only a named human review can accept, with the role it needs", out)


# ================================================================ ELK figures
def fig_authority(d: dict, s: dict) -> dict:
    t, hz = d["t"], d["hazards"]
    need = count((h.get("target_risk") or {}).get("risk_level") for h in hz.values())
    lvl_of = {v: k for k, v in t["acceptance_authority"].items()}
    nodes = [{"id": "LAD", "banner": "Acceptance authority · highest first", "tone": "work", "direction": "DOWN"}]
    edges = []
    rank = t["authority_rank"]
    for i, role in enumerate(rank):
        r = t["roles"][role]
        lvl = lvl_of.get(role, "")
        nodes.append({"id": role.replace("-", "_"), "parent": "LAD", "code": role,
                      "title": r["title"].replace(" (simulated)", ""),
                      "sub": f"accepts {lvl} and below · {need.get(lvl, 0)} hazards at {lvl} target · "
                             f"held by {r.get('holder') or 'nobody yet'}",
                      "tone": LEVEL_TONE.get(lvl, "system"), "legend": f"Accepts {lvl} risk"})
        if i:
            edges.append({"src": rank[i - 1].replace("-", "_"), "dst": role.replace("-", "_"), "label": "outranks"})
    ur = t["user_representative"]
    nodes.append({"id": "UR", "code": ur, "title": t["roles"][ur]["title"].replace(" (simulated)", ""),
                  "sub": f"concurs for {', '.join(t['user_concurrence_required_for'])} · held by "
                         f"{t['roles'][ur].get('holder') or 'nobody yet'}", "tone": "interface",
                  "legend": "User representative"})
    nodes.append({"id": "REV", "code": "reviews/", "title": plural(s["reviews"], "review record"),
                  "sub": "a named human, in the role needed, with an accepting outcome", "tone": "current"})
    nodes.append({"id": "AI", "code": "I0", "title": "AI reviewer or CI", "sub": "drafts and checks; never accepts",
                  "tone": "external"})
    edges += [{"src": "LAD", "dst": "REV", "label": "signs as reviewer", "tone": "safety"},
              {"src": "UR", "dst": "REV", "label": "concurs (High, Serious)", "tone": "interface"},
              {"src": "AI", "dst": "REV", "label": "in-progress or returned only", "dash": True}]
    return {"file": "fig-2-authority.svg", "number": "2", "title": "Who may accept what",
            "subtitle": "The acceptance authority from the tailoring, highest first. A role may accept its own risk "
                        f"level and anything lower. All {len(t['roles'])} roles are simulated; {s['holders']} have a "
                        "holder.",
            "ref": TAILORING, "direction": "RIGHT", "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Authority path", tone="safety"), edge_leg("Never accepts", True)]}


