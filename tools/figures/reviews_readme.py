# ================================================================ records
def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    repo = load_repo()
    t = repo.tailoring
    cat = yaml.safe_load(CATALOG.read_text())
    e7 = next(f for f in cat["folders"] if f["id"] == "E7")
    queue = []

    def add(kind, iid, title, state, role, concur, done):
        queue.append({"kind": kind, "id": iid, "title": title, "state": state, "role": role, "concur": concur,
                      "done": done})
    for hid, h in hazards.items():
        lvl = (h.get("target_risk") or {}).get("risk_level", "")
        accs = h.get("acceptances") or []
        done = any(_accepting_review(repo, a.get("review_id"), hid, a.get("authority_role"))[0] for a in accs)
        add("Hazard risk", hid, h.get("title", hid), f"{h.get('status')} · target {lvl}",
            t["acceptance_authority"].get(lvl), t["user_representative"] if lvl in t["user_concurrence_required_for"]
            else None, done)
    names = {x["id"]: x.get("name") or x.get("title", "") for x in repo.model["tasks"]}
    for tid, rec in sorted(repo.objects["task"].items()):
        add("Task record", f"T{tid}", names.get(tid) or f"Task {tid}", rec.get("status"), "any role", None,
            rec.get("status") == "approved" and _accepting_review(repo, rec.get("review_id"), f"T{tid}")[0])
    base = [q for q, r in reqs.items() if r.get("status") == "baselined"
            and _accepting_review(repo, r.get("review_id"), q)[0]]
    add("Requirements", f"{len(reqs)} SYS", "Baseline the system safety requirements",
        summary(count(r.get("status") for r in reqs.values())), "any role", None, len(base) == len(reqs))
    for label, block, sid in (("Tailoring", t.get("approval") or {}, "tailoring"),
                              ("Risk definitions", (t.get("risk_definitions") or {}).get("approval") or {},
                               (t.get("risk_definitions") or {}).get("id"))):
        add(label, sid, f"Approve the {label.lower()}", block.get("status"),
            block.get("authority_role") or block.get("authority") or "any role", None,
            block.get("status") == "approved" and _accepting_review(repo, block.get("record"), sid,
                                                                    block.get("authority_role"))[0])
    item = repo.item or {}
    add("Item definition", item.get("id", "SUS-I1"), "Approve the item definition", item.get("status"), "any role",
        None, item.get("status") == "approved" and _accepting_review(repo, item.get("review_id"), item.get("id"))[0])
    return {"ctx": ctx, "reqs": reqs, "hazards": hazards, "repo": repo, "t": t, "e7": e7, "queue": queue,
            "reviews": repo.objects["review"]}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def summary(c: dict) -> str:
    return ", ".join(f"{n} {k}" for k, n in sorted(c.items(), key=lambda x: str(x[0]))) or "none"


def stats(d: dict) -> dict:
    revs, q = d["reviews"], d["queue"]
    return {"reviews": len(revs), "outcome": count(r.get("outcome") for r in revs.values()),
            "accepting": sum(1 for r in revs.values() if r.get("outcome") in ACCEPTING),
            "ai": sum(1 for r in revs.values() if any(not x.get("human") for x in r.get("reviewers", []))),
            "waiting": sum(1 for x in q if not x["done"]), "items": len(q),
            "holders": sum(1 for r in d["t"]["roles"].values() if r.get("holder"))}


def role_label(t: dict, role: str | None) -> str:
    if not role:
        return "—"
    r = t["roles"].get(role)
    return f"{role} · {r['title'].replace(' (simulated)', '')}" if r else role


