def classify(d: dict) -> dict:
    steps = []
    for i, (val, cond) in enumerate(d["rules"]):
        nm = "is" + re.sub(r"\W", "", val.title())
        steps.append({"name": nm, "label": f"{val}: {cond}" if cond != "otherwise" else f"{val}: otherwise",
                      "safety": OUT_TONE.get(val) == "red"})
    return {"name": "ClassifyOutcome", "steps": steps, "loops": [],
            "doc": "How sim/uav/harness.py score() decides a run's outcome: the first test that holds, in this order."}


