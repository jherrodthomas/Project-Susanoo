def fig_timelines(d: dict) -> str:
    W, M = 1280, 40
    runs, sp = d["runs"], d["spec"]
    tmax = max(r["span"][1] for r in runs)
    amax = max(max(q[3] for q in r["trace"]) for r in runs) * 1.08
    head, y0 = fk.header(
        W, "2", "Every run over time",
        f"Altitude above the dock against time after the injection, coloured by PX4 mode, with the keep-out altitude "
        f"({sp['keepout_alt_m']:g} m) dashed. Red ticks mark samples inside the pilot keep-out: below that altitude and "
        f"within {sp['pilot_keepout_m']:g} m of the pilot station.", "trace in sim/results/uav/SU-*.json")
    out = list(head)
    x0, pw, ph = M + 170, W - 2 * M - 170, 70
    y = y0 + 20
    for r in runs:
        out.append(fk.text(M, y + 18, r["id"], size=12, fill=INK, weight=700, mono=True))
        t = TONES[OUT_TONE.get(r["outcome"], "system")]
        p, _ = fk.pill(M, y + 26, r["outcome"], t[1], color=t[0], stroke=t[0])
        out += p
        out.append(fk.rect(x0, y, pw, ph, fill="#FFFFFF", stroke="#CBD5E1", rx=3, sw=0.8))
        X = lambda tt: x0 + pw * tt / tmax  # noqa: E731
        Y = lambda a: y + ph - ph * max(a, 0) / amax  # noqa: E731
        ky = Y(sp["keepout_alt_m"])
        out.append(f'<line x1="{x0}" y1="{ky:.1f}" x2="{x0 + pw}" y2="{ky:.1f}" stroke="#B91C1C" stroke-width="1" '
                   'stroke-dasharray="4 3"/>')
        tr = r["trace"]
        for a, b in zip(tr, tr[1:]):
            col = MODE_COL.get(a[4], "#94A3B8")
            out.append(f'<line x1="{X(a[0]):.1f}" y1="{Y(a[3]):.1f}" x2="{X(b[0]):.1f}" y2="{Y(b[3]):.1f}" '
                       f'stroke="{col}" stroke-width="2.4" stroke-linecap="round"/>')
        for tt in r["inside"]:
            out.append(f'<line x1="{X(tt):.1f}" y1="{y + ph - 8:.1f}" x2="{X(tt):.1f}" y2="{y + ph:.1f}" '
                       'stroke="#DC2626" stroke-width="2"/>')
        if r["first"]:
            fx = X(r["first"][0])
            out.append(f'<line x1="{fx:.1f}" y1="{y}" x2="{fx:.1f}" y2="{y + ph}" stroke="#0F172A" stroke-width="1" '
                       'stroke-dasharray="2 2"/>')
            out.append(fk.text(fx + 4, y + 11, f"failsafe {r['first'][1]}", size=9, fill=INK))
        y += ph + 16
    for s in range(0, int(tmax) + 1, 20):
        xx = x0 + pw * s / tmax
        out.append(fk.text(xx, y + 2, f"{s} s", size=9, fill=MUTED, anchor="middle"))
    y += 20
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(c, c, m) for m, c in MODE_COL.items() if any(q[4] == m for r in runs for q in r["trace"])] + [
        ("#FFFFFF", "#B91C1C", f"Keep-out altitude {sp['keepout_alt_m']:g} m"), ("#DC2626", "#DC2626", "Inside the pilot keep-out")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    out.append(fk.text(M, y + 4, f"Altitude axis 0–{amax:.0f} m above the dock; dotted line: the first failsafe mode "
                                 "change.", size=10.5, fill=MUTED))
    y += 18
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Every run over time",
                  "Altitude and PX4 mode over time for every run, with the keep-out", out)


