def readable(cond: str) -> str:
    for pat, rep in READABLE:
        cond = re.sub(pat, rep, cond)
    return cond


def outcome_rules() -> list[tuple[str, str]]:
    """(outcome, condition) in the order score() tests them."""
    tree = ast.parse(HARNESS.read_text())
    fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "score")
    node = next(n for n in fn.body if isinstance(n, ast.If) and any(
        isinstance(t, ast.Name) and t.id == "outcome" for s in n.body for t in getattr(s, "targets", [])))
    rules = []
    while node is not None:
        if isinstance(node, ast.If):
            val = next(s.value.value for s in node.body if isinstance(s, ast.Assign))
            cond = ast.unparse(node.test)
            cond = readable(cond)
            rules.append((val, cond))
            node = node.orelse[0] if node.orelse else None
            if node is not None and not isinstance(node, ast.If):
                node = None
        else:
            node = None
    last = fn.body
    for n in ast.walk(fn):
        if isinstance(n, ast.If) and n.orelse and not isinstance(n.orelse[0], ast.If):
            s = n.orelse[0]
            if isinstance(s, ast.Assign) and getattr(s.targets[0], "id", "") == "outcome":
                rules.append((s.value.value, "otherwise"))
    _ = last
    return rules


def load() -> dict:
    ctx, _, hazards = load_reqs()
    spec = {k: v["value"] for k, v in yaml.safe_load(SPEC.read_text()).items() if isinstance(v, dict) and "value" in v}
    if not spec:
        raw = yaml.safe_load(SPEC.read_text())
        spec = {k: v["value"] for k, v in (raw.get("params") or raw).items() if isinstance(v, dict) and "value" in v}
    summary = (FOLDER / "summary.md").read_text()
    finds = {m.group(1): (m.group(2), m.group(3)) for m in
             re.finditer(r"^- \*\*(FND-UAV-\d+)\*\* \(([^;]+); ([^)]+)\): (.+)$", summary, re.M)}
    finds = {k: {"runs": [x.strip() for x in v[0].split(",")], "haz": v[1]} for k, v in finds.items()}
    runs = []
    for p in sorted(FOLDER.glob("SU-*.json")):
        d = json.loads(p.read_text())
        sc = d["scenario"]
        tr = d["trace"]
        pilot = d["pilot_m"]
        inside = [q[0] for q in tr if q[3] < spec["keepout_alt_m"] and math.dist(q[1:3], pilot) < spec["pilot_keepout_m"]]
        runs.append({"id": sc["id"], "title": sc["title"], "hazards": sc.get("hazards") or [], "inject": sc["inject"],
                     "params": d.get("params_set") or {}, "first": d.get("first_failsafe"), "outcome": d["outcome"],
                     "modes": d.get("mode_changes") or [], "trace": tr, "min_pilot": d.get("min_pilot_distance_low_m"),
                     "samples": len(tr), "span": (tr[0][0], tr[-1][0]) if tr else (0, 0), "kb": round(p.stat().st_size / 1024, 1),
                     "px4": d.get("px4"), "sim": d.get("simulator"), "speed": d.get("speed_factor"),
                     "inside": inside, "texts": len(d.get("statustext") or []), "est": d.get("max_estimate_error_m"),
                     "finds": [k for k, v in finds.items() if sc["id"] in v["runs"]], "file": p.name})
    hz = sorted({h for r in runs for h in r["hazards"]})
    subs = sorted({s for h in hz for s in hazards.get(h, {}).get("subsystems") or []})
    return {"ctx": ctx, "runs": runs, "spec": spec, "finds": finds, "rules": outcome_rules(), "hz": hz, "subs": subs,
            "summary_kb": round((FOLDER / "summary.md").stat().st_size / 1024, 1)}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def inj(i: dict) -> str:
    if "link_loss_at_s" in i:
        return f"link lost at {i['link_loss_at_s']} s"
    if "failure" in i:
        f = i["failure"]
        return f"{f.get('unit')} {f.get('type')} at {i.get('at_s')} s"
    if "set_params" in i:
        return ", ".join(f"{k}={v}" for k, v in i["set_params"].items()) + f" at {i.get('at_s')} s"
    if "reposition_beyond_fence_at_s" in i:
        return f"reposition beyond the fence at {i['reposition_beyond_fence_at_s']} s"
    return json.dumps(i)


