def fig_pages(d: dict) -> str:
    W, M = 1280, 40
    pages = d["pages"]
    head, y0 = fk.header(
        W, "1", "The 3D pages",
        f"Every page in docs/3d, read from the page itself: what it shows, the hazards it carries, its outcome or "
        f"contents, its size, its still and the CI check that opens it. Pages pin three.js "
        f"{', '.join(d['threes']) or '?'}; every 3D page shows the synthetic label.", "docs/3d/*.html")
    out = list(head)
    cx = {"f": M, "k": M + 140, "s": M + 330, "o": M + 800, "z": M + 960, "c": M + 1030}
    y = y0 + 30
    for k, lab in (("f", "Page"), ("k", "Kind"), ("s", "What it shows · hazards"), ("o", "Outcome"), ("z", "Size"),
                   ("c", "Still · CI check")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 54
    for n, r in enumerate(pages):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["f"], cy, r["file"], size=10.5, fill=INK, weight=700, mono=True))
        t = TONES[KIND_TONE[r["kind"]]]
        p, _ = fk.pill(cx["k"], cy - 12, KIND_LABEL[r["kind"]].lower(), t[1], color=t[0], stroke=t[0])
        out += p
        out.append(fk.text(cx["s"], cy - 12, fk.wrap(r["shows"], 450, 10.5, True, max_lines=1)[0], size=10.5,
                           fill=INK, weight=700))
        out.append(fk.text(cx["s"], cy + 2, fk.wrap(r["detail"], 450, 9.5, max_lines=1)[0], size=9.5, fill=MUTED))
        x = cx["s"]
        hz = r["hazards"] if len(r["hazards"]) <= 4 else []
        for h in hz:
            lv = (d["hazards"].get(h, {}).get("initial_risk") or {}).get("risk_level", "")
            tt = TONES[LEVEL_TONE.get(lv, "amber")]
            p, w = fk.pill(x, cy + 8, h, tt[1], color=tt[0], stroke=tt[0])
            out += p
            x += w + 4
        if len(r["hazards"]) > 4:
            out.append(fk.text(cx["s"], cy + 18, f"{len(r['hazards'])} hazards listed, with callouts on the model",
                               size=9.5, fill=INK))
        if r["outcome"]:
            tt = TONES[out_tone(r["outcome"])]
            p, _ = fk.pill(cx["o"], cy - 12, r["outcome"], tt[1], color=tt[0], stroke=tt[0])
            out += p
        else:
            out.append(fk.text(cx["o"], cy, "—", size=10.5, fill=MUTED))
        out.append(fk.text(cx["z"], cy, f"{r['kb']} KB", size=10, fill=INK))
        st = ", ".join(s.replace(".png", "") for s in r["stills"]) or "no still"
        out.append(fk.text(cx["c"], cy - 6, fk.wrap(st, 210, 9.5, max_lines=1)[0], size=9.5,
                           fill=TONES["ok" if r["stills"] or r["kind"] == "index" else "amber"][0]))
        out.append(fk.text(cx["c"], cy + 9, fk.wrap(r["check"].replace("sim/scenes3d/", ""), 210, 9.5, max_lines=1)[0],
                           size=9.5, fill=MUTED, mono=True))
    y += len(pages) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES[t][1], TONES[t][0], KIND_LABEL[k]) for k, t in KIND_TONE.items()] + [
        (TONES["red"][1], TONES["red"][0], "Mishap or unsafe outcome"), (TONES["ok"][1], TONES["ok"][0], "Clear")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · The 3D pages", "Every page in docs/3d with what it shows and what checks it", out)


# ================================================================ figure 2 · composition (ELK)
def fig_composition(d: dict) -> dict:
    nodes = [{"id": "SRC", "banner": "Built from", "tone": "work"}, {"id": "PG", "banner": "Pages", "tone": "work"},
             {"id": "CK", "banner": "Checked and drawn", "tone": "work"}]
    edges = []
    pages = d["pages"]
    groups = defaultdict(list)
    for r in pages:
        groups[r["kind"]].append(r)
    gid = {}
    for kind in ("sheet", "scene", "variant", "index"):
        for r in groups.get(kind, []):
            if kind == "sheet":
                key = "pg_" + mid(r["stem"])
                nodes.append({"id": key, "parent": "PG", "code": r["file"], "title": r["sheet"]["title"],
                              "tone": "interface", "maxw": 250, "legend": KIND_LABEL[kind]})
                gid[r["file"]] = key
        if kind in ("scene", "variant") and groups.get(kind):
            key = "pg_" + kind
            ids = [r["stem"] for r in groups[kind]]
            nodes.append({"id": key, "parent": "PG", "code": f"{plural(len(ids), KIND_LABEL[kind].lower())}",
                          "title": ", ".join(ids), "tone": KIND_TONE[kind], "maxw": 250, "legend": KIND_LABEL[kind]})
            for r in groups[kind]:
                gid[r["file"]] = key
        if kind == "index" and groups.get(kind):
            nodes.append({"id": "pg_index", "parent": "PG", "code": "index.html", "title": groups[kind][0]["shows"],
                          "tone": "system", "maxw": 250, "legend": KIND_LABEL[kind]})
            gid["index.html"] = "pg_index"
    srcs = [("s_out", "sim/scenes3d/out/*.json", "exported scene analysis", ["scene", "variant"]),
            ("s_lib", "sim/scenes3d/library, scenes.yaml", "look, variants", ["scene", "variant"]),
            ("s_sheet", "sheet.yaml, sheet_uav.yaml", "what each sheet draws", ["sheet"]),
            ("s_rec", "cad/metrics.json, safety/hazards", "concept metrics, hazards", ["sheet"])]
    for sid, code, lab, kinds in srcs:
        nodes.append({"id": sid, "parent": "SRC", "code": code, "title": lab, "tone": "software", "maxw": 240,
                      "legend": "Record or result"})
        for k in kinds:
            for key in sorted({gid[r["file"]] for r in groups.get(k, [])}):
                edges.append({"src": sid, "dst": key, "label": ""})
    for a in d["assets"]:
        aid = "s_" + mid(a["file"])
        nodes.append({"id": aid, "parent": "SRC", "code": f"assets/{a['file']}", "title": f"CL-05 geometry, {a['kb']} KB",
                      "tone": "software", "maxw": 240, "legend": "Record or result"})
        for u in a["users"]:
            edges.append({"src": aid, "dst": gid[u], "label": "", "dash": True})
    if d["threes"]:
        nodes.append({"id": "s_three", "parent": "SRC", "code": f"three.js {', '.join(d['threes'])}",
                      "title": "jsDelivr, pinned by SHA-256", "tone": "external", "maxw": 240, "legend": "External"})
        for key in sorted({gid[r["file"]] for r in pages if r["three"]}):
            edges.append({"src": "s_three", "dst": key, "label": "", "dash": True})
    checks = sorted({r["check"] for r in pages})
    for c in checks:
        cid = "c_" + mid(c)
        nodes.append({"id": cid, "parent": "CK", "code": c.replace("sim/scenes3d/", ""), "title": "CI check",
                      "tone": "current", "maxw": 230, "legend": "CI check"})
        for key in sorted({gid[r["file"]] for r in pages if r["check"] == c}):
            edges.append({"src": key, "dst": cid, "label": ""})
    stills = sorted({s for r in pages for s in r["stills"]})
    if stills:
        nodes.append({"id": "c_stills", "parent": "CK", "code": "docs/wiki/images/3d-*.png",
                      "title": f"{plural(len(stills), 'still')}", "tone": "system", "maxw": 230,
                      "legend": "Generated (checked in CI)"})
        for c in checks:
            if c.endswith(".mjs"):
                edges.append({"src": "c_" + mid(c), "dst": "c_stills", "label": "renders", "dash": True})
    return {"file": "fig-2-composition.svg", "number": "2", "title": "What each page is built from",
            "subtitle": "The records and results embedded in each kind of page, what it loads when opened, and the CI "
                        "check that opens it in headless Chromium and renders its still (read from the pages and the "
                        "checks' page filters).",
            "ref": "docs/3d · sim/scenes3d", "direction": "RIGHT", "orient": "fixed", "nodes": nodes,
            "edges": edges, "legend": [edge_leg("Embedded at build"), edge_leg("Loaded when opened", True)]}


# ================================================================ SysML
def fig_sysml(d: dict) -> tuple[dict, str]:
    nodes = [{"id": "Page3D", "shape": "class", "title": "Page3D", "stereotype": "part def",
              "attrs": ["file : String", "threeVersion : String", "syntheticLabel : Boolean", "ciCheck : String"],
              "tone": "system"},
             {"id": "ScenePage", "shape": "class", "title": "ScenePage", "stereotype": "part def :> Page3D",
              "attrs": ["scene : String", "hazards : String", "outcome : String", "look : String"], "tone": "safety"},
             {"id": "SheetPage", "shape": "class", "title": "SheetPage", "stereotype": "part def :> Page3D",
              "attrs": ["sheetNumber : String", "geometry : String", "hazardCount : Integer", "replays : String"],
              "tone": "interface"},
             {"id": "IndexPage", "shape": "class", "title": "IndexPage", "stereotype": "part def :> Page3D",
              "attrs": ["links : Integer"], "tone": "external"}]
    edges = [{"src": k, "dst": "Page3D", "label": "specializes", "dash": True}
             for k in ("ScenePage", "SheetPage", "IndexPage")]
    s = ["    part def Page3D {",
         "        doc /* A page in docs/3d: built from the records and results, opened by a CI check. */",
         "        attribute file : String;", "        attribute threeVersion : String;",
         "        attribute syntheticLabel : Boolean;", "        attribute ciCheck : String;", "    }",
         "    part def ScenePage :> Page3D {",
         "        doc /* A replay of one exported scene analysis in one look; a variant changes only the look. */",
         "        attribute scene : String;", "        attribute hazards : String;", "        attribute outcome : String;",
         "        attribute look : String;", "    }",
         "    part def SheetPage :> Page3D {",
         "        doc /* An interactive general-arrangement sheet on the CL-05 concept geometry. */",
         "        attribute sheetNumber : String;", "        attribute geometry : String;",
         "        attribute hazardCount : Integer;", "        attribute replays : String;", "    }",
         "    part def IndexPage :> Page3D {", "        doc /* Plain list of the pages. */",
         "        attribute links : Integer;", "    }"]
    for r in d["pages"]:
        pn = "p" + re.sub(r"\W", "", r["stem"].title())
        common = [f"        attribute :>> file = \"{r['file']}\";",
                  f"        attribute :>> threeVersion = \"{r['three']}\";",
                  f"        attribute :>> syntheticLabel = {'true' if r['label'] else 'false'};",
                  f"        attribute :>> ciCheck = \"{r['check']}\";"]
        if r["kind"] in ("scene", "variant"):
            s += [f"    part {pn} : ScenePage {{", f"        doc /* {r['title']} */", *common,
                  f"        attribute :>> scene = \"{r['base']}\";",
                  f"        attribute :>> hazards = \"{', '.join(r['hazards'])}\";",
                  f"        attribute :>> outcome = \"{r['outcome']}\";", f"        attribute :>> look = \"{r['look']}\";",
                  "    }"]
        elif r["kind"] == "sheet":
            geo = ", ".join(x for x in r["scripts"] if x.startswith("assets/"))
            s += [f"    part {pn} : SheetPage {{", f"        doc /* {r['title']} */", *common,
                  f"        attribute :>> sheetNumber = \"{r['sheet']['sheet']}\";",
                  f"        attribute :>> geometry = \"{geo}\";",
                  f"        attribute :>> hazardCount = {len(r['hazards'])};",
                  f"        attribute :>> replays = \"{', '.join(r['replay'])}\";", "    }"]
        else:
            s += [f"    part {pn} : IndexPage {{", f"        doc /* {r['title']} */", *common,
                  f"        attribute :>> links = {len(r['links'])};", "    }"]
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — Pages3D", "ref": "docs/3d/Pages3D.sysml",
            "subtitle": f"The three kinds of page and what each records; Pages3D.sysml also holds all "
                        f"{len(d['pages'])} pages as parts with their values read from the pages.",
            "frame": {"kind": "bdd", "type": "package", "name": "Pages3D"}, "direction": "DOWN",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Specializes", True), ("#EEF2FF", "#4F46E5", "Page"),
                       ("#FFF7ED", "#C2410C", "Scene replay"), ("#F5F3FF", "#7C3AED", "Sheet"),
                       ("#F1F5F9", "#475569", "Index")]}
    sysml = "\n".join([
        f"// Pages3D — generated by {GEN} from the pages in docs/3d.",
        "// Do not edit by hand: rebuild the pages or change the generator and regenerate.",
        "// Status: concept geometry and synthetic results; no evidence credit.", "",
        "package Pages3D {",
        "    private import ScalarValues::*;",
        "    doc /* The interactive 3D pages (docs/3d/README.md). */",
        *s, "}", ""])
    return spec, sysml


