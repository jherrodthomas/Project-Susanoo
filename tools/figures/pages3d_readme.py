def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    block = fig_block(ctx, {"scope": d["subs"]})
    by = defaultdict(list)
    for h in d["shown"]:
        for s in d["hazards"].get(h, {}).get("subsystems") or []:
            by[s].append(h)
    for n in block["nodes"]:
        if n.get("code") in by:
            hs = by[n["code"]]
            n["sub"] = ", ".join(hs) if len(hs) <= 3 else f"{len(hs)} hazards"
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"SUS-I1 decomposition. The {len(d['subs'])} subsystems named by the {len(d['shown'])} hazards "
                          "the pages show are coloured, with those hazards under each.")
    boundary = fig_boundary(ctx, {"path": "docs/3d", "boundary": {
        "name": "3D pages", "inside": ["Scene pages", "Sheet pages", "Index page", "Geometry asset"],
        "outside": ["3D scene builder", "CAD geometry", "three.js (pinned)", "CI", "Wiki", "Reader"],
        "flows": FLOWS}})
