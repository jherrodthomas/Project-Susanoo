def out_tone(o: str) -> str:
    return "ok" if o in GOOD else ("amber" if o == "landed-at-stale-home" else "red")


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


# ================================================================ records
def check_filters() -> dict:
    """Which pages each CI check opens, read from the checks themselves."""
    render = (ROOT / "sim/scenes3d/render.mjs").read_text()
    m = re.search(r"filter\(f => /(.+?)/\.test\(f\)\)", render)
    sheet = (ROOT / "sim/scenes3d/sheet_check.mjs").read_text().split("import", 1)[0]
    return {"render": re.compile(m.group(1)) if m else None,
            "sheet": sorted(set(re.findall(r"docs/3d/([\w-]+\.html)", sheet)))}


def embedded(text: str) -> tuple[str, dict]:
    m = re.search(r"window\.(SCENE|SHEET) = (\{.*?\});\s*</script>", text, re.S)
    return (m.group(1), json.loads(m.group(2))) if m else ("", {})


def sheet_sources(sheet_id: str) -> str:
    """The sheet file with this id and what its header says the figures come from."""
    for y in sorted((ROOT / "sim/scenes3d").glob("sheet*.yaml")):
        text = y.read_text()
        if re.search(rf"^id: {re.escape(sheet_id)}\s*$", text, re.M):
            head = " ".join(ln.lstrip("# ").strip() for ln in text.splitlines() if ln.startswith("#"))
            m = re.search(r"Figures (?:on the sheet )?come from (.*?); this file", head)
            return f"sim/scenes3d/{y.name}" + (f"; figures from {m.group(1)}" if m else "")
    return ""


def load() -> dict:
    ctx, _, hazards = load_reqs()
    filters = check_filters()
    pages = []
    for p in sorted(FOLDER.glob("*.html")):
        text = p.read_text()
        kind_tag, data = embedded(text)
        title = htmlmod.unescape(re.search(r"<title>(.*?)</title>", text, re.S).group(1))
        three = re.search(r"three@([\d.]+)/", text)
        scripts = re.findall(r'<script src="([^"]+)"', text)
        marker = GEN_MARK.search(text[:3000])
        r = {"file": p.name, "stem": p.stem, "title": title, "kb": round(p.stat().st_size / 1024),
             "three": three.group(1) if three else "", "scripts": scripts,
             "label": "no evidence credit" in text, "hazards": [], "outcome": "", "shows": "", "detail": ""}
        if kind_tag == "SCENE":
            a, lk = data["analysis"], data["look"]
            r.update(kind="scene" if a["id"] == p.stem else "variant", base=a["id"], hazards=a["hazards"],
                     outcome=a.get("outcome") or (a.get("performed") or {}).get("outcome", ""),
                     shows=a["title"], source=a["source"], reference=a["reference"],
                     look=f"{lk['names']['environment']} · {lk['names']['condition']} · camera {lk['camera']}",
                     builder="sim/scenes3d/build_pages.py", sources=f"sim/scenes3d/out/{a['id']}.json, scenes.yaml")
            r["detail"] = f"{a['source']} {a['reference']} · {r['look']}"
            r["stills"] = [x.name for x in [IMAGES / f"3d-{p.stem.lower()}.png"] if x.exists()]
        elif kind_tag == "SHEET":
            sh = data["sheet"]
            replay = [x["id"] for x in data.get("replay") or []]
            r.update(kind="sheet", base=p.stem, hazards=[h["id"] for h in data.get("hazards") or []],
                     shows=f"{sh['title']} (sheet {sh['sheet']}, {sh['layout']})", replay=replay,
                     postures=[x["label"] for x in data.get("postures") or []], sheet=sh,
                     builder=marker.group(1) if marker else "sim/scenes3d/build_sheet.py",
                     sources=sheet_sources(sh["id"]))
            bits = []
            if r["postures"]:
                bits.append(f"{len(r['postures'])} postures")
            bits.append(f"{len(data.get('anchors') or {})} hazard callouts")
            if replay:
                bits.append("replays " + ", ".join(replay))
            r["detail"] = " · ".join(bits)
            r["stills"] = sorted((x.name for x in IMAGES.glob(f"3d-{p.stem.lower()}*.png")), key=lambda n: (len(n), n))
        else:
            links = re.findall(r'<a href="([^"]+\.html)"', text)
            r.update(kind="index", base=p.stem, shows=f"links to {plural(len(links), 'page')}",
                     builder="sim/scenes3d/build_pages.py", sources="scenes.yaml, the sheet pages", stills=[],
                     links=links)
            r["detail"] = "plain HTML, no 3D"
        if r["kind"] in ("scene", "variant") and filters["render"] and filters["render"].match(p.name):
            r["check"] = "sim/scenes3d/render.mjs"
        elif p.name in filters["sheet"]:
            r["check"] = "sim/scenes3d/sheet_check.mjs"
        else:
            r["check"] = f"{r['builder']} --check"
        pages.append(r)
    order = {"sheet": 0, "scene": 1, "variant": 2, "index": 3}
    pages.sort(key=lambda r: (order[r["kind"]], r["base"], r["file"]))
    shown = sorted({h for r in pages for h in r["hazards"]})
    subs = sorted({x for h in shown for x in hazards.get(h, {}).get("subsystems") or []})
    assets = [{"file": a.name, "kb": round(a.stat().st_size / 1024),
               "users": [r["file"] for r in pages if f"assets/{a.name}" in r["scripts"]]}
              for a in sorted((FOLDER / "assets").glob("*.js"))]
    threes = sorted({r["three"] for r in pages if r["three"]})
    return {"ctx": ctx, "hazards": hazards, "pages": pages, "shown": shown, "subs": subs, "assets": assets,
            "threes": threes, "filters": filters}


