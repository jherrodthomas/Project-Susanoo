def fig_interfaces(d: dict) -> str:
    ifs, hz = d["ifs"], d["hazards"]
    W, M = 1120, 40
    head, y0 = fk.header(
        W, "1", "PX4 interface register",
        f"The {len(ifs)} IF-PX4 interfaces of the item definition: who sends what to whom, and which hazards each "
        f"carries, and whether PX4Integration.sysml models it as a connection. PX4 {d['tag']} is pinned; every "
        "interface is proposed.",
        "architecture/item-definition.yaml")
    out = list(head)
    cx = {"id": M, "name": M + 100, "from": M + 380, "to": M + 520, "kind": M + 660, "hz": M + 770, "st": M + 950}
    y = y0 + 30
    for k, lab in (("id", "Interface"), ("name", "Name / exchange"), ("from", "From"), ("to", "To"),
                   ("kind", "Kind"), ("hz", "Hazards"), ("st", "In SysML")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 40
    for n, i in enumerate(ifs):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        p, _ = fk.pill(cx["id"], cy - 12, i["id"], TONES["interface"][1], color=TONES["interface"][0],
                       stroke=TONES["interface"][0])
        out += p
        out.append(fk.text(cx["name"], cy - 6, fk.wrap(i["name"], 270, 11, True, max_lines=1)[0], size=11, fill=INK,
                           weight=700))
        out.append(fk.text(cx["name"], cy + 8, fk.wrap(i.get("exchange", ""), 270, 9.5, max_lines=1)[0], size=9.5,
                           fill=MUTED))
        arrow = "↔" if i.get("direction") == "bi" else "→"
        out.append(fk.text(cx["from"], cy, i["from"], size=10, fill=INK, mono=True))
        out.append(fk.text(cx["to"] - 22, cy, arrow, size=12, fill=MUTED))
        out.append(fk.text(cx["to"], cy, i["to"], size=10, fill=INK, mono=True))
        out.append(fk.text(cx["kind"], cy, ", ".join(i.get("kind", [])), size=10.5, fill=MUTED))
        x = cx["hz"]
        for h in i.get("hazard_ids") or []:
            lv = (hz.get(h, {}).get("initial_risk") or {}).get("risk_level", "")
            t = TONES[LEVEL_TONE.get(lv, "amber")]
            if x + fk.pill_w(h) > cx["st"] - 6:
                break
            p, w = fk.pill(x, cy - 12, h, t[1], color=t[0], stroke=t[0])
            out += p
            x += w + 4
        inm = i["id"] in d["modelled"]
        out.append(fk.text(cx["st"], cy, "connection" if inm else "not modelled", size=10.5,
                           fill=TONES["ok"][0] if inm else TONES["amber"][0]))
    y += len(ifs) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["interface"][1], TONES["interface"][0], "IF-PX4 interface")]
    for lv in ("High", "Serious", "Medium", "Low"):
        if any((hz.get(h, {}).get("initial_risk") or {}).get("risk_level") == lv
               for i in ifs for h in i.get("hazard_ids") or []):
            t = TONES[LEVEL_TONE[lv]]
            leg.append((t[1], t[0], f"Hazard, {lv} initial risk (preliminary)"))
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " ↔ two-way, → one-way.", W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · PX4 interface register",
                  "Every IF-PX4 interface with its ends, exchange and hazards", out)


