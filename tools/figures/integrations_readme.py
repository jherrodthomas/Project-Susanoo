# ================================================================ records
def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    item = yaml.safe_load((ROOT / "architecture" / "item-definition.yaml").read_text())
    ifs = [i for i in item["interfaces"] if i["id"].startswith("IF-PX4")]
    text = (ROOT / SYSML).read_text()
    preqs = [{"id": m.group(1), "name": m.group(2), "text": " ".join(m.group(3).split())}
             for m in re.finditer(r"requirement def <'([\w-]+)'> (\w+) \{\s*doc /\*\s*(.*?)\s*\*/", text, re.S)]
    parts = []
    for m in re.finditer(r"(part) def (\w+)(?: :> (\w+))?\s*\{(.*?)\n    \}", text, re.S):
        kind, name, sup, body = m.groups()
        doc = re.search(r"doc /\*\s*(.*?)\s*\*/", body, re.S)
        lines = [f"{a} : {t}" for a, t in re.findall(r"attribute (\w+) : (\w+);", body)]
        lines += [f"port {a} : {t}" for a, t in re.findall(r"port (\w+) : ([~\w]+);", body)]
        lines += [f"part {a} : {t}" for a, t in re.findall(r"part (\w+) : (\w+);", body)]
        parts.append({"kind": kind, "name": name, "super": sup,
                      "doc": " ".join(doc.group(1).replace("*", " ").split()) if doc else "", "lines": lines})
    for m in re.finditer(r"port def (\w+)\s*\{\s*doc /\*\s*(.*?)\s*\*/\s*\}", text):
        parts.append({"kind": "port", "name": m.group(1), "super": None, "doc": m.group(2), "lines": []})
    ssfs = {}
    for p in sorted((ROOT / "safety" / "software").glob("SSF-*.yaml")):
        s = yaml.safe_load(p.read_text())
        if "PX4" in (s.get("title", "") + s.get("description", "")):
            ssfs[s["id"]] = s
    scen = yaml.safe_load((ROOT / "sim" / "uav" / "scenarios.yaml").read_text())["scenarios"]
    uav = {p.stem: json.loads(p.read_text()) for p in sorted((ROOT / "sim" / "results" / "uav").glob("SU-*.json"))}
    tag = re.search(r'TAG="([^"]+)"', (ROOT / "sim" / "uav" / "fetch_px4.sh").read_text()).group(1)
    modelled = set()
    for m in re.finditer(r"connection \w+ connect .*?doc /\*\s*(IF-PX4-[\d/]+)", text):
        first, *rest = m.group(1).split("/")
        modelled |= {first} | {first[:-len(r)] + r for r in rest}
    dqs = [e for e in yaml.safe_load((ROOT / "decisions" / "register.yaml").read_text())["decisions"]
           if "PX4" in e.get("question", "") + str(e.get("context", ""))]
    hz = sorted({h for i in ifs for h in i.get("hazard_ids") or []} | {h for s in scen for h in s.get("hazards", [])})
    return {"ctx": ctx, "reqs": reqs, "hazards": hazards, "ifs": ifs, "preqs": preqs, "parts": parts, "ssfs": ssfs,
            "scen": scen, "uav": uav, "tag": tag, "hz": hz,
            "modelled": modelled, "dqs": dqs, "excluded": " ".join(re.search(
                r"(\*\*Explicitly excluded:\*\*.*?)\n\n", (ROOT / "integrations" / "px4" / "README.md").read_text(),
                re.S).group(1).split()),
            "sysreqs": [r for r in reqs.values() if {"SUS-A1", "SUS-A1-FC", "SUS-I1-INT"} & set(r.get("allocated_to", []))]}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def ssf_hazards(d: dict, sid: str) -> list[str]:
    out = []
    for hid, h in d["hazards"].items():
        refs = {x for cf in h.get("causal_factors") or [] for x in cf.get("ssf_ids") or []}
        refs |= {x for m in h.get("mitigations") or [] for x in m.get("ssf_ids") or []}
        if sid in refs:
            out.append(hid)
    return out


