def fig_sysml(d: dict) -> tuple[dict, str]:
    p = d["l2"]["params"]
    def lines(keys):
        return [f"{camel(k)} : Real = {p[k]['value']:g}  [{p[k]['unit']}]" for k in keys if k in p]
    nodes = [
        {"id": "WalkerL2", "shape": "class", "title": "WalkerL2", "stereotype": "part def",
         "attrs": lines(WORLD) + ["part torso : Torso", "part leftLeg : Leg", "part rightLeg : Leg"], "tone": "system"},
        {"id": "Torso", "shape": "class", "title": "Torso", "stereotype": "part def",
         "attrs": lines(TORSO) + ["joints: slide x, slide z, pitch"], "tone": "system"},
        {"id": "Leg", "shape": "class", "title": "Leg", "stereotype": "part def",
         "attrs": lines(LEG) + ["joints: hip, knee, ankle (hinge about y)", "box foot in ground contact"],
         "tone": "safety"}]
    edges = [{"src": "WalkerL2", "dst": "Torso", "label": "torso", "arrow": "diamond"},
             {"src": "WalkerL2", "dst": "Leg", "label": "leftLeg, rightLeg [2]", "arrow": "diamond"}]
    def attrs(keys, ind="        "):
        return [f"{ind}attribute {camel(k)} : Real = {float(p[k]['value'])};  // {p[k]['unit']}, {p[k]['status']}"
                for k in keys if k in p]
    s = ["    part def Torso {",
         "        doc /* Cockpit, pelvis, power and manipulators lumped above the hips; slide x, slide z and pitch. */",
         *attrs(TORSO), "    }",
         "    part def Leg {",
         "        doc /* Hip, knee and ankle hinges about y and a box foot; each joint has a lock for load holding. */",
         *attrs(LEG), "    }",
         "    part def WalkerL2 {",
         f"        doc /* {d['l2']['id']} {d['l2']['revision']}: the planar level-2 walker in MuJoCo. */",
         *attrs(WORLD),
         "        part torso : Torso;", "        part leftLeg : Leg;", "        part rightLeg : Leg;", "    }"]
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — WalkerL2", "ref": "sim/mujoco/WalkerL2.sysml",
            "subtitle": f"The planar level-2 walker: a torso and two legs with the parameters of {d['l2']['id']}, "
                        "generated into WalkerL2.sysml from the spec. The joint torques are the sized values.",
            "frame": {"kind": "bdd", "type": "package", "name": "WalkerL2"}, "direction": "RIGHT",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Composition (diamond at owner)"), ("#EEF2FF", "#4F46E5", "Part definition"),
                       ("#FFF7ED", "#C2410C", "Leg: carries the sized joint torques")]}
    sysml = "\n".join([
        f"// WalkerL2 — generated by {GEN} from sim/spec/walker_l2.yaml.",
        "// Do not edit by hand: change the spec or the generator and regenerate.",
        "// Status: level-2 concept assumptions; synthetic, no evidence credit.", "",
        "package WalkerL2 {",
        "    private import ScalarValues::*;",
        "    doc /* The level-2 MuJoCo walker model (sim/mujoco/README.md). */",
        *s, "}", ""])
    return spec, sysml


