# ================================================================ records
def load() -> dict:
    ctx, _, hazards = load_reqs()
    l2 = yaml.safe_load((ROOT / "sim" / "spec" / "walker_l2.yaml").read_text())
    cc = json.loads((RES / "l2-crosscheck.json").read_text())
    sz = json.loads((RES / "sizing-cf4.json").read_text())
    szdef = yaml.safe_load((FOLDER / "sizing.yaml").read_text())
    doc = (FOLDER / "l2.py").read_text().split('"""')[1]
    physics = [" ".join(m.group(1).split()) for m in re.finditer(r"^\s+- (.*?)(?=^\s+- |^What|\Z)",
                                                                   doc.split("What is unchanged", 1)[0], re.M | re.S)]
    rest = doc.split("What is unchanged from level 1", 1)[1].split("\n\n", 1)[0]
    unchanged = " ".join(rest.split()).split(":", 1)[1].strip()
    faults = {f["id"]: f for f in yaml.safe_load((ROOT / "sim" / "faults.yaml").read_text())["faults"]}
    hz = {sz["hazard"]}
    for r in cc["rows"]:
        f = (r.get("case") or {}).get("fault")
        if f in faults:
            hz |= {c.split(":")[0] for c in faults[f]["causes"]}
    hz = sorted(hz)
    subs = sorted({s for h in hz for s in hazards.get(h, {}).get("subsystems") or []})
    return {"ctx": ctx, "hazards": hazards, "l2": l2, "cc": cc, "sz": sz, "szdef": szdef, "physics": physics,
            "unchanged": unchanged, "hz": hz, "subs": subs}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


# ================================================================ figure 1 · cross-check (drawn directly)
def fig_crosscheck(d: dict) -> str:
    cc = d["cc"]
    rows = cc["rows"]
    agree = sum(1 for r in rows if r["agree"])
    W, M = 1240, 40
    head, y0 = fk.header(
        W, "1", "Level 1 against level 2, case by case",
        f"Every cross-check case run on the level-1 plant and the MuJoCo {cc['mujoco']} model: {agree} of {len(rows)} "
        f"outcome classes agree. Each disagreement carries a note explaining it ({plural(len(cc['unexplained']), 'case')} "
        "unexplained). A disagreement is a finding about the models, not something to tune away.",
        "sim/results/l2-crosscheck.json")
    out = list(head)
    cx = {"id": M, "fam": M + 120, "l1": M + 190, "l2": M + 300, "ag": M + 410, "note": M + 450}
    y = y0 + 30
    for k, lab in (("id", "Case"), ("fam", "Family"), ("l1", "Level 1"), ("l2", "Level 2"), ("note", "Note")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 24
    for n, r in enumerate(rows):
        top = y + n * rh
        if not r["agree"]:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=TONES["amber"][1], stroke="none", rx=5, sw=0))
        elif n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=5, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["id"], cy, r["id"], size=10, fill=INK, mono=True, weight=700))
        out.append(fk.text(cx["fam"], cy, r["family"], size=10, fill=MUTED, mono=True))
        for k in ("l1", "l2"):
            oc = r[k]["outcome"]
            t = TONES[OUT_TONE.get(oc, "amber")]
            p, _ = fk.pill(cx[k], cy - 12, oc, t[1], color=t[0], stroke=t[0])
            out += p
        out.append(fk.text(cx["ag"], cy, "=" if r["agree"] else "≠", size=13,
                           fill=TONES["ok"][0] if r["agree"] else TONES["amber"][0], weight=700))
        if r.get("note"):
            out.append(fk.text(cx["note"], cy, fk.wrap(r["note"], W - M - cx["note"], 9.5, max_lines=1)[0], size=9.5,
                               fill=INK))
    y += len(rows) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["ok"][1], TONES["ok"][0], "Safe"), (TONES["red"][1], TONES["red"][0], "Tip or hard drop"),
           (TONES["amber"][1], TONES["amber"][0], "Models disagree (note in the results)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " Families: " + "; ".join(f"{k} {v['title']} ({v['agree']}/{v['cases']})"
                                                        for k, v in cc["families"].items()) + ".",
                      W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Level 1 against level 2, case by case",
                  "Every cross-check case with both outcomes", out)


# ================================================================ figure 2 · sizing (drawn directly)
def fig_sizing(d: dict) -> str:
    sz, szdef = d["sz"], d["szdef"]
    W, M = 1240, 40
    prop = sz["proposal"]
    head, y0 = fk.header(
        W, "2", f"Sizing the joints against {sz['hazard']} {sz['causal_factor']} ({sz['id']})",
        f"{sz['title']}: failures on the {sz['grid_cases']}-case operating-envelope grid for each swept torque, with "
        f"load holding working. Proposal (preliminary, adopted in the level-2 spec by the lead, DQ-012): ankle "
        f"{prop['ankle_torque_max_nm']:,} N m ({prop['ankle_ratio']:.2f} m g L_foot), knee {prop['knee_torque_max_nm']:,} N m; "
        f"{prop['failures']} failures on the grid, {sz['lowest_clear_ankle_corner_failures']} on the {sz['corner_cases']}-case "
        "corner grid.", "sim/results/sizing-cf4.json")
    out = list(head)
    pw = (W - 2 * M - 40) / len(sz["sweeps"])
    ph = 260
    top = y0 + 40
    maxf = max(r["failures"] for sw in sz["sweeps"] for r in sw["rows"]) or 1
    for i, sw in enumerate(sz["sweeps"]):
        px = M + i * (pw + 40)
        held = next(s for s in szdef["sweeps"] if s["id"] == sw["id"]).get("with") or {}
        title = f"{sw['id']} torque (N m)" + ("".join(f" · {k} held at {v:,}" for k, v in held.items()))
        out.append(fk.text(px, top - 14, title, size=11, fill=INK, weight=700))
        base = top + ph
        out.append(fk.line(px, base, px + pw, base, stroke=HAIR, sw=1))
        bw = pw / len(sw["rows"])
        pval = prop.get(sw["param"])
        for k, r in enumerate(sw["rows"]):
            x = px + k * bw
            h = (ph - 30) * r["failures"] / maxf
            t = TONES["red" if r["failures"] else "ok"]
            out.append(fk.rect(x + 10, base - max(h, 2), bw - 20, max(h, 2), fill=t[0], stroke="none", rx=3, sw=0))
            out.append(fk.text(x + bw / 2, base - max(h, 2) - 6, f"{r['failures']} fail", size=10, fill=t[0],
                               anchor="middle", weight=700))
            lab = f"{r['value']:,}"
            out.append(fk.text(x + bw / 2, base + 16, lab, size=10, fill=INK, anchor="middle",
                               weight=700 if r["value"] == sw["lowest_clear"] else ""))
            if r["value"] == sw["lowest_clear"]:
                out.append(fk.text(x + bw / 2, base + 30, "lowest clear", size=9, fill=TONES["ok"][0], anchor="middle"))
        if pval is not None:
            vals = [r["value"] for r in sw["rows"]]
            lo, hi = min(vals), max(vals)
            span = (hi - lo) or 1
            fx = px + bw / 2 + (len(vals) - 1) * bw * (pval - lo) / span if lo <= pval <= hi else None
            if fx is not None:
                out.append(f'<line x1="{fx:.1f}" y1="{top:.1f}" x2="{fx:.1f}" y2="{base - 24:.1f}" stroke="{TONES["safety"][0]}" '
                           'stroke-width="1.5" stroke-dasharray="5 3"/>')
                out.append(fk.text(fx - 4, top + 10, f"proposal {pval:,}", size=10, fill=TONES["safety"][0], weight=700,
                                   anchor="end"))
    y = top + ph + 52
    g = szdef["grid"]
    out.append(fk.text(M, y, "Grid: " + "; ".join(f"{k} {', '.join(map(str, v))}" for k, v in g.items()), size=10,
                       fill=MUTED))
    y += 16
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["red"][1], TONES["red"][0], "Grid cases that fail"), (TONES["ok"][1], TONES["ok"][0], "Clears the grid"),
           ("#FFFFFF", TONES["safety"][0], "Proposal (preliminary)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " A proposal is a draft input to the actuation trade (TS-001), not a design value.",
                      W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, f"Figure 2 · Sizing the joints against {sz['hazard']} {sz['causal_factor']}",
                  "Failures on the envelope grid by swept joint torque", out)


