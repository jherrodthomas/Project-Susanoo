"""Build architecture/README.md and architecture/figures/*.svg from the item definition.

Everything on the page is read from records, so it cannot drift from them:

  architecture/item-definition.yaml   elements, externals, interfaces, functions (the single source)
  safety/hazards/HAZ-*.yaml           hazards that name an element (subsystems) or an interface
  requirements/SYS-*.yaml             requirements allocated to an element
  models/sysml/model/                 the SysML part hierarchy checked against the item definition

Figures (house style of framework/documentation-standard.md):

  fig-1-element-register.svg      every element: kind, safety role, status, interfaces, functions, hazards, requirements
  fig-2-functions.svg             which elements perform each function (F-nn), with modes
  fig-3-block-diagram.svg         SUS-I1 decomposition with every internal interface
  fig-4-boundary-diagram.svg      the SUS-I1 boundary: every interface to an external entity, numbered
  fig-5-sysml-block-definition.svg SysML part definitions and composition, read from Architecture.sysml
  fig-6-inputs-and-outputs.svg    what the item definition consumes and feeds

The README part above the END marker is generated; anything below it is preserved.

    python3 tools/figures/architecture_readme.py            # write
    python3 tools/figures/architecture_readme.py --check    # fail if anything is stale
"""
