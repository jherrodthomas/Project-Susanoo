# ================================================================ records
def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    item = yaml.safe_load((ROOT / ITEM).read_text())
    ex = {x["id"] for x in item["externals"]}
    ifs: Counter = Counter()
    for i in item["interfaces"]:
        ifs[i["from"]] += 1
        ifs[i["to"]] += 1
    fn: dict[str, list[str]] = {}
    for f in item["functions"]:
        for e in f["performed_by"]:
            fn.setdefault(e, []).append(f["id"])
    hz: dict[str, list[str]] = {}
    for hid, h in hazards.items():
        for e in h.get("subsystems") or []:
            hz.setdefault(e, []).append(hid)
    rq: dict[str, list[str]] = {}
    for rid, r in reqs.items():
        for e in r.get("allocated_to") or []:
            rq.setdefault(e, []).append(rid)
    return {"ctx": ctx, "item": item, "ex": ex, "ifs": ifs, "fn": fn, "hz": hz, "rq": rq, "hazards": hazards,
            "reqs": reqs}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def depth(item: dict, eid: str) -> int:
    par = {e["id"]: e["parent"] for e in item["elements"]}
    n = 0
    while par.get(eid) and par[eid] != item["id"]:
        eid, n = par[eid], n + 1
    return n


def ordered(item: dict) -> list[dict]:
    kids: dict[str, list[dict]] = {}
    for e in item["elements"]:
        kids.setdefault(e["parent"], []).append(e)
    out = []

    def walk(p):
        for e in kids.get(p, []):
            out.append(e)
            walk(e["id"])
    walk(item["id"])
    return out


# ================================================================ figure 1 · element register (drawn directly)
def fig_register(d: dict) -> str:
    item = d["item"]
    els = ordered(item)
    W, M = 1120, 40
    head, y0 = fk.header(
        W, "1", "Element register",
        f"{plural(len(els), 'element')} of {item['id']} ({item['revision']}, {item['status']}), "
        f"{plural(len(item['externals']), 'external')}, {plural(len(item['interfaces']), 'interface')} and "
        f"{plural(len(item['functions']), 'function')}. Counts show how much of the safety record rests on each element.",
        ITEM)
    out = list(head)
    cx = {"id": M, "name": M + 160, "kind": M + 470, "role": M + 580, "status": M + 670, "if": M + 760,
          "fn": M + 820, "hz": M + 950, "rq": M + 1010}
    y = y0 + 30
    for k, lab in (("id", "Element"), ("name", "Name"), ("kind", "Kind"), ("role", "Safety role"),
                   ("status", "Status"), ("if", "IFs"), ("fn", "Functions"), ("hz", "Hazards"),
                   ("rq", "Reqs")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 30
    for n, e in enumerate(els):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        ind = 14 * depth(item, e["id"])
        tone = TONES["safety" if e.get("safety_role") == "protective" else KIND_TONE.get(e.get("kind"), "system")]
        p, _ = fk.pill(cx["id"] + ind, cy - 12, e["id"], tone[1], color=tone[0], stroke=tone[0])
        out += p
        bold = depth(item, e["id"]) == 0
        out.append(fk.text(cx["name"], cy, fk.wrap(e["name"], 295, 11, bold, max_lines=1)[0], size=11, fill=INK,
                           weight=700 if bold else 400))
        out.append(fk.text(cx["kind"], cy, e.get("kind", ""), size=10.5, fill=MUTED))
        role = e.get("safety_role", "none")
        out.append(fk.text(cx["role"], cy, role, size=10.5, fill=TONES["safety"][0] if role != "none" else FAINT,
                           weight=700 if role != "none" else 400))
        st = e.get("status", "")
        out.append(fk.text(cx["status"], cy, st, size=10.5, fill=TONES["amber"][0] if st == "candidate" else MUTED))
        for k, v in (("if", d["ifs"].get(e["id"], 0)), ("hz", len(d["hz"].get(e["id"], []))),
                     ("rq", len(d["rq"].get(e["id"], [])))):
            out.append(fk.text(cx[k] + 10, cy, str(v) if v else "–", size=11, fill=INK if v else FAINT,
                               anchor="middle", weight=700 if v else 400))
        f = d["fn"].get(e["id"], [])
        out.append(fk.text(cx["fn"], cy, ", ".join(x.replace("F-0", "F") for x in f) or "–", size=10.5,
                           fill=INK if f else FAINT))
    y += len(els) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["system"][1], TONES["system"][0], "System element"),
           (TONES["software"][1], TONES["software"][0], "Computing"),
           (TONES["interface"][1], TONES["interface"][0], "Human interface"),
           (TONES["safety"][1], TONES["safety"][0], "Protective safety role"),
           ("#FFFFFF", TONES["work"][0], "Mixed")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " IFs = interfaces it is an end of; Hazards = hazard records naming it as a subsystem; "
                      "Reqs = requirements allocated to it.", W - 2 * M, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Element register",
                  "Every element of the item definition with its links into the safety record", out)


# ================================================================ ELK figures
def fig_functions(d: dict) -> dict:
    item, ctx = d["item"], d["ctx"]
    nodes = [{"id": "FN", "banner": "Functions · F-nn", "tone": "work"},
             {"id": "EL", "banner": "Performed by", "tone": "work"}]
    edges, used = [], []
    for f in item["functions"]:
        nodes.append({"id": mid(f["id"]), "parent": "FN", "code": f["id"], "title": f["name"],
                      "sub": "modes " + ", ".join(f.get("modes", [])) + " · " + ", ".join(f.get("scenarios", [])),
                      "tone": "system", "maxw": 260})
        for e in f["performed_by"]:
            if e not in used:
                used.append(e)
            edges.append({"src": mid(f["id"]), "dst": "el_" + mid(e), "label": ""})
    for e in used:
        nodes.append({**ctx.card(e, nid="el_" + mid(e)), "parent": "EL", "maxw": 240})
    return {"file": "fig-2-functions.svg", "number": "2", "title": "Functions and the elements that perform them",
            "subtitle": f"The {len(item['functions'])} system functions of the item definition, the operating modes "
                        "and CONOPS scenarios they serve, and the elements that perform them.",
            "ref": ITEM, "direction": "RIGHT", "orient": "fixed", "nodes": nodes, "edges": edges,
            "legend": [edge_leg("performed_by")]}


def boundary_flows(d: dict) -> list[tuple[str, str, str, dict]]:
    out = []
    for i in d["item"]["interfaces"]:
        if i["from"] in d["ex"] or i["to"] in d["ex"]:
            lab = f"{i['id']} {i['name'].lower()}"
            out.append((i["from"], i["to"], lab, i))
    return out


def figure_specs(d: dict) -> list[dict]:
    ctx, item = d["ctx"], d["item"]
    block = fig_block(ctx, {"scope": [item["id"]]})
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"{item['id']} decomposition with its internal interfaces (IF-nnn). Interfaces between "
                          "subsystems are grouped; the N2 chart lists each one.")
    flows = boundary_flows(d)
    inside = []
    for a, b, _, _ in flows:
        for k in (a, b):
            if k not in d["ex"] and k not in inside:
                inside.append(k)
    outside = [x["id"] for x in item["externals"] if any(x["id"] in (a, b) for a, b, _, _ in flows)]
    boundary = fig_boundary(ctx, {"path": "architecture", "boundary": {
        "name": f"{item['id']} system boundary", "inside": inside, "outside": outside,
        "flows": [[a, b, lab] for a, b, lab, _ in flows]}})
    for e, (_, _, _, i) in zip(boundary["edges"], flows):
        if i.get("direction") == "bi":
            e["arrow"] = "both"
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref=ITEM,
                    subtitle=f"Every interface between {item['id']} and the {len(outside)} external entities it "
                             "touches, numbered as in the table. Two-headed arrows are two-way interfaces.")
    bdd = system_bdd(ctx)
    bdd.update(file="fig-5-sysml-block-definition.svg", number="5")
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "architecture/README.md", "direction": "RIGHT",
          "subtitle": "What the item definition is built from (left) and what is checked against or drawn from it "
                      "(right).",
          "nodes": [
              {"id": "I1", "title": "CONOPS.md", "sub": "modes MOD-nn, scenarios SCN-nnn", "tone": "work"},
              {"id": "I2", "title": "Concept architecture", "sub": "concept/architecture.md", "tone": "work"},
              {"id": "I3", "title": "Trade studies", "sub": "architecture/trades", "tone": "work"},
              {"id": "I4", "title": "Decision register", "sub": "baseline decisions", "tone": "work"},
              {"id": "X", "code": "architecture/", "title": "Item definition", "tone": "current"},
              {"id": "O1", "title": "SysML model", "sub": "models/sysml/model (checked)", "tone": "software"},
              {"id": "O2", "title": "Hazards and requirements", "sub": "element and interface IDs", "tone": "work"},
              {"id": "O3", "title": "882E work-product tree", "sub": "block and boundary figures", "tone": "work"},
              {"id": "O4", "title": "Item-definition figures", "sub": "context, boundary, N2", "tone": "work"},
              {"id": "O5", "title": "Simulation and CAD", "sub": "sim/, cad/", "tone": "work"}],
          "edges": [{"src": "I1", "dst": "X", "label": "modes, scenarios"},
                    {"src": "I2", "dst": "X", "label": "elements"},
                    {"src": "I3", "dst": "X", "label": "candidate sub-elements"},
                    {"src": "I4", "dst": "X", "label": "applied answers"},
                    {"src": "X", "dst": "O1", "label": "M1 M2 M4 checks"},
                    {"src": "X", "dst": "O2", "label": "IDs (A03)"},
                    {"src": "X", "dst": "O3", "label": "scope, boundaries"},
                    {"src": "X", "dst": "O4", "label": "fig_item.py"},
                    {"src": "X", "dst": "O5", "label": "element IDs"}]}
    specs = [fig_functions(d), block, boundary, bdd, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    return specs


# ================================================================ README
def img(file: str, number: str, title: str) -> str:
    return f"![Figure {number} · {title}](figures/{file})\n"


