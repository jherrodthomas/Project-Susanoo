        + "Not a baseline: approving the item definition is a human review (rule R13).\n",
        "| Field | Value |", "|---|---|",
        f"| Record | [`item-definition.yaml`](item-definition.yaml) (schema `{item['schema']}`) |",
        f"| Scope | {item['scope'].strip()} |",
        f"| Protective elements | {', '.join(prot) or '—'} |",
        f"| SysML model | [`Architecture.sysml`](../{ARCH}) (checked against this record by `python -m tools.sysml.check`) |",
