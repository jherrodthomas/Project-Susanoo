           + ("" if all(i["src_exists"] for i in ims) and all(c["src_exists"] for c in d["clips"]) else " **except some**")
           + f"; {sum(1 for i in d['ideas'] if i['records'])} of {len(d['ideas'])} ideas carried by a record. "
           "AI-made, **not engineering and not evidence**.\n",
           "The folder holds AI concept art made from the project's own renders, to show what the machine is for and "
           "to surface ideas early. The page above is hand-written; this section is generated from it and the "
           "records, so the register, the source renders and the ideas stay in step.\n",
           "## Every image and clip\n", img("fig-1-art-register.svg", "1", "Every image and clip, against the CAD"),
           "| Image | Livery | Source render | Against the CAD |", "|---|---|---|---|",
           *[f"| {i['title']} | {i['livery']} | `{i['src']}` | {'close' if i['close'] else 'differs'} |" for i in ims],
           *[f"| `{c['file']}` ({c['secs']} s) | {'military' if 'military' in c['file'] else 'industrial'} | "
             f"`{c['start']}`{' → `' + c['end'] + '`' if c['end'] else ''} | motion; see above |" for c in d["clips"]],
