def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = load()
    specs, sysml = figure_specs(d)
    files = {SYSML: sysml, FIGS / "fig-1-art-register.svg": fig_register(d)}
    for spec, svg in zip(specs, diagram.render_all(specs)):
        files[FIGS / spec["file"]] = svg
    text = README.read_text()
    sec = section(d, specs)
    if START in text:
        before, rest = text.split(START, 1)
        files[README] = before + sec + rest.split(END, 1)[1]
    else:
        files[README] = text.rstrip("\n") + "\n\n" + sec + "\n"
    return emit(files, FIGS, args.check, GEN)


