"""Add the record-driven part of cad/concept-art/README.md, cad/concept-art/figures/*.svg and
cad/concept-art/ConceptArt.sysml.

cad/concept-art/README.md stays the hand-written page of AI concept art (what each image shows, the render and job it
came from, how it differs from the CAD). This generator writes only the section between the concept-art-records
markers at the end of the page, read from:

  cad/concept-art/README.md (hand part)   every image row (title, file, source render, job, how it differs from the
                                           CAD), every clip (start and end frame, job, frames sheet) and the ideas
                                           worth carrying back
  cad/concept-art/*                        which files exist, and any the page does not describe
  cad/renders/blender/                     whether each source render is still there
  decisions/register.yaml, safety/hazards  the records that cite this page, and the records that carry each idea

Figures (house style of framework/documentation-standard.md):

  fig-1-art-register.svg         every image and clip: setting, livery, source render, job, and whether it is close
                                 to the CAD or differs (with the difference)
  fig-2-render-to-record.svg     source renders → images → ideas and the records that carry them
  fig-3-block-diagram.svg        the system the images show
  fig-4-boundary-diagram.svg     what the folder holds and what crosses its boundary
  fig-5-sysml-block-definition.svg  ConceptArt (generated .sysml): image and clip, every file a part
  fig-6-inputs-and-outputs.svg   what the art is made from and what it feeds

    python3 tools/figures/art_readme.py            # write
    python3 tools/figures/art_readme.py --check    # fail if anything is stale
"""
