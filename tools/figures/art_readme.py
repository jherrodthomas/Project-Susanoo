def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    block = fig_block(ctx, {"scope": [d["root"]]})
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"The system the images show ({d['root']}). The art shows it; it does not describe it.")
    boundary = fig_boundary(ctx, {"path": "cad/concept-art", "boundary": {
        "name": "Concept art", "inside": ["Images", "Clips"],
        "outside": ["Blender renders", "Image model", "Project lead", "Design review", "Records", "CI"], "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="cad/concept-art/README.md",
                    subtitle="The folder holds the AI-made images and clips; the renders they start from, the model "
                             "that makes them and the records they feed are outside. Crossings are numbered as in the "
                             "table.")
    sysml_spec, sysml = fig_sysml(d)
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "cad/concept-art/README.md", "direction": "RIGHT",
          "subtitle": "What the art is made from (left) and what it feeds (right).",
          "nodes": [
              {"id": "I1", "title": "Blender renders", "sub": "cad/renders/blender/", "tone": "work"},
              {"id": "I2", "title": "Image model", "sub": "via the connector, job ids recorded", "tone": "external"},
              {"id": "X", "code": "cad/concept-art/", "title": "Concept art",
               "sub": f"{len(d['images'])} images, {len(d['clips'])} clips", "tone": "current"},
              {"id": "O1", "title": "Ideas for the design", "sub": f"{len(d['ideas'])} on the page", "tone": "work"},
              {"id": "O2", "title": "Lead decisions", "sub": ", ".join(q["id"] for q in d["citing"]) or "—",
               "tone": "work"},
              {"id": "O3", "title": "Communication", "sub": "pages and wiki", "tone": "work"}],
          "edges": [{"src": "I1", "dst": "X", "label": "source"}, {"src": "I2", "dst": "X", "label": "generated"},
                    {"src": "X", "dst": "O1", "label": "suggests"}, {"src": "X", "dst": "O2", "label": "cited"},
                    {"src": "X", "dst": "O3", "label": "shown"}]}
    specs = [fig_trace(d), block, boundary, sysml_spec, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    return specs, sysml


# ================================================================ README section
def img(file: str, number: str, title: str) -> str:
    return f"![Figure {number} · {title}](figures/{file})\n"


