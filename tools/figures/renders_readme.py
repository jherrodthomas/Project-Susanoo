SHOWN, UNSHOWN, MISSING = ("#DCFCE7", "#15803D"), ("#FEF3C7", "#B45309"), ("#FEE2E2", "#B91C1C")


def cell(out: list, x: float, y: float, w: float, h: float, c: dict) -> None:
    if not c["exists"]:
        fill, stroke, dash, lab, sub = MISSING[0], MISSING[1], "4 3", "missing", ""
    elif c["shown"]:
        fill, stroke, dash, lab, sub = SHOWN[0], SHOWN[1], "", f"{len(c['shown'])} page" + ("s" if len(c["shown"]) > 1 else ""), ""
    else:
        fill, stroke, dash, lab, sub = UNSHOWN[0], UNSHOWN[1], "4 3", "no page", ""
    out.append(fk.rect(x, y, w, h, fill=fill, stroke=stroke, rx=5, sw=1.1, dash=dash))
    out.append(fk.text(x + w / 2, y + h / 2 - 1, lab, size=10, fill=stroke, weight=700, anchor="middle"))
    if c.get("size"):
        out.append(fk.text(x + w / 2, y + h / 2 + 12, f"{c['size'][0]}×{c['size'][1]}", size=8.5, fill=MUTED,
                           anchor="middle", mono=True))


def fig_matrix(d: dict) -> str:
    W, M = 1240, 40
    rv, bl = d["review"], d["blender"]
    nu, ms = unshown(d), missing(d)
    head, y0 = fk.header(
        W, "1", "Every render, and whether a page shows it",
        f"{plural(len(rv), 'review render')} ({len(d['rows'])} layouts and postures × {len(d['views'])} views, from "
        f"render.cjs) and {plural(len(bl), 'Blender still')} ({len(d['shots'])} shots × {len(d['liveries'])} liveries, "
        f"from blender_render.py), plus the line-up and {plural(len(d['walks']), 'walk clip')}. {len(nu)} renders are shown "
        f"by no page; {len(ms)} are missing.", "cad/renders")
    out = list(head)
    x0, cw, ch, gap = M + 170, 112, 40, 8
    y = y0 + 26
    out.append(fk.text(M, y, "Review renders (tools/cad/render.cjs)", size=12, fill=INK, weight=700))
    y += 20
    for j, v in enumerate(d["views"]):
        out.append(fk.text(x0 + j * (cw + gap) + cw / 2, y, v, size=10.5, fill=MUTED, weight=700, anchor="middle"))
    y += 8
    for i, r in enumerate(d["rows"]):
        yy = y + i * (ch + 6)
        out.append(fk.text(M, yy + ch / 2 + 4, r, size=11, fill=INK, mono=True, weight=700))
        for j, v in enumerate(d["views"]):
            cell(out, x0 + j * (cw + gap), yy, cw, ch, rv[(r, v)])
    lx = x0 + len(d["views"]) * (cw + gap) + 30
    out.append(fk.text(lx, y - 8, "line-up", size=10.5, fill=MUTED, weight=700))
    cell(out, lx, y, cw + 30, ch, d["lineup"])
    out.append(fk.text(lx, y + ch + 16, "every standing layout side by side", size=9, fill=FAINT))
    y += len(d["rows"]) * (ch + 6) + 24
    out.append(fk.text(M, y, "Blender stills and walk clips (tools/cad/blender_render.py, blender_walk.py)", size=12,
                       fill=INK, weight=700))
    y += 20
    for j, lv in enumerate(d["liveries"]):
        out.append(fk.text(x0 + j * (cw + gap) + cw / 2, y, lv, size=10.5, fill=MUTED, weight=700, anchor="middle"))
    y += 8
    for i, (shot, src) in enumerate(d["shots"]):
        yy = y + i * (ch + 6)
        out.append(fk.text(M, yy + ch / 2 - 2, shot, size=11, fill=INK, mono=True, weight=700))
        out.append(fk.text(M, yy + ch / 2 + 12, src, size=9, fill=MUTED, mono=True))
        for j, lv in enumerate(d["liveries"]):
            cell(out, x0 + j * (cw + gap), yy, cw, ch, bl[(shot, lv)])
    wx = x0 + len(d["liveries"]) * (cw + gap) + 30
    out.append(fk.text(wx, y - 8, "walk clips", size=10.5, fill=MUTED, weight=700))
    for i, w in enumerate(d["walks"]):
        yy = y + i * (ch + 6)
        c = {"exists": True, "shown": w["shown"], "size": None}
        cell(out, wx, yy, cw, ch, c)
        out.append(fk.text(wx + cw + 10, yy + ch / 2 + 4, f"{w['file']} · {w['kb']:,} KB", size=10, fill=INK, mono=True))
    y += max(len(d["shots"]), len(d["walks"])) * (ch + 6) + 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 22
    leg = [(SHOWN[0], SHOWN[1], "Shown by a page (count of pages)"), (UNSHOWN[0], UNSHOWN[1], "Rendered, shown by no page"),
           (MISSING[0], MISSING[1], "Expected, not rendered")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    out.append(fk.text(M, y + 4, "Pages: the concept layouts review, the Blender and concept-art pages, the front-page "
                                 "banner and the wiki (counted once). Pixel size from the file header.", size=10.5,
                       fill=MUTED))
    y += 18
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Every render, and whether a page shows it",
                  "Every layout and posture against every review view and Blender shot, and the pages that show each", out)


# ================================================================ figure 2 · where shown (drawn directly)
def fig_shown(d: dict) -> str:
    W, M = 1240, 40
    groups = {"review": [v for v in d["review"].values() if v["exists"]] + ([d["lineup"]] if d["lineup"]["exists"] else []),
              "blender": [v for v in d["blender"].values() if v["exists"]], "walk": d["walks"]}
    head, y0 = fk.header(
        W, "2", "Which pages show the renders",
        "For each producer, how many of its renders each page shows (a page counted once per render; the wiki pages "
        "together). The review shows every standing view; the posture pages show two views each.", "every *.md")
    out = list(head)
    x0 = M + 300
    cw = (W - M - x0) / len(CONSUMERS)
    y = y0 + 26
    for j, (_, lab) in enumerate(CONSUMERS):
        out.append(fk.text(x0 + j * cw + cw / 2, y, lab, size=10.5, fill=MUTED, weight=700, anchor="middle"))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 56
    for i, (g, items) in enumerate(groups.items()):
        yy = y + i * rh
        if i % 2:
            out.append(fk.rect(M, yy + 1, W - 2 * M, rh, fill="#F8FAFC", stroke="none", rx=0, sw=0))
        n_un = sum(1 for it in items if not it["shown"])
        out.append(fk.text(M, yy + 24, WRITERS[g], size=11, fill=INK, mono=True, weight=700))
        out.append(fk.text(M, yy + 42, f"{plural(len(items), 'file')}" + (f" · {n_un} shown by no page" if n_un else ""),
                           size=9.5, fill="#B45309" if n_un else MUTED))
        for j, (key, _) in enumerate(CONSUMERS):
            n = sum(1 for it in items if key in it["shown"])
            cx, cy = x0 + j * cw + cw / 2, yy + rh / 2 + 2
            if n:
                r = 9 + 11 * (n / max(1, len(items))) ** 0.5
                out.append(f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r:.1f}" fill="#ECFDF5" stroke="#059669" stroke-width="1.4"/>')
                out.append(fk.text(cx, cy + 4, str(n), size=10.5, fill="#065F46", weight=700, anchor="middle"))
            else:
                out.append(fk.text(cx, cy + 4, "·", size=12, fill=FAINT, anchor="middle"))
    y += len(groups) * rh + 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 22
    nu = unshown(d)
    for ln in fk.wrap("Shown by no page: " + (", ".join(nu) if nu else "none") + ".", W - 2 * M - 20, 10.5, mono=bool(nu)):
        out.append(fk.text(M, y, ln, size=10.5, fill="#B45309" if nu else MUTED, mono=bool(nu)))
        y += 15
    y += 6
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Which pages show the renders",
                  "For each producer, how many of its renders each page shows", out)


# ================================================================ SysML and ELK figures
def fig_sysml(d: dict) -> tuple[dict, str]:
    nodes = [{"id": "Render", "shape": "class", "title": "Render", "stereotype": "part def",
              "attrs": ["fileName : String", "producer : String", "shownByPages : Integer"], "tone": "system"},
             {"id": "Review", "shape": "class", "title": "ReviewRender", "stereotype": "part def",
              "attrs": ["layoutId : String", "viewName : String", "widthPx : Integer", "heightPx : Integer"], "tone": "work"},
             {"id": "Blender", "shape": "class", "title": "BlenderRender", "stereotype": "part def",
              "attrs": ["shot : String", "livery : String", "sourceLayout : String"], "tone": "external"},
             {"id": "Walk", "shape": "class", "title": "WalkClip", "stereotype": "part def",
              "attrs": ["format : String"], "tone": "external"}]
    edges = [{"src": x, "dst": "Render", "label": "specializes", "arrow": "triangle"} for x in ("Review", "Blender", "Walk")]
    s = ["    part def Render {", "        doc /* One image or clip in cad/renders, rendered from the CAD meshes. */",
         "        attribute fileName : String;", "        attribute producer : String;",
         "        attribute shownByPages : Integer;", "    }",
         "    part def ReviewRender :> Render {", "        attribute layoutId : String;", "        attribute viewName : String;",
         "        attribute widthPx : Integer;", "        attribute heightPx : Integer;", "    }",
         "    part def BlenderRender :> Render {", "        attribute shot : String;", "        attribute livery : String;",
         "        attribute sourceLayout : String;", "    }",
         "    part def WalkClip :> Render {", "        attribute format : String;", "    }"]

    def nm(f: str, prefix: str = "review") -> str:
        return prefix + re.sub(r"\W", "", f.rsplit(".", 1)[0].title())
    for (r, v), c in d["review"].items():
        if not c["exists"]:
            continue
        s += [f"    part {nm(c['file'])} : ReviewRender {{", f"        attribute :>> fileName = \"{c['file']}\";",
              f"        attribute :>> producer = \"{WRITERS['review']}\";",
              f"        attribute :>> shownByPages = {len(c['shown'])};", f"        attribute :>> layoutId = \"{r}\";",
              f"        attribute :>> viewName = \"{v}\";", f"        attribute :>> widthPx = {c['size'][0]};",
              f"        attribute :>> heightPx = {c['size'][1]};", "    }"]
    for (shot, lv), c in d["blender"].items():
        if not c["exists"]:
            continue
        s += [f"    part {nm(c['file'], 'blender')} : BlenderRender {{", f"        attribute :>> fileName = \"{c['file']}\";",
              f"        attribute :>> producer = \"{WRITERS['blender']}\";",
              f"        attribute :>> shownByPages = {len(c['shown'])};", f"        attribute :>> shot = \"{shot}\";",
              f"        attribute :>> livery = \"{lv}\";", f"        attribute :>> sourceLayout = \"{c['src']}\";", "    }"]
    for w in d["walks"]:
        s += [f"    part {nm(w['file'], 'clip')}{w['file'].rsplit('.', 1)[1].title()} : WalkClip {{",
              f"        attribute :>> fileName = \"{w['file']}\";", f"        attribute :>> producer = \"{WRITERS['walk']}\";",
              f"        attribute :>> shownByPages = {len(w['shown'])};",
              f"        attribute :>> format = \"{w['file'].rsplit('.', 1)[1]}\";", "    }"]
    n = sum(1 for c in d["review"].values() if c["exists"]) + sum(1 for c in d["blender"].values() if c["exists"]) + len(d["walks"])
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — ReviewRenders", "ref": "cad/renders/ReviewRenders.sysml",
            "subtitle": f"Review renders, Blender stills and walk clips are renders with a producer and the number of "
                        f"pages that show them; ReviewRenders.sysml holds all {n} as parts.",
            "frame": {"kind": "bdd", "type": "package", "name": "ReviewRenders"}, "direction": "DOWN",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Specialization (hollow arrow)"), ("#EEF2FF", "#4F46E5", "Render"),
                       ("#FFFFFF", "#475569", "Review render"), ("#F1F5F9", "#475569", "Blender still and walk clip")]}
    sysml = "\n".join([
        f"// ReviewRenders — generated by {GEN} from cad/renders.",
        "// Do not edit by hand: re-render (tools/cad/make.sh) or change the generator and regenerate.",
        "// Status: renders of placeholder concept geometry, for review and communication; not a design.", "",
        "package ReviewRenders {",
        "    private import ScalarValues::*;",
        "    doc /* The concept layout renders (cad/renders/README.md). */",
        *s, "}", ""])
    return spec, sysml


