def png_size(p: Path) -> tuple[int, int]:
    return struct.unpack(">II", p.read_bytes()[16:24])


def jpg_size(p: Path) -> tuple[int, int] | None:
    b = p.read_bytes()
    i = 2
    while i < len(b) - 9:
        if b[i] != 0xFF:
            i += 1
            continue
        mk, ln = b[i + 1], int.from_bytes(b[i + 2:i + 4], "big")
        if mk in (0xC0, 0xC1, 0xC2):
            h, w = struct.unpack(">HH", b[i + 5:i + 9])
            return w, h
        i += 2 + ln
    return None


def tracked_pages() -> dict[str, str]:
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split()
    keep = {}
    for f in out:
        if not f.endswith((".md", ".py")) or f.startswith("cad/renders/README") or f == "docs/wiki/Concept-Renders.md":
            continue
        if f.endswith(".py") and f != "tools/readme/build_readme.py":
            continue
        t = (ROOT / f).read_text(errors="ignore")
        if "renders" in t:
            keep[f] = t
    return keep


def consumer_of(f: str) -> str | None:
    for key, _ in CONSUMERS:
        if f == key or (key.endswith("/") and f.startswith(key)):
            return key
    return None


def load() -> dict:
    ctx, _, _ = load_reqs()
    metrics = json.loads((ROOT / "cad" / "metrics.json").read_text())["concepts"]
    rows = []
    for lid, m in metrics.items():
        rows.append(lid)
        rows += [f"{lid}-{p}" for p in m.get("postures") or {}]
    views = re.findall(r"'(\w+)'", re.search(r"const VIEWS = \[([^\]]*)\]", (ROOT / WRITERS["review"]).read_text()).group(1))
    br = (ROOT / WRITERS["blender"]).read_text()
    shots_src = re.search(r"^SHOTS = \{(.*?)^\}", br, re.S | re.M).group(1)
    shots = re.findall(r'^\s+"(\w+)":\s*\{"src": "([\w-]+)"', shots_src, re.M)
    liveries = re.findall(r'^    "(\w+)": \{', re.search(r"^LIVERIES = \{(.*?)^\}", br, re.S | re.M).group(1), re.M)
    pages = tracked_pages()
    shown: dict[str, list[str]] = {}
    images = sorted([p for p in FOLDER.glob("*.png")] + [p for p in BLENDER.glob("*") if p.suffix in (".jpg", ".gif", ".mp4")])
    for p in images:
        shown[p.name] = sorted({c for f, t in pages.items() if p.name in t and (c := consumer_of(f))})
    review = {}
    for r in rows:
        for v in views:
            p = FOLDER / f"{r}-{v}.png"
            review[(r, v)] = {"file": p.name, "exists": p.exists(), "size": png_size(p) if p.exists() else None,
                              "kb": round(p.stat().st_size / 1024) if p.exists() else 0, "shown": shown.get(p.name, [])}
    lineup = FOLDER / "lineup.png"
    blender = {}
    for shot, src in shots:
        for lv in liveries:
            p = BLENDER / (f"{src.split('-')[0]}-{src.split('-')[1]}-{shot}" + ("" if lv == "industrial" else f"-{lv}") + ".jpg")
            blender[(shot, lv)] = {"file": p.name, "src": src, "exists": p.exists(), "size": jpg_size(p) if p.exists() else None,
                                   "kb": round(p.stat().st_size / 1024) if p.exists() else 0, "shown": shown.get(p.name, [])}
    walks = [{"file": p.name, "kb": round(p.stat().st_size / 1024), "shown": shown.get(p.name, [])}
             for p in sorted(BLENDER.glob("CL-05-walk*")) if p.suffix in (".mp4", ".gif")]
    expected = {v["file"] for v in review.values()} | {"lineup.png"} | {v["file"] for v in blender.values()} | {w["file"] for w in walks}
    extra = sorted(p.name for p in images if p.name not in expected)
    return {"ctx": ctx, "rows": rows, "views": views, "shots": shots, "liveries": liveries, "review": review,
            "lineup": {"file": "lineup.png", "exists": lineup.exists(), "size": png_size(lineup) if lineup.exists() else None,
                       "shown": shown.get("lineup.png", [])},
            "blender": blender, "walks": walks, "shown": shown, "extra": extra, "images": images,
            "root": next(k for k, v in ctx.nodes.items() if not v.get("parent") and v.get("kind") != "external")}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def unshown(d: dict) -> list[str]:
    return sorted(v["file"] for v in list(d["review"].values()) + list(d["blender"].values()) if v["exists"] and not v["shown"])


def missing(d: dict) -> list[str]:
    return sorted(v["file"] for v in list(d["review"].values()) + list(d["blender"].values()) if not v["exists"])


