# ================================================================ records
def load() -> dict:
    ctx, _, hazards = load_reqs()
    from sim.common import decorate
    from sim.scenes3d import export_scene
    outs = export_scene.outputs()
    cfg = yaml.safe_load(SCENES.read_text())
    sheet = yaml.safe_load(SHEET.read_text())
    vj = VIEWER.read_text()
    viewer_reads = set(re.findall(r"\bA\.(\w+(?:\.\w+)?)", vj))
    viewer_reads |= {k.split(".")[0] for k in viewer_reads if k.split(".")[0] not in ("performed", "intended")}
    bp = (ROOT / "sim" / "scenes3d" / "build_pages.py").read_text()
    viewer_reads |= set(re.findall(r"analysis(?:\.get\(|\[)\"(\w+)\"", bp))
    sheet_replay = set(sheet.get("replay") or [])
    ex = []
    for sc in cfg["scenes"]:
        rel = f"sim/scenes3d/out/{sc['id']}.json"
        path = ROOT / rel
        a = json.loads(path.read_text())
        current = path.read_text() == decorate(rel, outs[rel])
        pages = [f"{sc['id']}.html"] + [f"{v['id']}.html" for v in sc.get("variants") or []]
        if sc["id"] in sheet_replay:
            pages.append("SUS-M1.html")
        ex.append({"a": a, "file": path.name, "size": path.stat().st_size, "current": current, "pages": pages})
    hz = sorted({h for e in ex for h in e["a"]["hazards"]})
    subs = sorted({x for h in hz for x in hazards.get(h, {}).get("subsystems") or []})
    # export fields no page reads (beside provenance)
    unread = defaultdict(set)
    sheet_keys = {"id", "title", "hazards", "reference", "slope_deg", "spec", "source", "performed",
                  "intended.frames", "intended.outcome"}
    for e in ex:
        a = e["a"]
        for k, v in a.items():
            keys = [f"{k}.{s}" for s in v] if k in ("performed", "intended") else [k]
            for kk in keys:
                top = kk.split(".")[0]
                read = kk in viewer_reads or top in viewer_reads and "." not in kk
                if e["a"]["id"] in sheet_replay:
                    read = read or kk in sheet_keys or top in sheet_keys and top != "intended"
                if not read and top not in PROVENANCE:
                    unread[a["kind"]].add(kk)
    return {"ctx": ctx, "ex": ex, "hz": hz, "subs": subs, "unread": {k: sorted(v) for k, v in unread.items()},
            "viewer_reads": viewer_reads, "sheet_replay": sorted(sheet_replay)}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def outcome_of(a: dict) -> tuple[str, str]:
    if a["kind"] == "walker":
        return a["performed"]["outcome"], a["intended"]["outcome"]
    return a["outcome"], "docks clear of the pilot"


def frames_of(a: dict) -> tuple[int, float]:
    if a["kind"] == "walker":
        f = a["performed"]["frames"]
        return len(f) + len(a["intended"]["frames"]), max(f[-1][0], a["intended"]["frames"][-1][0])
    return len(a["frames"]), a["frames"][-1][0]


def inside(a: dict, p: list) -> bool:
    dn, de = p[1] - a["pilot_m"][0], p[2] - a["pilot_m"][1]
    return (dn * dn + de * de) ** 0.5 < a["keepout_m"] and p[3] < a["keepout_alt_m"]


