def polyline(pts: list, stroke: str, sw: float = 1.6, dash: str = "") -> str:
    d = " ".join(f"{x:.1f},{y:.1f}" for x, y in pts)
    da = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<polyline points="{d}" fill="none" stroke="{stroke}" stroke-width="{sw}"{da}/>'


PERF, INTD, EVC = "#DC2626", "#2563EB", "#0F172A"


def strip(out: list, x: float, y: float, w: float, h: float, tmax: float, lo: float, hi: float, series: list,
          label: str, ref: tuple | None = None) -> None:
    out.append(fk.rect(x, y, w, h, fill="#FFFFFF", stroke="#E2E8F0", rx=3, sw=1))
    out.append(fk.text(x - 6, y + 10, label, size=9, fill=MUTED, anchor="end"))
    out.append(fk.text(x - 6, y + h, f"{lo:g}–{hi:g}", size=8.5, fill=FAINT, anchor="end"))
    sx = lambda t: x + w * t / tmax  # noqa: E731
    sy = lambda v: y + h - h * (v - lo) / (hi - lo)  # noqa: E731
    if ref:
        v, txt = ref
        out.append(fk.line(x, sy(v), x + w, sy(v), stroke="#F59E0B", sw=1, dash="4 3"))
        out.append(fk.text(x + w - 4, sy(v) - 3, txt, size=8.5, fill="#B45309", anchor="end"))
    for pts, col, dash in series:
        out.append(polyline([(sx(t), sy(v)) for t, v in pts], col, dash=dash))


def fig_timelines(d: dict) -> str:
    W, M = 1240, 40
    ex = d["ex"]
    head, y0 = fk.header(
        W, "2", "What each export holds",
        "Every frame of every export over time. Walker: centre-of-mass offset from the support centre (x) and height (z), "
        "the performed run against the intended run, with the alarm, stop, lock and mishap events. UAV: altitude with "
        "the PX4 mode, and the samples inside the pilot keep-out.", "sim/scenes3d/out/*.json")
    out = list(head)
    cw = (W - 2 * M - 40) / 2
    ph = 168
    y = y0 + 20
    for i, e in enumerate(ex):
        a = e["a"]
        x = M + (i % 2) * (cw + 40)
        yy = y + (i // 2) * (ph + 20)
        out.append(fk.text(x, yy + 12, f"{a['id']} · {a['reference']} · {', '.join(a['hazards'])}", size=11, fill=INK,
                           weight=700))
        got, want = outcome_of(a)
        out.append(fk.text(x + cw, yy + 12, got, size=10.5, fill="#991B1B" if got in BAD else "#166534", weight=700,
                           anchor="end"))
        px, pw = x + 74, cw - 74
        if a["kind"] == "walker":
            P, I = a["performed"]["frames"], a["intended"]["frames"]
            tmax = max(P[-1][0], I[-1][0])
            sp = a["spec"]
            strip(out, px, yy + 24, pw, 52, tmax, 0.0, round(sp["tip_offset_m"] * 1.2, 2),
                  [([(f[0], f[1]) for f in I], INTD, "5 3"), ([(f[0], f[1]) for f in P], PERF, "")],
                  "x (m)", (sp["tip_offset_m"], f"tip {sp['tip_offset_m']:g} m"))
            strip(out, px, yy + 84, pw, 52, tmax, round(sp["crouch_height_m"] * 0.9, 2),
                  round(sp["com_height_m"] * 1.05, 2),
                  [([(f[0], f[2]) for f in I], INTD, "5 3"), ([(f[0], f[2]) for f in P], PERF, "")],
                  "z (m)", (sp["crouch_height_m"], f"crouch {sp['crouch_height_m']:g} m"))
            ev = a["performed"]["events"]
            for k, lab in (("alarm_t", "alarm"), ("stop_t", "stop"), ("lock_t", "lock"), ("mishap_t", "mishap")):
                if ev.get(k) is not None:
                    tx = px + pw * ev[k] / tmax
                    out.append(fk.line(tx, yy + 24, tx, yy + 140, stroke=EVC if k == "mishap_t" else "#94A3B8", sw=0.9,
                                       dash="" if k == "mishap_t" else "2 2"))
            labs = [f"{lab} {ev[k]:g} s" for k, lab in (("alarm_t", "alarm"), ("stop_t", "stop"), ("lock_t", "lock"),
                                                        ("mishap_t", "mishap")) if ev.get(k) is not None]
            if ev.get("impact_speed"):
                labs.append(f"impact {ev['impact_speed']:.1f} m/s")
            out.append(fk.text(px, yy + 156, "performed: " + (", ".join(labs) or "no events") + f" · 0–{tmax:g} s",
                               size=9.5, fill=MUTED))
        else:
            F = a["frames"]
            t0, tmax = F[0][0], F[-1][0]
            hi = max(f[3] for f in F) * 1.1
            strip(out, px, yy + 24, pw, 96, tmax, 0.0, round(hi, 1), [([(f[0], f[3]) for f in F], INTD, "")],
                  "alt (m)", (a["keepout_alt_m"], f"keep-out below {a['keepout_alt_m']:g} m"))
            n_in = 0
            for f in F:
                if inside(a, f):
                    n_in += 1
                    cx = px + pw * f[0] / tmax
                    cy = yy + 24 + 96 - 96 * f[3] / round(hi, 1)
                    out.append(f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="3" fill="{PERF}"/>')
            # mode band
            modes = []
            for f in F:
                if not modes or modes[-1][1] != f[4]:
                    modes.append([f[0], f[4]])
            for j, (t, m) in enumerate(modes):
                t1 = modes[j + 1][0] if j + 1 < len(modes) else tmax
                bx, bw = px + pw * t / tmax, pw * (t1 - t) / tmax
                out.append(fk.rect(bx, yy + 126, max(bw, 1), 12, fill="#E0E7FF" if j % 2 == 0 else "#C7D2FE",
                                   stroke="none", rx=0, sw=0))
                if bw > 60:
                    out.append(fk.text(bx + 4, yy + 135, m, size=8.5, fill="#3730A3", mono=True))
            out.append(fk.text(px - 6, yy + 136, "mode", size=9, fill=MUTED, anchor="end"))
            note = (f"{n_in} samples inside the keep-out · closest low pass {a['min_pilot_distance_low_m']:g} m · landed "
                    f"{a['landing_to_dock_m']:g} m from the dock · walker moved: {'yes' if a['walker_moved'] else 'no'} · "
                    f"{t0:g}–{tmax:g} s")
            for k, ln in enumerate(fk.wrap(note, pw, 9.5, max_lines=2)):
                out.append(fk.text(px, yy + 156 + 13 * k, ln, size=9.5, fill=MUTED))
    y += ((len(ex) + 1) // 2) * (ph + 20)
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 22
    leg = [("#FFFFFF", PERF, "Performed run (walker) · sample inside the keep-out (UAV)"),
           ("#FFFFFF", INTD, "Intended run (walker, dashed) · UAV altitude"),
           ("#FFFFFF", "#F59E0B", "Limit from the spec"), ("#FFFFFF", EVC, "Mishap (other events dotted)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · What each export holds",
                  "Every frame of every exported scene over time, performed against intended", out)


