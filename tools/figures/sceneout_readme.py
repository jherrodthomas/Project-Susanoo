        "| Checked by | `export_scene --check` and `sim/tests/test_scenes3d.py` (the look never reaches the export) |",
        "| SysML | [`SceneExports.sysml`](SceneExports.sysml) (generated) |", "",
        "## Purpose\n",
        "One JSON file per 3D scene: the analysis the page replays. `export_scene.py` reads only each scene's id, "
