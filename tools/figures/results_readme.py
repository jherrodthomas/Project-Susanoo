HAZ = re.compile(r"HAZ-[A-Z]+-\d{3}")


# ================================================================ records
def module_name(p: Path) -> str:
    return ".".join(p.relative_to(ROOT).with_suffix("").parts)


def load() -> dict:
    ctx, _, hazards = load_reqs()
    sources = {p: p.read_text() for d in ("sim", "tools") for p in sorted((ROOT / d).rglob("*.py"))
               if not ({"tests", "node_modules", "__pycache__"} & set(p.parts))}
    workflows = {}
    for wf in sorted((ROOT / ".github" / "workflows").glob("*.y*ml")):
        w = yaml.safe_load(wf.read_text())
        for job, jd in (w.get("jobs") or {}).items():
            for st in jd.get("steps") or []:
                if st.get("run"):
                    workflows.setdefault(f"{wf.stem} · {job}", []).append(st["run"])
    current = plant_spec.digest()
    stems = sorted({p.stem for p in FOLDER.glob("*.json")})
    sets = []
    for stem in stems:
        js = FOLDER / f"{stem}.json"
        data = json.loads(js.read_text())
        prefixes = [stem] + ([stem.split("-")[0] + "-"] if stem.startswith("search-") else [])
        pats = [re.compile(rf'OUT_JSON\s*=.*["\']{re.escape(stem)}\.json["\']')] + [
            re.compile(rf'sim/results/{re.escape(px)}[^\n]*?\.json["\']\s*[\]:]') for px in prefixes]
        writer = next((p for p, t in sources.items() if p.parts[len(ROOT.parts)] == "sim"
                       and any(pt.search(t) for pt in pats)), None)
        readers = sorted({module_name(p) for p, t in sources.items() if p != writer and p.name != Path(GEN).name
                          and (f"{stem}.json" in t or (stem.startswith("search-") and ("search-*.json" in t
                                                                                         or "search-{" in t)))})
        ci = []
        if writer is not None:
            mod = module_name(writer)
            for job, runs in workflows.items():
                for run in runs:
                    if mod in run:
                        mode = "--compare" if "--compare" in run else ("--check" if "--check" in run else "run")
                        ci.append((job, mode))
        md = FOLDER / f"{stem}.md"
        sets.append({"stem": stem, "json": js.name, "md": md.name if md.exists() else None,
                     "writer": module_name(writer) if writer else None, "readers": readers, "ci": ci,
                     "synthetic": "Synthetic" in str(data.get("about", "")), "digest": data.get("spec_digest"),
                     "current": data.get("spec_digest") == current,
                     "hazards": sorted(set(HAZ.findall(js.read_text()))), "size": js.stat().st_size})
    others = sorted(p.name for p in FOLDER.glob("*.md") if p.stem not in stems and p.name != "README.md")
    uav = sorted(p.name for p in (FOLDER / "uav").glob("*.json"))
    hz = sorted({h for s in sets for h in s["hazards"]})
    subs = sorted({x for h in hz for x in hazards.get(h, {}).get("subsystems") or []})
    return {"ctx": ctx, "hazards": hazards, "sets": sets, "current": current, "others": others, "uav": uav,
            "hz": hz, "subs": subs}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


# ================================================================ figure 1 · result files (drawn directly)
def fig_files(d: dict) -> str:
    W, M = 1240, 40
    sets = d["sets"]
    stale = [s for s in sets if s["digest"] and not s["current"]]
    head, y0 = fk.header(
        W, "1", "Every committed result and how it is kept honest",
        f"The {len(sets)} result sets in sim/results: the module that writes each, the CI job that re-runs it, its "
        f"synthetic label and whether it was built from the current plant spec (digest {d['current']}); "
        f"{plural(len(stale), 'set')} stale. PX4 SITL runs are in uav/.", "sim/results/")
    out = list(head)
    cx = {"f": M, "w": M + 300, "ci": M + 510, "lab": M + 760, "dg": M + 840, "hz": M + 955}
    y = y0 + 30
    for k, lab in (("f", "Result set"), ("w", "Written by"), ("ci", "Re-run in CI"), ("lab", "Label"),
                   ("dg", "Spec digest"), ("hz", "Hazards named")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 50
    for n, s in enumerate(sets):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["f"], cy - 6, s["stem"], size=11, fill=INK, weight=700, mono=True))
        out.append(fk.text(cx["f"], cy + 9, " + ".join(x for x in (s["json"], s["md"]) if x) + f" · {s['size'] // 1024} KB",
                           size=9.5, fill=MUTED))
        out.append(fk.text(cx["w"], cy, s["writer"] or "—", size=10, fill=INK, mono=True))
        ci = s["ci"]
        out.append(fk.text(cx["ci"], cy - 6 if ci else cy, f"{ci[0][0]}" if ci else "not in CI", size=10,
                           fill=INK if ci else TONES["amber"][0]))
        if ci:
            out.append(fk.text(cx["ci"], cy + 9, ci[0][1] + (" (outcomes exact, numbers in tolerance)"
                                                             if ci[0][1] == "--compare" else " (reproduce exactly)"),
                               size=9.5, fill=MUTED))
        t = TONES["ok" if s["synthetic"] else "red"]
        p, _ = fk.pill(cx["lab"], cy - 12, "synthetic" if s["synthetic"] else "no label", t[1], color=t[0], stroke=t[0])
        out += p
        if s["digest"]:
            t = TONES["ok" if s["current"] else "red"]
            p, _ = fk.pill(cx["dg"], cy - 12, s["digest"][:6] + (" current" if s["current"] else " stale"), t[1],
                           color=t[0], stroke=t[0])
            out += p
        else:
            out.append(fk.text(cx["dg"], cy, "—", size=10, fill=FAINT))
        hl = fk.wrap(", ".join(s["hazards"]) or "—", W - M - cx["hz"], 9.5, max_lines=3)
        for k, ln in enumerate(hl):
            out.append(fk.text(cx["hz"], cy - 6 * (len(hl) - 1) + 12 * k, ln, size=9.5, fill=INK))
    y += len(sets) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["ok"][1], TONES["ok"][0], "Labelled synthetic / built from the current spec"),
           (TONES["red"][1], TONES["red"][0], "Missing label or stale spec digest")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    extra = f" Also here: {', '.join(d['others'])} (written with the search results)." if d["others"] else ""
    for ln in fk.wrap(FOOTER + extra + " Hazards named: the hazard IDs in each result file.",
                      W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Every committed result and how it is kept honest",
                  "Every result set with its writer, CI check, label and spec digest", out)


# ================================================================ ELK figures and SysML
def fig_lineage(d: dict) -> dict:
    nodes = [{"id": "W", "banner": "Writers", "tone": "work"}, {"id": "R", "banner": "Result sets", "tone": "work"},
             {"id": "U", "banner": "Read by", "tone": "work"}]
    edges, seen = [], set()
    for s in d["sets"]:
        rid = "r_" + mid(s["stem"])
        nodes.append({"id": rid, "parent": "R", "code": s["stem"], "title": " + ".join(x for x in (s["json"], s["md"]) if x),
                      "tone": "current", "maxw": 240})
        if s["writer"]:
            wid = "w_" + mid(s["writer"])
            if wid not in seen:
                seen.add(wid)
                nodes.append({"id": wid, "parent": "W", "code": s["writer"], "title": "", "tone": "software",
                              "maxw": 220, "legend": "Simulation code"})
            edges.append({"src": wid, "dst": rid, "label": ""})
        for r in s["readers"]:
            uid = "u_" + mid(r)
            if uid not in seen:
                seen.add(uid)
                nodes.append({"id": uid, "parent": "U", "code": r, "title": "",
                              "tone": "system" if r.startswith("tools") else "software", "maxw": 230,
                              "legend": "Page or figure generator" if r.startswith("tools") else "Simulation code"})
            edges.append({"src": rid, "dst": uid, "label": "", "dash": True})
    return {"file": "fig-2-lineage.svg", "number": "2", "title": "Who writes and who reads each result",
            "subtitle": "The module that writes each result set and every module that reads it, both read from the code. "
                        "A changed result moves every page and figure downstream of it.",
            "ref": "sim/**/*.py · tools/**/*.py", "direction": "RIGHT", "orient": "fixed", "nodes": nodes,
            "edges": edges, "legend": [edge_leg("Writes"), edge_leg("Read by", True)]}


def fig_sysml(d: dict) -> tuple[dict, str]:
    nodes = [{"id": "ResultSet", "shape": "class", "title": "ResultSet", "stereotype": "part def",
              "attrs": ["dataKind : String", "evidenceCredit : Boolean", "specDigest : String", "writer : String",
                        "ciCheck : String"], "tone": "system"}]
    edges = []
    s = ["    part def ResultSet {",
         "        doc /* A committed simulation result: synthetic, no evidence credit, re-run and compared in CI. */",
         "        attribute dataKind : String;", "        attribute evidenceCredit : Boolean;",
         "        attribute specDigest : String;", "        attribute writer : String;", "        attribute ciCheck : String;",
         "    }"]
    for r in d["sets"]:
        pn = re.sub(r"\W", "", r["stem"].title())
        pn = pn[0].lower() + pn[1:]
        ci = r["ci"][0][1] if r["ci"] else "none"
        nodes.append({"id": pn, "shape": "class", "title": f"{pn} : ResultSet", "stereotype": "part",
                      "attrs": [f"dataKind = {'synthetic' if r['synthetic'] else '?'}", "evidenceCredit = false",
                                f"specDigest = {r['digest'] or '—'}", f"writer = {r['writer'] or '—'}", f"ciCheck = {ci}"],
                      "tone": "safety"})
        edges.append({"src": pn, "dst": "ResultSet", "label": "", "dash": True})
        s += [f"    part {pn} : ResultSet {{", f"        doc /* sim/results/{r['json']} */",
              f"        attribute :>> dataKind = \"{'synthetic' if r['synthetic'] else 'unlabelled'}\";",
              "        attribute :>> evidenceCredit = false;",
              f"        attribute :>> specDigest = \"{r['digest'] or ''}\";",
              f"        attribute :>> writer = \"{r['writer'] or ''}\";",
              f"        attribute :>> ciCheck = \"{ci}\";", "    }"]
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — ResultSets", "ref": "sim/results/ResultSets.sysml",
            "subtitle": "The result block and every committed result set with its label, spec digest, writer and CI "
                        "check, generated into ResultSets.sysml. evidenceCredit is false for every one.",
            "frame": {"kind": "bdd", "type": "package", "name": "ResultSets"}, "direction": "DOWN",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Typed by (part : ResultSet)", True), ("#EEF2FF", "#4F46E5", "Part definition"),
                       ("#FFF7ED", "#C2410C", "Result set")]}
    sysml = "\n".join([
        f"// ResultSets — generated by {GEN} from the committed results in sim/results.",
        "// Do not edit by hand: re-run the simulations or change the generator and regenerate.",
        "// Status: synthetic results; no evidence credit.", "",
        "package ResultSets {",
        "    private import ScalarValues::*;",
        "    doc /* The committed simulation results (sim/results/README.md). */",
        *s, "}", ""])
    return spec, sysml


FLOWS = [["Simulation code", "Result sets", "JSON and Markdown, labelled synthetic"],
         ["Plant spec", "Result sets", "spec digest recorded in each"],
         ["CI", "Result sets", "--check / --compare: must reproduce"],
         ["Result sets", "Pages and figures", "READMEs, scenes, front page, wiki"],
         ["Result sets", "Level-2 cross-check", "search edge cases"],
         ["@boundary", "Safety lead", "findings for review"],
         ["Fidelity case (none yet)", "@boundary", "the only way a result could count as evidence"]]


def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    block = fig_block(ctx, {"scope": d["subs"]})
    by = defaultdict(list)
    for h in d["hz"]:
        for s in d["hazards"].get(h, {}).get("subsystems") or []:
            by[s].append(h)
    for n in block["nodes"]:
        if n.get("code") in by:
            n["sub"] = ", ".join(by[n["code"]])
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"SUS-I1 decomposition. The {len(d['subs'])} subsystems named by the hazards the results "
                          "name are coloured, with those hazards under each.")
    boundary = fig_boundary(ctx, {"path": "sim/results", "boundary": {
        "name": "Results", "inside": ["Result sets"],
        "outside": ["Simulation code", "Plant spec", "CI", "Pages and figures", "Level-2 cross-check", "Safety lead",
                    "Fidelity case (none yet)"],
        "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="sim/results/README.md",
                    subtitle="The folder holds generated results only; nothing here is edited by hand, and nothing "
                             "leaves it as evidence. Crossings are numbered as in the table.")
    sysml_spec, sysml = fig_sysml(d)
    writers = sorted({s["writer"] for s in d["sets"] if s["writer"]})
    readers = sorted({r for s in d["sets"] for r in s["readers"]})
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "sim/results/README.md", "direction": "RIGHT",
          "subtitle": "What writes the folder (left) and what reads it (right).",
          "nodes": [*[{"id": f"I{i}", "title": w.replace("sim.", "").replace(".", "/"), "sub": "writer",
                       "tone": "software"} for i, w in enumerate(writers, 1)],
                    {"id": "X", "code": "sim/results/", "title": "Committed results", "tone": "current"},
                    {"id": "O1", "title": "Simulation pages", "sub": "sim READMEs, scenes, 3D",
                     "tone": "work"},
                    {"id": "O2", "title": "Front page and wiki", "sub": "summary figures", "tone": "work"},
                    {"id": "O3", "title": "Safety lead", "sub": "findings for review", "tone": "safety",
                     "legend": "Human review"}],
          "edges": [{"src": f"I{i}", "dst": "X", "label": ""} for i in range(1, len(writers) + 1)]
          + [{"src": "X", "dst": "O1", "label": "results"}, {"src": "X", "dst": "O2", "label": "summaries"},
             {"src": "X", "dst": "O3", "label": "findings"}]}
    _ = readers
    specs = [fig_lineage(d), block, boundary, sysml_spec, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    return specs, sysml


# ================================================================ README
def img(file: str, number: str, title: str) -> str:
    return f"![Figure {number} · {title}](figures/{file})\n"


