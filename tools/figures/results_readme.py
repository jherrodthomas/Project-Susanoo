#!/usr/bin/env python3
"""Build sim/results/README.md, sim/results/figures/*.svg and sim/results/ResultSets.sysml: the committed results.

Everything on the page is read from the result files, the code that writes and reads them, and CI:

  sim/results/*.json, *.md          every committed result: its synthetic label, plant-spec digest, hazards named
  sim/**/*.py                       which module writes each result (it names the file and writes outputs)
  sim/**/*.py, tools/**/*.py        which modules read each result
  .github/workflows/*.yml           which CI job re-runs each writer, and how (--check or --compare)
  sim/spec/walker.yaml              the current plant-spec digest, to tell current results from stale ones

Figures (house style of framework/documentation-standard.md):

  fig-1-result-files.svg         every result file: writer, CI check, synthetic label, spec digest current or stale
  fig-2-lineage.svg              inputs → writers → result files → the pages and figures that read them
  fig-3-block-diagram.svg        SUS-I1 decomposition; the subsystems of the hazards the results name are coloured
  fig-4-boundary-diagram.svg     what the folder holds and what crosses its boundary
  fig-5-sysml-block-definition.svg  ResultSets (generated .sysml): the result block and every result set
  fig-6-inputs-and-outputs.svg   what writes the folder and what reads it

    python3 tools/figures/results_readme.py            # write
    python3 tools/figures/results_readme.py --check    # fail if anything is stale
"""
