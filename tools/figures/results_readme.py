def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = load()
    specs, sysml = figure_specs(d)
    files = {SYSML: sysml, FIGS / "fig-1-result-files.svg": fig_files(d)}
    for spec, svg in zip(specs, diagram.render_all(specs)):
        files[FIGS / spec["file"]] = svg
    files[README] = readme(d, specs)
    return emit(files, FIGS, args.check, GEN)


if __name__ == "__main__":
    sys.exit(main())
