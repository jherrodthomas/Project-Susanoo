def first_line(doc: str) -> str:
    s = " ".join((doc or "").strip().split("\n\n")[0].split())
    return re.sub(r"\s*Usage:.*$", "", s)


def package_of(rel: str) -> str:
    parts = Path(rel).parts
    return parts[1] if len(parts) > 2 else "(top level)"


def kind_of(rel: str, main: bool) -> str:
    if rel in HELPERS:
        return "helper"
    if rel in VALIDATORS:
        return "conformance" if rel.endswith(".sh") else "validator"
    if not main:
        return "library"
    return "cad" if rel.startswith("tools/cad/") else "generator"


def scan_modules() -> list[dict]:
    mods = []
    for p in sorted(TOOLS.rglob("*.py")):
        if SKIP & set(p.relative_to(ROOT).parts) or p.name == "__init__.py":
            continue
        text = p.read_text()
        tree = ast.parse(text)
        rel = str(p.relative_to(ROOT))
        main = "__main__" in text
        imports = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module:
                imports.add(node.module)
            elif isinstance(node, ast.Import):
                imports.update(a.name for a in node.names)
        mods.append({"rel": rel, "pkg": package_of(rel), "doc": first_line(ast.get_docstring(tree) or ""),
                     "main": main, "kind": kind_of(rel, main), "imports": imports, "lines": text.count("\n")})
    for sh in ("tools/validate_doc_sysml.sh", "tools/sysml/pilot/validate.sh", "tools/cad/make.sh"):
        p = ROOT / sh
        if p.exists():
            com = [ln[1:].strip() for ln in p.read_text().splitlines()[1:8]
                   if ln.startswith("#") and "SPDX" not in ln]
            mods.append({"rel": sh, "pkg": package_of(sh), "doc": first_line(" ".join(com).split(". ")[0] + "."),
                         "main": True, "kind": kind_of(sh, True), "imports": set(), "lines": p.read_text().count("\n")})
    return mods


def resolve(name: str, mods: list[dict]) -> str | None:
    """Package of an imported module name, or None if it is not a tool."""
    parts = name.split(".")
    if parts[0] == "tools" and len(parts) > 1:
        cand = "/".join(parts) + ".py"
        if any(m["rel"] == cand for m in mods):
            return package_of(cand)
        return parts[1] if (TOOLS / parts[1]).is_dir() else "(top level)"
    for m in mods:
        if Path(m["rel"]).stem == parts[0] and m["rel"].endswith(".py"):
            return m["pkg"]
    return None


def scan_ci(mods: list[dict]) -> list[dict]:
    """Every workflow step that runs a tool: workflow, job, step name, entry point."""
    rels = {m["rel"] for m in mods}
    out = []
    for wf in sorted(WORKFLOWS.glob("*.y*ml")):
        w = yaml.safe_load(wf.read_text())
        for job, jd in (w.get("jobs") or {}).items():
            for st in jd.get("steps") or []:
                run = st.get("run")
                if not run:
                    continue
                run = "\n".join(ln for ln in run.splitlines() if not ln.strip().startswith("echo"))
                found = []
                for m in re.finditer(r"-m (tools\.[\w.]+)", run):
                    found.append(m.group(1).replace(".", "/") + ".py")
                for m in re.finditer(r"(?<![\w/])(tools/[\w./*-]+\.(?:py|sh))", run):
                    found += sorted(str(p.relative_to(ROOT)) for p in ROOT.glob(m.group(1))) or [m.group(1)]
                for rel in dict.fromkeys(found):
                    if rel in rels:
                        out.append({"wf": wf.stem, "job": job, "step": st.get("name", ""), "rel": rel})
    return out


def load() -> dict:
    ctx, _, _ = load_reqs()
    mods = scan_modules()
    ci = scan_ci(mods)
    via = []
    for root, prof in ENFORCED.items():
        for gen in [prof.get("generator")] + prof.get("extra_generators", []):
            if gen and gen[0] not in via:
                via.append(gen[0])
    runs: dict[str, list[str]] = {}
    for c in ci:
        runs.setdefault(c["rel"], [])
        lab = f"{c['wf']} · {c['job']}"
        if lab not in runs[c["rel"]]:
            runs[c["rel"]].append(lab)
    for rel in via:
        runs.setdefault(rel, []).append("via check_readme_diagrams")
    for sh in [m for m in mods if m["rel"].endswith(".sh")]:
        text = (ROOT / sh["rel"]).read_text()
        for m in mods:
            if m is not sh and Path(m["rel"]).name in text and m["rel"] not in runs:
                runs[m["rel"]] = [f"via {Path(sh['rel']).name}"]
    pk_edges: dict[tuple[str, str], int] = {}
    for m in mods:
        for name in m["imports"]:
            p = resolve(name, mods)
            if p and p != m["pkg"]:
                pk_edges[(m["pkg"], p)] = pk_edges.get((m["pkg"], p), 0) + 1
    ci_jobs = {f"{c['wf']} · {c['job']}" for c in ci}
    in_ci = {rel for rel, labs in runs.items()
             if any(lab in ci_jobs or lab == "via check_readme_diagrams" for lab in labs)}
    for rel, labs in runs.items():
        for lab in labs:
            if lab.startswith("via ") and lab != "via check_readme_diagrams":
                src = next((m["rel"] for m in mods if Path(m["rel"]).name == lab[4:]), None)
                if src in in_ci:
                    in_ci.add(rel)
    pkgs = sorted({m["pkg"] for m in mods}, key=lambda p: (p == "(top level)", p))
    docs_steps = [st for st in yaml.safe_load((WORKFLOWS / f"{DOCS_JOB[0]}.yml").read_text())["jobs"][DOCS_JOB[1]]["steps"]
                  if st.get("run") and not st["run"].lstrip().startswith("pip ")]
    return {"ctx": ctx, "mods": mods, "ci": ci, "runs": runs, "via": via, "pk_edges": pk_edges, "pkgs": pkgs, "in_ci": in_ci,
            "docs_steps": docs_steps}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def entry_points(d: dict) -> list[dict]:
    return [m for m in d["mods"] if m["main"]]


