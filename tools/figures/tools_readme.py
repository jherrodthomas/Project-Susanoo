def node_id(rel: str) -> str:
    return re.sub(r"\W", "_", rel)


def fig_ci(d: dict) -> dict:
    mods = {m["rel"]: m for m in d["mods"]}
    nodes = [{"id": "JOBS", "banner": "CI jobs", "tone": "work"},
             {"id": "TOOLS", "banner": "Tools they run", "tone": "work"}]
    edges, jobs, seen = [], [], set()
    for c in d["ci"]:
        j = (c["wf"], c["job"])
        if j not in jobs:
            jobs.append(j)
    for wf, job in jobs:
        jid = node_id(f"job-{wf}-{job}")
        nodes.append({"id": jid, "parent": "JOBS", "code": f"{wf} · {job}", "title": f"{wf}.yml",
                      "tone": "external", "legend": "CI job (workflow · job)"})
        for rel in dict.fromkeys(c["rel"] for c in d["ci"] if (c["wf"], c["job"]) == (wf, job)):
            m = mods[rel]
            tid = node_id(rel)
            if tid not in seen:
                seen.add(tid)
                nodes.append({"id": tid, "parent": "TOOLS", "code": rel.replace("tools/", "", 1),
                              "title": fk.wrap(m["doc"], 330, 11, max_lines=1)[0] if m["doc"] else rel,
                              "tone": KIND_TONE[m["kind"]], "maxw": 260,
                              "legend": {"validator": "Validator", "conformance": "SysML conformance",
                                         "generator": "Generator (--check)", "cad": "CAD pipeline",
                                         "helper": "Helper", "library": "Library"}[m["kind"]]})
            edges.append({"src": jid, "dst": tid, "label": ""})
    dc = node_id("tools/check_readme_diagrams.py")
    if dc in seen:
        nodes.append({"id": "VIA", "banner": "Folder README generators", "tone": "work"})
        for rel in d["via"]:
            nodes.append({"id": "via_" + node_id(rel), "parent": "VIA", "code": rel.replace("tools/", "", 1),
                          "title": "", "tone": "system", "maxw": 220, "legend": "Generator (--check)"})
        edges.append({"src": dc, "dst": "VIA", "label": f"runs {len(d['via'])} with --check"})
    return {"file": "fig-2-ci-coverage.svg", "number": "2", "title": "What CI runs on every push and pull request",
            "subtitle": "Each CI job that runs a tool, and the tools it runs. The README check runs every folder "
                        "generator with --check and fails on stale output. Simulation jobs are on the simulation page.",
            "ref": ".github/workflows", "direction": "RIGHT", "orient": "fixed", "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Runs")]}


def fig_blocks(d: dict) -> dict:
    nodes = [{"id": "T", "banner": "tools/", "tone": "work"}]
    for p in d["pkgs"]:
        ms = [m for m in d["mods"] if m["pkg"] == p]
        nodes.append({"id": "p_" + node_id(p), "parent": "T", "code": f"{p}/" if p != "(top level)" else "top level",
                      "title": f"{plural(len(ms), 'module')}, {sum(m['lines'] for m in ms):,} lines",
                      "sub": plural(sum(1 for m in ms if m["main"]), "entry point")
                             + (" · own README" if (TOOLS / p / "README.md").exists() else ""),
                      "tone": "safety" if any(m["kind"] in ("validator", "conformance") for m in ms) else
                      ("work" if p == "cad" else "system"), "maxw": 250,
                      "legend": "Package with a validator" if any(m["kind"] in ("validator", "conformance") for m in ms)
                      else ("CAD pipeline" if p == "cad" else "Package")})
    edges = [{"src": "p_" + node_id(a), "dst": "p_" + node_id(b), "label": f"{n} import{'s' if n > 1 else ''}",
              "dash": True} for (a, b), n in sorted(d["pk_edges"].items())]
    return {"file": "fig-3-block-diagram.svg", "number": "3", "title": "Block diagram",
            "subtitle": "The tool packages and top-level scripts, with how many modules of each import another "
                        "package. Every package imports terms/: each page and figure is decorated with its terms "
                        "before it is written.",
            "ref": "tools/", "direction": "DOWN", "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Imports (count of modules)", True)]}


def docs_activity(d: dict) -> dict:
    steps, seen = [], set()
    for st in d["docs_steps"]:
        name = sysml_name(st["name"])[:40]
        name = name[0].lower() + name[1:]
        while name in seen:
            name += "_"
        seen.add(name)
        label = re.sub(r"\s*\(.*?\)", "", st["name"])
        steps.append({"name": name, "label": label, "safety": "check_readme_diagrams" in st["run"]})
    return {"name": "DocsCheck", "steps": steps,
            "doc": f"The {DOCS_JOB[0]} workflow, job {DOCS_JOB[1]}: its steps in order (generated from the workflow)."}


