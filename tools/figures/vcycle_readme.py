def fig_gates(d: dict) -> str:
    W, M = 1240, 40
    blocks, gates = d["blocks"], d["gates"]
    gaps_now = sum(1 for b in blocks if cell(b, d["cur_i"]) == "gap")
    head, y0 = fk.header(
        W, "2", "What the gate scrubber shows",
        f"Each block at each gate, by the page's own rule: a block is due from its exit gate, and is met once its least "
        f"mature record reaches the rung the page asks for (left side baselined, right side verified). The rule is a "
        f"placeholder for real exit criteria. At the current gate {d['cur']}: {gaps_now} "
        f"gap{'' if gaps_now == 1 else 's'}.", "tools/vcycle/page.html (gate rule)")
    out = list(head)
    x0, cw, rh = M + 320, (W - 2 * M - 320) / len(gates), 34
    y = y0 + 26
    for i, g in enumerate(gates):
        cxm = x0 + i * cw + cw / 2
        if i == d["cur_i"]:
            out.append(fk.rect(x0 + i * cw + 2, y - 16, cw - 4, 52 + len(blocks) * rh, fill="#FEF3C7", stroke="#D97706",
                               rx=6, sw=1))
        out.append(fk.text(cxm, y, g["id"], size=11.5, fill=INK, weight=700, anchor="middle", mono=True))
        for j, ln in enumerate(fk.wrap(g["title"], cw - 10, 8.5, max_lines=2)):
            out.append(fk.text(cxm, y + 14 + j * 11, ln, size=8.5, fill=MUTED, anchor="middle"))
    y += 36
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    tone = {"met": TONES["ok"], "gap": TONES["red"]}
    for n, b in enumerate(blocks):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, 316, rh - 2, fill=GREY_BG, stroke="none", rx=5, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(M + 6, cy, b["title"], size=10.5, fill=INK, weight=700))
        out.append(fk.text(M + 200, cy, f"needs {vc.STATES[b['need']].lower()}", size=9, fill=MUTED))
        for i in range(len(gates)):
            c = cell(b, i)
            cxm = x0 + i * cw + cw / 2
            if c == "not due":
                out.append(fk.text(cxm, cy, "·", size=12, fill=FAINT, anchor="middle"))
            else:
                t = tone[c]
                p, w = fk.pill(cxm - fk.pill_w(c) / 2, cy - 12, c, t[1], color=t[0], stroke=t[0])
                out += p
    y += len(blocks) * rh + 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["ok"][1], TONES["ok"][0], "Met: lowest rung reached"),
           (TONES["red"][1], TONES["red"][0], "Gap: due and below the rung"),
           ("#FEF3C7", "#D97706", f"Current gate {d['cur']}")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    out.append(fk.text(M, y + 4, "· not due yet at that gate", size=10.5, fill=MUTED))
    y += 18
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · What the gate scrubber shows", "Every block at every gate: not due, met or gap",
                  out)


# ================================================================ SysML state machine
def ladder(d: dict) -> dict:
    states = []
    for i, (name, meaning, _) in enumerate(vc.LADDER):
        c = d["status"].get(i, 0)
        states.append({"name": sysml_name(name), "title": name,
                       "doc": f"{meaning}." + (f" Now: {c} record{'' if c == 1 else 's'}." if c else ""),
                       "tone": "safety" if c else "system"})
    trans = [[states[i]["name"], states[i + 1]["name"], vc.LADDER[i + 1][2]] for i in range(len(states) - 1)]
    return {"name": "MaturityLadder", "states": states, "initial": states[0]["name"], "transitions": trans,
            "final": [], "doc": "Rungs of record maturity on the System V cycle page; the trigger is who may move a "
                                "record up. Computed from record status for orientation only (rule R13)."}


