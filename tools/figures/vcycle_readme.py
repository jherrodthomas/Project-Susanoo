# ================================================================ records
def js_map(text: str, name: str) -> dict:
    m = re.search(rf"const {name}=\{{([^}}]*)\}}", text)
    if not m:
        raise SystemExit(f"{GEN}: const {name} not found in {PAGE_SRC.relative_to(ROOT)}")
    return {k: int(v) for k, v in re.findall(r"(\w+):(\d+)", m.group(1))}


def views(text: str) -> list[str]:
    return re.findall(r'<button id="m-[\w-]+"[^>]*>([^<]+)</button>', text)


def load() -> dict:
    ctx, _, _ = load_reqs()
    data = vc.records()
    blocks = vc.system_blocks(data)
    src = PAGE_SRC.read_text(encoding="utf-8")
    exit_, need = js_map(src, "EXIT"), js_map(src, "NEED")
    gates = data["gates"]
    for b in blocks:
        b["side"] = SIDE[b["k"][0]]
        b["exit_i"] = exit_[b["k"]]
        b["need"] = need[b["k"]]
        b["dist"] = Counter(b["states"])
    status = Counter()
    for kind in ("reqs", "haz", "events", "trades", "changes"):
        for r in data[kind]:
            status[vc.STATE.get(r.get("status"), 1)] += 1
    top = [e for e in data["elements"] if e["parent"] == "SUS-I1"]
    alloc = {e["id"]: sum(1 for r in data["reqs"] if any(a == e["id"] or a.startswith(e["id"] + "-") for a in r["alloc"]))
             for e in top}
    page = FOLDER / "index.html"
    return {"ctx": ctx, "data": data, "blocks": blocks, "gates": gates, "cur": data["current_gate"],
            "cur_i": next(i for i, g in enumerate(gates) if g["id"] == data["current_gate"]), "views": views(src),
            "status": status, "top": top, "alloc": alloc, "page_kb": round(page.stat().st_size / 1024)}


def cell(b: dict, gi: int) -> str:
    if b["exit_i"] > gi:
        return "not due"
    return "met" if b["state"] >= b["need"] else "gap"


# ================================================================ figure 1 · system blocks (drawn directly)
def fig_blocks(d: dict) -> str:
    W, M = 1240, 40
    blocks = d["blocks"]
    head, y0 = fk.header(
        W, "1", "The system-level V, block by block",
        f"The {len(blocks)} blocks of the SUS-I1 V as the page computes them: the side, the gate each block is due by, "
        "the records in it and how mature they are. A block takes the colour of its least mature record.",
        "tools/vcycle/build_vcycle.py")
    out = list(head)
    cx = {"b": M, "s": M + 250, "g": M + 380, "n": M + 450, "bar": M + 640, "lo": M + 1000}
    y = y0 + 30
    for k, lab in (("b", "Block"), ("s", "Side"), ("g", "Due by"), ("n", "Records"), ("bar", "Maturity of its records"),
                   ("lo", "Lowest rung")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh, bw = 46, 340
    for n, b in enumerate(blocks):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["b"], cy - 7, b["title"], size=11, fill=INK, weight=700))
        out.append(fk.text(cx["b"], cy + 8, b["sub"], size=9.5, fill=MUTED))
        tone = TONES["interface" if b["k"][0] == "L" else ("ok" if b["k"][0] == "R" else "amber")]
        p, _ = fk.pill(cx["s"], cy - 12, b["side"].split()[0].lower(), tone[1], color=tone[0], stroke=tone[0])
        out += p
        out.append(fk.text(cx["g"], cy, b["gate"], size=11, fill=INK, weight=700, mono=True))
        out.append(fk.text(cx["n"], cy - 7, str(len(b["states"])), size=11, fill=INK, weight=700))
        out.append(fk.text(cx["n"], cy + 8, fk.wrap(b["what"], 175, 9, max_lines=1)[0], size=9, fill=MUTED))
        x, total = cx["bar"], max(len(b["states"]), 1)
        for rung in range(len(vc.STATES)):
            c = b["dist"].get(rung, 0)
            if not c:
                continue
            w = bw * c / total
            out.append(fk.rect(x, cy - 12, w, 16, fill=vc.FILL[rung], stroke="#94A3B8", rx=2, sw=0.6))
            if w > 22:
                out.append(fk.text(x + w / 2, cy, str(c), size=9.5, fill=INK if rung < 3 else "#FFFFFF", weight=700,
                                   anchor="middle"))
            x += w
        if not b["states"]:
            out.append(fk.text(cx["bar"], cy, "no records yet", size=9.5, fill=MUTED))
        out.append(fk.rect(cx["lo"], cy - 12, 14, 14, fill=vc.FILL[b["state"]], stroke="#94A3B8", rx=3, sw=0.8))
        out.append(fk.text(cx["lo"] + 22, cy - 1, vc.STATES[b["state"]], size=10.5, fill=INK))
    y += len(blocks) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(vc.FILL[i], "#94A3B8", s) for i, s in enumerate(vc.STATES)]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · The system-level V, block by block",
                  "Every block of the system-level V with its records and their maturity", out)


