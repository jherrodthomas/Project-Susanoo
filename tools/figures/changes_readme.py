def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = load()
    s = stats(d)
    specs = figure_specs(d, s)
    files = {FIGS / "fig-1-impact-surface.svg": fig_surface(d, s)}
    for spec, svg in zip(specs, diagram.render_all(specs)):
        files[FIGS / spec["file"]] = svg
    tail = "\n"
    if README.exists() and END_MARKER in README.read_text():
        tail = README.read_text().split(END_MARKER, 1)[1]
    files[README] = readme(d, s, specs, tail)
    return emit(files, FIGS, args.check, GEN)


