# ================================================================ records
def links(h: dict) -> dict[str, list[str]]:
    """The items of a hazard that a change request can name in `affects` (as rule R10 matches them)."""
    reqs = set(h.get("requirement_ids") or [])
    mits = []
    for m in h.get("mitigations") or []:
        mits.append(f"{h['id']}:{m['id']}")
        reqs.update(m.get("requirement_ids") or [])
    return {"requirements": sorted(reqs), "ssfs": sorted(hazard_ssf_ids(h)), "mitigations": mits,
            "configurations": list(h["applicability"]["configurations"])}


def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    repo = load_repo()
    crs = repo.objects["change"]
    cat = yaml.safe_load(CATALOG.read_text())
    t304 = next(f for f in cat["folders"] if f["id"] == "T304")
    rows = {}
    for hid, h in hazards.items():
        lk = links(h)
        spread = set()
        for item in lk["requirements"] + lk["ssfs"]:
            spread |= impacted_hazards(repo, [item])
        rows[hid] = {"links": lk, "spread": sorted(spread - {hid}),
                     "cr": sorted(c for c, r in crs.items() if hid in impacted_hazards(repo, r.get("affects") or [])),
                     "reassess": len(h.get("reassessments") or []), "accept": len(h.get("acceptances") or [])}
    configs = sorted({c for h in hazards.values() for c in h["applicability"]["configurations"]})
    baseline = {c: sorted(impacted_hazards(repo, [c])) for c in configs}
    events = sorted(p.stem for p in (ROOT / "safety" / "events").glob("EVT-*.yaml"))
    return {"ctx": ctx, "reqs": reqs, "hazards": hazards, "repo": repo, "crs": crs, "t304": t304, "rows": rows,
            "baseline": baseline, "events": events, "ssfs": repo.objects["ssf"]}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def summary(c: dict) -> str:
    return ", ".join(f"{n} {k}" for k, n in sorted(c.items())) or "none"


def stats(d: dict) -> dict:
    crs, hz = d["crs"], d["hazards"]
    gated = [c for c, r in crs.items() if r.get("status") in ("approved", "implemented")]
    impacted = set()
    for c in gated:
        impacted |= impacted_hazards(d["repo"], crs[c].get("affects") or [])
    return {"crs": len(crs), "status": count(r.get("status", "draft") for r in crs.values()),
            "kind": count(r.get("kind") for r in crs.values()), "gated": len(gated), "impacted": len(impacted),
            "reassess": sum(len(h.get("reassessments") or []) for h in hz.values()),
            "accepted": sum(1 for h in hz.values() if h.get("acceptances")),
            "mits": sum(len(h.get("mitigations") or []) for h in hz.values())}


# ================================================================ figure 1 · impact surface (drawn directly)
def fig_surface(d: dict, s: dict) -> str:
    hazards, rows = d["hazards"], d["rows"]
    W, M = 1120, 40
    base = next(iter(d["baseline"].items()), ("—", []))
    head, y0 = fk.header(
        W, "1", "What a change can reopen",
        f"Each hazard links to requirements, SSFs, mitigations and a configuration; a change naming any of them reopens "
        f"the hazard (rule R10). A change to {base[0]} reopens all {len(base[1])}. Spread: other hazards that share a "
        "requirement or SSF.", "safety/hazards · tools/pdac/rules.py")
    out = list(head)
    cx = {"id": M, "title": M + 118, "req": M + 420, "ssf": M + 520, "mit": M + 600, "spread": M + 690,
          "rea": M + 870, "acc": M + 960}
    y = y0 + 30
    for k, lab, anchor in (("id", "Hazard", ""), ("title", "Title", ""), ("req", "Requirements", "middle"),
                           ("ssf", "SSFs", "middle"), ("mit", "Mitigations", "middle"),
                           ("spread", "Spread to other hazards", ""), ("rea", "Reassessed", "middle"),
                           ("acc", "Accepted", "middle")):
        out.append(fk.text(cx[k] + (40 if anchor else 0), y, lab, size=10.5, fill=MUTED, weight=700, anchor=anchor))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh, accent = 36, TONES["system"]
    for n, (hid, h) in enumerate(hazards.items()):
        r, top = rows[hid], y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        lvl = (h.get("initial_risk") or {}).get("risk_level", "")
        tone = TONES[LEVEL_TONE.get(lvl, "amber")]
        p, _ = fk.pill(cx["id"], cy - 12, hid, tone[1], color=tone[0], stroke=tone[0])
        out += p
        lines = fk.wrap(h.get("title", hid), 285, 11.5, True, max_lines=2)
        for j, ln in enumerate(lines):
            out.append(fk.text(cx["title"], cy + (-5 + 14 * j if len(lines) > 1 else 0), ln, size=11.5, fill=INK,
                               weight=700))
        for k, key in (("req", "requirements"), ("ssf", "ssfs"), ("mit", "mitigations")):
            v = len(r["links"][key])
            if v:
                out.append(fk.circle(cx[k] + 40, cy - 4, 8 + 1.1 * min(v, 8), fill=accent[1], stroke=accent[0], sw=1.4))
                out.append(fk.text(cx[k] + 40, cy, str(v), size=10.5, fill=accent[0], weight=700, anchor="middle"))
            else:
                out.append(fk.text(cx[k] + 40, cy, "–", size=11, fill=FAINT, anchor="middle"))
        sp = r["spread"]
        if sp:
            t = ", ".join(sp) if len(sp) <= 2 else f"{sp[0]}, {sp[1]} +{len(sp) - 2}"
            st = TONES["amber"]
            p, w = fk.pill(cx["spread"], cy - 12, str(len(sp)), st[1], color=st[0], stroke=st[0])
            out += p
            out.append(fk.text(cx["spread"] + w + 6, cy, t, size=10, fill=MUTED))
        else:
            out.append(fk.text(cx["spread"], cy, "none", size=10.5, fill=FAINT))
        for k, v in (("rea", r["reassess"]), ("acc", r["accept"])):
            out.append(fk.text(cx[k] + 40, cy, str(v), size=11, fill=INK if v else FAINT, anchor="middle"))
    y += len(hazards) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(accent[1], accent[0], "Linked items a change can name (count)"),
           (TONES["amber"][1], TONES["amber"][0], "Other hazards reopened through a shared item"),
           (TONES["red"][1], TONES["red"][0], "Hazard, High initial risk"),
           (TONES["safety"][1], TONES["safety"][0], "Serious"), (TONES["amber"][1], TONES["amber"][0], "Medium")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · What a change can reopen",
                  "Per hazard, the linked items a change can name and how far a change spreads", out)


