# ================================================================ records
def strip_code(t: str) -> str:
    return re.sub(r"```.*?```|`[^`\n]*`", "", t, flags=re.S)


def links_of(t: str) -> list[str]:
    t = strip_code(t)
    return re.findall(r"\]\(([^)\s]+)\)", t) + re.findall(r'(?:src|href)="([^"]+)"', t)


def classify(link: str, src: Path, pages: set[str], assets: set[str]) -> tuple[str, bool, str]:
    tgt = link.split("#")[0]
    if re.match(r"(https?:|mailto:)", link):
        return "web", True, ""
    if link.startswith("#"):
        return "anchor", True, ""
    if tgt.startswith("images/"):
        return "image", (WIKI / tgt).exists(), tgt
    if tgt.startswith("assets/"):
        return "asset", tgt[7:] in assets and (ROOT / tgt[7:]).exists(), tgt
    if tgt.endswith(".md"):
        return "page", (src.parent / tgt).exists(), Path(tgt).stem
    if tgt not in pages and "." in Path(tgt).name and (src.parent / tgt).is_file():
        return "repo", True, tgt                          # resolves in the repository; not published to the wiki
    return "page", tgt in pages, tgt


def load() -> dict:
    ctx, _, _ = load_reqs()
    files = sorted(p for p in WIKI.glob("*.md") if not p.name.startswith("_"))
    names = {p.stem for p in files}
    assets = {ln.strip() for ln in (WIKI / "assets.txt").read_text().splitlines() if ln.strip()}
    side = (WIKI / "_Sidebar.md").read_text()
    side_links = {lk.split("#")[0] for lk in links_of(side)}
    home_links = {classify(lk, WIKI / "Home.md", names, assets)[2] for lk in links_of((WIKI / "Home.md").read_text())}
    pages, inbound, kinds, broken, by_src = [], Counter(), Counter(), [], defaultdict(Counter)
    for p in files:
        text = p.read_text(encoding="utf-8")
        head = text.split("<!-- terms:start", 1)[0][:3000]
        m = MARK.search(head)
        if m and m.group(1) == COPY:
            src = re.search(r"GENERATED by tools/wiki/build_wiki\.py from (\S+?)\.\s", head)
            kind, prod = "copy", src.group(1) if src else COPY
        elif m and m.group(1) != "tools/terms/terms.py":
            kind, prod = "generated", m.group(1)
        else:
            kind, prod = "hand", ""
        targets = set()
        for lk in links_of(text):
            k, ok, tgt = classify(lk, p, names, assets)
            kinds[k] += 1
            by_src[kind][k] += 1
            if not ok:
                broken.append((p.name, lk))
            if k == "page" and ok and tgt != p.stem:
                targets.add(tgt)
        for t in targets:
            inbound[t] += 1
        pages.append({"name": p.stem, "kind": kind, "prod": prod, "side": p.stem in side_links,
                      "home": p.stem in home_links, "kb": round(p.stat().st_size / 1024)})
    for pg in pages:
        pg["inbound"] = inbound.get(pg["name"], 0)
        pg["orphan"] = not pg["side"] and pg["inbound"] == 0 and pg["name"] not in ("Home", "README")
    wf = WORKFLOW.read_text()
    trig = re.findall(r"^\s+- '([^']+)'", wf.split("permissions:")[0], re.M)
    steps = [lab for pat, lab in STEP_PATTERNS if re.search(pat, wf)]
    images = sorted(p.name for p in IMAGES.iterdir() if p.suffix in (".svg", ".png") and not p.name.startswith(PREFIX))
    used_images = {lk.split("#")[0][7:] for p in files for lk in links_of(p.read_text()) if lk.startswith("images/")}
    return {"ctx": ctx, "pages": pages, "kinds": kinds, "broken": broken, "by_src": by_src, "assets": sorted(assets),
            "trig": trig, "steps": steps, "images": images,
            "unused_images": [i for i in images if i not in used_images],
            "root": next(k for k, v in ctx.nodes.items() if not v.get("parent") and v.get("kind") != "external")}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


# ================================================================ figure 1 · pages (drawn directly)
def fig_pages(d: dict) -> str:
    W, M = 1280, 40
    pages = d["pages"]
    cnt = Counter(p["kind"] for p in pages)
    orph = [p for p in pages if p["orphan"]]
    head, y0 = fk.header(
        W, "1", "Every wiki page and where it comes from",
        f"{plural(len(pages), 'page')}: {cnt['copy']} copied from repository pages by build_wiki.py, {cnt['generated']} "
        f"written by other generators, {cnt['hand']} hand-written here. {sum(p['side'] for p in pages)} are in the "
        f"sidebar; {len(orph)} are reached neither from the sidebar nor from any other page.", "docs/wiki/*.md")
    out = list(head)
    y = y0 + 20
    cols, gap = 5, 8
    cw = (W - 2 * M - (cols - 1) * gap) / cols
    for kind in ("copy", "generated", "hand"):
        group = sorted([p for p in pages if p["kind"] == kind], key=lambda p: p["name"].lower())
        if not group:
            continue
        t = TONES[KIND_TONE[kind]]
        out.append(fk.rect(M, y, 10, 10, fill=t[1], stroke=t[0], rx=2, sw=1.2))
        out.append(fk.text(M + 18, y + 9, f"{KIND_LABEL[kind]} · {len(group)}", size=11.5, fill=INK, weight=700))
        y += 20
        for i, p in enumerate(group):
            x = M + (i % cols) * (cw + gap)
            yy = y + (i // cols) * 26
            stroke = TONES["red"][0] if p["orphan"] else t[0]
            out.append(fk.rect(x, yy, cw, 22, fill=t[1] if p["side"] else "#FFFFFF", stroke=stroke,
                               rx=5, sw=1.8 if p["orphan"] else 0.9, dash="4 3" if p["orphan"] else ""))
            out.append(fk.text(x + 7, yy + 15, fk.wrap(p["name"], cw - 40, 9.5, max_lines=1)[0], size=9.5, fill=INK))
            out.append(fk.text(x + cw - 6, yy + 15, str(p["inbound"]), size=9, fill=MUTED, anchor="end", mono=True))
        y += ((len(group) + cols - 1) // cols) * 26 + 16
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES[KIND_TONE[k]][1], TONES[KIND_TONE[k]][0], KIND_LABEL[k]) for k in KIND_TONE] + [
        ("#FFFFFF", "#94A3B8", "Not in the sidebar (filled: in the sidebar)"),
        ("#FFFFFF", TONES["red"][0], "Reached from nowhere")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    out.append(fk.text(M, y + 4, "The number on each page is how many other wiki pages link to it.", size=10.5, fill=MUTED))
    y += 18
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Every wiki page and where it comes from",
                  "Every wiki page by where it comes from, with sidebar and inbound links", out)


# ================================================================ figure 2 · links (drawn directly)
def fig_links(d: dict) -> str:
    W, M = 1280, 40
    kinds = ["page", "asset", "image", "web", "anchor", "repo"]
    lab = {"page": "to wiki pages", "asset": "to repository figures (assets/)", "image": "to images/",
           "web": "to the web (GitHub files, standards)", "anchor": "within the page",
           "repo": "to repository files (work in the repository only)"}
    tone = {"page": "interface", "asset": "ok", "image": "work", "web": "external", "anchor": "system", "repo": "amber"}
    total = sum(d["kinds"].values())
    head, y0 = fk.header(
        W, "2", "Every link in the wiki, and whether it resolves",
        f"{plural(total, 'link')} across the pages, by kind and by where the page comes from. A wiki link must name an "
        f"existing page, an image must be in images/, a figure must be listed in assets.txt. "
        f"{plural(len(d['broken']), 'link')} do not resolve; {plural(len(d['unused_images']), 'image')} in images/ "
        "are not linked from any page.", "docs/wiki · assets.txt")
    out = list(head)
    y = y0 + 30
    bw = W - 2 * M - 380
    mx = max(max(c.values()) for c in d["by_src"].values()) if d["by_src"] else 1
    for kind in ("copy", "generated", "hand"):
        c = d["by_src"].get(kind, Counter())
        out.append(fk.text(M, y + 12, KIND_LABEL[kind], size=11, fill=INK, weight=700))
        out.append(fk.text(M, y + 27, plural(sum(c.values()), "link"), size=9.5, fill=MUTED))
        x = M + 300
        for k in kinds:
            n = c.get(k, 0)
            if not n:
                continue
            w = bw * n / max(sum(cc.values()) for cc in d["by_src"].values())
            t = TONES[tone[k]]
            out.append(fk.rect(x, y, w, 26, fill=t[1], stroke=t[0], rx=3, sw=0.8))
            if w > 34:
                out.append(fk.text(x + w / 2, y + 17, str(n), size=10, fill=t[0], weight=700, anchor="middle"))
            x += w
        y += 44
    _ = mx
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 26
    out.append(fk.text(M, y, "Links that do not resolve", size=11.5, fill=INK, weight=700))
    y += 18
    if d["broken"]:
        for src, lk in d["broken"][:12]:
            out.append(fk.text(M + 10, y, f"{src} → {lk}", size=10, fill=TONES["red"][0], mono=True))
            y += 15
    else:
        out.append(fk.text(M + 10, y, "none", size=10.5, fill=TONES["ok"][0], weight=700))
        y += 16
    y += 10
    out.append(fk.text(M, y, "Images in images/ that no page links to", size=11.5, fill=INK, weight=700))
    y += 18
    for ln in fk.wrap(", ".join(d["unused_images"]) or "none", W - 2 * M - 20, 10, max_lines=4):
        out.append(fk.text(M + 10, y, ln, size=10, fill=MUTED if d["unused_images"] else TONES["ok"][0], mono=True))
        y += 15
    y += 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES[tone[k]][1], TONES[tone[k]][0], f"Links {lab[k]}") for k in kinds]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Every link in the wiki, and whether it resolves",
                  "Every link in the wiki by kind and source, with any that do not resolve", out)


