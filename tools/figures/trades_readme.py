def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    scope = [e for e in d["elements"] if e in ctx.nodes]
    block = fig_block(ctx, {"scope": scope})
    by = defaultdict(list)
    for a in d["ts"]["alternatives"]:
        for el in a.get("elements") or []:
            by[el].append(a["id"])
    for n in block["nodes"]:
        if n.get("code") in by:
            n["sub"] = "alternatives " + ", ".join(by[n["code"]])
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"SUS-I1 decomposition. The {len(scope)} power elements of the {d['ts']['id']} alternatives are "
                          "coloured, with the alternatives that use each.")
    boundary = fig_boundary(ctx, {"path": "sim/trades", "boundary": {
        "name": "Trade-study evidence", "inside": ["Evidence definition", "Runner"],
        "outside": ["Trade study", "Plant specs and adopted torques", "Walker models", "Committed results", "CI",
                    "Project lead"],
        "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="sim/trades/README.md",
                    subtitle="The folder owns the evidence definition and its runner; the models and the trade study "
                             "live elsewhere, and only the lead decides the trade. Crossings are numbered as in the table.")
    sysml_spec, sysml = fig_sysml(d)
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "sim/trades/README.md", "direction": "RIGHT",
          "subtitle": "What the evidence consumes (left) and what reads it (right).",
          "nodes": [
              {"id": "I1", "title": f"Trade study {d['ts']['id']}", "sub": "alternatives, criteria", "tone": "work"},
              {"id": "I2", "title": "Walker models", "sub": "level 1 and level 2 (MuJoCo)", "tone": "software"},
              {"id": "I3", "title": "Adopted torques", "sub": "level-2 spec (DQ-012)", "tone": "work"},
              {"id": "X", "code": "sim/trades/", "title": "Trade-study evidence", "tone": "current"},
              {"id": "O1", "title": "Committed results", "sub": "ts001-fault-response", "tone": "work"},
              {"id": "O2", "title": f"{d['ts']['id']} scores", "sub": f"criterion {', '.join(d['e']['criteria'])} (draft)",
               "tone": "work"},
              {"id": "O3", "title": "Project lead", "sub": "architecture decision DQ-006", "tone": "safety",
               "legend": "Human decision"}],
          "edges": [{"src": "I1", "dst": "X", "label": "alternatives"}, {"src": "I2", "dst": "X", "label": "models"},
                    {"src": "I3", "dst": "X", "label": "torques"},
                    {"src": "X", "dst": "O1", "label": "outcomes"}, {"src": "X", "dst": "O2", "label": "evidence"},
                    {"src": "X", "dst": "O3", "label": "input to the decision"}]}
    specs = [fig_trace(d), block, boundary, sysml_spec, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    return specs, sysml


# ================================================================ README
