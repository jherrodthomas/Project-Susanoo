#!/usr/bin/env python3
"""Build sim/trades/README.md, sim/trades/figures/*.svg and sim/trades/SupplyLossModes.sysml: trade-study evidence.

Everything on the page is read from the evidence definition, its committed results and the trade study it feeds:

  sim/trades/fault_response.yaml           the supply-loss modes per alternative, the grid and the load-holding cases
  sim/results/ts001-fault-response.json    outcome counts per mode, load holding and level, agreement, worst impact
  architecture/trades/TS-001.yaml          the alternatives, their elements, the criterion the evidence feeds, and
                                           the preliminary scores that cite it
  sim/spec/walker.yaml                     the safe drop speed and the assumed residual bus floor

Figures (house style of framework/documentation-standard.md):

  fig-1-outcomes.svg             outcome counts for every mode, with load holding working and failed, on both levels
  fig-2-evidence-trace.svg       alternatives to supply-loss modes to the criterion and the scores that cite them
  fig-3-block-diagram.svg        SUS-I1 decomposition; the power elements of the alternatives are coloured
  fig-4-boundary-diagram.svg     what the evidence owns and what crosses its boundary
  fig-5-sysml-block-definition.svg  SupplyLossModes (generated .sysml): the mode block and each mode
  fig-6-inputs-and-outputs.svg   what the evidence consumes and what reads it

    python3 tools/figures/trades_readme.py            # write
    python3 tools/figures/trades_readme.py --check    # fail if anything is stale
"""
