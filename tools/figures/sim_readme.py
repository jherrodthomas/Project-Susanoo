"""Build the generated part of sim/README.md, sim/SimulationEvidence.sysml and sim/figures/*.svg.

Everything generated is read from the committed simulation inputs and results, so it cannot drift from them:

  sim/faults.yaml, sim/search/families.yaml, sim/uav/scenarios.yaml    what is simulated and which hazards it traces to
  sim/results/*.json, sim/results/uav/SU-*.json                        what the runs found (synthetic, no evidence credit)
  safety/hazards/HAZ-*.yaml                                            hazard titles and preliminary risk

Figures (house style of framework/documentation-standard.md):

  fig-1-result-sets.svg          every result set: layer, cases, outcomes, hazards, level-1/level-2 agreement
  fig-2-hazard-trace.svg         faults, the failure-search family and UAV scenarios traced to the hazards they exercise
  fig-3-block-diagram.svg        SUS-I1 decomposition; elements carrying a simulated hazard are coloured
  fig-4-boundary-diagram.svg     what the simulation track owns and what crosses its boundary
  fig-5-sysml-state-machine.svg  SysML state machine of the evidence gate (SimulationEvidence.sysml, generated here)
  fig-6-inputs-and-outputs.svg   what the simulation track consumes and feeds

The hand-written part of the page (evidence gate, layers, commands, honesty rules) sits below the END marker and is
preserved.

    python3 tools/figures/sim_readme.py            # write
    python3 tools/figures/sim_readme.py --check    # fail if anything is stale
"""
