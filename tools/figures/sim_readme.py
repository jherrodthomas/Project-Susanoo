def head_title(p: Path) -> str:
    for ln in (p / "README.md").read_text().splitlines():
        if ln.startswith("# "):
            return ln[2:].strip()
    return p.name


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = load()
