# ================================================================ records
def tone_of(outcome: str) -> str:
    return "ok" if outcome in GOOD else ("amber" if outcome in WARN else "red")


def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    j = lambda p: json.loads((RES / p).read_text())  # noqa: E731
    faults = yaml.safe_load((FOLDER / "faults.yaml").read_text())["faults"]
    fams = yaml.safe_load((FOLDER / "search" / "families.yaml").read_text())
    scen = yaml.safe_load((FOLDER / "uav" / "scenarios.yaml").read_text())["scenarios"]
    plant, search, cross, size, trade = (j("plant-results.json"), j("search-SF-01.json"), j("l2-crosscheck.json"),
                                         j("sizing-cf4.json"), j("ts001-fault-response.json"))
    uav = {p.stem: json.loads(p.read_text()) for p in sorted((RES / "uav").glob("SU-*.json"))}
    fault_hz = sorted({c.split(":")[0] for f in faults for c in f.get("causes", [])})
    rows = [
        {"id": "plant-results", "layer": "1 · plant", "cases": len(plant["runs"]) + len(plant["nominal"]),
         "outcomes": Counter(r["outcome"] for r in plant["runs"]), "hazards": fault_hz, "agree": None,
         "file": "results/plant-results.md", "what": "fault catalogue on 0° and 8° slopes, with and without mitigation"},
        {"id": "search-SF-01", "layer": "1 · search", "cases": search["monte_carlo"]["n"],
         "outcomes": Counter(search["monte_carlo"]["by_outcome"]),
         "hazards": sorted({e["hazard"] for e in search["edge_cases"] if e.get("hazard")}), "agree": None,
         "file": "results/search-SF-01.md",
         "what": f"failure search, {len(search['edge_cases'])} edge cases, {len(search['findings'])} findings"},
        {"id": "l2-crosscheck", "layer": "1 vs 2", "cases": len(cross["rows"]),
         "outcomes": Counter("agree" if r["agree"] else "differ" for r in cross["rows"]), "hazards": [],
         "agree": (sum(1 for r in cross["rows"] if r["agree"]), len(cross["rows"])),
         "file": "results/l2-crosscheck.md",
         "what": f"level 1 against MuJoCo {cross['mujoco']}, {len(cross['unexplained'])} unexplained"},
        {"id": "sizing-cf4", "layer": "2 · sizing", "cases": size["grid_cases"] + size["corner_cases"],
         "outcomes": Counter({"failures at proposal": size["proposal"]["failures"]}), "hazards": [size["hazard"]],
         "agree": None, "file": "results/sizing-cf4.md",
         "what": f"ankle {size['proposal']['ankle_torque_max_nm']} N m, knee {size['proposal']['knee_torque_max_nm']} "
                 "N m proposed (preliminary)"},
        {"id": "ts001-fault-response", "layer": "1 + 2 · trade", "cases": trade["cases"] * len(trade["rows"]),
         "outcomes": Counter(), "hazards": [],
         "agree": (sum(r["agree"] for r in trade["rows"]), trade["cases"] * len(trade["rows"])),
         "file": "results/ts001-fault-response.md", "what": f"{trade['trade']} supply-loss response per alternative"},
    ]
    for sid, r in uav.items():
        s = next((x for x in scen if x["id"] == sid), {})
        rows.append({"id": sid, "layer": "PX4 SITL", "cases": 1, "outcomes": Counter([r["outcome"]]),
                     "hazards": s.get("hazards", []), "agree": None, "file": "results/uav/summary.md",
                     "what": s.get("title", "")})
    touched = sorted({h for r in rows for h in r["hazards"]})
    named: dict[str, list[str]] = {}
    for h in touched:
        for e in hazards.get(h, {}).get("subsystems") or []:
            named.setdefault(e, []).append(h)
    return {"ctx": ctx, "hazards": hazards, "faults": faults, "fams": fams, "scen": scen, "search": search,
            "rows": rows, "touched": touched, "named": named, "uav": uav}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


# ================================================================ figure 1 · result sets (drawn directly)
def fig_results(d: dict) -> str:
    rows = d["rows"]
    W, M = 1120, 40
    head, y0 = fk.header(
        W, "1", "Simulation result sets",
        f"{plural(len(rows), 'committed result set')} across level 1 (reduced-order plant), level 2 (MuJoCo) and PX4 "
        f"SITL, touching {plural(len(d['touched']), 'hazard')}. All synthetic: none is verification evidence.",
        "sim/results/")
    out = list(head)
    cx = {"id": M, "layer": M + 170, "what": M + 270, "cases": M + 600, "out": M + 660, "hz": M + 900}
    y = y0 + 30
    for k, lab in (("id", "Result set"), ("layer", "Layer"), ("what", "What it runs"), ("cases", "Cases"),
                   ("out", "Outcomes"), ("hz", "Hazards")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 36
    for n, r in enumerate(rows):
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["id"], cy, r["id"], size=10.5, fill=INK, weight=700, mono=True))
        lt = TONES["software" if "SITL" in r["layer"] else "system"]
        p, _ = fk.pill(cx["layer"], cy - 12, r["layer"], lt[1], color=lt[0], stroke=lt[0])
        out += p
        lines = fk.wrap(r["what"], 320, 10.5, max_lines=2)
        for j, ln in enumerate(lines):
            out.append(fk.text(cx["what"], cy + (-6 + 13 * j if len(lines) > 1 else 0), ln, size=10.5, fill=INK))
        out.append(fk.text(cx["cases"] + 24, cy, f"{r['cases']:,}", size=10.5, fill=INK, weight=700,
                           anchor="end"))
        x = cx["out"]
        if r["agree"]:
            a, t = r["agree"]
            tt = TONES["ok" if a == t else "amber"]
            p, w = fk.pill(x, cy - 12, f"agree {a}/{t}", tt[1], color=tt[0], stroke=tt[0])
            out += p
        else:
            for k, v in sorted(r["outcomes"].items(), key=lambda kv: (tone_of(kv[0]) != "red", kv[0])):
                tt = TONES["ok" if k == "failures at proposal" and v == 0 else tone_of(k)]
                lab = f"{k} {v}" if r["cases"] > 1 else k
                w = fk.pill_w(lab)
                if x + w > cx["hz"] - 8:
                    break
                p, w = fk.pill(x, cy - 12, lab, tt[1], color=tt[0], stroke=tt[0])
                out += p
                x += w + 4
        hz = r["hazards"]
        out.append(fk.text(cx["hz"], cy, (", ".join(hz) if len(hz) <= 2 else f"{hz[0]}, {hz[1]} +{len(hz) - 2}")
                           or "–", size=10, fill=INK if hz else FAINT))
    y += len(rows) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["ok"][1], TONES["ok"][0], "Safe outcome / agreement"),
           (TONES["amber"][1], TONES["amber"][0], "Tip, stale home or partial agreement"),
           (TONES["red"][1], TONES["red"][0], "Hard drop or keep-out breach"),
           (TONES["system"][1], TONES["system"][0], "Walker levels 1–2"),
           (TONES["software"][1], TONES["software"][0], "PX4 SITL")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Simulation result sets",
                  "Every committed result set with its cases, outcomes and hazards", out)


# ================================================================ ELK figures
def fig_trace(d: dict) -> dict:
    hz = d["hazards"]
    nodes = [{"id": "SRC", "banner": "Simulated · faults, search, UAV scenarios", "tone": "work"},
             {"id": "HZ", "banner": "Hazards exercised · safety/hazards", "tone": "work"}]
    edges = []
    for f in d["faults"]:
        nodes.append({"id": mid(f["id"]), "parent": "SRC", "code": f["id"], "title": f["name"],
                      "sub": f"plant variant: {f.get('variant', 'any')}", "tone": "system", "maxw": 230,
                      "legend": "Walker fault (levels 1–2)"})
        by_h: dict[str, list[str]] = {}
        for c in f.get("causes", []):
            h, cf = c.split(":")
            by_h.setdefault(h, []).append(cf)
        for h, cfs in by_h.items():
            edges.append({"src": mid(f["id"]), "dst": "h_" + mid(h), "label": ", ".join(cfs)})
    fam = d["search"]["family"]
    nodes.append({"id": mid(fam["id"]), "parent": "SRC", "code": fam["id"], "title": fam.get("title", "Search family"),
                  "sub": f"{len(d['search']['edge_cases'])} edge cases", "tone": "system", "maxw": 230,
                  "legend": "Walker fault (levels 1–2)"})
    for h in sorted({e["hazard"] for e in d["search"]["edge_cases"] if e.get("hazard")}):
        k = sum(1 for e in d["search"]["edge_cases"] if e.get("hazard") == h)
        edges.append({"src": mid(fam["id"]), "dst": "h_" + mid(h), "label": plural(k, "edge case")})
    for s in d["scen"]:
        out = d["uav"].get(s["id"], {}).get("outcome", "")
        nodes.append({"id": mid(s["id"]), "parent": "SRC", "code": s["id"], "title": s["title"],
                      "sub": f"outcome: {out}", "tone": "software", "maxw": 230, "legend": "UAV scenario (PX4 SITL)"})
        for h in s.get("hazards", []):
            edges.append({"src": mid(s["id"]), "dst": "h_" + mid(h), "label": ""})
    for h in d["touched"]:
        lvl = (hz.get(h, {}).get("initial_risk") or {}).get("risk_level", "")
        nodes.append({"id": "h_" + mid(h), "parent": "HZ", "code": h, "title": hz.get(h, {}).get("title", h),
                      "sub": f"initial {lvl} (preliminary)", "tone": LEVEL_TONE.get(lvl, "amber"), "maxw": 230,
                      "legend": f"Hazard, {lvl} initial risk"})
    return {"file": "fig-2-hazard-trace.svg", "number": "2", "title": "What is simulated, traced to the hazards",
            "subtitle": "Each fault realises named hazard causal factors (CFn); the search family and UAV scenarios "
                        "name the hazards they exercise. Hazards no simulation touches are not shown.",
            "ref": "sim/faults.yaml · sim/uav/scenarios.yaml", "direction": "RIGHT", "orient": "fixed",
            "nodes": nodes, "edges": edges, "legend": [edge_leg("Traces to (causal factors)")]}


def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    scope = sorted(d["named"])
    block = fig_block(ctx, {"scope": scope})
    for n in block["nodes"]:
        if n.get("code") in d["named"]:
            n["sub"] = ", ".join(d["named"][n["code"]])
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"SUS-I1 decomposition. The {len(scope)} elements that carry a simulated hazard are "
                          "coloured, with those hazards under each; the models are concept assumptions, not designs.")
    boundary = fig_boundary(ctx, {"path": "sim", "boundary": {
        "name": "Simulation track",
        "inside": ["Specs and faults", "Level 1 and level 2 models", "PX4 SITL harness", "Committed results"],
        "outside": ["Hazard records", "Trade studies and decisions", "Named human review", "Wiki and 3D pages",
                    "Verification records"],
        "flows": [["Hazard records", "Specs and faults", "causal factors to realise"],
                  ["Specs and faults", "Level 1 and level 2 models", "parameters, faults"],
                  ["Level 1 and level 2 models", "Committed results", "seeded runs"],
                  ["PX4 SITL harness", "Committed results", "failsafe runs"],
                  ["@boundary", "Trade studies and decisions", "evidence for a choice"],
                  ["@boundary", "Wiki and 3D pages", "scenes"],
                  ["@boundary", "Named human review", "findings, fidelity cases"],
                  ["Named human review", "Verification records", "only after the gate"]]}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="sim/README.md",
                    subtitle="The track owns its specs, models, harness and committed results. Results reach "
                             "verification only through a reviewed fidelity case. Crossings are numbered as in the table.")
    frag, body = view_stm(GATE)
    for n in frag["nodes"]:
        if n.get("shape") == "state":
            k = len(d["rows"]) if n["id"] == "Synthetic" else 0
            n["sub"] = (n.get("sub", "") + f" · {k} result sets now").lstrip(" ·")
    stm = {**frag, "file": "fig-5-sysml-state-machine.svg", "number": "5",
           "title": "SysML state machine — EvidenceGate", "ref": "sim/SimulationEvidence.sysml",
           "subtitle": "When a simulation result may count as evidence, from the evidence gate below, with how many "
                       "result sets are in each state now. No fidelity case has been approved."}
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "sim/README.md", "direction": "RIGHT",
          "subtitle": "What the simulation track consumes (left) and what reads its results (right).",
          "nodes": [
              {"id": "I1", "title": "Hazard records", "sub": "causal factors", "tone": "work"},
              {"id": "I2", "title": "CONOPS and item definition", "sub": "modes, elements", "tone": "work"},
              {"id": "I3", "title": "PX4 v1.16.2", "sub": "upstream autopilot", "tone": "external"},
              {"id": "I4", "title": "Decision register", "sub": "slope, CoM, torques", "tone": "work"},
              {"id": "X", "code": "sim/", "title": "Simulation track", "tone": "current"},
              {"id": "O1", "title": "Trade studies", "sub": "TS-001 evidence", "tone": "work"},
              {"id": "O2", "title": "Requirements", "sub": "SYS-016 draft sizing", "tone": "work"},
              {"id": "O3", "title": "Simulation wiki pages", "sub": "2D and 3D scenes", "tone": "work"},
              {"id": "O4", "title": "Safety lead", "sub": "findings for review", "tone": "safety",
               "legend": "Human review"}],
          "edges": [{"src": "I1", "dst": "X", "label": "faults to realise"},
                    {"src": "I2", "dst": "X", "label": "modes, elements"},
                    {"src": "I3", "dst": "X", "label": "SITL"},
                    {"src": "I4", "dst": "X", "label": "parameters"},
                    {"src": "X", "dst": "O1", "label": "evidence (synthetic)"},
                    {"src": "X", "dst": "O2", "label": "draft values"},
                    {"src": "X", "dst": "O3", "label": "scenes"},
                    {"src": "X", "dst": "O4", "label": "findings"}]}
    specs = [fig_trace(d), block, boundary, stm, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    sysml = "\n".join([
        f"// SimulationEvidence — generated by {GEN} from the evidence gate in sim/README.md.",
        "// Do not edit by hand: change the generator and regenerate.",
        "// Status: when a simulation result may count as evidence; not evidence itself.", "",
        "package SimulationEvidence {",
        "    doc /* Evidence gate for simulation results (sim/README.md; rule R13 for the fidelity case). */",
        body, "}", ""])
    return specs, sysml


