def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    block = fig_block(ctx, {"scope": d["subs"]})
    by = defaultdict(list)
    for h in d["hz"]:
        for s in d["hazards"].get(h, {}).get("subsystems") or []:
            by[s].append(h)
    for n in block["nodes"]:
        if n.get("code") in by:
            n["sub"] = ", ".join(by[n["code"]])
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"SUS-I1 decomposition. The {len(d['subs'])} subsystems named by the hazards the scenes show "
                          "are coloured, with those hazards under each.")
    boundary = fig_boundary(ctx, {"path": "sim/figures", "boundary": {
        "name": "2D scene code", "inside": ["Side-view scenes", "Top-down scenes"],
        "outside": ["Walker plant", "Failure search results", "PX4 SITL results", "Wiki images and pages", "UAV summary",
                    "CI"],
        "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="sim/figures/README.md",
                    subtitle="The folder owns the two scene generators; the runs they draw and the images they write "
                             "live elsewhere. Crossings are numbered as in the table.")
    sysml_spec, sysml = fig_sysml(d)
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "sim/figures/README.md", "direction": "RIGHT",
          "subtitle": "What the scene code consumes (left) and what it writes (right).",
          "nodes": [
              {"id": "I1", "title": "Walker plant", "sub": "sim/plant", "tone": "software"},
              {"id": "I2", "title": "Search edge cases", "sub": "sim/results/search-*.json", "tone": "work"},
              {"id": "I3", "title": "PX4 SITL runs", "sub": "sim/results/uav", "tone": "work"},
              {"id": "X", "code": "sim/figures/", "title": "2D scene code", "tone": "current"},
              {"id": "O1", "title": "Scene images", "sub": "docs/wiki/images/sim-*.svg", "tone": "work"},
              {"id": "O2", "title": "Wiki pages", "sub": "Simulation, UAV-Simulation", "tone": "work"},
              {"id": "O3", "title": "UAV summary", "sub": "sim/results/uav/summary.md", "tone": "work"}],
          "edges": [{"src": "I1", "dst": "X", "label": "runs"}, {"src": "I2", "dst": "X", "label": "edge cases"},
                    {"src": "I3", "dst": "X", "label": "SITL runs"},
                    {"src": "X", "dst": "O1", "label": "images"}, {"src": "X", "dst": "O2", "label": "pages"},
                    {"src": "X", "dst": "O3", "label": "summary"}]}
    specs = [fig_outputs(d), block, boundary, sysml_spec, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    return specs, sysml


