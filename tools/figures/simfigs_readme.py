GOOD = {"safe", "landed-clear", "contained"}


def out_tone(o: str) -> str:
    return "ok" if o in GOOD else ("amber" if o == "landed-at-stale-home" else "red")


# ================================================================ records
def outputs_of(path: Path) -> list[str]:
    text = path.read_text()
    found = re.findall(r'outs\[f?"([^"]+)"\]', text) + re.findall(r'outs = \{f?"([^"]+)"\s*:', text)
    return sorted(set(found))


def load() -> dict:
    ctx, _, hazards = load_reqs()
    p = plant_spec.load()
    rows = []
    for sc in walker_scenes.SCENES:
        perf, intd = walker_scenes.cases(sc)
        rp, ri = walker.simulate(perf, p), (walker.simulate(intd, p) if intd else None)
        rows.append({"id": sc["id"], "kind": "side view (walker)", "hazards": [sc["hazard"]], "title": sc["title"],
                     "source": sc["source"], "performed": rp["outcome"], "intended": ri["outcome"] if ri else "—",
                     "image": f"docs/wiki/images/sim-{sc['id'].lower()}.svg"})
    for f in sorted((ROOT / "sim" / "results" / "uav").glob("SU-*.json")):
        r = json.loads(f.read_text())
        s = r["scenario"]
        rows.append({"id": s["id"], "kind": "top down (UAV)", "hazards": s.get("hazards", []), "title": s["title"],
                     "source": f"PX4 SITL run {s['id']}", "performed": r["outcome"], "intended": "contract: "
                     + s.get("contract", "")[:60], "image": f"docs/wiki/images/sim-{s['id'].lower()}.svg"})
    for r in rows:
        r["exists"] = (ROOT / r["image"]).exists()
    doc = (FOLDER / "scenes.py").read_text().split('"""')[1]
    conventions = [" ".join(m.group(1).split()) for m in re.finditer(r"^\s+- (.*?)(?=^\s+- |^\S|\Z)", doc, re.M | re.S)]
    gens = {"sim/figures/scenes.py": outputs_of(FOLDER / "scenes.py"),
            "sim/figures/uav_scenes.py": outputs_of(FOLDER / "uav_scenes.py")}
    hz = sorted({h for r in rows for h in r["hazards"]})
    subs = sorted({x for h in hz for x in hazards.get(h, {}).get("subsystems") or []})
    own = sorted(p.name for p in FOLDER.glob("*.svg"))
    return {"ctx": ctx, "hazards": hazards, "rows": rows, "conventions": conventions, "gens": gens, "hz": hz,
            "subs": subs, "own": own}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


# ================================================================ figure 1 · scenes (drawn directly)
def fig_scenes(d: dict) -> str:
    W, M = 1240, 40
    rows = d["rows"]
    nw = sum(1 for r in rows if r["kind"].startswith("side"))
    head, y0 = fk.header(
        W, "1", "The 2D hazard scenes",
        f"{plural(nw, 'side-view walker scene')} and {plural(len(rows) - nw, 'top-down UAV scene')}: the hazard each "
        "shows, the run it replays, and what happens against what should happen. Walker outcomes are re-run here from "
        "the plant model; UAV outcomes come from the committed SITL runs.", "sim/figures/scenes.py · uav_scenes.py")
    out = list(head)
    cx = {"id": M, "t": M + 80, "src": M + 520, "p": M + 760, "i": M + 920}
    y = y0 + 30
    for k, lab in (("id", "Scene"), ("t", "Title and hazards"), ("src", "Replays"), ("p", "What happens"),
                   ("i", "What should happen")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 46
    last = None
    for n, r in enumerate(rows):
        top = y + n * rh
        if last and last != r["kind"]:
            out.append(fk.line(M, top, W - M, top, stroke=HAIR, sw=1.2))
        last = r["kind"]
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["id"], cy - 6, r["id"], size=11, fill=INK, weight=700, mono=True))
        out.append(fk.text(cx["id"], cy + 9, r["kind"].split(" (")[0], size=9, fill=MUTED))
        out.append(fk.text(cx["t"], cy - 7, fk.wrap(r["title"], 420, 10.5, True, max_lines=1)[0], size=10.5, fill=INK,
                           weight=700))
        x = cx["t"]
        for h in r["hazards"]:
            lv = (d["hazards"].get(h, {}).get("initial_risk") or {}).get("risk_level", "")
            t = TONES[LEVEL_TONE.get(lv, "amber")]
            p, w = fk.pill(x, cy, h, t[1], color=t[0], stroke=t[0])
            out += p
            x += w + 4
        out.append(fk.text(cx["src"], cy, fk.wrap(r["source"], 230, 10, max_lines=1)[0], size=10, fill=INK))
        t = TONES[out_tone(r["performed"])]
        p, _ = fk.pill(cx["p"], cy - 12, r["performed"], t[1], color=t[0], stroke=t[0])
        out += p
        if r["kind"].startswith("side"):
            t = TONES[out_tone(r["intended"])]
            p, _ = fk.pill(cx["i"], cy - 12, r["intended"], t[1], color=t[0], stroke=t[0])
            out += p
        else:
            out.append(fk.text(cx["i"], cy, fk.wrap(r["intended"], W - M - cx["i"], 9.5, max_lines=1)[0], size=9.5,
                               fill=MUTED))
    y += len(rows) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["red"][1], TONES["red"][0], "Mishap or unsafe outcome (solid red in the scene)"),
           (TONES["amber"][1], TONES["amber"][0], "Needs review"),
           (TONES["ok"][1], TONES["ok"][0], "Safe (dashed green in the scene)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · The 2D hazard scenes", "Every 2D hazard scene with what happens and what should",
                  out)


# ================================================================ ELK figures and SysML
def fig_outputs(d: dict) -> dict:
    nodes = [{"id": "IN", "banner": "Inputs", "tone": "work"}, {"id": "G", "banner": "Scene code", "tone": "work"},
             {"id": "O", "banner": "Outputs", "tone": "work"}]
    edges = []
    ins = {"sim/figures/scenes.py": [("plant", "sim/plant/walker.py", "plant runs, re-run per scene"),
                                     ("search", "sim/results/search-*.json", "edge cases")],
           "sim/figures/uav_scenes.py": [("uav", "sim/results/uav/SU-*.json", "PX4 SITL runs"),
                                         ("uavspec", "sim/uav/scenarios.yaml, spec.yaml", "scenarios, geometry")]}
    seen = set()
    for g, outs in d["gens"].items():
        gid = "g_" + mid(g)
        nodes.append({"id": gid, "parent": "G", "code": g.replace("sim/figures/", ""), "title": "", "tone": "current"})
        for key, code, lab in ins[g]:
            if key not in seen:
                seen.add(key)
                nodes.append({"id": "i_" + key, "parent": "IN", "code": code, "title": lab, "tone": "software",
                              "maxw": 240, "legend": "Model or result"})
            edges.append({"src": "i_" + key, "dst": gid, "label": ""})
        groups = defaultdict(list)
        for o in outs:
            wild = "sc-*" if g.endswith("/scenes.py") else "su-*"
            groups[re.sub(r"\{[^}]*\}", wild, o)].append(o)
        for pat in groups:
            oid = "o_" + mid(pat)
            nodes.append({"id": oid, "parent": "O", "code": pat, "title": "", "tone": "system", "maxw": 260,
                          "legend": "Generated (checked in CI)"})
            edges.append({"src": gid, "dst": oid, "label": "", "dash": True})
    return {"file": "fig-2-outputs.svg", "number": "2", "title": "What the scene code reads and writes",
            "subtitle": "The two scene generators with the models and results they draw from and every file they "
                        "write (read from their outputs()). CI re-runs both with --check.",
            "ref": "sim/figures/scenes.py · uav_scenes.py", "direction": "RIGHT", "orient": "fixed", "nodes": nodes,
            "edges": edges, "legend": [edge_leg("Reads"), edge_leg("Writes", True)]}


def fig_sysml(d: dict) -> tuple[dict, str]:
    nodes = [{"id": "HazardScene", "shape": "class", "title": "HazardScene", "stereotype": "part def",
              "attrs": ["hazards : String", "replays : String", "performedOutcome : String"], "tone": "system"},
             {"id": "SideViewScene", "shape": "class", "title": "SideViewScene", "stereotype": "part def :> HazardScene",
              "attrs": ["intendedOutcome : String", "dashed green = intended", "solid red = performed",
                        "freezes at the first mishap"], "tone": "safety"},
             {"id": "TopDownScene", "shape": "class", "title": "TopDownScene", "stereotype": "part def :> HazardScene",
              "attrs": ["contract : String", "overview + dock zoom"], "tone": "interface"}]
    edges = [{"src": "SideViewScene", "dst": "HazardScene", "label": "specializes", "dash": True},
             {"src": "TopDownScene", "dst": "HazardScene", "label": "specializes", "dash": True}]
    s = ["    part def HazardScene {",
         "        doc /* An animated 2D scene of a synthetic run that shows a hazard. */",
         "        attribute hazards : String;", "        attribute replays : String;",
         "        attribute performedOutcome : String;", "    }",
         "    part def SideViewScene :> HazardScene {",
         "        doc /* Walker side view: the intended run dashed green, the performed run solid red; freezes at the "
         "first mishap. */",
         "        attribute intendedOutcome : String;", "    }",
         "    part def TopDownScene :> HazardScene {",
         "        doc /* UAV top-down view: overview of fence, walker and path, with a zoom on the dock. */",
         "        attribute contract : String;", "    }"]
    for r in d["rows"]:
        side = r["kind"].startswith("side")
        pn = r["id"].replace("-", "").lower()
        s += [f"    part {pn} : {'SideViewScene' if side else 'TopDownScene'} {{", f"        doc /* {r['id']}: {r['title']} */",
              f"        attribute :>> hazards = \"{', '.join(r['hazards'])}\";",
              f"        attribute :>> replays = \"{r['source']}\";",
              f"        attribute :>> performedOutcome = \"{r['performed']}\";",
              (f"        attribute :>> intendedOutcome = \"{r['intended']}\";" if side else
               f"        attribute :>> contract = \"{r['intended'].replace('contract: ', '')}\";"), "    }"]
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — HazardScenes", "ref": "sim/figures/HazardScenes.sysml",
            "subtitle": f"The two kinds of 2D hazard scene and their conventions; HazardScenes.sysml also holds all "
                        f"{len(d['rows'])} scenes as parts.",
            "frame": {"kind": "bdd", "type": "package", "name": "HazardScenes"}, "direction": "DOWN",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Specializes", True), ("#EEF2FF", "#4F46E5", "Scene"),
                       ("#FFF7ED", "#C2410C", "Walker side view"), ("#F5F3FF", "#7C3AED", "UAV top-down view")]}
    sysml = "\n".join([
        f"// HazardScenes — generated by {GEN} from sim/figures/scenes.py and the committed SITL results.",
        "// Do not edit by hand: change the scenes or the generator and regenerate.",
        "// Status: pictures of synthetic simulation output; no evidence credit.", "",
        "package HazardScenes {",
        "    private import ScalarValues::*;",
        "    doc /* The 2D hazard scenes (sim/figures/README.md). */",
        *s, "}", ""])
    return spec, sysml


