#!/usr/bin/env python3
"""Build sim/figures/README.md, sim/figures/readme/*.svg and sim/figures/HazardScenes.sysml: the 2D hazard scenes.

sim/figures is the code that draws the animated 2D hazard scenes and the UAV scene pages, and also holds the
simulation page's own figures (sim/figures/*.svg, written by tools/figures/sim_readme.py). This page's figures sit
in readme/. Everything on the page is read from the scene code and the results it draws:

  sim/figures/scenes.py             SCENES: the side-view walker scenes, their hazard and the runs they replay;
                                    the scene conventions (module docstring)
  sim/figures/uav_scenes.py         the top-down UAV scenes and what they write
  sim/plant/walker.py               the performed and intended run of every walker scene, re-run here (deterministic)
  sim/results/uav/SU-*.json         the committed PX4 SITL runs the UAV scenes draw
  safety/hazards                    the hazards the scenes show

Figures (house style of framework/documentation-standard.md):

  fig-1-scenes.svg               every scene: hazard, what it replays, what happens and what should happen
  fig-2-outputs.svg              inputs → the two scene generators → the images and pages they write
  fig-3-block-diagram.svg        SUS-I1 decomposition; the subsystems of the hazards shown are coloured
  fig-4-boundary-diagram.svg     what the scene code owns and what crosses its boundary
  fig-5-sysml-block-definition.svg  HazardScenes (generated .sysml): side-view and top-down scenes
  fig-6-inputs-and-outputs.svg   what the scene code consumes and what it writes

    python3 tools/figures/simfigs_readme.py            # write
    python3 tools/figures/simfigs_readme.py --check    # fail if anything is stale
"""
