# ================================================================ records
def load() -> dict:
    ctx, _, hazards = load_reqs()
    sc = yaml.safe_load((FOLDER / "scenarios.yaml").read_text())
    spec = {k: v["value"] for k, v in yaml.safe_load((FOLDER / "spec.yaml").read_text())["params"].items()}
    runs = {p.stem: json.loads(p.read_text()) for p in sorted(RES.glob("SU-*.json"))}
    tag = re.search(r'TAG="([^"]+)"', (FOLDER / "fetch_px4.sh").read_text()).group(1)
    item = yaml.safe_load((ROOT / "architecture" / "item-definition.yaml").read_text())
    ifs = {i["id"]: i for i in item["interfaces"]}
    findings = []
    for s in sc["scenarios"]:
        r = runs.get(s["id"], {})
        rule = next((x for x in sc["outcome_rules"] if x["outcome"] == r.get("outcome")), None)
        if rule and rule.get("finding"):
            findings.append({"id": s["id"], "kind": r.get("outcome"), "hazard": rule["hazard"], "text": rule["finding"]})
        for mr in sc.get("metric_rules", []):
            v = r.get(mr["metric"])
            if v is not None and v > mr["above"]:
                findings.append({"id": s["id"], "kind": f"{mr['metric']} {v:g}", "hazard": mr["hazard"],
                                 "text": mr["finding"]})
    text = json.dumps(sc)
    if_ids = set()
    for m in IFX.finditer(text):
        if_ids.add(f"IF-PX4-{m.group(1)}")
        if_ids |= {f"IF-PX4-{x}" for x in m.group(2).split("/") if x}
    hz = sorted({h for s in sc["scenarios"] for h in s.get("hazards", [])})
    elements = sorted({e for i in if_ids if i in ifs for e in (ifs[i]["from"], ifs[i]["to"])}
                      | {e for h in hz for e in hazards.get(h, {}).get("subsystems") or []})
    trans: dict[tuple[str, str], list[str]] = defaultdict(list)
    first = None
    for sid, r in runs.items():
        modes = [m[1] for m in r.get("mode_changes") or []]
        first = first or (modes[0] if modes else None)
        for a, b in zip(modes, modes[1:]):
            trans[(a, b)].append(sid)
    return {"ctx": ctx, "hazards": hazards, "sc": sc["scenarios"], "spec": spec, "runs": runs, "tag": tag,
            "findings": findings, "if_ids": sorted(if_ids), "ifs": ifs, "hz": hz, "elements": elements,
            "trans": dict(trans), "first_mode": first}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def params_str(s: dict) -> str:
    p = dict(s.get("params") or {})
    p.update((s.get("inject") or {}).get("set_params") or {})
    return ", ".join(f"{k}={v}" for k, v in p.items()) or "defaults"


def inject_str(s: dict) -> str:
    inj = s.get("inject") or {}
    if "link_loss_at_s" in inj:
        return f"link loss at {inj['link_loss_at_s']} s"
    if "failure" in inj:
        return f"{inj['failure']['unit']} {inj['failure']['type']} at {inj.get('at_s')} s"
    if "reposition_beyond_fence_at_s" in inj:
        return f"reposition beyond fence at {inj['reposition_beyond_fence_at_s']} s"
    if "set_params" in inj:
        return f"parameter change at {inj.get('at_s')} s"
    return "—"


def m(v, unit="m") -> str:
    return "—" if v is None else f"{v:,.1f} {unit}"


# ================================================================ figure 1 · scenarios (drawn directly)
def fig_scenarios(d: dict) -> str:
    W, M = 1240, 40
    ko = d["spec"]["pilot_keepout_m"]
    head, y0 = fk.header(
        W, "1", "PX4 SITL failsafe scenarios",
        f"The {len(d['sc'])} scenarios run on PX4 {d['tag']} (SIH quadrotor): what each sets and injects, the outcome "
        f"class the harness scored, and the closest approach to the pilot below the keep-out altitude (keep-out "
        f"{ko:g} m). Synthetic findings for the safety lead, not verification evidence.", "sim/uav/scenarios.yaml")
    out = list(head)
    cx = {"id": M, "t": M + 70, "p": M + 430, "o": M + 700, "d": M + 880, "e": M + 990, "h": M + 1090}
    y = y0 + 30
    for k, lab in (("id", "Run"), ("t", "Scenario / injection"), ("p", "PX4 parameters set"), ("o", "Outcome"),
                   ("d", "To pilot (low)"), ("e", "Nav error"), ("h", "Hazards")):
        out.append(fk.text(cx[k], y, lab, size=10.5, fill=MUTED, weight=700))
    y += 12
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    rh = 46
    for n, s in enumerate(d["sc"]):
        r = d["runs"].get(s["id"], {})
        top = y + n * rh
        if n % 2:
            out.append(fk.rect(M, top + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=6, sw=0))
        cy = top + rh / 2 + 4
        out.append(fk.text(cx["id"], cy, s["id"], size=11, fill=INK, weight=700, mono=True))
        out.append(fk.text(cx["t"], cy - 7, fk.wrap(s["title"], 350, 11, True, max_lines=1)[0], size=11, fill=INK,
                           weight=700))
        out.append(fk.text(cx["t"], cy + 9, inject_str(s) + (" · walker moved" if s.get("walker_moved") else ""),
                           size=9.5, fill=MUTED))
        out.append(fk.text(cx["p"], cy, fk.wrap(params_str(s), 260, 9.5, mono=True, max_lines=1)[0], size=9.5,
                           fill=INK, mono=True))
        oc = r.get("outcome", "not run")
        t = TONES[tone_of(oc)]
        p, _ = fk.pill(cx["o"], cy - 12, oc, t[1], color=t[0], stroke=t[0])
        out += p
        low = r.get("min_pilot_distance_low_m")
        bad = low is not None and low < ko
        out.append(fk.text(cx["d"], cy, m(low), size=10.5, fill=TONES["red"][0] if bad else INK,
                           weight=700 if bad else ""))
        err = r.get("max_estimate_error_m")
        out.append(fk.text(cx["e"], cy, m(err), size=10.5, fill=TONES["red"][0] if err and err > 10 else INK,
                           weight=700 if err and err > 10 else ""))
        x = cx["h"]
        for h in s.get("hazards", []):
            lv = (d["hazards"].get(h, {}).get("initial_risk") or {}).get("risk_level", "")
            ht = TONES[LEVEL_TONE.get(lv, "amber")]
            hp, w = fk.pill(x, cy - 20 + 18 * s["hazards"].index(h), h, ht[1], color=ht[0], stroke=ht[0])
            out += hp
    y += len(d["sc"]) * rh + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES["ok"][1], TONES["ok"][0], "Outcome clear"), (TONES["amber"][1], TONES["amber"][0], "Needs review"),
           (TONES["red"][1], TONES["red"][0], "Unsafe outcome, or a value past its rule (red figure)")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER + " To pilot (low): closest approach below the keep-out altitude; nav error: largest "
                      "error of PX4's reported position.", W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · PX4 SITL failsafe scenarios",
                  "Every SITL scenario with its outcome and closest approach to the pilot", out)


# ================================================================ figure 2 · flight paths (drawn directly)
def fig_paths(d: dict) -> str:
    W, M = 1240, 40
    sp = d["spec"]
    head, y0 = fk.header(
        W, "2", "Ground tracks of the runs",
        "Plan view of each run from the committed trace (north up, metres from the take-off point), with the dock, "
        f"the pilot station and its {sp['pilot_keepout_m']:g} m keep-out, and the {sp['geofence_radius_m']:g} m "
        "geofence. Grey before the injection, coloured after; the cross is where the run ended.",
        "sim/results/uav/SU-*.json")
    out = list(head)
    cols, gap = 3, 24
    pw = (W - 2 * M - gap * (cols - 1)) / cols
    ph = pw * 0.82
    R = sp["geofence_radius_m"] + 8
    for k, s in enumerate(d["sc"]):
        r = d["runs"].get(s["id"], {})
        px, py = M + (k % cols) * (pw + gap), y0 + 24 + (k // cols) * (ph + gap + 30)
        oc = r.get("outcome", "not run")
        t = TONES[tone_of(oc)]
        out.append(fk.rect(px, py, pw, ph + 30, fill="#FFFFFF", stroke=HAIR, rx=8, sw=1))
        out.append(fk.text(px + 12, py + 20, s["id"], size=11.5, fill=INK, weight=700, mono=True))
        p, _ = fk.pill(px + 60, py + 8, oc, t[1], color=t[0], stroke=t[0])
        out += p
        cxp, cyp, sc = px + pw / 2, py + 30 + ph / 2, (min(pw, ph) / 2 - 12) / R
        to = lambda n, e: (cxp + e * sc, cyp - n * sc)  # noqa: E731  north up, east right
        gx, gy = to(0, 0)
        out.append(f'<circle cx="{gx:.1f}" cy="{gy:.1f}" r="{sp["geofence_radius_m"] * sc:.1f}" fill="none" '
                   f'stroke="{TONES["external"][0]}" stroke-width="1" stroke-dasharray="4 3"/>')
        pilot, dock = r.get("pilot_m") or [sp["pilot_station_n_m"], 0], r.get("dock_m") or [0, 0]
        kx, ky = to(*pilot)
        out.append(f'<circle cx="{kx:.1f}" cy="{ky:.1f}" r="{max(sp["pilot_keepout_m"] * sc, 3):.1f}" '
                   f'fill="{TONES["red"][1]}" stroke="{TONES["red"][0]}" stroke-width="1"/>')
        dx, dy = to(*dock)
        out.append(f'<rect x="{dx - 3:.1f}" y="{dy - 3:.1f}" width="6" height="6" fill="{INK}"/>')
        if s.get("walker_moved"):
            hx, hy = to(0, 0)
            out.append(f'<rect x="{hx - 3:.1f}" y="{hy - 3:.1f}" width="6" height="6" fill="none" stroke="{INK}"/>')
        inj = s.get("inject") or {}
        t0 = next((inj[k] for k in ("link_loss_at_s", "reposition_beyond_fence_at_s", "at_s") if k in inj), 0)
        pre = [to(p_[1], p_[2]) for p_ in r.get("trace") or [] if p_[0] <= t0]
        post = [to(p_[1], p_[2]) for p_ in r.get("trace") or [] if p_[0] >= t0]
        for pts, col, w in ((pre, FAINT, 1.2), (post, t[0], 2)):
            if len(pts) > 1:
                out.append('<polyline fill="none" stroke="{}" stroke-width="{}" points="{}"/>'.format(
                    col, w, " ".join(f"{a:.1f},{b:.1f}" for a, b in pts)))
        if post:
            ex, ey = post[-1]
            out.append(f'<path d="M{ex - 4:.1f},{ey - 4:.1f}L{ex + 4:.1f},{ey + 4:.1f}M{ex - 4:.1f},{ey + 4:.1f}'
                       f'L{ex + 4:.1f},{ey - 4:.1f}" stroke="{t[0]}" stroke-width="2"/>')
        out.append(fk.text(px + 12, py + ph + 22, fk.wrap(s["title"], pw - 24, 9.5, max_lines=1)[0], size=9.5,
                           fill=MUTED))
    rows = math.ceil(len(d["sc"]) / cols)
    y = y0 + 24 + rows * (ph + gap + 30)
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(INK, INK, "Dock (hollow: take-off point when the walker moved)"),
           (TONES["red"][1], TONES["red"][0], "Pilot station keep-out"),
           ("#FFFFFF", TONES["external"][0], "Geofence"), ("#FFFFFF", FAINT, "Before the injection")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Ground tracks of the runs", "Plan view of every SITL run", out)


