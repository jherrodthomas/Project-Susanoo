def mode_name(mode: str) -> str:
    return "".join(w.capitalize() for w in re.split(r"[._]", mode))


def modes_view(d: dict) -> dict:
    states = sorted({mode for pair in d["trans"] for mode in pair} | ({d["first_mode"]} if d["first_mode"] else set()))
    return {"name": "Px4FailsafeModes", "initial": mode_name(d["first_mode"]),
            "doc": "PX4 flight modes and the changes between them seen in the committed SITL runs after the injection.",
            "states": [{"name": mode_name(s), "doc": s} for s in states],
            "transitions": [[mode_name(a), mode_name(b), "seen in " + " ".join(runs)]
                            for (a, b), runs in sorted(d["trans"].items())],
            "final": []}


