def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    scope = [e for e in d["elements"] if e in ctx.nodes]
    block = fig_block(ctx, {"scope": scope})
    hz_by = defaultdict(list)
    for h in d["hz"]:
        for e in d["hazards"].get(h, {}).get("subsystems") or []:
            hz_by[e].append(h)
    for i in d["if_ids"]:
        for e in (d["ifs"][i]["from"], d["ifs"][i]["to"]):
            hz_by[e].append(i)
    for n in block["nodes"]:
        if n.get("code") in hz_by:
            n["sub"] = ", ".join(dict.fromkeys(hz_by[n["code"]]))
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"SUS-I1 decomposition. The {len(scope)} elements the scenarios exercise are coloured: those "
                          "named by their hazards and at the ends of the PX4 interfaces their contracts cite.")
    boundary = fig_boundary(ctx, {"path": "sim/uav", "boundary": {
        "name": "UAV SITL harness", "inside": ["Scenarios and spec", "Harness", "PX4 SITL"],
        "outside": ["PX4 upstream", "Hazard records", "Committed results", "Simulation figures and pages",
                    "Safety lead", "CI"],
        "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="sim/uav/README.md",
                    subtitle="The harness plays the ground station against a local PX4 SITL build. It does not "
                             "implement the integration manager. Crossings are numbered as in the table.")
