    args = ap.parse_args()
    d = load()
    specs, sysml = figure_specs(d)
    files = {SYSML: sysml, FIGS / "fig-1-palette.svg": fig_palette(d), FIGS / "fig-2-look-matrix.svg": fig_matrix(d)}
