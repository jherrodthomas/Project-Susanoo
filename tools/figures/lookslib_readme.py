# ================================================================ records
def load() -> dict:
    ctx, _, hazards = load_reqs()
    envs = yaml.safe_load((FOLDER / "environments.yaml").read_text())["environments"]
    conds = yaml.safe_load((FOLDER / "conditions.yaml").read_text())["conditions"]
    cfg = yaml.safe_load(SCENES.read_text())
    uses = defaultdict(list)
    hz = set()
    for s in cfg["scenes"]:
        hz |= set(s["hazards"])
        for vid, look in [(s["id"], s["look"])] + [(v["id"], {**s["look"], **v["look"]}) for v in s.get("variants") or []]:
            uses[(look["environment"], look["condition"])].append(vid)
    vj = VIEWER.read_text()
    read = {"environment": set(re.findall(r"L\.environment\.(\w+)", vj)),
            "condition": set(re.findall(r"L\.condition\.(\w+)", vj))}
    exp = EXPORT.read_text()
    export_reads = any(w in exp for w in ("library", "environments.yaml", "conditions.yaml"))
    subs = sorted({x for h in hz for x in hazards.get(h, {}).get("subsystems") or []})
    return {"ctx": ctx, "envs": envs, "conds": conds, "uses": dict(uses), "read": read, "export_reads": export_reads,
            "hz": sorted(hz), "subs": subs}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def hexrgb(h: str) -> tuple[float, float, float]:
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def rgbhex(c) -> str:
    return "#" + "".join(f"{max(0, min(255, round(v * 255))):02x}" for v in c)


def lit(col: str, cond: dict) -> str:
    """The ground as the viewer lights it, roughly: hemisphere ambient plus a sun at 1.6 times its value."""
    k = min(1.25, 0.55 * cond["ambient"] + 0.45 * 1.6 * cond["sun"])
    return rgbhex([v * k for v in hexrgb(col)])


def mix(a: str, b: str, t: float) -> str:
    return rgbhex([x * (1 - t) + y * t for x, y in zip(hexrgb(a), hexrgb(b))])


def unused(d: dict) -> list[str]:
    out = []
    for kind, table in (("environment", d["envs"]), ("condition", d["conds"])):
        keys = sorted({k for v in table.values() for k in v})
        out += [f"{kind}.{k}" for k in keys if k not in d["read"][kind]]
    return out


