# ================================================================ figure 2 · look matrix (drawn directly)
def fig_matrix(d: dict) -> str:
    W, M = 1240, 40
    envs, conds = d["envs"], d["conds"]
    used = sum(1 for k in d["uses"])
    head, y0 = fk.header(
        W, "2", "Every look the library can make",
        f"Each environment under each condition, lit roughly as viewer.js lights it: sky from the condition's tint or the "
        f"environment's sky, ground under ambient plus sun, fog fading to the sky. {used} of "
        f"{len(envs) * len(conds)} pairs are used, by the scenes named in them.", "sim/scenes3d/scenes.yaml · viewer.js")
    out = list(head)
    x0 = M + 110
    cw = (W - M - x0 - 12 * (len(conds) - 1)) / len(conds)
    ch = 110
    y = y0 + 26
    for j, cn in enumerate(conds):
        out.append(fk.text(x0 + j * (cw + 12) + cw / 2, y, cn, size=11.5, fill=INK, weight=700, anchor="middle"))
    y += 12
    for i, (en, e) in enumerate(envs.items()):
        yy = y + i * (ch + 14)
        out.append(fk.text(M, yy + ch / 2 + 4, en, size=11.5, fill=INK, weight=700))
        for j, (cn, c) in enumerate(conds.items()):
            x = x0 + j * (cw + 12)
            sky = c.get("sky_tint") or e["sky"]
            ground = lit(e["ground"], c)
            if c.get("fog_m"):
                ground = mix(ground, sky, min(0.75, 40 / c["fog_m"]))
            ids = d["uses"].get((en, cn), [])
            out.append(fk.rect(x, yy, cw, ch * 0.5, fill=sky, stroke="none", rx=6, sw=0))
            out.append(fk.rect(x, yy + ch * 0.45, cw, ch * 0.55, fill=ground, stroke="none", rx=6, sw=0))
            grid = lit(e["grid"], c)
            for k in range(20, int(cw), 22):
                out.append(f'<line x1="{x + k:.1f}" y1="{yy + ch * 0.48:.1f}" x2="{x + k - 18:.1f}" y2="{yy + ch:.1f}" '
                           f'stroke="{grid}" stroke-width="0.8" opacity="0.7"/>')
            out.append(fk.rect(x, yy, cw, ch, fill="none", stroke=TONES["interface"][0] if ids else "#CBD5E1", rx=6,
                               sw=2.2 if ids else 1, dash="" if ids else "4 3"))
            if ids:
                p, w = fk.pill(x + 8, yy + 8, ", ".join(ids), "#FFFFFF", color=INK, stroke=TONES["interface"][0])
                out += p
    y += len(envs) * (ch + 14) + 8
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [("#FFFFFF", TONES["interface"][0], "Used by a scene or variant"), ("#FFFFFF", "#CBD5E1", "Available, not used")]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 6
    out.append(fk.text(M, y + 4, "An approximation of the viewer's lighting for comparing looks, not a render; the stills "
                                 "are rendered from the pages themselves.", size=10.5, fill=MUTED))
    y += 18
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 2 · Every look the library can make",
                  "Every environment under every condition, with the scenes that use each look", out)


# ================================================================ SysML and ELK figures
def fig_sysml(d: dict) -> tuple[dict, str]:
    envs, conds = d["envs"], d["conds"]
    nodes = [{"id": "Environment", "shape": "class", "title": "Environment", "stereotype": "part def",
              "attrs": ["ground : String", "ground2 : String", "sky : String", "grid : String", "extentMetres : Real"],
              "tone": "work"},
             {"id": "Condition", "shape": "class", "title": "Condition", "stereotype": "part def",
              "attrs": ["sun : Real", "ambient : Real", "fogMetres : Real [0..1]", "skyTint : String [0..1]"],
              "tone": "external"},
             {"id": "Look", "shape": "class", "title": "Look", "stereotype": "part def",
              "attrs": ["camera : String", "part environment : Environment", "part condition : Condition"],
              "tone": "system"}]
    edges = [{"src": "Look", "dst": "Environment", "label": "environment", "arrow": "diamond"},
             {"src": "Look", "dst": "Condition", "label": "condition", "arrow": "diamond"}]
    s = ["    part def Environment {", "        doc /* Picture only: ground, sky and grid colours and the extent drawn. */",
         "        attribute ground : String;", "        attribute ground2 : String;", "        attribute sky : String;",
         "        attribute grid : String;", "        attribute extentMetres : Real;", "    }",
         "    part def Condition {", "        doc /* Picture only: lighting and fog. Never changes a run. */",
         "        attribute sun : Real;", "        attribute ambient : Real;", "        attribute fogMetres : Real [0..1];",
         "        attribute skyTint : String [0..1];", "    }",
         "    part def Look {", "        attribute camera : String;", "        part environment : Environment;",
         "        part condition : Condition;", "    }"]
    for n, e in envs.items():
        s += [f"    part {n}Environment : Environment {{", f"        attribute :>> ground = \"{e['ground']}\";",
              f"        attribute :>> ground2 = \"{e.get('ground2', '')}\";", f"        attribute :>> sky = \"{e['sky']}\";",
              f"        attribute :>> grid = \"{e['grid']}\";", f"        attribute :>> extentMetres = {float(e['extent_m'])};",
              "    }"]
    for n, c in conds.items():
        s += [f"    part {n}Condition : Condition {{", f"        attribute :>> sun = {float(c['sun'])};",
              f"        attribute :>> ambient = {float(c['ambient'])};"]
        if c.get("fog_m") is not None:
            s.append(f"        attribute :>> fogMetres = {float(c['fog_m'])};")
        if c.get("sky_tint"):
            s.append(f"        attribute :>> skyTint = \"{c['sky_tint']}\";")
        s.append("    }")
    spec = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
            "title": "SysML block definition — LookLibrary", "ref": "sim/scenes3d/library/LookLibrary.sysml",
            "subtitle": f"A look is an environment, a condition and a camera; LookLibrary.sysml holds the "
                        f"{len(envs)} environments and {len(conds)} conditions as parts with their values.",
            "frame": {"kind": "bdd", "type": "package", "name": "LookLibrary"}, "direction": "RIGHT",
            "nodes": nodes, "edges": edges,
            "legend": [edge_leg("Composition (diamond at owner)"), ("#F1F5F9", "#475569", "Condition"),
                       ("#FFFFFF", "#475569", "Environment"), ("#EEF2FF", "#4F46E5", "Look")]}
    sysml = "\n".join([
        f"// LookLibrary — generated by {GEN} from sim/scenes3d/library.",
        "// Do not edit by hand: change the library or the generator and regenerate.",
        "// Status: picture only; no look changes a run.", "",
        "package LookLibrary {",
        "    private import ScalarValues::*;",
        "    doc /* The look-only library of the 3D scenes (sim/scenes3d/library/README.md). */",
        *s, "}", ""])
    return spec, sysml


