def figure_specs(d: dict) -> tuple[list[dict], str]:
    ctx = d["ctx"]
    block = fig_block(ctx, {"scope": d["subs"]})
    by = defaultdict(list)
    for h in d["hz"]:
        for s in d["hazards"].get(h, {}).get("subsystems") or []:
            by[s].append(h)
    for n in block["nodes"]:
        if n.get("code") in by:
            n["sub"] = ", ".join(by[n["code"]])
    block.update(file="fig-3-block-diagram.svg", number="3",
                 subtitle=f"SUS-I1 decomposition. The {len(d['subs'])} subsystems named by the hazards the parameter "
                          "sources cite are coloured. The specs describe SUS-M1 lumped into a body and two legs.")
    boundary = fig_boundary(ctx, {"path": "sim/spec", "boundary": {
        "name": "Plant specs", "inside": ["Specs", "Spec check"],
        "outside": ["Lead decisions and records", "Sizing study", "Walker models", "Scenes and 3D pages", "Results",
                    "CI"],
        "flows": FLOWS}})
    boundary.update(file="fig-4-boundary-diagram.svg", number="4", ref="sim/spec/README.md",
                    subtitle="The folder owns the parameter values; spec.py checks them before any model runs. "
                             "Crossings are numbered as in the table.")
    sysml_spec, sysml = fig_sysml(d)
    io = {"file": "fig-6-inputs-and-outputs.svg", "number": "6", "title": "Inputs and outputs",
          "ref": "sim/spec/README.md", "direction": "RIGHT",
          "subtitle": "What the specs come from (left) and what reads them (right).",
          "nodes": [
              {"id": "I1", "title": "Lead decisions", "sub": ", ".join(c for c in d["cites"] if c.startswith("DQ")) or "—",
               "tone": "work"},
              {"id": "I2", "title": "Hazards and requirements",
               "sub": ", ".join(c for c in d["cites"] if c.startswith(("HAZ", "SYS"))), "tone": "work"},
              {"id": "I3", "title": "CONOPS and sizing", "sub": ", ".join(c for c in d["cites"]
                                                                          if c.startswith(("CONOPS", "MOD", "SZ"))),
               "tone": "work"},
              {"id": "X", "code": "sim/spec/", "title": "Plant specs", "tone": "current"},
              *[{"id": f"O{i}", "title": pk, "sub": "loads " + ", ".join(f for f, pks in d["users"].items() if pk in pks),
                 "tone": "software"} for i, pk in enumerate(sorted({p for v in d["users"].values() for p in v}), 1)]],
          "edges": [{"src": "I1", "dst": "X", "label": "limits"}, {"src": "I2", "dst": "X", "label": "basis"},
                    {"src": "I3", "dst": "X", "label": "values"}]}
    io["edges"] += [{"src": "X", "dst": n["id"], "label": ""} for n in io["nodes"] if n["id"].startswith("O")]
    specs = [fig_uses(d), block, boundary, sysml_spec, io]
    for sp in specs:
        sp.setdefault("footer", FOOTER)
        sp["edges"] = [dict(e) for e in sp.get("edges", [])]
        sp["legend"] = [tuple(x) for x in sp.get("legend", [])]
    return specs, sysml


