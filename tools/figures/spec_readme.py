def fig_params(d: dict) -> str:
    W, M = 1240, 40
    allp = [(s, n, p) for s in d["specs"] for n, p in s["params"].items()]
    st = Counter(p["status"] for _, _, p in allp)
    head, y0 = fk.header(
        W, "1", "Every plant parameter inside its allowed range",
        f"The {len(allp)} parameters of {' and '.join(s['id'] for s in d['specs'])}: each value marked inside the range "
        f"spec.py enforces (it refuses a value outside it or without a source), with its status — "
        + ", ".join(f"{n} {k}" for k, n in st.most_common()) + ". Nothing here is a design value.",
        "sim/spec/*.yaml")
    out = list(head)
    cx = {"n": M + 10, "v": M + 240, "bar": M + 350, "st": M + 615, "src": M + 700}
    barw = 190
    y = y0 + 26
    for s in d["specs"]:
        y += 8
        out.append(fk.text(M, y + 14, f"{s['file']} · {s['id']} · {s['revision']}", size=11.5, fill=INK, weight=700,
                           mono=True))
        y += 22
        for k, lab in (("n", "Parameter"), ("v", "Value"), ("bar", "Allowed range"), ("st", "Status"), ("src", "Source")):
            out.append(fk.text(cx[k], y + 10, lab, size=10, fill=MUTED, weight=700))
        y += 16
        rh = 22
        for i, (n, p) in enumerate(s["params"].items()):
            if i % 2:
                out.append(fk.rect(M, y + 1, W - 2 * M, rh - 2, fill=GREY_BG, stroke="none", rx=4, sw=0))
            cy = y + rh / 2 + 4
            out.append(fk.text(cx["n"], cy, n, size=10, fill=INK, mono=True))
            out.append(fk.text(cx["v"], cy, f"{p['value']:g} {p['unit'] if p['unit'] != '-' else ''}".strip(), size=10,
                               fill=INK, weight=700))
            lo, hi = p["range"]
            frac = (p["value"] - lo) / (hi - lo) if hi > lo else 0.5
            out.append(fk.rect(cx["bar"], cy - 6, barw, 6, fill=GREY_BG, stroke=HAIR, rx=3, sw=1))
            t = TONES[STATUS_TONE.get(p["status"], "amber")]
            out.append(f'<circle cx="{cx["bar"] + barw * frac:.1f}" cy="{cy - 3:.1f}" r="4.5" fill="{t[0]}"/>')
            out.append(fk.text(cx["bar"] - 4, cy + 1, f"{lo:g}", size=8.5, fill=FAINT, anchor="end"))
            out.append(fk.text(cx["bar"] + barw + 4, cy + 1, f"{hi:g}", size=8.5, fill=FAINT))
            pp, _ = fk.pill(cx["st"], cy - 12, p["status"], t[1], color=t[0], stroke=t[0])
            out += pp
            out.append(fk.text(cx["src"], cy, fk.wrap(p["source"], W - M - cx["src"], 9.5, max_lines=1)[0], size=9.5,
                               fill=MUTED))
            y += rh
    y += 10
    out.append(fk.line(M, y, W - M, y, stroke=HAIR, sw=1))
    y += 24
    leg = [(TONES[STATUS_TONE[s]][1], TONES[STATUS_TONE[s]][0],
            {"assumed": "Assumed (engineering assumption, no design yet)", "derived": "Derived (computed or sized)",
             "published": "Published (cited external source)"}[s]) for s in d["statuses"]]
    lg, y = fk.legend(M, y, leg, W - M)
    out += lg
    y += 10
    for ln in fk.wrap(FOOTER, W - 2 * M - 40, 10.5):
        out.append(fk.text(M, y + 4, ln, size=10.5, fill=FAINT))
        y += 15
    return fk.svg(W, y + 18, "Figure 1 · Every plant parameter inside its allowed range",
                  "All plant parameters with value, range, status and source", out)


# ================================================================ ELK figures and SysML
def fig_uses(d: dict) -> dict:
    nodes = [{"id": "C", "banner": "Cited in the sources", "tone": "work"},
             {"id": "S", "banner": "Specs", "tone": "work"},
             {"id": "U", "banner": "Loaded by", "tone": "work"}]
    edges = []
    for c, files in sorted(d["cites"].items()):
        tone = "safety" if c.startswith("HAZ") else ("interface" if c.startswith("SYS") else
                                                     ("external" if c.startswith("DQ") else "system"))
        nodes.append({"id": "c_" + mid(c), "parent": "C", "code": c, "title": cite_title(d, c),
                      "tone": tone, "maxw": 250,
                      "legend": {"safety": "Hazard", "interface": "Requirement", "external": "Lead decision",
                                 "system": "Other source"}[tone]})
        for f in files:
            edges.append({"src": "c_" + mid(c), "dst": "s_" + mid(f), "label": ""})
    for s in d["specs"]:
        st = Counter(p["status"] for p in s["params"].values())
        nodes.append({"id": "s_" + mid(s["file"]), "parent": "S", "code": s["file"], "title": s["id"],
                      "sub": f"{len(s['params'])} parameters · " + ", ".join(f"{n} {k}" for k, n in st.most_common()),
                      "tone": "current", "maxw": 240})
    for f, pkgs in d["users"].items():
        for pk in pkgs:
            uid = "u_" + mid(pk)
            if not any(n["id"] == uid for n in nodes):
                nodes.append({"id": uid, "parent": "U", "code": pk,
                              "title": "loads " + ", ".join(f2 for f2, p2 in d["users"].items() if pk in p2),
                              "tone": "software", "maxw": 220,
                              "legend": "Simulation code"})
            edges.append({"src": "s_" + mid(f), "dst": uid, "label": "", "dash": True})
    if "walker_l2.yaml" in d["users"]:
        edges.append({"src": "s_" + mid("walker.yaml"), "dst": "s_" + mid("walker_l2.yaml"), "label": "extends"})
    return {"file": "fig-2-sources-and-uses.svg", "number": "2", "title": "Where the parameters come from and go",
            "subtitle": "The records the parameter sources cite, the two specs, and the simulation code that loads "
                        "each (read from the code). A change to a spec changes every result downstream.",
            "ref": "sim/spec/*.yaml · sim/**/*.py", "direction": "RIGHT", "orient": "fixed", "nodes": nodes,
            "edges": edges, "legend": [edge_leg("Cited by a parameter source"), edge_leg("Loaded by", True)]}


def fig_sysml(d: dict) -> tuple[dict, str]:
    nodes = [{"id": "ParamStatus", "shape": "class", "title": "ParamStatus", "stereotype": "enum def",
              "attrs": d["statuses"], "tone": "interface"},
             {"id": "SpecParameter", "shape": "class", "title": "SpecParameter", "stereotype": "part def",
              "attrs": ["value : Real", "unit : String", "rangeLow : Real", "rangeHigh : Real", "status : ParamStatus",
                        "source : String"], "tone": "system"},
             {"id": "ParameterSpec", "shape": "class", "title": "ParameterSpec", "stereotype": "part def",
              "attrs": ["specId : String", "revision : String", "part parameters : SpecParameter [*]"], "tone": "system"}]
    edges = [{"src": "ParameterSpec", "dst": "SpecParameter", "label": "parameters [*]", "arrow": "diamond"},
             {"src": "SpecParameter", "dst": "ParamStatus", "label": "status", "dash": True}]
    s = ["    enum def ParamStatus {",
         "        doc /* The statuses sim/plant/spec.py accepts. */",
         *[f"        enum '{x}';" for x in d["statuses"]], "    }",
         "    part def SpecParameter {",
         "        doc /* One plant parameter; spec.py refuses it without every field or outside its range. */",
         "        attribute value : Real;", "        attribute unit : String;", "        attribute rangeLow : Real;",
         "        attribute rangeHigh : Real;", "        attribute status : ParamStatus;", "        attribute source : String;",
         "    }",
         "    part def ParameterSpec {",
         "        attribute specId : String;", "        attribute revision : String;",
         "        part parameters : SpecParameter[*];", "    }"]
    for sp in d["specs"]:
        pn = camel(sp["file"].replace(".yaml", "").replace("-", "_")) + "Spec"
        st = Counter(p["status"] for p in sp["params"].values())
        nodes.append({"id": pn, "shape": "class", "title": f"{pn} : ParameterSpec", "stereotype": "part",
                      "attrs": [f"specId = {sp['id']}", f"revision = {sp['revision']}",
                                f"parameters: {len(sp['params'])} (" + ", ".join(f"{n} {k}" for k, n in st.most_common())
                                + ")"], "tone": "safety"})
        edges.append({"src": pn, "dst": "ParameterSpec", "label": "", "dash": True})
        s += [f"    part {pn} : ParameterSpec {{", f"        doc /* sim/spec/{sp['file']}: {len(sp['params'])} parameters */",
              f"        attribute :>> specId = \"{sp['id']}\";", f"        attribute :>> revision = \"{sp['revision']}\";",
              "    }"]
    spec_fig = {"file": "fig-5-sysml-block-definition.svg", "number": "5",
                "title": "SysML block definition — PlantSpecs", "ref": "sim/spec/PlantSpecs.sysml",
                "subtitle": "What a parameter spec is, with the statuses spec.py accepts and the two specs, generated "
                            "into PlantSpecs.sysml. The values themselves are in Figure 1.",
                "frame": {"kind": "bdd", "type": "package", "name": "PlantSpecs"}, "direction": "RIGHT",
                "nodes": nodes, "edges": edges,
                "legend": [edge_leg("Composition (diamond at owner)"), edge_leg("Typed by", True),
                           ("#F5F3FF", "#7C3AED", "Enumeration"), ("#EEF2FF", "#4F46E5", "Part definition"),
                           ("#FFF7ED", "#C2410C", "Spec in this folder")]}
    sysml = "\n".join([
        f"// PlantSpecs — generated by {GEN} from sim/spec/*.yaml and sim/plant/spec.py.",
        "// Do not edit by hand: change the specs or the generator and regenerate.",
        "// Status: concept assumptions, not design values.", "",
        "package PlantSpecs {",
        "    private import ScalarValues::*;",
        "    doc /* Walker parameter specs for the level-1 and level-2 models (sim/spec/README.md). */",
        *s, "}", ""])
    return spec_fig, sysml


