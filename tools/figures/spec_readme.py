# ================================================================ records
def load() -> dict:
    ctx, reqs, hazards = load_reqs()
    specs = []
    for p in sorted(FOLDER.glob("*.yaml")):
        d = yaml.safe_load(p.read_text())
        specs.append({"file": p.name, "id": d["id"], "revision": d["revision"], "params": d["params"],
                      "doc": " ".join(ln[1:].strip() for ln in p.read_text().splitlines() if ln.startswith("#"))})
    src = (ROOT / "sim" / "plant" / "spec.py").read_text()
    tree = ast.parse(src)
    statuses = next(sorted(ast.literal_eval(n.value)) for n in ast.walk(tree)
                    if isinstance(n, ast.Assign) and any(getattr(t, "id", "") == "STATUSES" for t in n.targets))
    fields = re.search(r'for key in \(([^)]*)\)', src).group(1)
    fields = [f.strip().strip('"\'') for f in fields.split(",") if f.strip()]
    users: dict[str, set] = defaultdict(set)
    for py in sorted((ROOT / "sim").rglob("*.py")):
        if "tests" in py.parts or py.parent == FOLDER:
            continue
        t = py.read_text()
        pkg = "/".join(py.relative_to(ROOT).parts[:2]) if len(py.relative_to(ROOT).parts) > 2 else str(py.relative_to(ROOT))
        if py.relative_to(ROOT).as_posix() == "sim/plant/spec.py":
            continue
        if "walker_l2" in t:
            users["walker_l2.yaml"].add(pkg)
        if re.search(r"plant import spec|spec\.load\(|walker\.yaml", t):
            users["walker.yaml"].add(pkg)
    reg = {d["id"]: d for d in yaml.safe_load((ROOT / "decisions" / "register.yaml").read_text())["decisions"]}
    cites = defaultdict(set)
    for s in specs:
        for n, p in s["params"].items():
            for c in CITE.findall(p["source"]):
                cites[c].add(s["file"])
    hz = sorted(c for c in cites if c.startswith("HAZ"))
    subs = sorted({x for h in hz for x in hazards.get(h, {}).get("subsystems") or []})
    return {"ctx": ctx, "reqs": reqs, "hazards": hazards, "reg": reg, "specs": specs, "statuses": statuses,
            "fields": fields, "users": {k: sorted(v) for k, v in users.items()}, "cites": dict(cites), "hz": hz,
            "subs": subs}


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def cite_title(d: dict, c: str) -> str:
    if c.startswith("HAZ"):
        return d["hazards"].get(c, {}).get("title", c)
    if c.startswith("SYS"):
        return d["reqs"].get(c, {}).get("title", c)
    if c.startswith("DQ"):
        return d["reg"].get(c, {}).get("question", c)
    return {"CONOPS": "Concept of operations", "SZ-01": "Actuator sizing study (sim/mujoco)",
            "SSF-004": "Feedback staleness monitor (software function)"}.get(
        c, "Operating mode in the CONOPS" if c.startswith("MOD") else c)


