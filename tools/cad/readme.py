"""Build the layout tables of cad/README.md (SUS-CAD-001) from cad/metrics.json and the layout parameters.

    python -m tools.cad.readme            # write
    python -m tools.cad.readme --check    # fail if the page is stale

Only the block between <!-- cad:layouts:start --> and <!-- cad:layouts:end --> is generated; the rest of the page
is hand-written. The page then gets its terms block (tools/terms/terms.py). Standard library + PyYAML.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.terms.terms import decorate  # noqa: E402

PAGE = ROOT / "cad/README.md"
START = "<!-- cad:layouts:start (generated by tools/cad/readme.py from cad/metrics.json; do not edit) -->"
END = "<!-- cad:layouts:end -->"
FLAG_MARGIN, FLAG_ROTOR = 0.30, 1.0  # provisional review flags, as drawn on the review images

LAYOUT_ROWS = [
    ("Locomotion", lambda m: m["locomotion"]),
    ("UAV dock", lambda m: m["dock"]),
    ("Envelope L × W × H", lambda m: " × ".join(f"{v:.1f}" for v in m["envelope_m"]) + " m"),
    ("Overall height", lambda m: f"{m['height_m']:.2f} m"),
    ("Pilot eye height", lambda m: f"{m['pilot_eye_m']:.2f} m"),
    ("Cockpit floor (egress drop)", lambda m: f"{m['cockpit_floor_m']:.2f} m"),
    ("CG height", lambda m: f"{m['cg_m'][2]:.2f} m"),
    ("Static margin", lambda m: f"{m['static_margin_m']:.2f} m" + (" ⚠" if m["static_margin_m"] < FLAG_MARGIN else "")),
    ("Static tip angle", lambda m: f"{m['static_tip_angle_deg']:.1f}°"),
    ("Rotor ↔ pilot (docked)", lambda m: f"{m['rotor_to_pilot_m']:.2f} m" + (" ⚠" if m["rotor_to_pilot_m"] < FLAG_ROTOR else "")),
    ("Rotor ↔ own structure (docked)",
     lambda m: "off-board" if m.get("rotor_to_structure_m") is None else f"{m['rotor_to_structure_m']:.2f} m"),
    ("Placeholder mass", lambda m: f"~{m['placeholder_mass_kg'] / 1000:.1f} t"),
]

POSTURE_ROWS = [  # label, metrics key (None = CG height), format
    ("Cockpit floor (egress drop)", "cockpit_floor_m", "{:.2f} m"), ("Hip height", "hip_height_m", "{:.2f} m"),
    ("Overall height", "height_m", "{:.2f} m"), ("CG height", None, "{:.2f} m"),
    ("Static margin", "static_margin_m", "{:.2f} m"), ("Static tip angle", "static_tip_angle_deg", "{:.1f}°"),
    ("Claws above ground", "arm_ground_clearance_m", "{:.2f} m"),
    ("Front-opening sill (actual climb height)", "egress_sill_m", "{:.2f} m"),
    ("Ladder treads", "steps", "{}"), ("Largest step rise", "max_step_rise_m", "{:.2f} m"),
    ("Emergency hatch sill", "emergency_sill_m", "{:.2f} m"),
    ("Emergency hatch clear opening", "emergency_clear_m", "{0[0]:.2f} × {0[1]:.2f} m"),
    ("Escape ladder clearance to the walker", "escape_clearance_m", "{:.2f} m"),
    ("Shoulder step height (flush with the hatch sill)", "hatch_step_m", "{:.2f} m"),
    ("Gap from shoulder step to escape ladder", "step_to_ladder_gap_m", "{:.2f} m"),
    ("Carried load envelope (placeholder)", "carry_load_envelope_m", "{0[0]:.2f} × {0[1]:.2f} × {0[2]:.2f} m"),
    ("Load bottom above ground", "carry_load_bottom_m", "{:.2f} m"),
    ("Arm angles (upper arm below horizontal / forearm)", "carry_arm_angles_deg", "{0[0]:.0f}° / {0[1]:.0f}°"),
    ("Nearest ground seen straight ahead", "ground_seen_ahead_loaded_m", "{:.2f} m"),
    ("Load mass giving the largest static margin", "carry_margin_peak", "{0[load_kg]} kg ({0[static_margin_m]:.2f} m)"),
    ("Load mass at the 0.30 m margin flag", "carry_load_at_margin_flag_kg", "{} kg"),
    ("Load mass at standstill tip-over", "carry_load_at_tipover_kg", "{} kg"),
]


def block() -> str:
    data = json.loads((ROOT / "cad/metrics.json").read_text(encoding="utf-8"))
    met = data["concepts"]
    ids = sorted(met)
    out = [f"*Metrics from [`metrics.json`](metrics.json) (FreeCAD {data.get('freecad', '?')}); "
           "⚠ marks the provisional review flags of §1.*", "",
           "| | " + " | ".join(ids) + " |", "|---|" + "---|" * len(ids)]
    for name, fn in LAYOUT_ROWS:
        out.append(f"| {name} | " + " | ".join(fn(met[i]) for i in ids) + " |")
    for i in ids:
        m = met[i]
        out += ["", f"### {i} · {m['title']}", ""]
        if (ROOT / f"cad/drawings/{i}.svg").is_file():
            out += [f"Drawing sheet: [SUS-CAD-001-{i}](drawings/{i}.svg) (420 × 297 mm, 1:50, dimensioned side, plan and front views)."]
        poses = yaml.safe_load((ROOT / f"cad/params/{i}.yaml").read_text(encoding="utf-8")).get("postures") or {}
        for posture, pm in sorted(m.get("postures", {}).items()):
            label_ = poses.get(posture, {}).get("label", posture)
            out += ["", f"**{posture.capitalize()} posture** ({label_}).", "",
                    f"| | Standing | {posture.capitalize()} |", "|---|---|---|"]
            for label, key, fmt in POSTURE_ROWS:
                if key and key not in m and key not in pm:
                    continue
                a, b = (m["cg_m"][2], pm["cg_m"][2]) if key is None else (m.get(key), pm.get(key))
                if key == "ground_seen_ahead_loaded_m":  # standing column: the same sight line without a load
                    a = pm.get("ground_seen_ahead_unloaded_m")
                show = lambda v: "—" if v is None else fmt.format(v)  # noqa: E731
                out.append(f"| {label} | {show(a)} | {show(b)} |")
            rp = f"renders/{i}-{posture}"
            out += ["", "| | |", "|---|---|",
                    f"| ![{i} {posture}, front view]({rp}-hero.png) | ![{i} {posture}, side elevation]({rp}-side.png) |"]
            if (ROOT / f"cad/drawings/{i}-{posture}.svg").is_file():
                out += ["", f"Drawing sheet: [SUS-CAD-001-{i}-{posture}](drawings/{i}-{posture}.svg)."]
        r = f"renders/{i}"
        if (ROOT / f"cad/{r}-hero.png").is_file():
            out += ["", f"![{i} front view from eye height]({r}-hero.png)", "", "| | |", "|---|---|",
                    f"| ![{i} three-quarter view]({r}-iso.png) | ![{i} side elevation]({r}-side.png) |",
                    f"| ![{i} plan view with support polygon and centre of gravity]({r}-top.png) "
                    f"| ![{i} UAV dock and rotor clearance to the pilot]({r}-dock.png) |"]
    return "\n".join(out)


def render() -> str:
    text = PAGE.read_text(encoding="utf-8")
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        raise SystemExit(f"{PAGE.relative_to(ROOT)}: generated block markers missing")
    text = pat.sub(lambda _m: f"{START}\n{block()}\n{END}", text)
    return decorate(PAGE.relative_to(ROOT).as_posix(), text)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    new = render()
    if PAGE.read_text(encoding="utf-8") == new:
        return 0
    if args.check:
        print("Stale: cad/README.md (run python -m tools.cad.readme)")
        return 1
    PAGE.write_text(new, encoding="utf-8")
    print("wrote cad/README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
