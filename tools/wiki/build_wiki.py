#!/usr/bin/env python3
"""Publish the repository's documentation pages to the GitHub Wiki source folder (docs/wiki).

The wiki is published from docs/wiki by .github/workflows/publish-wiki.yml. Pages written elsewhere in the
repository (the front page, the MIL-STD-882E work-product tree, concept, PX4 integration, the documentation standard
and the abbreviations page) are copied here as wiki pages, with every relative link rewritten for the wiki:

- a link to another published page becomes a link to its copy here (`[text](Page-Name.md)`);
- a figure keeps a path relative to docs/wiki (`../../safety/.../fig-1.svg`); docs/wiki/assets.txt lists every
  such file;
- any other repository file or folder becomes a link to it on github.com.

So the pages render when browsed in this repository. Publishing (`--publish DIR`, run by the publish workflow)
copies every docs/wiki page into the wiki checkout DIR and rewrites those two forms for the wiki: page links lose
`.md`, and each figure becomes `assets/<repo path>`, with the figure copied there and docs/wiki/images copied too.

    python -m tools.wiki.build_wiki            # write the wiki pages, _Sidebar section and assets.txt
    python -m tools.wiki.build_wiki --check    # fail if any of them is stale
    python -m tools.wiki.build_wiki --publish wiki-checkout   # copy pages, images and figures for the wiki

Standard library + PyYAML (through tools.terms). Output is deterministic.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.terms.terms import decorate  # noqa: E402

WIKI = ROOT / "docs" / "wiki"
BLOB = "https://github.com/jherrodthomas/Project-Susanoo/blob/main/"
TREE = "https://github.com/jherrodthomas/Project-Susanoo/tree/main/"
GEN = "tools/wiki/build_wiki.py"
TREE_DIR = ROOT / "safety" / "mil-std-882e"
SIDEBAR = WIKI / "_Sidebar.md"
SIDE_START = "<!-- wiki:published:start (generated by tools/wiki/build_wiki.py; do not edit) -->"
SIDE_END = "<!-- wiki:published:end -->"
IMAGE = re.compile(r"\.(svg|png|jpe?g|gif)$", re.I)


def tree_page(readme: Path) -> str:
    rel = readme.parent.relative_to(TREE_DIR)
    return "882E-Work-Products" if str(rel) == "." else "882E-" + rel.name.replace("_", "-")


def sources() -> dict[Path, str]:
    """Source page -> wiki page name."""
    pages = {ROOT / "README.md": "Project-Overview",
             ROOT / "docs/terms.md": "Abbreviations-and-Codes",
             ROOT / "framework/documentation-standard.md": "Documentation-Standard",
             ROOT / "concept/README.md": "Concept-Model",
             ROOT / "integrations/px4/README.md": "PX4-Integration-Model"}
    for r in sorted(TREE_DIR.rglob("README.md")):
        if "figures" not in r.parts:
            pages[r] = tree_page(r)
    return pages


def existing_wiki_pages() -> dict[Path, str]:
    return {p: p.stem for p in WIKI.glob("*.md") if not p.name.startswith("_")}


def rewrite(text: str, src: Path, names: dict[Path, str], assets: set[str]) -> str:
    """Rewrite relative links and image paths for the wiki; code spans and fences are left alone."""
    def target(link: str) -> str:
        if re.match(r"^(https?:|mailto:|#)", link) or link.startswith("/"):
            return link
        path, _, frag = link.partition("#")
        p = (src.parent / path).resolve()
        try:
            rel = p.relative_to(ROOT).as_posix()
        except ValueError:
            return link
        if p in names:
            return names[p] + ".md" + (f"#{frag}" if frag else "")
        if p.is_dir() and (p / "README.md") in names:
            return names[p / "README.md"] + ".md"
        if IMAGE.search(rel) and p.is_file():
            assets.add(rel)
            return os.path.relpath(p, WIKI).replace(os.sep, "/")
        if not p.exists():
            return link                                   # leave unresolved links visible rather than invent one
        return (TREE if p.is_dir() else BLOB) + rel + (f"#{frag}" if frag else "")

    parts = re.split(r"(```.*?```|`[^`\n]*`)", text, flags=re.S)
    for i in range(0, len(parts), 2):
        seg = parts[i]
        seg = re.sub(r"\]\(([^)\s]+)\)", lambda m: f"]({target(m.group(1))})", seg)
        seg = re.sub(r'\b(src|href)="([^"]+)"', lambda m: f'{m.group(1)}="{target(m.group(2))}"', seg)
        parts[i] = seg
    return "".join(parts)


def build() -> dict[Path, str]:
    names = {**existing_wiki_pages(), **sources()}
    assets: set[str] = set()
    out: dict[Path, str] = {}
    for src, page in sources().items():
        text = src.read_text(encoding="utf-8")
        rel = src.relative_to(ROOT).as_posix()
        banner = (f"<!-- GENERATED by {GEN} from {rel}. Do not edit here; edit the source and re-run. -->\n\n"
                  f"> Published from [`{rel}`]({BLOB}{rel}) in the repository.\n\n")
        body = rewrite(text, src, names, assets)
        body = re.sub(r"^<!-- GENERATED[^\n]*-->\n+", "", body)          # one banner is enough
        out[WIKI / f"{page}.md"] = banner + body
    # 3D stills and other images that existing wiki pages reference from images/ are published by the workflow;
    # these assets are the figures of the pages copied above.
    out[WIKI / "assets.txt"] = "".join(f"{a}\n" for a in sorted(assets))
    out[SIDEBAR] = sidebar(SIDEBAR.read_text(encoding="utf-8"))
    return out


def sidebar(current: str) -> str:
    tree = sorted(((p, n) for p, n in sources().items() if p.is_relative_to(TREE_DIR)), key=lambda t: str(t[0]))
    lines = [SIDE_START, "", "**Published from the repository**", "",
             "- [Project overview](Project-Overview)",
             "- [Abbreviations & codes](Abbreviations-and-Codes)",
             "- [Documentation standard](Documentation-Standard)",
             "- [Concept model & figures](Concept-Model)",
             "- [PX4 integration model](PX4-Integration-Model)",
             "- [882E workflow](Project-Overview#the-mil-std-882e-workflow)",
             "- [882E work products](882E-Work-Products)"]
    for p, n in tree:
        depth = len(p.parent.relative_to(TREE_DIR).parts)
        if depth == 1:
            title = re.search(r"^# (.+)$", p.read_text(encoding="utf-8"), re.M).group(1)
            lines.append(f"  - [{title}]({n})")
    lines += ["", SIDE_END]
    block = "\n".join(lines)
    pat = re.compile(re.escape(SIDE_START) + r".*?" + re.escape(SIDE_END), re.S)
    if pat.search(current):
        return pat.sub(lambda _m: block, current)
    return current.rstrip("\n") + "\n\n" + block + "\n"


def for_wiki(text: str, pages: set[str], assets: list[str]) -> str:
    """The published form of a docs/wiki page: figure paths to assets/<repo path>, page links without .md."""
    for a in assets:
        r = os.path.relpath(ROOT / a, WIKI).replace(os.sep, "/")
        if not r.startswith("../"):                       # already inside docs/wiki (images/): same path in the wiki
            continue
        text = text.replace(f"]({r}", f"](assets/{a}").replace(f'="{r}"', f'="assets/{a}"')
    names = "|".join(re.escape(n) for n in sorted(pages, key=len, reverse=True))
    text = re.sub(rf"(\]\(|href=\")({names})\.md(?=[#)\"])", r"\1\2", text)
    return text


def publish(dest: Path) -> int:
    """Copy every docs/wiki page, image and listed figure into the wiki checkout dest, in wiki form."""
    assets = [a for a in (WIKI / "assets.txt").read_text(encoding="utf-8").splitlines() if a]
    pages = {p.stem for p in WIKI.glob("*.md")}
    for p in sorted(WIKI.glob("*.md")):
        (dest / p.name).write_text(for_wiki(p.read_text(encoding="utf-8"), pages, assets), encoding="utf-8")
    (dest / "images").mkdir(parents=True, exist_ok=True)
    for img in sorted(WIKI.glob("images/*")):
        if img.suffix.lower() in (".svg", ".png"):
            shutil.copy2(img, dest / "images" / img.name)
    for a in assets:
        (dest / "assets" / a).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / a, dest / "assets" / a)
    print(f"published {len(pages)} pages and {len(assets)} figures to {dest}")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--publish", metavar="DIR", help="copy pages, images and figures into a wiki checkout")
    a = ap.parse_args(argv)
    if a.publish:
        return publish(Path(a.publish))
    stale = []
    pages = build()
    for p, text in pages.items():
        text = decorate(p.relative_to(ROOT).as_posix(), text)
        if p.exists() and p.read_text(encoding="utf-8") == text:
            continue
        if a.check:
            stale.append(p.relative_to(ROOT).as_posix())
        else:
            p.write_text(text, encoding="utf-8")
            print(f"wrote {p.relative_to(ROOT).as_posix()}")
    published = {p for p in pages if p.suffix == ".md" and p != SIDEBAR}
    for old in WIKI.glob("*.md"):                       # a page whose source was removed
        if old not in published and old.read_text(encoding="utf-8").startswith(f"<!-- GENERATED by {GEN}"):
            stale.append(old.relative_to(ROOT).as_posix() + " (orphan)") if a.check else old.unlink()
    if stale:
        print("Wiki pages are out of date; run: python -m tools.wiki.build_wiki")
        for s in stale:
            print(f"  {s}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
