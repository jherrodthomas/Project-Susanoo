"""How the MIL-STD-882E tasks relate: four figures drawn from the work-product catalog's inputs and outputs.

    task-flow.svg    Figure 5  task-to-task flows, grouped by process element (ELK layout)
    task-thread.svg  Figure 6  the hand-off chains from the first hazard analyses to risk acceptance (ELK layout)
    task-matrix.svg  Figure 7  who feeds whom: a design structure matrix, feedback marked below the diagonal
    task-hub.svg     Figure 8  the hazard tracking system (Task 106) as the hub: who writes into it, who reads from it

Called by tools/readme/build_readme.py, which decorates and writes them to docs/readme/. Deterministic.
"""
from __future__ import annotations

import collections
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "figures"))
import layoutkit as fk  # noqa: E402
import diagram  # noqa: E402
from layoutkit import MUTED, FAINT, HAIR, TONES  # noqa: E402

GEN = "tools/readme/build_readme.py"
SRC = "safety/mil-std-882e/catalog.yaml"
M = 40
# catalog folder IDs that are not defined terms: show what they are instead
LABEL = {"HTS": "Task 106", "SWS": "Section 4.4", "SREQ": "Requirements", "ACC": "Acceptance",
         "SYSDEF": "Baseline", "TPL": "Templates"}
HUBS = {"HTS", "E1", "E2", "E3", "SYSDEF", "TPL"}       # left out of the hand-off chains: everything touches them
THREAD_STARTS = ("T201", "T208", "T206")
THREAD_END = "ACC"


class Catalog:
    def __init__(self, cat: dict, tailor: dict):
        self.cat, self.tl = cat, tailor
        self.f = {f["id"]: f for f in cat["folders"]}
        edges = set()
        for f in cat["folders"]:
            for i in f.get("inputs") or []:
                if i.get("ref"):
                    edges.add((i["ref"], f["id"], i["item"]))
            for o in f.get("outputs") or []:
                if o.get("ref"):
                    edges.add((f["id"], o["ref"], o["item"]))
        self.edges = sorted(e for e in edges if e[0] != e[1])

    def code(self, fid: str) -> str:
        f = self.f[fid]
        if fid in LABEL:
            return LABEL[fid]
        if fid[:1] == "E" and fid[1:].isdigit():
            return f"Element {fid[1:]}"
        return f"Task {f['tasks'][0]['id']}" if f.get("tasks") else fid

    def name(self, fid: str) -> str:
        return self.f[fid]["title"].split("·")[-1].strip().split(" (")[0]

    def tone(self, fid: str) -> str:
        tid = (self.f[fid].get("tasks") or [{}])[0].get("id")
        d = self.tl["tasks"][tid]["disposition"] if tid else "selected"
        return {"selected": "system", "conditional": "amber"}.get(d, "muted")


def _footer(text: str) -> str:
    return f"Generated by {GEN} from {SRC} (inputs and outputs of every work-product folder). {text}"


def flow_spec(c: Catalog) -> dict:
    tasks = [f for f in c.cat["folders"] if f["id"].startswith("T") and f.get("tasks")]
    ids = {f["id"] for f in tasks}
    nodes = []
    for e in c.cat["elements"]:
        members = [f for f in tasks if f.get("element") == e["n"]]
        if not members:
            continue
        nodes.append({"id": f"EL{e['n']}", "banner": f"{e['n']} · {e['short']}", "tone": "work"})
        nodes += [{"id": f["id"], "parent": f"EL{e['n']}", "code": c.code(f["id"]), "title": c.name(f["id"]),
                   "tone": c.tone(f["id"])} for f in members]
    edges = [{"src": a, "dst": b, "label": ""} for a, b, _ in c.edges if a in ids and b in ids]
    return {"number": "5", "title": "How the tasks feed each other",
            "subtitle": "Every task-to-task flow in the work-product catalog, grouped by process element. The hazard "
                        "tracking system and the element-level hubs are left out here; Figure 8 shows them.",
            "ref": SRC, "direction": "RIGHT", "nodes": nodes, "edges": edges, "legend_only": True,
            "legend": [(TONES["system"][1], TONES["system"][0], "Selected task"),
                       (TONES["amber"][1], TONES["amber"][0], "Conditional"),
                       ("#F1F5F9", "#94A3B8 dashed", "Not selected or not applicable")],
            "footer": _footer("Planned flows, not completed work.")}


def thread_spec(c: Catalog) -> dict:
    g = collections.defaultdict(list)
    for a, b, it in c.edges:
        g[a].append((b, it))

    def path(s, t):
        q, seen = collections.deque([[s]]), {s}
        while q:
            p = q.popleft()
            if p[-1] == t:
                return p
            for nb, _ in g[p[-1]]:
                if nb not in seen and (nb not in HUBS or nb == t):
                    seen.add(nb)
                    q.append(p + [nb])
        return []
    nodes, edges, seen = [], [], set()
    for start in THREAD_STARTS:
        th = path(start, THREAD_END)
        for i, o in enumerate(th):
            if o not in seen:
                seen.add(o)
                nodes.append({"id": o, "code": c.code(o), "title": c.name(o), "sub": c.f[o].get("gate", ""),
                              "tone": "safety" if o == THREAD_END else c.tone(o)})
            if i and (th[i - 1], o) not in {(e["src"], e["dst"]) for e in edges}:
                edges.append({"src": th[i - 1], "dst": o, "label": next(x for nb, x in g[th[i - 1]] if nb == o)})
    return {"number": "6", "title": "The main thread: from first hazards to risk acceptance",
            "subtitle": "The shortest chains of hand-offs from the preliminary hazard list, the functional hazard "
                        "analysis and the operating and support analysis to risk acceptance, with what each step hands "
                        "on and the gates each step spans.",
            "ref": SRC, "direction": "RIGHT", "nodes": nodes, "edges": edges, "legend_only": True,
            "legend": [(TONES["system"][1], TONES["system"][0], "Task or work product"),
                       (TONES["safety"][1], TONES["safety"][0], "Risk acceptance")],
            "footer": _footer("Planned hand-offs, not completed work.")}


def matrix(c: Catalog) -> str:
    order = ["SYSDEF"]
    for e in c.cat["elements"]:
        order += [f["id"] for f in c.cat["folders"] if f.get("element") == e["n"] and f["id"] not in ("SREQ", "ACC")]
    order += ["SREQ", "ACC", "HTS", "SWS"]
    order = [o for o in order if any(o in (a, b) for a, b, _ in c.edges)]
    n, idx = len(order), {o: i for i, o in enumerate(order)}
    cs, lw = 17, 300
    W = M + lw + n * cs + M + 24
    out, yl = fk.header(W, "7", "Who feeds whom", "Design structure matrix: a row feeds a column. Read across a row "
                        "for what a task sends, down a column for what it needs. Marks below the diagonal feed back to "
                        "earlier work.", SRC)
    top, x0 = yl + 112, M + lw
    for j, o in enumerate(order):
        cx = x0 + j * cs + cs / 2
        out.append(f'<text x="{fk.fmt(cx + 3)}" y="{top - 6}" font-size="9.5" fill="{MUTED}" font-weight="700" '
                   f'transform="rotate(-60 {fk.fmt(cx + 3)} {top - 6})">{c.code(o)}</text>')
    for i, o in enumerate(order):
        y = top + i * cs
        if i % 2 == 0:
            out.append(fk.rect(M, y, lw + n * cs, cs, fill="#F8FAFC", stroke="none", rx=0, sw=0))
        label = f"{c.code(o)}  {c.name(o)}"
        while fk.text_w(label, 10) > lw - 10 and len(label) > 6:
            label = label[:-2].rstrip() + "…"
        out.append(fk.text(M + 4, y + 12, label, size=10))
        out.append(fk.rect(x0 + i * cs, y, cs, cs, fill="#CBD5E1", stroke="none", rx=0, sw=0))
    for a, b, _ in c.edges:
        if a in idx and b in idx:
            i, j = idx[a], idx[b]
            s = TONES["system"][0] if i < j else TONES["safety"][0]
            out.append(fk.circle(x0 + j * cs + cs / 2, top + i * cs + cs / 2, 5, fill=s, stroke=s, sw=1))
    for k in range(n + 1):
        out.append(fk.line(x0 + k * cs, top, x0 + k * cs, top + n * cs, stroke=HAIR, sw=0.5))
        out.append(fk.line(x0, top + k * cs, x0 + n * cs, top + k * cs, stroke=HAIR, sw=0.5))
    fwd = sum(1 for a, b, _ in c.edges if a in idx and b in idx and idx[a] < idx[b])
    back = sum(1 for a, b, _ in c.edges if a in idx and b in idx and idx[a] > idx[b])
    leg, y = fk.legend(M, top + n * cs + 26, [
        (TONES["system"][0], TONES["system"][0], f"Feeds later work, above the diagonal ({fwd})"),
        (TONES["safety"][0], TONES["safety"][0], f"Feeds back to earlier work, below the diagonal ({back})")], W - M)
    out += leg
    out.append(fk.text(M, y + 14, _footer(""), size=10.5, fill=FAINT))
    return fk.svg(W, y + 34, "Figure 7 · Who feeds whom", "Design structure matrix of the MIL-STD-882E tasks", out)


def hub(c: Catalog) -> str:
    ins = sorted({a for a, b, _ in c.edges if b == "HTS"})
    outs = sorted({b for a, b, _ in c.edges if a == "HTS"})
    both = [x for x in ins if x in outs]
    left = [x for x in ins if x not in both]
    right = [x for x in outs if x not in both] + both
    W, cw, rh = 1180, 340, 44
    out, yl = fk.header(W, "8", "Everything runs through the hazard tracking system",
                        "Task 106 is the hub. Left: the work that writes hazards, risk and mitigations into it. Right: "
                        "the work that reads from it, and below that the work that does both.", SRC)
    top = yl + 30
    rows = max(len(left), len(right))
    hx, hy = W / 2 - 120, top + rows * rh / 2 - 40

    def card(x, y, o, tone):
        s, f = TONES[tone]
        out.append(fk.rect(x, y, cw, 36, fill=f, stroke=s, rx=8, sw=1.1))
        p, pw = fk.pill(x + 8, y + 10, c.code(o), fill=s, color="#FFFFFF", h=16, size=9)
        out.extend(p)
        name = c.name(o)
        while fk.text_w(name, 10.5) > cw - pw - 30 and len(name) > 6:
            name = name[:-2].rstrip() + "…"
        out.append(fk.text(x + 16 + pw, y + 23, name, size=10.5))
    for i, o in enumerate(left):
        y = top + i * rh
        card(M, y, o, "system")
        out.append(fk.path(fk.rounded_path([(M + cw, y + 18), (hx - 30, y + 18), (hx - 30, hy + 40), (hx - 2, hy + 40)]),
                           stroke=TONES["system"][0], sw=1, marker_end="url(#arr-system)"))
    rx = W - M - cw
    for i, o in enumerate(right):
        y = top + i * rh
        tone = "amber" if o in both else "software"
        card(rx, y, o, tone)
        out.append(fk.path(fk.rounded_path([(hx + 242, hy + 40), (rx - 30, hy + 40), (rx - 30, y + 18), (rx - 2, y + 18)]),
                           stroke=TONES[tone][0], sw=1, marker_end=f"url(#arr-{tone})"))
    out.append(fk.rect(hx, hy, 240, 80, fill=TONES["safety"][1], stroke=TONES["safety"][0], rx=12, sw=1.6))
    out.append(fk.text(hx + 120, hy + 34, "Hazard tracking system", size=14, weight=700, anchor="middle"))
    out.append(fk.text(hx + 120, hy + 54, "Task 106 · safety/hazards/", size=10.5, fill=MUTED, anchor="middle"))
    leg, y = fk.legend(M, top + rows * rh + 20, [
        (TONES["system"][1], TONES["system"][0], f"Writes into it ({len(left)})"),
        (TONES["software"][1], TONES["software"][0], f"Reads from it ({len(right) - len(both)})"),
        (TONES["amber"][1], TONES["amber"][0], f"Both ({len(both)})")], W - M)
    out += leg
    out.append(fk.text(M, y + 14, _footer(""), size=10.5, fill=FAINT))
    return fk.svg(W, y + 34, "Figure 8 · Everything runs through the hazard tracking system",
                  "Who writes into and reads from the hazard tracking system", out)


def figures(cat: dict, tailor: dict) -> dict[str, str]:
    c = Catalog(cat, tailor)
    flow, thread = diagram.render_all([flow_spec(c), thread_spec(c)])
    return {"task-flow.svg": flow, "task-thread.svg": thread, "task-matrix.svg": matrix(c), "task-hub.svg": hub(c)}
